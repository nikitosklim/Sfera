# ядро_голое_железо.s — первый шаг к настоящей загрузке БЕЗ какой-либо
# операционной системы вообще (не как обычный Linux-процесс, а как
# полноценное "ядро", которое загружает сам эмулятор/BIOS/GRUB).
#
# АРХИТЕКТУРНАЯ ИДЕЯ: вместо того чтобы писать собственный загрузчик для
# BIOS с нуля (отдельная, большая тема — переход из 16-битного реального
# режима, чтение секторов диска вручную и так далее), используется
# стандарт MULTIBOOT — тот же, что понимает GRUB. QEMU умеет загружать
# multiboot-совместимое "ядро" НАПРЯМУЮ (флаг -kernel), без какого-либо
# диска или загрузчика вообще — достаточно правильного заголовка в
# начале файла.
#
# ⚠️ ЧЕСТНОЕ ОГРАНИЧЕНИЕ ЭТОГО ШАГА: Multiboot передаёт управление в
# 32-БИТНОМ защищённом режиме процессора — не в 64-битном, в котором
# работает весь остальной наш компилятор. Значит на этом первом шаге
# код на языке Сфера (main, главная) ЕЩЁ НЕ запускается — это отдельный,
# следующий шаг (переход в 64-битный режим). Пока — доказательство того,
# что сама ЗАГРУЗКА через QEMU реально работает, самым простым и честным
# способом: прямая запись в видеопамять на чистом ассемблере.

.intel_syntax noprefix

# Заголовок Multiboot — магическое число + флаги + контрольная сумма,
# сумма которых должна быть равна нулю (это и есть весь "протокол",
# по которому GRUB/QEMU опознают файл как загружаемое ядро).
.set MULTIBOOT_МАГИЯ, 0x1BADB002
.set MULTIBOOT_ФЛАГИ, 0x0
.set MULTIBOOT_КОНТРОЛЬНАЯ_СУММА, -(MULTIBOOT_МАГИЯ + MULTIBOOT_ФЛАГИ)

.section .multiboot
.align 4
    .long MULTIBOOT_МАГИЯ
    .long MULTIBOOT_ФЛАГИ
    .long MULTIBOOT_КОНТРОЛЬНАЯ_СУММА

# Собственный, небольшой стек — на голом железе нет операционной системы,
# которая выделила бы его заранее, как это происходит для обычного
# Linux-процесса. Резервируем 16 КБ прямо здесь.
.section .bss
.align 16
стек_снизу:
    .skip 16384
стек_сверху:

.section .text
.global _start
.code32
_start:
    mov esp, offset стек_сверху

    # Прямая запись в видеопамять (0xB8000) — стандартный, известный ещё
    # с первых IBM PC способ вывести текст на экран без единого
    # системного вызова, без единого драйвера — просто фиксированный
    # адрес памяти, который видеокарта сама отображает на экран.
    # Формат: два байта на символ — (символ, цветовой атрибут).
    #
    # ⚠️ ЧЕСТНОЕ ОГРАНИЧЕНИЕ: текст здесь латиницей, не кириллицей — VGA
    # текстовый режим использует ОДНОБАЙТОВУЮ кодировку (классически
    # CP437/CP866), а сам символьный литерал в UTF-8 занимает для
    # кириллицы 2 байта, что не поместилось бы в "byte ptr" вообще.
    # Вывод кириллицы потребовал бы загрузки собственного VGA-шрифта с
    # кириллическими глифами — самостоятельный, отдельно честно названный
    # следующий шаг, не решаемый прямой записью байт.
    mov edi, 0xB8000
    mov byte ptr [edi], 'S'
    mov byte ptr [edi+1], 0x0A      # ярко-зелёный текст на чёрном фоне
    mov byte ptr [edi+2], 'f'
    mov byte ptr [edi+3], 0x0A
    mov byte ptr [edi+4], 'e'
    mov byte ptr [edi+5], 0x0A
    mov byte ptr [edi+6], 'r'
    mov byte ptr [edi+7], 0x0A
    mov byte ptr [edi+8], 'a'
    mov byte ptr [edi+9], 0x0A
    mov byte ptr [edi+10], ':'
    mov byte ptr [edi+11], 0x0A
    mov byte ptr [edi+12], ' '
    mov byte ptr [edi+13], 0x0A
    mov byte ptr [edi+14], 'b'
    mov byte ptr [edi+15], 0x0A
    mov byte ptr [edi+16], 'a'
    mov byte ptr [edi+17], 0x0A
    mov byte ptr [edi+18], 'r'
    mov byte ptr [edi+19], 0x0A
    mov byte ptr [edi+20], 'e'
    mov byte ptr [edi+21], 0x0A
    mov byte ptr [edi+22], ' '
    mov byte ptr [edi+23], 0x0A
    mov byte ptr [edi+24], 'm'
    mov byte ptr [edi+25], 0x0A
    mov byte ptr [edi+26], 'e'
    mov byte ptr [edi+27], 0x0A
    mov byte ptr [edi+28], 't'
    mov byte ptr [edi+29], 0x0A
    mov byte ptr [edi+30], 'a'
    mov byte ptr [edi+31], 0x0A
    mov byte ptr [edi+32], 'l'
    mov byte ptr [edi+33], 0x0A
    mov byte ptr [edi+34], ' '
    mov byte ptr [edi+35], 0x0A
    mov byte ptr [edi+36], 'O'
    mov byte ptr [edi+37], 0x0A
    mov byte ptr [edi+38], 'K'
    mov byte ptr [edi+39], 0x0A

останов:
    hlt
    jmp останов
