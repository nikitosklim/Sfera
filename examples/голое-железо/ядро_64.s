# ядро_64.s — второй, решающий шаг к настоящей загрузке "на голом
# железе": полный переход из 32-битного защищённого режима (в котором
# Multiboot передаёт управление) в 64-битный (long mode) — тот самый,
# в котором работает весь наш компилятор — чтобы наконец вызвать
# настоящую, скомпилированную языком Сфера функцию "main" БЕЗ какой-либо
# операционной системы вообще.
#
# Последовательность перехода — хорошо документированная (см. OSDev
# wiki "Setting Up Long Mode"), но объёмная: настройка таблиц страниц,
# включение PAE, загрузка адреса таблиц в CR3, включение long mode через
# регистр EFER, включение самой страничной адресации, и, наконец,
# загрузка 64-битной GDT с дальним переходом в 64-битный код.

.intel_syntax noprefix

.set MULTIBOOT_МАГИЯ, 0x1BADB002
.set MULTIBOOT_ФЛАГИ, 0x0
.set MULTIBOOT_КОНТРОЛЬНАЯ_СУММА, -(MULTIBOOT_МАГИЯ + MULTIBOOT_ФЛАГИ)

.section .multiboot
.align 4
    .long MULTIBOOT_МАГИЯ
    .long MULTIBOOT_ФЛАГИ
    .long MULTIBOOT_КОНТРОЛЬНАЯ_СУММА

.section .bss
.align 16
стек_снизу:
    .skip 16384
стек_сверху:

# Таблицы страниц для перехода в long mode — используем страницы по 2 МБ
# ("huge pages"), это позволяет обойтись всего одной записью на каждом
# уровне вместо полной четырёхуровневой иерархии с 4 КБ страницами.
# Каждая таблица обязана быть выровнена по границе 4 КБ.
.align 4096
пмл4:
    .skip 4096
пдпт:
    .skip 4096
пд:
    .skip 4096

# НОВОЕ: область памяти для распределителя структур (см. подробное
# объяснение в арена_распределитель.код — тот же самый bump allocator,
# написанный на языке Сфера, что уже работал в автономном Linux-режиме,
# просто теперь со своей, отдельной ареной прямо здесь). Помещается в
# только что расширенное отображение памяти (0-4 МБ).
.align 16
арена64:
    .skip 1048576

.section .rodata
.align 8
подпись_результата:
    .asciz "\nResult: "

.align 8
gdt64:
    .quad 0                              # обязательный нулевой дескриптор
    .quad 0x00209A0000000000              # 64-битный код: present, исполняемый, кольцо 0, бит L (long mode)
    .quad 0x0000920000000000              # данные: present, доступен для записи, кольцо 0
gdt64_конец:
gdt64_указатель:
    .word gdt64_конец - gdt64 - 1
    .quad gdt64

.section .text
.global _start
.code32
_start:
    mov esp, offset стек_сверху

    # --- Шаг 1: строим таблицы страниц (identity mapping первых 2 МБ) ---
    # PML4[0] -> PDPT (present + доступна для записи)
    mov eax, offset пдпт
    or eax, 0b11
    mov dword ptr [пмл4], eax
    mov dword ptr [пмл4 + 4], 0

    # PDPT[0] -> PD (present + доступна для записи)
    mov eax, offset пд
    or eax, 0b11
    mov dword ptr [пдпт], eax
    mov dword ptr [пдпт + 4], 0

    # PD[0] и PD[1] -> две страницы по 2 МБ (0-2МБ и 2-4МБ), начиная с
    # физического адреса 0 (present + доступна для записи + флаг
    # "страница 2 МБ") — расширено с одной страницы до двух, чтобы
    # осталось место для арены распределителя памяти (см. ниже) —
    # ядро загружается по адресу 1 МБ, значит одной страницы (0-2МБ)
    # было бы впритык.
    mov dword ptr [пд], 0b10000011
    mov dword ptr [пд + 4], 0
    mov dword ptr [пд + 8], 0x200083
    mov dword ptr [пд + 12], 0

    # --- Шаг 2: включаем PAE (Physical Address Extension) — бит 5 в CR4 ---
    mov eax, cr4
    or eax, 1 << 5
    mov cr4, eax

    # --- Шаг 3: загружаем физический адрес PML4 в CR3 ---
    mov eax, offset пмл4
    mov cr3, eax

    # --- Шаг 4: включаем Long Mode — бит LME в MSR EFER (адрес 0xC0000080) ---
    mov ecx, 0xC0000080
    rdmsr
    or eax, 1 << 8
    wrmsr

    # --- Шаг 5: включаем саму страничную адресацию — бит PG в CR0 (бит 31) ---
    mov eax, cr0
    or eax, 1 << 31
    mov cr0, eax

    # --- Шаг 6: загружаем 64-битную GDT и делаем дальний переход ---
    # Именно этот переход и переключает процессор в полноценный
    # 64-битный режим выполнения — до этого момента, несмотря на все
    # предыдущие шаги, инструкции всё ещё декодируются как 32-битные.
    lgdt [gdt64_указатель]
    jmp 0x08:точка_входа_64

.code64
точка_входа_64:
    # Настраиваем сегментные регистры данных на наш сегмент данных
    # (индекс 2 в GDT, то есть смещение 2*8=0x10) — в 64-битном режиме
    # они по большей части игнорируются процессором, но должны быть
    # валидными, иначе последующие инструкции с памятью могут вызвать
    # исключение.
    mov ax, 0x10
    mov ds, ax
    mov es, ax
    mov ss, ax

    # Тот же стек, что использовался в 32-битном коде, — он уже
    # идентично отображён (identity-mapped) и полностью годится для
    # использования как RSP в 64-битном режиме.
    mov rsp, offset стек_сверху

    # НОВОЕ: инициализация арены — первые 8 байт хранят "текущее
    # смещение", начинаем с 8 (пропуская сам этот заголовок) — та же
    # логика, что и в минимальный_рантайм.s для автономного Linux-режима.
    lea rax, [rip + арена64]
    mov qword ptr [rax], 8

    # ЗДЕСЬ И ПРОИСХОДИТ ГЛАВНОЕ: вызов настоящей, скомпилированной
    # языком Сфера функции "main" — БЕЗ Linux, БЕЗ libc, БЕЗ вообще
    # какой-либо операционной системы, только что включённый нами самими
    # 64-битный режим процессора.
    call main

    # main вернула целое значение в eax — выводим её через ТОТ ЖЕ
    # механизм курсора, что и printf/вывести(...), а не напрямую по
    # фиксированному адресу 0xB8000 — иначе этот вывод затирал бы начало
    # текста, уже выведенного изнутри main через вывести(...) (реальная
    # находка: оба способа записи по одному и тому же начальному адресу
    # экрана конфликтовали друг с другом).
    mov r15, rax
    lea rdi, [rip + подпись_результата]
    call vga_записать_строку
    mov rdi, r15
    call vga_записать_целое

останов:
    hlt
    jmp останов

# text sfera_адрес_арены() — возвращает адрес арены (см. .bss выше).
# Та же самая функция, что уже работала в автономном Linux-режиме —
# распределитель памяти на языке Сфера (арена_распределитель.код)
# использует её без единого изменения.
.global sfera_адрес_арены
sfera_адрес_арены:
    lea rax, [rip + арена64]
    ret

# --- НОВОЕ: собственная, ограниченная реализация printf для настоящего
# "голого железа" — вывести(...) внутри себя вызывает НАСТОЯЩИЙ printf,
# которого здесь взять неоткуда (нет ни libc, ни даже системных вызовов,
# как в автономном Linux-режиме — здесь просто нет ядра ОС вообще).
# Пишем текст напрямую в видеопамять, с сохранением позиции курсора
# между вызовами (иначе каждый следующий вызов "вывести" затирал бы
# предыдущий, начиная с самого начала экрана).

.section .bss
.align 8
# Текущее смещение записи в видеопамяти — в БАЙТАХ от начала 0xB8000,
# продвигается на 2 (символ + цвет) за каждый выведенный символ, либо
# перескакивает на начало следующей строки экрана при переводе строки.
курсор_vga:
    .skip 8

.section .text

# void vga_записать_символ(al = символ) — пишет один символ текущим
# цветом (жёлтый — 0x0E) в текущую позицию курсора, продвигает курсор.
# Символ перевода строки (0x0A) обрабатывается отдельно — переносит
# курсор на начало следующей строки экрана (80 символов * 2 байта = 160).
.global vga_записать_символ
vga_записать_символ:
    push rbx
    push rdx

    cmp al, 10                       # '\n' — перевод строки
    je .vga_символ_перевод_строки

    mov rbx, [rip + курсор_vga]
    mov edx, 0xB8000
    add rbx, rdx
    mov byte ptr [rbx], al
    mov byte ptr [rbx + 1], 0x0E      # жёлтый текст на чёрном фоне

    add qword ptr [rip + курсор_vga], 2
    jmp .vga_символ_конец

.vga_символ_перевод_строки:
    mov rax, [rip + курсор_vga]
    xor rdx, rdx
    mov rbx, 160
    div rbx                           # rax = номер текущей строки (0..24)
    inc rax
    imul rax, rax, 160
    mov [rip + курсор_vga], rax

.vga_символ_конец:
    pop rdx
    pop rbx
    ret

# void vga_записать_строку(rdi = указатель на null-terminated текст) —
# выводит текст посимвольно через vga_записать_символ до нулевого байта.
.global vga_записать_строку
vga_записать_строку:
    push rbx
    mov rbx, rdi

.vga_строка_цикл:
    movzx eax, byte ptr [rbx]
    test al, al
    jz .vga_строка_конец
    call vga_записать_символ
    inc rbx
    jmp .vga_строка_цикл

.vga_строка_конец:
    pop rbx
    ret

# void vga_записать_целое(rdi = знаковое 64-битное число) — переводит
# число в десятичную запись и выводит её. Простой, но корректный подход:
# делим на 10 в цикле, накапливая цифры на стеке (в обратном порядке, раз
# первая полученная цифра — младшая), затем выводим их в правильном
# порядке.
.global vga_записать_целое
vga_записать_целое:
    push rbx
    push r12
    push r13
    mov rax, rdi
    xor r13, r13                      # r13 = 1, если число отрицательное

    test rax, rax
    jns .vga_целое_положительное
    mov r13, 1
    neg rax

.vga_целое_положительное:
    mov r12, rsp                      # запомним вершину стека до push цифр
    mov rbx, 10

.vga_целое_цикл_деления:
    xor rdx, rdx
    div rbx
    add dl, '0'
    push rdx
    test rax, rax
    jnz .vga_целое_цикл_деления

    test r13, r13
    jz .vga_целое_вывод_цифр
    mov al, '-'
    call vga_записать_символ

.vga_целое_вывод_цифр:
    cmp rsp, r12
    je .vga_целое_конец
    pop rax
    call vga_записать_символ
    jmp .vga_целое_вывод_цифр

.vga_целое_конец:
    pop r13
    pop r12
    pop rbx
    ret

# int printf(rdi = формат, ...) — собственная, ограниченная реализация:
# поддерживает ровно то, что реально использует "вывести(...)" внутри
# компилятора — %s (текст), %lld (64-битное целое), \n (перевод строки),
# %% (буквальный процент). Обычные символы выводятся как есть.
#
# Целочисленные/указательные variadic-аргументы приходят по System V ABI
# в rsi, rdx, rcx, r8, r9 (rdi уже занят форматной строкой) — сохраняем
# их на стек в начале функции, чтобы можно было брать по порядковому
# номеру, а не жёстко привязываться к конкретному регистру для каждого
# спецификатора формата.
.global printf
printf:
    push rbx
    push r12
    push r13
    push r14
    sub rsp, 40                       # место под 5 сохранённых регистров-аргументов

    mov [rsp], rsi
    mov [rsp + 8], rdx
    mov [rsp + 16], rcx
    mov [rsp + 24], r8
    mov [rsp + 32], r9

    mov r12, rdi                      # r12 = указатель на текущий символ формата
    xor r13, r13                      # r13 = индекс следующего аргумента (0..4)

.printf_цикл:
    movzx eax, byte ptr [r12]
    test al, al
    jz .printf_конец
    cmp al, '%'
    je .printf_спецификатор

    call vga_записать_символ
    inc r12
    jmp .printf_цикл

.printf_спецификатор:
    inc r12
    movzx eax, byte ptr [r12]

    cmp al, 's'
    jne .printf_проверка_l
    mov rdi, [rsp + r13*8]
    inc r13
    call vga_записать_строку
    inc r12
    jmp .printf_цикл

.printf_проверка_l:
    cmp al, 'l'
    jne .printf_проверка_процент
    inc r12                            # пропускаем первую 'l'
    inc r12                            # пропускаем вторую 'l' (формат "lld")
    inc r12                            # пропускаем 'd'
    mov rdi, [rsp + r13*8]
    inc r13
    call vga_записать_целое
    jmp .printf_цикл

.printf_проверка_процент:
    cmp al, '%'
    jne .printf_неизвестный
    mov al, '%'
    call vga_записать_символ
    inc r12
    jmp .printf_цикл

.printf_неизвестный:
    # Неизвестный спецификатор — выводим его как есть (символ '%' и то,
    # что за ним следует), не падаем и не портим остальной вывод.
    mov al, '%'
    call vga_записать_символ
    jmp .printf_цикл

.printf_конец:
    add rsp, 40
    pop r14
    pop r13
    pop r12
    pop rbx
    xor eax, eax
    ret
