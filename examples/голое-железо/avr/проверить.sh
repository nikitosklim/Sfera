#!/bin/sh
# Собирает мигалку на Сфере под ATmega328P и проверяет её в эмуляторе simavr:
# вывод PB5 (светодиод на плате) должен включаться и выключаться.
# Требуется: avr-gcc с avr-libc, simavr (libsimavr-dev, libelf-dev), gcc, собранный компилятор.
set -e
DIR=$(cd "$(dirname "$0")" && pwd)
SFERA="${SFERA_BIN:-$DIR/../../../target/release/запустить}"
WORK=$(mktemp -d)
cp "$DIR/мигалка.код" "$DIR/проверка_порта.c" "$WORK/"
cd "$WORK"
"$SFERA" мигалка.код --только-собрать --без-ос --целевая-платформа avr >/dev/null
avr-gcc -mmcu=atmega328p мигалка.o -o мигалка.elf
avr-size мигалка.elf
gcc проверка_порта.c -o проверка_порта -lsimavr -lelf -lm
./проверка_порта мигалка.elf 1.0 | grep "PB5" > вывод.txt
cat вывод.txt
# ожидается: светодиод включается и выключается как минимум по два раза
ON=$(grep -c "= 1" вывод.txt || true)
OFF=$(grep -c "= 0" вывод.txt || true)
if [ "$ON" -ge 2 ] && [ "$OFF" -ge 2 ]; then
    echo "ПРОЙДЕНО: AVR мигалка"
else
    echo "НЕ ПРОЙДЕНО: AVR мигалка"; exit 1
fi

# Прерывание таймера: светодиод переключается из обработчика каждые 100 мс
cp "$DIR/прерывание.код" "$WORK/"
"$SFERA" прерывание.код --только-собрать --без-ос --целевая-платформа avr >/dev/null
avr-gcc -mmcu=atmega328p прерывание.o -o прерывание.elf
./проверка_порта прерывание.elf 0.35 | grep "PB5" > вывод2.txt
cat вывод2.txt
N=$(wc -l < вывод2.txt)
if [ "$N" -ge 3 ]; then
    echo "ПРОЙДЕНО: AVR прерывание таймера"
else
    echo "НЕ ПРОЙДЕНО: AVR прерывание таймера"; exit 1
fi

# Глобальные массивы: таблица во флэш-памяти (lpm) и в оперативной; светодиод должен остаться включённым
cp "$DIR/таблицы.код" "$WORK/"
"$SFERA" таблицы.код --только-собрать --без-ос --целевая-платформа avr >/dev/null
avr-gcc -mmcu=atmega328p таблицы.o -o таблицы.elf
./проверка_порта таблицы.elf 0.05 | grep "PB5" > вывод3.txt
cat вывод3.txt
if [ "$(tail -n 1 вывод3.txt | grep -c '= 1')" -eq 1 ] && avr-objdump -d таблицы.elf | grep -q lpm; then
    echo "ПРОЙДЕНО: AVR глобальные массивы и таблица во флэш-памяти"
else
    echo "НЕ ПРОЙДЕНО: AVR глобальные массивы и таблица во флэш-памяти"; exit 1
fi
