#!/bin/sh
# Собирает мини-ОС целиком: программу пользователя (кольцо 3), стартовый код, шрифт и ядро на Сфере.
# Использование:  ./собрать_ядро.sh ос.bin        (результат — ядро ос.bin и рядом диск данных.img;
#                 запуск: qemu-system-x86_64 -kernel ос.bin -vga std -drive file=данные.img,format=raw,if=ide,index=2)
# Требуется: as, ld, objcopy (binutils), python3 и собранный компилятор.
set -e
DIR=$(cd "$(dirname "$0")" && pwd)
SFERA="${SFERA_BIN:-$DIR/../../target/release/запустить}"
OUT=$(cd "$(dirname "$1")" && pwd)/$(basename "$1")
WORK=$(mktemp -d)
cp "$DIR/ос.код" "$DIR/пользователь/программа.код" "$DIR/пользователь/считалка.код" "$WORK/"
cd "$WORK"
# программа пользователя: отдельный образ с адресами 0x40400000…
as "$DIR/пользователь/старт.s" -o старт_п.o
"$SFERA" программа.код --только-собрать --без-ос >/dev/null
ld -m elf_x86_64 -T "$DIR/пользователь/компоновка.ld" старт_п.o программа.o -o программа.elf 2>/dev/null
objcopy -O binary программа.elf пользователь.bin
as "$DIR/пользователь/образ.s" -o образ.o
# вторая программа — только на диске данных: данные.img (запуск: -drive file=данные.img,format=raw,if=ide,index=2)
"$SFERA" считалка.код --только-собрать --без-ос >/dev/null
ld -m elf_x86_64 -T "$DIR/пользователь/компоновка.ld" старт_п.o считалка.o -o считалка.elf 2>/dev/null
objcopy -O binary считалка.elf считалка.bin
python3 "$DIR/../../инструменты/диск/собрать_диск.py" "$(dirname "$OUT")/данные.img" "привет=пользователь.bin" "считалка=считалка.bin" >/dev/null
# ядро
as "$DIR/запуск_ос.s" -o запуск.o
as "$DIR/шрифт_8х16.s" -o шрифт.o 2>/dev/null
"$SFERA" ос.код --только-собрать --без-ос >/dev/null
ld -m elf_x86_64 -T "$DIR/../голое-железо/компоновка_ядра_64.ld" запуск.o шрифт.o образ.o ос.o -o "$OUT" 2>/dev/null
