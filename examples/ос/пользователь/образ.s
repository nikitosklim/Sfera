# образ.s — готовый образ программы пользователя (пользователь.bin) внутри ядра; ядро копирует его в страницы пользователя.
.intel_syntax noprefix
.section .rodata
.align 16
образ_начало:
    .incbin "пользователь.bin"
образ_конец:
образ_длина:
    .quad образ_конец - образ_начало

.section .text
.global "sfera_образ_пользователя_начало"
"sfera_образ_пользователя_начало":
    lea rax, [rip + образ_начало]
    ret
.global "sfera_образ_пользователя_размер"
"sfera_образ_пользователя_размер":
    mov rax, [rip + образ_длина]
    ret
.section .note.GNU-stack,"",@progbits
