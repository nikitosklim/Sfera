//! Вспомогательный модуль для языкового сервера — НЕ часть самого
//! компилятора (не используется main.rs), нужен только для автодополнения
//! и подсказок при наведении (src/bin/сфера_lsp.rs). Вынесен в библиотеку,
//! а не прямо в сфера_lsp.rs, чтобы форматирование типов было в одном
//! месте, не дублировалось.

use crate::ast::Тип;

/// Превращает Тип обратно в читаемый текст языка "Сфера" — например,
/// Тип::Целое -> "целое", Тип::Пользовательский("Пользователь") ->
/// "Пользователь". Используется для показа сигнатур функций/методов и
/// полей структур в автодополнении и при наведении — без этого пришлось
/// бы показывать сырой Rust-Debug вывод (с заглавными буквами вариантов
/// enum, что не похоже на то, как это реально пишется в самом языке).
pub fn тип_в_текст(тип: &Тип) -> String {
    match тип {
        Тип::Целое => "целое".to_string(),
        Тип::Целое8 => "целое8".to_string(),
        Тип::Целое16 => "целое16".to_string(),
        Тип::Целое32 => "целое32".to_string(),
        Тип::Целое64 => "целое64".to_string(),
        Тип::Беззнак8 => "беззнак8".to_string(),
        Тип::Беззнак16 => "беззнак16".to_string(),
        Тип::Беззнак32 => "беззнак32".to_string(),
        Тип::Беззнак64 => "беззнак64".to_string(),
        Тип::Дробное => "дробное".to_string(),
        Тип::Дробное32 => "дробное32".to_string(),
        Тип::Дробное64 => "дробное64".to_string(),
        Тип::Текст => "текст".to_string(),
        Тип::Верно => "верно".to_string(),
        Тип::Пользовательский(имя) => имя.clone(),
        Тип::Обобщённый { имя, параметры } => {
            let параметры_текст: Vec<String> = параметры.iter().map(тип_в_текст).collect();
            format!("{} из {}", имя, параметры_текст.join(" и "))
        }
        Тип::Массив { элемент, размер } => match размер {
            Some(n) => format!("{}({})", тип_в_текст(элемент), n),
            None => format!("{}()", тип_в_текст(элемент)),
        },
        Тип::Опциональный(внутренний) => format!("{}?", тип_в_текст(внутренний)),
        Тип::Результат(внутренний) => format!("результат из {}", тип_в_текст(внутренний)),
        Тип::Канал(внутренний) => format!("канал из {}", тип_в_текст(внутренний)),
    }
}

