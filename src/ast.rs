//! AST — абстрактное синтаксическое дерево.
//! Это структурированное представление программы: не текст, а дерево из
//! узлов, отражающее реальную вложенность и смысл конструкций.
//!
//! Например, код:
//!     целое а = 2 + 3 * 4;
//! превращается не в "текст с плюсом и звёздочкой", а в дерево, где
//! видно, что умножение должно посчитаться раньше сложения — это
//! прямое следствие приоритета операторов (грамматика, раздел 8).

// --- Типы (раздел 3 грамматики) ---

#[derive(Debug, Clone, PartialEq)]
pub enum Тип {
    Целое,
    Целое8,
    Целое16,
    Целое32,
    Целое64,
    Беззнак8,
    Беззнак16,
    Беззнак32,
    Беззнак64,
    Дробное,
    Дробное32,
    Дробное64,
    Текст,
    Верно,

    /// Пользовательский тип — структура, объявленная программистом
    Пользовательский(String),

    /// Обобщённый тип с параметрами: Список<целое>, Словарь<текст, целое>
    Обобщённый {
        имя: String,
        параметры: Vec<Тип>,
    },

    /// Массив: целое[5] (фиксированный) или целое[] (размер по литералу)
    Массив {
        элемент: Box<Тип>,
        размер: Option<i64>,
    },

    /// Опциональный тип: текст?
    Опциональный(Box<Тип>),

    /// результат<тип>
    Результат(Box<Тип>),

    /// НОВОЕ (многопоточность, вторая часть): канал<тип> — простой,
    /// потокобезопасный "почтовый ящик" для одного значения — способ
    /// безопасно передать результат ИЗ блока "параллельно" обратно в
    /// вызвавший его код. См. подробное архитектурное объяснение в
    /// codegen.rs, сгенерировать_параллельно — канал единственный тип,
    /// которому разрешено "пересекать границу" в тело потока, поскольку
    /// он живёт в куче (безопасно копировать указатель), а не на стеке
    /// (в отличие от обычных локальных переменных).
    Канал(Box<Тип>),
}

// --- Выражения (раздел 8 грамматики) ---

#[derive(Debug, Clone, PartialEq)]
pub enum Выражение {
    ЦелоеЛит(i64),
    ДробноеЛит(f64),
    ТекстЛит(String),
    /// Текстовый литерал с интерполяцией: "Привет, $имя!" или
    /// "Итог: ${а + б}!" — состоит из чередующихся кусков обычного текста
    /// и вставленных выражений. Полноценное текстовое значение (настоящий
    /// malloc-буфер через конкатенацию, см. codegen.rs,
    /// сгенерировать_интерполированный_текст) — используется где угодно,
    /// как и любой другой текст: присваивается в переменную, передаётся
    /// в функцию, возвращается, склеивается через "+" и т.д. (раньше было
    /// жёстко ограничено ТОЛЬКО прямым единственным аргументом вывести(...)
    /// через printf-трюк — см. историю в ИСТОРИЯ_РАЗРАБОТКИ.md).
    /// "$имя" — короткая форма для простого имени переменной, сахар для
    /// "${имя}". "${выражение}" принимает ЛЮБОЕ выражение форматируемого
    /// типа (текст, целые числа любой разрядности, дробное, верно) — см.
    /// является_форматируемым в semantic.rs.
    /// ⚠️ ЧЕСТНОЕ ОГРАНИЧЕНИЕ: строковые литералы ВНУТРИ "${...}"
    /// не поддерживаются (лексер разбирает внешнюю строку целиком ДО
    /// того, как парсер узнаёт о вложенном "${...}", поэтому неэкранированная
    /// кавычка внутри "${...}" преждевременно закрыла бы внешний литерал —
    /// см. подробности в parser.rs, разобрать_текстовый_литерал).
    ИнтерполированныйТекст(Vec<ФрагментТекста>),
    ВерноЛит(bool),
    НеуказаноЛит,

    /// Обращение к переменной по имени
    Идентификатор(String),

    /// Массив-литерал: [1, 2, 3]
    МассивЛит(Vec<Выражение>),

    /// Вызов функции: имя(аргументы), возможно с явными типовыми параметрами
    ВызовФункции {
        имя: String,
        типовые_параметры: Vec<Тип>,
        аргументы: Vec<Выражение>,
    },

    /// обращение.к_полю
    ДоступКПолю {
        объект: Box<Выражение>,
        поле: String,
    },

    /// объект.метод(аргументы) — отличается от ДоступКПолю + ВызовФункции тем,
    /// что метод принадлежит конкретной структуре, а не является свободной
    /// функцией с таким именем. "это" внутри метода неявно ссылается на объект.
    /// НОВОЕ: типовые_параметры — явные типы для обобщённого метода
    /// ("объект.метод<целое>(...)"), то же самое, что и у ВызовФункции
    /// выше — пустой Vec для обычного, необобщённого вызова метода.
    ВызовМетода {
        объект: Box<Выражение>,
        метод: String,
        типовые_параметры: Vec<Тип>,
        аргументы: Vec<Выражение>,
    },

    /// массив[индекс]
    ДоступПоИндексу {
        массив: Box<Выражение>,
        индекс: Box<Выражение>,
    },

    /// левое ОПЕРАТОР правое
    Бинарное {
        левое: Box<Выражение>,
        оператор: БинарныйОператор,
        правое: Box<Выражение>,
    },

    /// ОПЕРАТОР операнд (унарный минус, логическое "не")
    Унарное {
        оператор: УнарныйОператор,
        операнд: Box<Выражение>,
    },

    /// выражение? — проброс ошибки из результат<тип> (раздел 9)
    Проброс(Box<Выражение>),

    /// успех(выражение) / ошибка(выражение) — конструкторы результат<тип>
    Успех(Box<Выражение>),
    Ошибка(Box<Выражение>),
}

/// Один кусочек интерполированной строки — либо обычный текст "как есть",
/// либо произвольное выражение, которое нужно вычислить, привести к
/// тексту и подставить на это место. Короткая форма "$имя" превращается
/// парсером в Выражение(Идентификатор(имя)) — отдельного варианта для
/// неё больше нет, это просто частный случай произвольного выражения.
#[derive(Debug, Clone, PartialEq)]
pub enum ФрагментТекста {
    Текст(String),
    Выражение(Box<Выражение>),
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum БинарныйОператор {
    Плюс,
    Минус,
    Умножить,
    Разделить,
    Остаток,
    Равно,
    НеРавно,
    Меньше,
    Больше,
    МеньшеРавно,
    БольшеРавно,
    И,
    Или,
    // НОВОЕ: настоящие побитовые операторы (см. подробное объяснение в
    // token.rs про честное отсутствие сдвигов в этой версии).
    БитИ,
    БитИли,
    БитИскл,
    /// НОВОЕ: `<<` — сдвиг влево. Раньше сдвигов не было вообще (см.
    /// token.rs) — риск был не в самой операции, а в том, что лексер уже
    /// использует '<'/'>' для обобщённых типов (Список<T>). Решение здесь
    /// НЕ трогает лексер: он по-прежнему выдаёт '<' и '>' как отдельные,
    /// не склеенные токены (Меньше/Больше), ровно как раньше — сдвиг
    /// распознаётся только в ОДНОМ месте, на уровне разбора ВЫРАЖЕНИЙ
    /// (см. parser.rs, разобрать_сдвиг), где два токена Меньше/Больше
    /// подряд без ничего между ними не могут означать ничего, кроме
    /// сдвига (в отличие от закрытия вложенных обобщённых типов, которое
    /// целиком происходит в разборе ТИПОВ, отдельном коде, никогда не
    /// проходящем через разбор выражений — конфликта нет).
    СдвигВлево,
    /// НОВОЕ: `>>` — сдвиг вправо (арифметический, знаковый — тот же
    /// выбор, что уже негласно сделан для '<'/'>'/'/' у ЦЕЛЫХ чисел в
    /// codegen.rs: беззнаковые типы там тоже трактуются как знаковые,
    /// честно унаследованное, не новое ограничение).
    СдвигВправо,
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum УнарныйОператор {
    Минус,
    Не,
    БитНе,
}

/// "Место записи" (lvalue) — то, во что можно присвоить значение.
/// Не любое выражение годится слева от "=": нельзя написать "5 = х;".
/// Явное отдельное понятие вместо переиспользования Выражение отражает
/// именно это ограничение прямо в дереве, а не оставляет его неявным
/// правилом, которое пришлось бы проверять постфактум.
#[derive(Debug, Clone, PartialEq)]
pub enum МестоЗаписи {
    /// имя = значение;
    Имя(String),
    /// объект.поле = значение;
    /// объект — тоже МестоЗаписи, а не Выражение: это позволяет естественно
    /// разобрать цепочки вида "а.б.в = значение;" рекурсивно.
    Поле {
        объект: Box<МестоЗаписи>,
        поле: String,
    },
    /// массив[индекс] = значение;
    Индекс {
        массив: Box<МестоЗаписи>,
        индекс: Box<Выражение>,
    },
}

// --- Операторы / statements (раздел 7 грамматики) ---

#[derive(Debug, Clone, PartialEq)]
pub enum Оператор {
    /// тип имя = значение; — объявление с явным типом
    ОбъявлениеСТипом {
        тип: Тип,
        имя: String,
        значение: Выражение,
    },

    /// неизменно тип имя = значение;
    ОбъявлениеНеизменное {
        тип: Тип,
        имя: String,
        значение: Выражение,
    },

    /// место = значение; — присваивание существующей переменной/полю,
    /// ИЛИ объявление с выводом типа, если это простое новое имя
    /// (см. grammar.md, раздел 4 — различение делает семантический анализ).
    /// Обратите внимание: вывод типа возможен только для варианта
    /// МестоЗаписи::Имя с ещё не объявленным именем — присваивание в поле
    /// (объект.поле = значение;) всегда именно присваивание, никогда
    /// не объявление (у поля тип уже определён структурой).
    Присваивание {
        место: МестоЗаписи,
        значение: Выражение,
    },

    /// выражение, использованное как самостоятельный оператор (например, вызов функции)
    ВыражениеОператор(Выражение),

    Если {
        условие: Выражение,
        тогда: Блок,
        иначе: Option<Блок>,
    },

    ЦиклДляКаждого {
        переменная: String,
        коллекция: Выражение,
        тело: Блок,
    },

    ЦиклПока {
        условие: Выражение,
        тело: Блок,
    },

    Вернуть(Option<Выражение>),

    /// "параллельно { ... }" (детерминировано == false, поведение как
    /// раньше: настоящий поток ОС, порядок побочных эффектов между
    /// несколькими такими потоками НЕ детерминирован — см.
    /// ДОКУМЕНТАЦИЯ_ЯЗЫКА.md, "Детерминированность") или
    /// "параллельно детерминировано { ... }" (детерминировано == true —
    /// поток участвует в глобальной "эстафете": реального параллелизма с
    /// другими "детерминировано"-потоками нет, они по очереди передают
    /// друг другу ход на каждой yield-точке, зато относительный порядок
    /// их видимых эффектов — всегда один и тот же между запусками).
    Параллельно(Блок, bool),

    /// прервать; — немедленный выход из ближайшего охватывающего цикла.
    /// Семантический анализ отвечает за запрет вне цикла (см. semantic.rs).
    Прервать,

    /// продолжить; — переход к следующей итерации ближайшего охватывающего
    /// цикла, минуя остаток тела.
    Продолжить,
}

/// НОВОЕ (номера строк в сообщениях об ошибках семантического анализа):
/// каждый оператор в блоке несёт номер строки, на которой он начинается
/// в исходном тексте — не полноценная система позиций для каждого
/// выражения (это было бы гораздо большей переработкой AST), а более
/// скромный, прагматичный компромисс: точность "на уровне оператора"
/// (строки кода), а не до символа — семантический анализатор отслеживает
/// "текущий оператор" и использует его строку для ЛЮБОЙ ошибки внутри
/// (включая вложенные выражения), даже не зная точной позиции самого
/// выражения.
pub type Блок = Vec<(Оператор, usize)>;

