//! AST — абстрактное синтаксическое дерево.
//! Это структурированное представление программы: не текст, а дерево из
//! узлов, отражающее реальную вложенность и смысл конструкций.
//!
//! Например, код:
//!     целое а = 2 + 3 * 4;
//! превращается не в "текст с плюсом и звёздочкой", а в дерево, где
//! видно, что умножение должно посчитаться раньше сложения — это
//! прямое следствие приоритета операторов (грамматика, раздел 8).

// --- Типы (раздел 3 грамматики) ---

#[derive(Debug, Clone, PartialEq)]
pub enum Тип {
    Целое,
    Целое8,
    Целое16,
    Целое32,
    Целое64,
    Беззнак8,
    Беззнак16,
    Беззнак32,
    Беззнак64,
    Дробное,
    Дробное32,
    Дробное64,
    Текст,
    Верно,

    /// Пользовательский тип — структура, объявленная программистом
    Пользовательский(String),

    /// Обобщённый тип с параметрами: Список<целое>, Словарь<текст, целое>
    Обобщённый {
        имя: String,
        параметры: Vec<Тип>,
    },

    /// Массив: целое[5] (фиксированный) или целое[] (размер по литералу)
    Массив {
        элемент: Box<Тип>,
        размер: Option<i64>,
    },

    /// Опциональный тип: текст?
    Опциональный(Box<Тип>),

    /// результат<тип>
    Результат(Box<Тип>),

    /// НОВОЕ (многопоточность, вторая часть): канал<тип> — простой,
    /// потокобезопасный "почтовый ящик" для одного значения — способ
    /// безопасно передать результат ИЗ блока "параллельно" обратно в
    /// вызвавший его код. См. подробное архитектурное объяснение в
    /// codegen.rs, сгенерировать_параллельно — канал единственный тип,
    /// которому разрешено "пересекать границу" в тело потока, поскольку
    /// он живёт в куче (безопасно копировать указатель), а не на стеке
    /// (в отличие от обычных локальных переменных).
    Канал(Box<Тип>),
}

// --- Выражения (раздел 8 грамматики) ---

#[derive(Debug, Clone, PartialEq)]
pub enum Выражение {
    ЦелоеЛит(i64),
    ДробноеЛит(f64),
    ТекстЛит(String),
    /// Текстовый литерал с интерполяцией: "Привет, $имя!" — состоит из
    /// чередующихся кусков обычного текста и вставленных переменных.
    /// ОГРАНИЧЕНИЕ ЭТОЙ ВЕРСИИ (см. grammar.md, раздел 13 и README):
    /// поддерживается только простая форма $имя (одно имя переменной),
    /// НЕ поддерживается ${выражение} с произвольным выражением внутри —
    /// это осознанное сужение объёма, задокументированный следующий шаг.
    /// Также семантически разрешено использовать этот узел ТОЛЬКО как
    /// прямой единственный аргумент вызова вывести(...) — см. semantic.rs.
    ИнтерполированныйТекст(Vec<ФрагментТекста>),
    ВерноЛит(bool),
    НеуказаноЛит,

    /// Обращение к переменной по имени
    Идентификатор(String),

    /// Массив-литерал: [1, 2, 3]
    МассивЛит(Vec<Выражение>),

    /// Вызов функции: имя(аргументы), возможно с явными типовыми параметрами
    ВызовФункции {
        имя: String,
        типовые_параметры: Vec<Тип>,
        аргументы: Vec<Выражение>,
    },

    /// обращение.к_полю
    ДоступКПолю {
        объект: Box<Выражение>,
        поле: String,
    },

    /// объект.метод(аргументы) — отличается от ДоступКПолю + ВызовФункции тем,
    /// что метод принадлежит конкретной структуре, а не является свободной
    /// функцией с таким именем. "это" внутри метода неявно ссылается на объект.
    ВызовМетода {
        объект: Box<Выражение>,
        метод: String,
        аргументы: Vec<Выражение>,
    },

    /// массив[индекс]
    ДоступПоИндексу {
        массив: Box<Выражение>,
        индекс: Box<Выражение>,
    },

    /// левое ОПЕРАТОР правое
    Бинарное {
        левое: Box<Выражение>,
        оператор: БинарныйОператор,
        правое: Box<Выражение>,
    },

    /// ОПЕРАТОР операнд (унарный минус, логическое "не")
    Унарное {
        оператор: УнарныйОператор,
        операнд: Box<Выражение>,
    },

    /// выражение? — проброс ошибки из результат<тип> (раздел 9)
    Проброс(Box<Выражение>),

    /// успех(выражение) / ошибка(выражение) — конструкторы результат<тип>
    Успех(Box<Выражение>),
    Ошибка(Box<Выражение>),
}

/// Один кусочек интерполированной строки — либо обычный текст "как есть",
/// либо имя переменной, которую нужно подставить на это место.
#[derive(Debug, Clone, PartialEq)]
pub enum ФрагментТекста {
    Текст(String),
    Переменная(String),
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum БинарныйОператор {
    Плюс,
    Минус,
    Умножить,
    Разделить,
    Остаток,
    Равно,
    НеРавно,
    Меньше,
    Больше,
    МеньшеРавно,
    БольшеРавно,
    И,
    Или,
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum УнарныйОператор {
    Минус,
    Не,
}

/// "Место записи" (lvalue) — то, во что можно присвоить значение.
/// Не любое выражение годится слева от "=": нельзя написать "5 = х;".
/// Явное отдельное понятие вместо переиспользования Выражение отражает
/// именно это ограничение прямо в дереве, а не оставляет его неявным
/// правилом, которое пришлось бы проверять постфактум.
#[derive(Debug, Clone, PartialEq)]
pub enum МестоЗаписи {
    /// имя = значение;
    Имя(String),
    /// объект.поле = значение;
    /// объект — тоже МестоЗаписи, а не Выражение: это позволяет естественно
    /// разобрать цепочки вида "а.б.в = значение;" рекурсивно.
    Поле {
        объект: Box<МестоЗаписи>,
        поле: String,
    },
    /// массив[индекс] = значение;
    Индекс {
        массив: Box<МестоЗаписи>,
        индекс: Box<Выражение>,
    },
}

// --- Операторы / statements (раздел 7 грамматики) ---

#[derive(Debug, Clone, PartialEq)]
pub enum Оператор {
    /// тип имя = значение; — объявление с явным типом
    ОбъявлениеСТипом {
        тип: Тип,
        имя: String,
        значение: Выражение,
    },

    /// неизменно тип имя = значение;
    ОбъявлениеНеизменное {
        тип: Тип,
        имя: String,
        значение: Выражение,
    },

    /// место = значение; — присваивание существующей переменной/полю,
    /// ИЛИ объявление с выводом типа, если это простое новое имя
    /// (см. grammar.md, раздел 4 — различение делает семантический анализ).
    /// Обратите внимание: вывод типа возможен только для варианта
    /// МестоЗаписи::Имя с ещё не объявленным именем — присваивание в поле
    /// (объект.поле = значение;) всегда именно присваивание, никогда
    /// не объявление (у поля тип уже определён структурой).
    Присваивание {
        место: МестоЗаписи,
        значение: Выражение,
    },

    /// выражение, использованное как самостоятельный оператор (например, вызов функции)
    ВыражениеОператор(Выражение),

    Если {
        условие: Выражение,
        тогда: Блок,
        иначе: Option<Блок>,
    },

    ЦиклДляКаждого {
        переменная: String,
        коллекция: Выражение,
        тело: Блок,
    },

    ЦиклПока {
        условие: Выражение,
        тело: Блок,
    },

    Вернуть(Option<Выражение>),

    Параллельно(Блок),
}

pub type Блок = Vec<Оператор>;

// --- Верхнеуровневые объявления (раздел 1 грамматики) ---

#[derive(Debug, Clone, PartialEq)]
pub struct Параметр {
    pub тип: Тип,
    pub имя: String,
    pub по_ссылке: bool,
}

#[derive(Debug, Clone, PartialEq)]
pub struct ОбъявлениеФункции {
    pub имя: String,
    /// Видимость метода (публично/приватно) — имеет смысл только когда эта
    /// структура используется как МЕТОД структуры (через методы: в
    /// ОбъявлениеСтруктуры). Для свободных функций верхнего уровня всегда
    /// None (у них пока нет концепции видимости — модульная система,
    /// где это было бы осмысленно, ещё не реализована).
    pub видимость: Option<Видимость>,
    pub обобщённые_параметры: Vec<ОбобщённыйПараметр>,
    pub параметры: Vec<Параметр>,
    pub тип_возврата: Option<Тип>,
    pub тело: Блок,
    /// НОВОЕ: позиция (строка, столбец) начала объявления в исходном
    /// тексте — нужна ТОЛЬКО языковому серверу, для "перейти к определению".
    /// Компилятору для генерации кода эта информация не нужна вообще.
    /// `None` — для СИНТЕТИЧЕСКИ построенных объявлений (например,
    /// мономорфизированные методы обобщённых структур в semantic.rs) —
    /// у них нет одного, единственного "места в файле", это машинно
    /// сгенерированная копия шаблона.
    pub позиция: Option<(usize, usize)>,
}

#[derive(Debug, Clone, PartialEq)]
pub struct ОбобщённыйПараметр {
    pub имя: String, // обычно "тип", но допускаем и другие имена (Ключ, Значение)
    pub ограничения: Vec<String>,
}

#[derive(Debug, Clone, PartialEq)]
pub enum Видимость {
    Публично,
    Приватно,
}

#[derive(Debug, Clone, PartialEq)]
pub struct ПолеСтруктуры {
    pub видимость: Option<Видимость>,
    pub слабая: bool,
    pub тип: Тип,
    pub имя: String,
}

#[derive(Debug, Clone, PartialEq)]
pub struct ОбъявлениеСтруктуры {
    pub имя: String,
    pub обобщённые_параметры: Vec<ОбобщённыйПараметр>,
    pub контракты: Vec<String>,
    pub поля: Vec<ПолеСтруктуры>,
    pub методы: Vec<ОбъявлениеФункции>,
    /// НОВОЕ: та же логика, что и у ОбъявлениеФункции.позиция — только для
    /// языкового сервера, компилятору не нужна.
    pub позиция: Option<(usize, usize)>,
}

#[derive(Debug, Clone, PartialEq)]
pub enum ВерхнийУзел {
    Подключение(String),
    Структура(ОбъявлениеСтруктуры),
    Функция(ОбъявлениеФункции),
    Контракт(ОбъявлениеКонтракта),
    ВнешняяФункция(ОбъявлениеВнешнейФункции),
}

/// "внешняя функция имя(параметры) -> тип;" — объявление привязки к
/// функции из внешней C-библиотеки (FFI, foreign function interface).
/// НЕТ тела — реализация приходит ИЗВНЕ, из библиотеки, слинкованной при
/// сборке программы (см. main.rs, флаг "--линковать"). Это то, что
/// позволяет писать НАСТОЯЩИЕ библиотеки (например, привязки к SDL2 для
/// графики) КАК ОБЫЧНЫЕ .код-файлы, подключаемые через "подключить" —
/// а не вшивать конкретные C-библиотеки прямо в компилятор.
///
/// ⚠️ LLVM-имя такой функции — БУКВАЛЬНОЕ имя (не манглированное, в
/// отличие от обычных функций из подключённых модулей, см. пространства
/// имён v2) — оно должно ТОЧНО совпадать с именем символа в C-библиотеке
/// (например, "SDL_Init"), иначе линковщик не найдёт функцию при сборке.
#[derive(Debug, Clone, PartialEq)]
pub struct ОбъявлениеВнешнейФункции {
    pub имя: String,
    pub параметры: Vec<Параметр>,
    pub тип_возврата: Option<Тип>,
    /// НОВОЕ: "внешняя функция инициализировать(...) -> тип как "SDL_Init";" —
    /// позволяет вызывать функцию ПОЛНОСТЬЮ по-русски ("имя" — то, как её
    /// зовут в коде программиста), сохраняя реальное имя символа
    /// C-библиотеки (нужное линковщику) СПРЯТАННЫМ в этой одной строке.
    /// `None` — без "как ..." — используется буквальное "имя" (текущее,
    /// уже существовавшее поведение, без изменений).
    pub реальное_имя: Option<String>,
}

/// Сигнатура ОДНОГО требуемого метода контракта — БЕЗ тела (контракт
/// только заявляет, что метод с такой сигнатурой должен существовать у
/// реализующей структуры, саму реализацию контракт не содержит).
#[derive(Debug, Clone, PartialEq)]
pub struct СигнатураМетодаКонтракта {
    pub имя: String,
    pub параметры: Vec<Параметр>,
    pub тип_возврата: Option<Тип>,
}

/// "контракт Печатаемый { функция напечатать() -> текст; }" — v1: только
/// проверка на этапе компиляции, что реализующая структура (см.
/// ОбъявлениеСтруктуры.контракты) имеет все требуемые методы с
/// совпадающими сигнатурами. НЕ даёт настоящего полиморфизма (нельзя ещё
/// написать функцию, принимающую "любую структуру, реализующую контракт X"
/// — это потребовало бы динамического диспетчинга, отдельный, более
/// крупный следующий шаг) — см. README.
#[derive(Debug, Clone, PartialEq)]
pub struct ОбъявлениеКонтракта {
    pub имя: String,
    pub методы: Vec<СигнатураМетодаКонтракта>,
}

pub type Программа = Vec<ВерхнийУзел>;
