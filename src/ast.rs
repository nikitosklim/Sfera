/// "внешняя функция имя(параметры) -> тип;" — объявление привязки к
/// функции из внешней C-библиотеки (FFI, foreign function interface).
/// НЕТ тела — реализация приходит ИЗВНЕ, из библиотеки, слинкованной при
/// сборке программы (см. main.rs, флаг "--линковать"). Это то, что
/// позволяет писать НАСТОЯЩИЕ библиотеки (например, привязки к SDL2 для
/// графики) КАК ОБЫЧНЫЕ .код-файлы, подключаемые через "подключить" —
/// а не вшивать конкретные C-библиотеки прямо в компилятор.
///
/// ⚠️ LLVM-имя такой функции — БУКВАЛЬНОЕ имя (не манглированное, в
/// отличие от обычных функций из подключённых модулей, см. пространства
/// имён v2) — оно должно ТОЧНО совпадать с именем символа в C-библиотеке
/// (например, "SDL_Init"), иначе линковщик не найдёт функцию при сборке.
#[derive(Debug, Clone, PartialEq)]
pub struct ОбъявлениеВнешнейФункции {
    pub имя: String,
    pub параметры: Vec<Параметр>,
    pub тип_возврата: Option<Тип>,
    /// НОВОЕ: "внешняя функция инициализировать(...) -> тип как "SDL_Init";" —
    /// позволяет вызывать функцию ПОЛНОСТЬЮ по-русски ("имя" — то, как её
    /// зовут в коде программиста), сохраняя реальное имя символа
    /// C-библиотеки (нужное линковщику) СПРЯТАННЫМ в этой одной строке.
    /// `None` — без "как ..." — используется буквальное "имя" (текущее,
    /// уже существовавшее поведение, без изменений).
    pub реальное_имя: Option<String>,
}

/// Сигнатура ОДНОГО требуемого метода контракта — БЕЗ тела (контракт
