//! Перечисления с данными и оператор «выбрать».
//!
//! Эти конструкции НЕ доходят ни до семантики, ни до кодогенерации: сразу
//! после разбора (и сборки подключённых файлов) их раскрывает функция
//! `раскрыть` в обычные средства языка, которые уже проверены годами:
//!
//!   перечисление Фигура               структура Фигура
//!       круг(дробное радиус);    =>       целое тег;
//!       точка;                            дробное круг_радиус;
//!   конец                             конец
//!                                     функция Фигура__круг(дробное радиус): Фигура …
//!                                     функция Фигура__точка(): Фигура …
//!
//!   Фигура.круг(2.0)            =>    Фигура__круг(2.0)
//!
//!   выбрать ф                         неизменно Фигура __выбор1 = ф;
//!       когда круг(р)         =>      если (__выбор1.тег == 0)
//!           …                             неизменно дробное р = __выбор1.круг_радиус;
//!       иначе                             …
//!           …                         иначе
//!   конец                                 …
//!                                     конец
//!
//! Память и подсчёт ссылок поэтому работают ровно так же, как у обычных
//! структур. Поля незадействованных вариантов заполняются нулями («»
//! для текста), чтобы автоконструктор получил все свои значения.
//!
//! Текстовые данные привязываются КОПИЕЙ («» + поле): иначе имя в ветке
//! указывало бы на буфер внутри структуры, а структура может исчезнуть
//! раньше (например, при `вернуть` из функции).

use crate::ast::*;
use std::collections::HashMap;

const ТЕГ: &str = "тег";

struct Раскрыватель {
    перечисления: HashMap<String, ОбъявлениеПеречисления>,
    /// имя варианта → в каких перечислениях он есть
    варианты: HashMap<String, Vec<String>>,
    счётчик: usize,
    строка: usize,
}

fn имя_поля(вариант: &str, поле: &str) -> String {
    format!("{}_{}", вариант, поле)
}

/// «1 значение», «2 значения», «5 значений».
fn значений(н: usize) -> String {
    let последняя = н % 10;
    let предпоследняя = (н / 10) % 10;
    let слово = if предпоследняя == 1 || последняя == 0 || последняя >= 5 {
        "значений"
    } else if последняя == 1 {
        "значение"
    } else {
        "значения"
    };
    format!("{} {}", н, слово)
}

fn имя_конструктора(перечисление: &str, вариант: &str) -> String {
    format!("{}__{}", перечисление, вариант)
}

fn значение_по_умолчанию(тип: &Тип) -> Option<Выражение> {
    match тип {
        Тип::Целое | Тип::Целое8 | Тип::Целое16 | Тип::Целое32 | Тип::Целое64
        | Тип::Беззнак8 | Тип::Беззнак16 | Тип::Беззнак32 | Тип::Беззнак64 => Some(Выражение::ЦелоеЛит(0)),
        Тип::Дробное | Тип::Дробное32 | Тип::Дробное64 => Some(Выражение::ДробноеЛит(0.0)),
        Тип::Текст => Some(Выражение::ТекстЛит(String::new())),
        Тип::Верно => Some(Выражение::ВерноЛит(false)),
        _ => None,
    }
}

/// Раскрывает перечисления и «выбрать» во всей программе. `модули` —
/// необязательный параллельный список «из какого модуля узел»: для новых
/// узлов он дополняется тем же значением, что у исходного перечисления.
pub fn раскрыть(программа: &mut Программа, модули: Option<&mut Vec<Option<String>>>) -> Result<(), String> {
    let mut перечисления: HashMap<String, ОбъявлениеПеречисления> = HashMap::new();
    let mut варианты: HashMap<String, Vec<String>> = HashMap::new();
    let mut есть = false;
    for узел in программа.iter() {
        if let ВерхнийУзел::Перечисление(п) = узел {
            есть = true;
            if перечисления.contains_key(&п.имя) {
                return Err(ошибка_в(п.позиция.map(|(с, _)| с).unwrap_or(0), &format!("перечисление «{}» объявлено дважды", п.имя)));
            }
            for в in &п.варианты {
                варианты.entry(в.имя.clone()).or_default().push(п.имя.clone());
            }
            перечисления.insert(п.имя.clone(), п.clone());
        }
    }
    // Быстрый выход: в программе нет перечислений, а «выбрать» без них не бывает.
    if !есть {
        if программа_содержит_выбрать(программа) {
            return Err(ошибка_в(0, "оператор «выбрать» работает только с перечислениями, а ни одного «перечисление» в программе нет"));
        }
        return Ok(());
    }

    let мои_модули_пусто = модули.is_none();
    let mut модули = модули;
    let старые: Vec<ВерхнийУзел> = std::mem::take(программа);
    let старые_модули: Vec<Option<String>> = match &модули {
        Some(м) => (**м).clone(),
        None => vec![None; старые.len()],
    };
    let mut новые_модули: Vec<Option<String>> = Vec::new();

    let mut р = Раскрыватель { перечисления, варианты, счётчик: 0, строка: 0 };

    for (i, узел) in старые.into_iter().enumerate() {
        let модуль = старые_модули.get(i).cloned().flatten();
        match узел {
            ВерхнийУзел::Перечисление(п) => {
                for новый in р.развернуть_объявление(&п)? {
                    программа.push(новый);
                    новые_модули.push(модуль.clone());
                }
            }
            ВерхнийУзел::Функция(mut ф) => {
                р.строка = ф.позиция.map(|(с, _)| с).unwrap_or(0);
                р.блок(&mut ф.тело)?;
                программа.push(ВерхнийУзел::Функция(ф));
                новые_модули.push(модуль);
            }
            ВерхнийУзел::Структура(mut с) => {
                for м in с.методы.iter_mut() {
                    р.строка = м.позиция.map(|(с, _)| с).unwrap_or(0);
                    р.блок(&mut м.тело)?;
                }
                программа.push(ВерхнийУзел::Структура(с));
                новые_модули.push(модуль);
            }
            ВерхнийУзел::Глобальная { тип, имя, mut значение, неизменная } => {
                р.выражение(&mut значение)?;
                программа.push(ВерхнийУзел::Глобальная { тип, имя, значение, неизменная });
                новые_модули.push(модуль);
            }
            другой => {
                программа.push(другой);
                новые_модули.push(модуль);
            }
        }
    }
    if let Some(м) = модули.as_mut() {
        **м = новые_модули;
    }
    let _ = мои_модули_пусто;
    Ok(())
}

fn ошибка_в(строка: usize, текст: &str) -> String {
    if строка > 0 {
        format!("Ошибка в перечислении или «выбрать» на строке {}: {}", строка, текст)
    } else {
        format!("Ошибка в перечислении или «выбрать»: {}", текст)
    }
}

fn программа_содержит_выбрать(программа: &Программа) -> bool {
    fn в_блоке(б: &Блок) -> bool {
        б.iter().any(|(о, _)| match о {
            Оператор::Выбрать { .. } => true,
            Оператор::Если { тогда, иначе, .. } => в_блоке(тогда) || иначе.as_ref().map_or(false, в_блоке),
            Оператор::ЦиклДляКаждого { тело, .. } | Оператор::ЦиклПока { тело, .. } => в_блоке(тело),
            Оператор::Параллельно(т, _) => в_блоке(т),
            _ => false,
        })
    }
    программа.iter().any(|у| match у {
        ВерхнийУзел::Функция(ф) => в_блоке(&ф.тело),
        ВерхнийУзел::Структура(с) => с.методы.iter().any(|м| в_блоке(&м.тело)),
        _ => false,
    })
}

impl Раскрыватель {
    fn ошибка(&self, текст: &str) -> String {
        ошибка_в(self.строка, текст)
    }

    /// Структура + по функции-конструктору на каждый вариант.
    fn развернуть_объявление(&mut self, п: &ОбъявлениеПеречисления) -> Result<Vec<ВерхнийУзел>, String> {
        let строка = п.позиция.map(|(с, _)| с).unwrap_or(0);
        let mut поля = vec![ПолеСтруктуры { видимость: None, слабая: false, тип: Тип::Целое, имя: ТЕГ.to_string() }];
        for в in &п.варианты {
            for (тип, имя) in &в.поля {
                if значение_по_умолчанию(тип).is_none() {
                    return Err(ошибка_в(строка, &format!(
                        "данные «{}» варианта «{}»: пока поддерживаются числа, текст и «верно»",
                        имя, в.имя
                    )));
                }
                поля.push(ПолеСтруктуры { видимость: None, слабая: false, тип: тип.clone(), имя: имя_поля(&в.имя, имя) });
            }
        }
        let mut узлы = vec![ВерхнийУзел::Структура(ОбъявлениеСтруктуры {
            имя: п.имя.clone(),
            обобщённые_параметры: Vec::new(),
            контракты: Vec::new(),
            поля,
            методы: Vec::new(),
            позиция: п.позиция,
        })];
        for (номер, в) in п.варианты.iter().enumerate() {
            let mut аргументы = vec![Выражение::ЦелоеЛит(номер as i64)];
            for другой in &п.варианты {
                for (тип, имя) in &другой.поля {
                    if другой.имя == в.имя {
                        аргументы.push(Выражение::Идентификатор(имя.clone()));
                    } else {
                        аргументы.push(значение_по_умолчанию(тип).unwrap());
                    }
                }
            }
            let вызов = Выражение::ВызовФункции { имя: п.имя.clone(), типовые_параметры: Vec::new(), аргументы };
            узлы.push(ВерхнийУзел::Функция(ОбъявлениеФункции {
                имя: имя_конструктора(&п.имя, &в.имя),
                видимость: None,
                обобщённые_параметры: Vec::new(),
                параметры: в.поля.iter().map(|(т, и)| Параметр { тип: т.clone(), имя: и.clone(), по_ссылке: false }).collect(),
                тип_возврата: Some(Тип::Пользовательский(п.имя.clone())),
                тело: vec![(Оператор::Вернуть(Some(вызов)), строка)],
                позиция: п.позиция,
            }));
        }
        Ok(узлы)
    }

    // ---------------------------------------------------------------- операторы

    fn блок(&mut self, б: &mut Блок) -> Result<(), String> {
        let старый: Vec<(Оператор, usize)> = std::mem::take(б);
        for (оператор, строка) in старый {
            self.строка = строка;
            for новый in self.оператор(оператор, строка)? {
                б.push(новый);
            }
        }
        Ok(())
    }

    fn оператор(&mut self, оператор: Оператор, строка: usize) -> Result<Vec<(Оператор, usize)>, String> {
        let mut о = оператор;
        match &mut о {
            Оператор::ОбъявлениеСТипом { значение, .. } | Оператор::ОбъявлениеНеизменное { значение, .. } => {
                self.выражение(значение)?;
            }
            Оператор::Присваивание { место, значение } => {
                self.место(место)?;
                self.выражение(значение)?;
            }
            Оператор::ВыражениеОператор(в) => self.выражение(в)?,
            Оператор::Если { условие, тогда, иначе } => {
                self.выражение(условие)?;
                self.блок(тогда)?;
                if let Some(и) = иначе {
                    self.блок(и)?;
                }
            }
            Оператор::ЦиклДляКаждого { коллекция, тело, .. } => {
                self.выражение(коллекция)?;
                self.блок(тело)?;
            }
            Оператор::ЦиклПока { условие, тело } => {
                self.выражение(условие)?;
                self.блок(тело)?;
            }
            Оператор::Вернуть(в) => {
                if let Some(в) = в {
                    self.выражение(в)?;
                }
            }
            Оператор::Параллельно(тело, _) => self.блок(тело)?,
            Оператор::Прервать | Оператор::Продолжить => {}
            Оператор::Выбрать { .. } => return self.развернуть_выбрать(о, строка),
        }
        Ok(vec![(о, строка)])
    }

    fn место(&mut self, м: &mut МестоЗаписи) -> Result<(), String> {
        match м {
            МестоЗаписи::Имя(_) => Ok(()),
            МестоЗаписи::Поле { объект, .. } => self.место(объект),
            МестоЗаписи::Индекс { массив, индекс } => {
                self.место(массив)?;
                self.выражение(индекс)
            }
        }
    }

    fn развернуть_выбрать(&mut self, о: Оператор, строка: usize) -> Result<Vec<(Оператор, usize)>, String> {
        let (mut значение, ветки, иначе) = match о {
            Оператор::Выбрать { значение, ветки, иначе } => (значение, ветки, иначе),
            _ => unreachable!(),
        };
        self.выражение(&mut значение)?;

        // 1. Какое перечисление разбираем.
        let mut найденное: Option<String> = None;
        for в in &ветки {
            self.строка = в.строка;
            let это = match &в.перечисление {
                Some(п) => {
                    if !self.перечисления.contains_key(п) {
                        return Err(self.ошибка(&format!("перечисления «{}» нет", п)));
                    }
                    п.clone()
                }
                None => {
                    let варианты = self.варианты.get(&в.вариант).cloned().unwrap_or_default();
                    match варианты.len() {
                        0 => return Err(self.ошибка(&format!("варианта «{}» нет ни в одном перечислении", в.вариант))),
                        1 => варианты[0].clone(),
                        _ => {
                            // Если другая ветка уже назвала перечисление — берём его.
                            match &найденное {
                                Some(н) if варианты.contains(н) => н.clone(),
                                _ => return Err(self.ошибка(&format!(
                                    "вариант «{}» есть в нескольких перечислениях ({}): напишите «когда Имя.{}»",
                                    в.вариант, варианты.join(", "), в.вариант
                                ))),
                            }
                        }
                    }
                }
            };
            match &найденное {
                None => найденное = Some(это),
                Some(н) if *н == это => {}
                Some(н) => {
                    return Err(self.ошибка(&format!("ветки разбирают разные перечисления: «{}» и «{}»", н, это)));
                }
            }
        }
        let имя_п = найденное.unwrap();
        let п = self.перечисления.get(&имя_п).unwrap().clone();

        // 2. Проверки веток и полнота.
        let mut разобрано: Vec<usize> = Vec::new();
        for в in &ветки {
            self.строка = в.строка;
            let номер = match п.варианты.iter().position(|х| х.имя == в.вариант) {
                Some(н) => н,
                None => return Err(self.ошибка(&format!("в перечислении «{}» нет варианта «{}»", имя_п, в.вариант))),
            };
            if разобрано.contains(&номер) {
                return Err(self.ошибка(&format!("вариант «{}» разобран дважды", в.вариант)));
            }
            let поля = &п.варианты[номер].поля;
            if !в.привязки.is_empty() && в.привязки.len() != поля.len() {
                return Err(self.ошибка(&format!(
                    "у варианта «{}» {}, а в «когда» названо имён: {}",
                    в.вариант, значений(поля.len()), в.привязки.len()
                )));
            }
            разобрано.push(номер);
        }
        self.строка = строка;
        if иначе.is_none() && разобрано.len() < п.варианты.len() {
            let нет: Vec<&str> = п.варианты.iter().enumerate()
                .filter(|(н, _)| !разобрано.contains(н)).map(|(_, в)| в.имя.as_str()).collect();
            return Err(self.ошибка(&format!(
                "«выбрать» не разбирает: {}. Добавьте ветки «когда» или «иначе»",
                нет.join(", ")
            )));
        }

        // 3. Сборка: временная переменная и цепочка «если».
        self.счётчик += 1;
        let временная = format!("__выбор{}", self.счётчик);
        let объявление = Оператор::ОбъявлениеНеизменное {
            тип: Тип::Пользовательский(имя_п.clone()),
            имя: временная.clone(),
            значение,
        };

        // Каждая ветка превращается в (номер варианта, тело с привязками).
        let mut собранные: Vec<(usize, Блок)> = Vec::new();
        for в in ветки {
            self.строка = в.строка;
            let номер = п.варианты.iter().position(|х| х.имя == в.вариант).unwrap();
            let mut тело = в.тело;
            self.блок(&mut тело)?;
            let mut с_привязками: Блок = Vec::new();
            for (k, имя) in в.привязки.iter().enumerate() {
                if имя == "_" {
                    continue;
                }
                let (тип, поле) = &п.варианты[номер].поля[k];
                let доступ = Выражение::ДоступКПолю {
                    объект: Box::new(Выражение::Идентификатор(временная.clone())),
                    поле: имя_поля(&в.вариант, поле),
                };
                let значение = if *тип == Тип::Текст {
                    // Копия, а не ссылка на буфер внутри структуры.
                    Выражение::Бинарное {
                        левое: Box::new(Выражение::ТекстЛит(String::new())),
                        оператор: БинарныйОператор::Плюс,
                        правое: Box::new(доступ),
                    }
                } else {
                    доступ
                };
                с_привязками.push((Оператор::ОбъявлениеНеизменное { тип: тип.clone(), имя: имя.clone(), значение }, в.строка));
            }
            с_привязками.extend(тело);
            собранные.push((номер, с_привязками));
        }
        let mut хвост: Option<Блок> = match иначе {
            Some(mut и) => {
                self.блок(&mut и)?;
                Some(и)
            }
            None => None,
        };
        // Всё разобрано и «иначе» нет: последняя ветка идёт без проверки
        // (так анализ «функция вернула значение на всех путях» видит конец цепочки).
        if хвост.is_none() {
            if let Some((_, тело)) = собранные.pop() {
                хвост = Some(тело);
            }
        }
        let mut цепочка: Option<Блок> = хвост;
        while let Some((номер, тело)) = собранные.pop() {
            let условие = Выражение::Бинарное {
                левое: Box::new(Выражение::ДоступКПолю {
                    объект: Box::new(Выражение::Идентификатор(временная.clone())),
                    поле: ТЕГ.to_string(),
                }),
                оператор: БинарныйОператор::Равно,
                правое: Box::new(Выражение::ЦелоеЛит(номер as i64)),
            };
            цепочка = Some(vec![(Оператор::Если { условие, тогда: тело, иначе: цепочка }, строка)]);
        }
        let mut результат = vec![(объявление, строка)];
        if let Some(ц) = цепочка {
            результат.extend(ц);
        }
        Ok(результат)
    }

    // -------------------------------------------------------------- выражения

    fn выражение(&mut self, в: &mut Выражение) -> Result<(), String> {
        // Сначала — «Перечисление.вариант(…)» и «Перечисление.вариант».
        let замена: Option<Выражение> = match в {
            Выражение::ВызовМетода { объект, метод, типовые_параметры, аргументы } if типовые_параметры.is_empty() => {
                match &**объект {
                    Выражение::Идентификатор(имя_п) if self.это_вариант(имя_п, метод) => {
                        let п = self.перечисления.get(имя_п).unwrap();
                        let вариант = п.варианты.iter().find(|х| х.имя == *метод).unwrap();
                        if вариант.поля.len() != аргументы.len() {
                            return Err(self.ошибка(&format!(
                                "у варианта «{}.{}» {}, а передано {}",
                                имя_п, метод, значений(вариант.поля.len()), аргументы.len()
                            )));
                        }
                        Some(Выражение::ВызовФункции {
                            имя: имя_конструктора(имя_п, метод),
                            типовые_параметры: Vec::new(),
                            аргументы: std::mem::take(аргументы),
                        })
                    }
                    _ => None,
                }
            }
            Выражение::ДоступКПолю { объект, поле } => match &**объект {
                Выражение::Идентификатор(имя_п) if self.это_вариант(имя_п, поле) => {
                    let п = self.перечисления.get(имя_п).unwrap();
                    let вариант = п.варианты.iter().find(|х| х.имя == *поле).unwrap();
                    if !вариант.поля.is_empty() {
                        return Err(self.ошибка(&format!(
                            "у варианта «{}.{}» есть данные ({}): вызывайте его со скобками",
                            имя_п, поле, значений(вариант.поля.len())
                        )));
                    }
                    Some(Выражение::ВызовФункции {
                        имя: имя_конструктора(имя_п, поле),
                        типовые_параметры: Vec::new(),
                        аргументы: Vec::new(),
                    })
                }
                _ => None,
            },
            _ => None,
        };
        if let Some(з) = замена {
            *в = з;
        }

        match в {
            Выражение::ЦелоеЛит(_) | Выражение::ДробноеЛит(_) | Выражение::ТекстЛит(_)
            | Выражение::ВерноЛит(_) | Выражение::НеуказаноЛит | Выражение::Идентификатор(_) => {}
            Выражение::ИнтерполированныйТекст(куски) => {
                for к in куски.iter_mut() {
                    if let ФрагментТекста::Выражение(е) = к {
                        self.выражение(е)?;
                    }
                }
            }
            Выражение::МассивЛит(э) => {
                for е in э.iter_mut() {
                    self.выражение(е)?;
                }
            }
            Выражение::ВызовФункции { аргументы, .. } => {
                for а in аргументы.iter_mut() {
                    self.выражение(а)?;
                }
            }
            Выражение::ДоступКПолю { объект, .. } => self.выражение(объект)?,
            Выражение::ВызовМетода { объект, аргументы, .. } => {
                self.выражение(объект)?;
                for а in аргументы.iter_mut() {
                    self.выражение(а)?;
                }
            }
            Выражение::ДоступПоИндексу { массив, индекс } => {
                self.выражение(массив)?;
                self.выражение(индекс)?;
            }
            Выражение::Бинарное { левое, правое, .. } => {
                self.выражение(левое)?;
                self.выражение(правое)?;
            }
            Выражение::Унарное { операнд, .. } => self.выражение(операнд)?,
            Выражение::Проброс(е) | Выражение::Успех(е) | Выражение::Ошибка(е) => self.выражение(е)?,
        }
        Ok(())
    }

    fn это_вариант(&self, имя_п: &str, вариант: &str) -> bool {
        self.перечисления.get(имя_п).map_or(false, |п| п.варианты.iter().any(|в| в.имя == вариант))
    }
}
