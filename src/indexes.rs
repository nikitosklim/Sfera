//! Проход после парсера: отличает индексацию "числа(0)" от вызова.
//!
//! В русской раскладке нет квадратных скобок удобно под рукой, поэтому
//! элемент массива можно писать как "числа(0)". Парсер сам не знает, что
//! стоит перед скобками — функция или переменная, поэтому сначала читает
//! это как вызов. Здесь, когда все объявления известны, мы решаем:
//!   * "имя(арг)" — индексация, если "имя" — локальная переменная/параметр
//!     (локальное имя побеждает одноимённую функцию);
//!   * "объект.имя(арг)" — индексация поля-массива, если "имя" — поле
//!     какой-то структуры и НЕ объявленный метод;
//!   * "выражение(арг)" (парсер пометил пустым именем метода) — всегда
//!     индексация.

use crate::ast::*;
use std::collections::HashSet;

struct Контекст {
    поля: HashSet<String>,
    методы: HashSet<String>,
    локальные: HashSet<String>,
}

pub fn развернуть_индексы(узлы: &mut Vec<ВерхнийУзел>) {
    let mut поля = HashSet::new();
    let mut методы = HashSet::new();
    for узел in узлы.iter() {
        match узел {
            ВерхнийУзел::Структура(с) => {
                for п in &с.поля {
                    поля.insert(п.имя.clone());
                }
                for м in &с.методы {
                    методы.insert(м.имя.clone());
                }
            }
            ВерхнийУзел::Контракт(к) => {
                for м in &к.методы {
                    методы.insert(м.имя.clone());
                }
            }
            _ => {}
        }
    }
    let mut к = Контекст { поля, методы, локальные: HashSet::new() };
    for узел in узлы.iter_mut() {
        match узел {
            ВерхнийУзел::Функция(ф) => функция(&mut к, ф),
            ВерхнийУзел::Структура(с) => {
                for м in &mut с.методы {
                    функция(&mut к, м);
                }
            }
            _ => {}
        }
    }
}

fn функция(к: &mut Контекст, ф: &mut ОбъявлениеФункции) {
    к.локальные.clear();
    for п in &ф.параметры {
        к.локальные.insert(п.имя.clone());
    }
    собрать_имена(&ф.тело, &mut к.локальные);
    блок(к, &mut ф.тело);
}

fn собрать_имена(б: &Блок, имена: &mut HashSet<String>) {
    for (о, _) in б {
        match о {
            Оператор::ОбъявлениеСТипом { имя, .. } | Оператор::ОбъявлениеНеизменное { имя, .. } => {
                имена.insert(имя.clone());
            }
            Оператор::Если { тогда, иначе, .. } => {
                собрать_имена(тогда, имена);
                if let Some(и) = иначе {
                    собрать_имена(и, имена);
                }
            }
            Оператор::ЦиклДляКаждого { переменная, тело, .. } => {
                имена.insert(переменная.clone());
                собрать_имена(тело, имена);
            }
            Оператор::ЦиклПока { тело, .. } => собрать_имена(тело, имена),
            Оператор::Параллельно(тело, _) => собрать_имена(тело, имена),
            _ => {}
        }
    }
}

fn блок(к: &Контекст, б: &mut Блок) {
    for (о, _) in б.iter_mut() {
        оператор(к, о);
    }
}

fn оператор(к: &Контекст, о: &mut Оператор) {
    match о {
        Оператор::ОбъявлениеСТипом { значение, .. } | Оператор::ОбъявлениеНеизменное { значение, .. } => {
            выражение(к, значение)
        }
        Оператор::Присваивание { место, значение } => {
            место_записи(к, место);
            выражение(к, значение);
        }
        Оператор::ВыражениеОператор(в) => выражение(к, в),
        Оператор::Если { условие, тогда, иначе } => {
            выражение(к, условие);
            блок(к, тогда);
            if let Some(и) = иначе {
                блок(к, и);
            }
        }
        Оператор::ЦиклДляКаждого { коллекция, тело, .. } => {
            выражение(к, коллекция);
            блок(к, тело);
        }
        Оператор::ЦиклПока { условие, тело } => {
            выражение(к, условие);
            блок(к, тело);
        }
        Оператор::Вернуть(Some(в)) => выражение(к, в),
        Оператор::Параллельно(тело, _) => блок(к, тело),
        _ => {}
    }
}

fn место_записи(к: &Контекст, м: &mut МестоЗаписи) {
    match м {
        МестоЗаписи::Имя(_) => {}
        МестоЗаписи::Поле { объект, .. } => место_записи(к, объект),
        МестоЗаписи::Индекс { массив, индекс } => {
            место_записи(к, массив);
            выражение(к, индекс);
        }
    }
}

fn выражение(к: &Контекст, в: &mut Выражение) {
    // сначала — вложенные части
    match в {
        Выражение::ИнтерполированныйТекст(ф) => {
            for фр in ф.iter_mut() {
                if let ФрагментТекста::Выражение(е) = фр {
                    выражение(к, е);
                }
            }
        }
        Выражение::МассивЛит(э) => э.iter_mut().for_each(|е| выражение(к, е)),
        Выражение::ВызовФункции { аргументы, .. } => аргументы.iter_mut().for_each(|е| выражение(к, е)),
        Выражение::ДоступКПолю { объект, .. } => выражение(к, объект),
        Выражение::ВызовМетода { объект, аргументы, .. } => {
            выражение(к, объект);
            аргументы.iter_mut().for_each(|е| выражение(к, е));
        }
        Выражение::ДоступПоИндексу { массив, индекс } => {
            выражение(к, массив);
            выражение(к, индекс);
        }
        Выражение::Бинарное { левое, правое, .. } => {
            выражение(к, левое);
            выражение(к, правое);
        }
        Выражение::Унарное { операнд, .. } => выражение(к, операнд),
        Выражение::Проброс(е) | Выражение::Успех(е) | Выражение::Ошибка(е) => выражение(к, е),
        _ => {}
    }

    // затем — решение для самого узла
    let замена = match в {
        // НОВОЕ: "массив(1, 2, 3)" — литерал массива (если "массив" — не
        // локальная переменная, которую индексируют).
        Выражение::ВызовФункции { имя, типовые_параметры, аргументы }
            if имя == "массив" && типовые_параметры.is_empty() && !к.локальные.contains("массив") =>
        {
            Some(Выражение::МассивЛит(std::mem::take(аргументы)))
        }
        Выражение::ВызовФункции { имя, типовые_параметры, аргументы }
            if типовые_параметры.is_empty() && аргументы.len() == 1 && к.локальные.contains(имя.as_str()) =>
        {
            Some(Выражение::ДоступПоИндексу {
                массив: Box::new(Выражение::Идентификатор(имя.clone())),
                индекс: Box::new(аргументы.remove(0)),
            })
        }
        Выражение::ВызовМетода { объект, метод, типовые_параметры, аргументы }
            if типовые_параметры.is_empty()
                && аргументы.len() == 1
                && (метод.is_empty() || (к.поля.contains(метод.as_str()) && !к.методы.contains(метод.as_str()))) =>
        {
            let основа = if метод.is_empty() {
                std::mem::replace(объект.as_mut(), Выражение::НеуказаноЛит)
            } else {
                Выражение::ДоступКПолю {
                    объект: Box::new(std::mem::replace(объект.as_mut(), Выражение::НеуказаноЛит)),
                    поле: метод.clone(),
                }
            };
            Some(Выражение::ДоступПоИндексу {
                массив: Box::new(основа),
                индекс: Box::new(аргументы.remove(0)),
            })
        }
        _ => None,
    };
    if let Some(з) = замена {
        *в = з;
    }
}
