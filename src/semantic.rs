/// НОВОЕ (подсказки по опечаткам): классическое расстояние Левенштейна —
/// минимальное число вставок/удалений/замен одного символа, чтобы
/// превратить одну строку в другую. Считает ПО СИМВОЛАМ (chars), не
/// байтам — язык "Сфера" полностью кириллический, а в UTF-8 кириллица
/// занимает 2 байта на символ, побайтовое расстояние давало бы неверные,
/// завышенные числа для кириллических имён.
fn расстояние_левенштейна(а: &str, б: &str) -> usize {
    let а: Vec<char> = а.chars().collect();
    let б: Vec<char> = б.chars().collect();
    let (n, m) = (а.len(), б.len());

    let mut текущая_строка: Vec<usize> = (0..=m).collect();
    for i in 1..=n {
        let предыдущая_строка = текущая_строка.clone();
        текущая_строка[0] = i;
        for j in 1..=m {
            let стоимость_замены = if а[i - 1] == б[j - 1] { 0 } else { 1 };
            текущая_строка[j] = (предыдущая_строка[j] + 1)
                .min(текущая_строка[j - 1] + 1)
                .min(предыдущая_строка[j - 1] + стоимость_замены);
        }
    }
    текущая_строка[m]
}

/// НОВОЕ (подсказки по опечаткам): ищет среди кандидатов имя, ближайшее
/// к введённому (по расстоянию Левенштейна) — с разумным порогом, чтобы
/// не предлагать совершенно непохожие имена как "похожие" (например,
/// однобуквенную переменную "х" при опечатке в длинном имени функции).
/// Порог — не более трети длины введённого имени (минимум 1, максимум 3)
/// — небольшая, но реальная опечатка (переставленная/пропущенная буква)
/// пройдёт, случайное совпадение с чем-то отдалённым — нет.
fn найти_похожее_имя<'a>(введённое: &str, кандидаты: impl Iterator<Item = &'a String>) -> Option<&'a str> {
    let длина_введённого = введённое.chars().count();
    if длина_введённого == 0 {
        return None;
    }
    let порог = (длина_введённого / 3).clamp(1, 3);

    кандидаты
        .filter(|кандидат| кандидат.as_str() != введённое)
        .map(|кандидат| (кандидат, расстояние_левенштейна(введённое, кандидат)))
        .filter(|(_, расстояние)| *расстояние <= порог)
        .min_by_key(|(_, расстояние)| *расстояние)
        .map(|(кандидат, _)| кандидат.as_str())
}

/// НОВОЕ (подсказки по опечаткам): единообразная приписка "(может, вы
/// имели в виду 'X'?)" к сообщению об ошибке — либо пустая строка, если
/// похожего имени не нашлось.
fn подсказка_похожего_имени(введённое: &str, кандидаты: impl Iterator<Item = impl AsRef<str>>) -> String {
    let кандидаты: Vec<String> = кандидаты.map(|к| к.as_ref().to_string()).collect();
    match найти_похожее_имя(введённое, кандидаты.iter()) {
        Some(похожее) => format!(" (может, вы имели в виду '{}'?)", похожее),
        None => String::new(),
    }
}

