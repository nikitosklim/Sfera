//! Семантический анализ — этап между парсером и кодогенерацией.
//! Парсер проверяет только СИНТАКСИС (правильно ли расставлены скобки,
//! ключевые слова и т.д.) — он ничего не знает о смысле программы.
//! Семантический анализ проверяет СМЫСЛ: существует ли переменная,
//! к которой обращаются; совпадают ли типы в операции; не пытаются ли
//! изменить то, что помечено как "неизменно".
//!
//! Ключевая задача этой версии — разрешить неоднозначность из грамматики
//! (раздел 4): "имя = значение;" без явного типа — это ОБЪЯВЛЕНИЕ
//! (если имя встречается впервые) или ПРИСВАИВАНИЕ (если имя уже известно)?
//! Парсер не может это решить сам, потому что для этого нужно "помнить",
//! какие имена уже были объявлены раньше по ходу кода — а это уже вопрос
//! смысла программы, не только её формы.
//!
//! Результат работы анализатора — не новое дерево, а "обогащённая"
//! информация поверх существующего AST: для каждого узла Присваивание
//! мы определяем, что это на самом деле, и какой у переменной тип.
//! Дальше кодогенератор сможет использовать эту информацию, вместо того
//! чтобы просто отказываться от таких узлов.

use std::collections::HashMap;

use crate::ast::*;

#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum РешённыйТип {
    Целое,
    Целое8,
    Целое16,
    Целое32,
    Целое64,
    Беззнак8,
    Беззнак16,
    Беззнак32,
    Беззнак64,
    Дробное,
    Дробное32,
    Дробное64,
    Текст,
    Верно,
    /// Пользовательский тип — структура, по имени. Само определение
    /// структуры (список полей и их типов) хранится отдельно, в таблице
    /// структур анализатора (см. СемантическийАнализатор::структуры).
    Структура(String),
    /// Массив фиксированного размера: тип[N]. Размер — часть типа (как в C),
    /// а не отдельное runtime-значение — соответствует нашему решению
    /// "массив — примитив языка, а не структура из стандартной библиотеки"
    /// (см. grammar.md, раздел про массивы/коллекции).
    Массив {
        элемент: Box<РешённыйТип>,
        размер: usize,
    },
    /// результат<тип> — модель ошибок в духе Rust (grammar.md, раздел 9).
    /// Тип ошибки у нас всегда неявно "текст" (сообщение об ошибке) — мы не
    /// параметризуем тип ошибки отдельно, в отличие от Rust'овского
    /// Result<T, E> с двумя параметрами. Это сознательное упрощение.
    Результат(Box<РешённыйТип>),
    /// Список<тип> — встроенный обобщённый тип (не пользовательская структура,
    /// не общий механизм generics для произвольных структур — см. подробное
    /// обсуждение архитектурного решения перед реализацией этой фичи).
    /// Растущий список элементов одного типа, живёт в куче, управляется ARC
    /// так же, как обычные структуры.
    Список(Box<РешённыйТип>),
    /// Словарь<Ключ, Значение> — как и Список<тип>, встроенный в компилятор тип, не общий
    /// механизм generics. Реализован как список пар ключ-значение с линейным
    /// поиском (не настоящая хеш-таблица) — переиспользует архитектуру
    /// Список<тип>. Сознательное ограничение этой версии: только целочисленные
    /// ключи (сравнение текста в кодогенераторе ещё не реализовано).
    Словарь(Box<РешённыйТип>, Box<РешённыйТип>),
    /// НОВОЕ (многопоточность, вторая часть): канал<тип> — простой,
    /// потокобезопасный "почтовый ящик" для одного значения. См. подробное
    /// объяснение в ast.rs и codegen.rs (сгенерировать_параллельно).
    Канал(Box<РешённыйТип>),
    /// НОВОЕ (настоящий полиморфизм через контракты): переменная типа
    /// "контракт" — может хранить ЛЮБУЮ структуру, реализующую этот
    /// контракт, известную только в рантайме (не на этапе компиляции).
    /// В памяти представлена "толстым указателем" — парой (указатель на
    /// данные структуры, указатель на vtable для конкретной пары
    /// структура+контракт) — см. подробное объяснение в codegen.rs.
    Контракт(String),
    /// Тип пока не удалось однозначно определить (нужна дальнейшая работа
    /// анализатора — например, вызовы пользовательских функций с обобщёнными
    /// типами). Помечаем явно вместо того, чтобы гадать.
    Неизвестен,
}

impl From<&Тип> for РешённыйТип {
    fn from(тип: &Тип) -> Self {
        match тип {
            Тип::Целое => РешённыйТип::Целое,
            Тип::Целое8 => РешённыйТип::Целое8,
            Тип::Целое16 => РешённыйТип::Целое16,
            Тип::Целое32 => РешённыйТип::Целое32,
            Тип::Целое64 => РешённыйТип::Целое64,
            Тип::Беззнак8 => РешённыйТип::Беззнак8,
            Тип::Беззнак16 => РешённыйТип::Беззнак16,
            Тип::Беззнак32 => РешённыйТип::Беззнак32,
            Тип::Беззнак64 => РешённыйТип::Беззнак64,
            Тип::Дробное => РешённыйТип::Дробное,
            Тип::Дробное32 => РешённыйТип::Дробное32,
            Тип::Дробное64 => РешённыйТип::Дробное64,
            Тип::Текст => РешённыйТип::Текст,
            Тип::Верно => РешённыйТип::Верно,
            Тип::Пользовательский(имя) => РешённыйТип::Структура(имя.clone()),
            Тип::Массив { элемент, размер: Some(n) } => РешённыйТип::Массив {
                элемент: Box::new(РешённыйТип::from(элемент.as_ref())),
                размер: *n as usize,
            },
            Тип::Результат(внутренний) => РешённыйТип::Результат(Box::new(РешённыйТип::from(внутренний.as_ref()))),
            Тип::Канал(внутренний) => РешённыйТип::Канал(Box::new(РешённыйТип::from(внутренний.as_ref()))),
            Тип::Обобщённый { имя, параметры } if имя == "Список" && параметры.len() == 1 => {
                РешённыйТип::Список(Box::new(РешённыйТип::from(&параметры[0])))
            }
            Тип::Обобщённый { имя, параметры } if имя == "Словарь" && параметры.len() == 2 => {
                РешённыйТип::Словарь(
                    Box::new(РешённыйТип::from(&параметры[0])),
                    Box::new(РешённыйТип::from(&параметры[1])),
                )
            }
            // НОВОЕ: пользовательская обобщённая структура с явным типом
            // слева (Коробка<целое> коробка = ...;) — честно
            // задокументированное ограничение снято (ДОКУМЕНТАЦИЯ_ЯЗЫКА.md).
            // Раньше любое имя, кроме встроенных Список/Словарь, попадало
            // в заглушку "_ => Неизвестен" ниже — явный тип никогда не
            // совпадал с тем, что реально возвращал конструктор
            // (Структура("Коробка__целое")). Используем ту же функцию
            // мангл-имени, что и сам конструктор — гарантирует совпадение.
            // Ограничение ровно то же, что и у конструктора — один
            // типовый параметр (манглированное_имя принимает только один).
            Тип::Обобщённый { имя, параметры } if параметры.len() == 1 => {
                let конкретный_тип = РешённыйТип::from(&параметры[0]);
                РешённыйТип::Структура(манглированное_имя(имя, &конкретный_тип))
            }
            // Тип::Массив { размер: None, .. } ("целое[]" без явного числа) —
            // размер не известен из одного только текста типа, его нужно
            // вывести из литерала-инициализатора. Это делает отдельная
            // логика в решить_тип_объявления, а не эта функция (она
            // работает только с самим типом, без доступа к выражению).
            _ => РешённыйТип::Неизвестен,
        }
    }
}

/// То, во что превращается неоднозначный узел Оператор::Присваивание
/// после семантического анализа — теперь мы точно знаем, что это такое.
#[derive(Debug, Clone)]
pub enum РазрешённоеПрисваивание {
    /// Оказалось объявлением новой переменной — компилятор сам вывел тип
    НовоеОбъявление { тип: РешённыйТип },
    /// Оказалось присваиванием существующей переменной
    Присваивание,
}

/// Информация об одной переменной в области видимости.
#[derive(Debug, Clone)]
struct ИнформацияОПеременной {
    тип: РешённыйТип,
    неизменна: bool,
}

/// Область видимости — таблица имён, известных в данном блоке кода.
/// Реализована как стек областей: при входе в новый блок ({}) добавляем
/// новый уровень, при выходе — убираем. Поиск имени идёт от внутреннего
/// уровня к внешним (как и полагается вложенным блокам в C-подобных языках).
struct СтекОбластей {
    уровни: Vec<HashMap<String, ИнформацияОПеременной>>,
}

impl СтекОбластей {
    fn новый() -> Self {
        СтекОбластей { уровни: vec![HashMap::new()] }
    }

    fn войти_в_блок(&mut self) {
        self.уровни.push(HashMap::new());
    }

    fn выйти_из_блока(&mut self) {
        self.уровни.pop();
    }

    fn объявить(&mut self, имя: &str, тип: РешённыйТип, неизменна: bool) {
        // Объявляем всегда в САМОМ ВНУТРЕННЕМ текущем уровне —
        // это соответствует обычной, ожидаемой семантике блоков видимости.
        self.уровни
            .last_mut()
            .expect("стек областей видимости не может быть пустым")
            .insert(имя.to_string(), ИнформацияОПеременной { тип, неизменна });
    }

    /// Ищет имя, начиная с самого внутреннего уровня и двигаясь наружу.
    fn найти(&self, имя: &str) -> Option<&ИнформацияОПеременной> {
        for уровень in self.уровни.iter().rev() {
            if let Some(инфо) = уровень.get(имя) {
                return Some(инфо);
            }
        }
        None
    }

    /// Проверяет, объявлено ли имя именно в ТЕКУЩЕМ (самом внутреннем) уровне.
    /// Отличается от найти() тем, что не заглядывает в объемлющие блоки —
    /// нужно для правила "тип имя = значение;" при уже существующем имени
    /// В ТОМ ЖЕ блоке — это ошибка повторного объявления (см. grammar.md,
    /// раздел 4), а не переменная, которая просто видна и снаружи.
    fn объявлено_в_текущем_блоке(&self, имя: &str) -> bool {
        self.уровни
            .last()
            .map(|уровень| уровень.contains_key(имя))
            .unwrap_or(false)
    }

    /// НОВОЕ (подсказки по опечаткам): все имена, видимые прямо сейчас —
    /// из всех уровней стека, а не только самого внутреннего — нужно для
    /// "может, вы имели в виду...?" при "переменная не объявлена".
    fn все_видимые_имена(&self) -> Vec<&String> {
        self.уровни.iter().flat_map(|уровень| уровень.keys()).collect()
    }
}

pub struct СемантическийАнализатор {
    области: СтекОбластей,
    /// Результаты разрешения неоднозначных узлов Присваивание, по порядку
    /// их обнаружения при обходе дерева. Кодогенератор будет брать решения
    /// отсюда по мере того, как сам проходит то же дерево в том же порядке.
    решения_присваиваний: Vec<РазрешённоеПрисваивание>,
    /// Известные сигнатуры функций (имя -> (типы параметров, тип
    /// возврата)), чтобы можно было определить тип результата вызова
    /// функции при выводе типа. НОВОЕ (проверка аргументов при вызове):
    /// раньше здесь хранился только тип возврата — компилятор физически
    /// не мог проверить ни количество, ни типы аргументов вызова
    /// пользовательской функции (встроенные функции стандартной
    /// библиотеки такую проверку УЖЕ делали явно, вручную, для каждой —
    /// но не обычные, пользовательские). Найдено реальной проверкой:
    /// "сложить(целое, целое)" вызванная как "сложить(5)" (одним
    /// аргументом) компилировалась и запускалась без единой ошибки —
    /// второй параметр читал неопределённое значение из памяти/регистра
    /// (undefined behavior), тихо, без диагностики.
    функции: HashMap<String, (Vec<РешённыйТип>, Option<РешённыйТип>)>,
    /// Известные структуры: имя -> список (имя_поля, тип), В ПОРЯДКЕ
    /// ОБЪЯВЛЕНИЯ. Порядок важен — это буквально порядок полей в памяти,
    /// и порядок аргументов автоконструктора (см. grammar.md, раздел 5
    /// и наше решение "конструктор по умолчанию из полей по порядку").
    структуры: HashMap<String, Vec<(String, РешённыйТип)>>,
    /// НОВОЕ (настоящий полиморфизм через контракты): имя структуры ->
    /// список имён контрактов, которые она заявляет реализующими (см.
    /// ast::ОбъявлениеСтруктуры.контракты) — нужно, чтобы при объявлении
    /// "ИмяКонтракта переменная = экземпляр_структуры;" проверить, что
    /// эта КОНКРЕТНАЯ структура реально заявлена реализующей именно этот
    /// контракт (простого совпадения методов недостаточно — нужна явная,
    /// осознанная декларация "структура X : Контракт").
    структуры_контракты: HashMap<String, Vec<String>>,
    /// Видимость каждого поля: (имя_структуры, имя_поля) -> Видимость.
    /// ОТДЕЛЬНАЯ таблица, а не расширение self.структуры — потому что
    /// self.структуры() отдаётся наружу публичным геттером и используется
    /// кодогенератором (codegen.rs) в уже устоявшемся формате; заводить
    /// здесь отдельную таблицу безопаснее, чем менять формат существующей
    /// и рисковать сломать код, который его не касается.
    видимость_полей: HashMap<(String, String), Видимость>,
    /// НОВОЕ: "(имя_структуры, имя_поля)" для полей, объявленных с
    /// модификатором "слабая" — см. подробное объяснение у места сбора
    /// этой карты (регистрация структур).
    слабые_поля: std::collections::HashSet<(String, String)>,
    /// Известные методы структур: (имя_структуры, имя_метода) -> сигнатура
    /// (типы параметров БЕЗ "это" + тип возврата + видимость). Отдельная
    /// таблица от "функции", потому что методы принадлежат конкретной
    /// структуре — один и тот же метод-имя может существовать у разных
    /// структур одновременно без конфликта (в отличие от свободных функций).
    методы_структур: HashMap<(String, String), (Vec<РешённыйТип>, Option<РешённыйТип>, Option<Видимость>)>,
    /// Тип возврата функции/метода, чьё тело сейчас проверяется — нужен,
    /// чтобы проверить "вернуть выражение;" на совпадение с объявленным
    /// типом, а также чтобы "?" (Проброс) знал, во что он "разворачивается"
    /// и что текущая функция вообще способна досрочно вернуть ошибку
    /// (то есть сама объявлена как результат<тип>).
    текущий_тип_возврата: Option<РешённыйТип>,
    /// Имя структуры, ЧЕЙ метод сейчас проверяется (None — если сейчас
    /// проверяется свободная функция, не метод). Нужно, чтобы проверить
    /// доступ к приватным полям/методам: "изнутри метода структуры X можно
    /// трогать приватные поля структуры X, но не структуры Y".
    текущая_структура_метода: Option<String>,
    /// Множество всех конкретных типов элементов, для которых в программе
    /// хоть раз был создан Список<тип> (например, Список<целое>() где-то в коде
    /// добавляет РешённыйТип::Целое сюда). Нужно кодогенератору, чтобы ЗАРАНЕЕ,
    /// одним проходом до генерации тел функций, синтезировать LLVM-структуру
    /// для каждой использованной инстанциации — по той же схеме, что и для
    /// обычных пользовательских структур (см. codegen.rs, зарегистрировать_структуры).
    используемые_списки: std::collections::HashSet<РешённыйТип>,
    /// То же самое, но для Словарь<Ключ, Значение> — множество пар (тип_ключа, тип_значения).
    используемые_словари: std::collections::HashSet<(РешённыйТип, РешённыйТип)>,
    /// НОВОЕ: шаблоны ПОЛЬЗОВАТЕЛЬСКИХ обобщённых структур (не встроенных
    /// Список/Словарь) — "структура Коробка<тип> { ... }" хранится здесь
    /// КАК ЕСТЬ (AST, с "тип" как placeholder), а не в обычной self.структуры
    /// (та ожидает уже вычисленные, конкретные РешённыйТип для полей).
    ///
    /// ⚠️ ОГРАНИЧЕНИЕ v1: только ОДИН параметр типа на структуру
    /// (аналогично тому, как Список<тип> — один параметр). Несколько
    /// параметров (как у встроенного Словарь<Ключ, Значение>) для
    /// ПОЛЬЗОВАТЕЛЬСКИХ обобщённых структур пока не поддержаны —
    /// осознанное сужение объёма первой версии, не забытый случай.
    обобщённые_структуры: HashMap<String, ОбъявлениеСтруктуры>,
    /// Уже выполненные инстанциации: (имя_шаблона, конкретный_тип) ->
    /// манглированное имя (например, ("Коробка", Целое) -> "Коробка__целое").
    /// Идемпотентность: одна и та же инстанциация, встреченная несколько
    /// раз в программе, регистрируется только один раз — эта таблица и
    /// есть механизм проверки "уже было или нет".
    инстанциации_обобщённых_структур: HashMap<(String, РешённыйТип), String>,
    /// Полностью мономорфизированные структуры (манглированное имя, уже
    /// подставленные методы С ТЕЛАМИ) — нужны КОДОГЕНЕРАТОРУ, чтобы
    /// реально сгенерировать LLVM-код методов каждой инстанциации.
    /// ⚠️ Поле "поля" здесь НЕ подставлено (остаётся как в шаблоне,
    /// placeholder-типы) — это не проблема: кодогенератор берёт ТИПЫ полей
    /// из self.структуры (уже корректно подставленной RешённыйТип-таблицы),
    /// не из этой AST-копии. Единственное, для чего кодогенератору реально
    /// нужна эта структура — её МЕТОДЫ (тип структуры для методов берётся
    /// из ключа HashMap — манглированного имени, — не из поля "имя" внутри).
    инстанциированные_обобщённые_структуры: HashMap<String, ОбъявлениеСтруктуры>,
    /// ⚠️ НАЙДЕННЫЙ ПРИ РЕАЛЬНОМ ТЕСТИРОВАНИИ АРХИТЕКТУРНЫЙ БАГ: решения
    /// присваиваний (self.решения_присваиваний) — ОБЩИЙ, РАЗДЕЛЯЕМЫЙ список,
    /// который кодогенератор читает СТРОГО ПО ПОРЯДКУ, СООТВЕТСТВУЮЩЕМУ
    /// порядку, в котором ОН САМ встречает операторы присваивания при
    /// генерации кода. Но гарантировать_инстанциацию_обобщённой_структуры()
    /// вызывается как ПОБОЧНЫЙ ЭФФЕКТ внутри тип_выражения() — то есть
    /// МОЖЕТ произойти "внутри" проверки СОВЕРШЕННО ДРУГОГО оператора
    /// (например, "коробка = Коробка<целое>(42);") — а ВНУТРИ САМОЙ
    /// инстанциации мы проверяем ТЕЛА МЕТОДОВ (проверить_метод), которые
    /// МОГУТ содержать СВОИ собственные присваивания — они добавлялись бы
    /// в ОБЩИЙ список РАНЬШЕ решения для "коробка = ...", хотя кодогенератор
    /// встретит "коробка = ..." РАНЬШЕ (методы генерируются ОТДЕЛЬНЫМ,
    /// ПОСЛЕДУЮЩИМ проходом) — рассинхронизация порядка, ведущая к тому,
    /// что кодогенератор получает "решение" для СОВСЕМ ДРУГОГО присваивания.
    ///
    /// Решение — ИЗОЛИРОВАТЬ решения присваиваний КАЖДОЙ инстанциации в
    /// ОТДЕЛЬНЫЙ список (манглированное имя -> её собственные решения, по
    /// порядку её методов) — не смешивая с общим потоком программы.
    решения_присваиваний_обобщённых_структур: HashMap<String, Vec<РазрешённоеПрисваивание>>,
    /// НОВОЕ: та же самая мономорфизация, что уже реализована для
    /// обобщённых структур выше (ровно та же архитектура, до буквального
    /// повторения комментариев — см. подробности там), только для
    /// СВОБОДНЫХ ФУНКЦИЙ. v1, честно узкий объём: только функции ГЛАВНОГО
    /// файла (не из подключённых модулей — квалифицированный вызов вида
    /// "модуль.обобщённая<тип>(...)" не поддержан), только ОДИН обобщённый
    /// параметр, только явное указание типа в вызове ("имя<тип>(...)") —
    /// вывод типа из аргументов без явного указания не реализован (это
    /// потребовало бы знать выведенный семантикой тип уже В кодогенераторе,
    /// у которого пока нет для этого отдельного канала передачи данных,
    /// в отличие от типовых_параметров, уже присутствующих в AST от парсера
    /// напрямую при явном указании).
    обобщённые_функции: HashMap<String, ОбъявлениеФункции>,
    /// Тот же кэш идемпотентности, что и для структур: (имя_шаблона,
    /// конкретный_тип) -> манглированное имя.
    инстанциации_обобщённых_функций: HashMap<(String, РешённыйТип), String>,
    /// Полностью мономорфизированные функции (манглированное имя, уже
    /// подставленные параметры/возврат/тело) — нужны кодогенератору для
    /// реальной генерации LLVM-кода каждой инстанциации.
    инстанциированные_обобщённые_функции: HashMap<String, ОбъявлениеФункции>,
    /// Та же самая изоляция решений присваиваний, что и у методов
    /// обобщённых структур — см. подробное объяснение найденного бага
    /// у решения_присваиваний_обобщённых_структур выше.
    решения_присваиваний_обобщённых_функций: HashMap<String, Vec<РазрешённоеПрисваивание>>,
    /// НОВОЕ (первый шаг к настоящим пространствам имён): "имя модуля"
    /// (имя подключённого файла без ".код") -> множество имён функций/структур,
    /// объявленных ИМЕННО в этом модуле — собирается в main.rs (при разборе
    /// "подключить"), передаётся сюда как параметр проверить_программу.
    /// Используется, чтобы распознать "модуль.имя(...)" как квалифицированный
    /// вызов функции ИЗ ЭТОГО МОДУЛЯ, а не как попытку вызвать метод на
    /// переменной с таким именем (парсер их не различает — оба выглядят
    /// как ВызовМетода, различение происходит только здесь, семантически).
    ///
    /// ⚠️ ЧЕСТНОЕ ОГРАНИЧЕНИЕ v1: НЕ решает коллизии имён между модулями —
    /// если два модуля объявляют функцию с одинаковым именем, это by-прежнему
    /// ошибка компиляции при регистрации (см. проверку дубликатов) — эта
    /// карта добавляет только СИНТАКСИС квалифицированного доступа для уже
    /// уникальных имён, не полноценную изоляцию пространств имён. Решение
    /// коллизий — отдельный, более крупный следующий шаг (v2).
    модули_программы: HashMap<String, std::collections::HashSet<String>>,
    /// НОВОЕ (v2 — разрешение коллизий имён между модулями): функции из
    /// ПОДКЛЮЧЁННЫХ файлов регистрируются здесь, по ключу (модуль, имя) —
    /// В ОТЛИЧИЕ от self.функции (плоская таблица по простому имени),
    /// эта таблица допускает ДВЕ разные функции с ОДИНАКОВЫМ именем, если
    /// они из РАЗНЫХ модулей — коллизия перестаёт быть ошибкой сама по
    /// себе, ошибкой становится только НЕОДНОЗНАЧНОЕ (неквалифицированное)
    /// обращение к такому имени.
    /// НОВОЕ (проверка аргументов при вызове): тот же формат, что и
    /// self.функции выше — (типы параметров, тип возврата), не просто
    /// тип возврата — по тем же причинам (см. подробный комментарий там).
    функции_по_модулю: HashMap<(String, String), (Vec<РешённыйТип>, Option<РешённыйТип>)>,
    /// "имя функции -> модуль", ТОЛЬКО для функций, которые ОДНОЗНАЧНЫ —
    /// объявлены РОВНО в одном подключённом модуле И не коллизируют с
    /// именем, объявленным в главном файле. Для таких имён по-прежнему
    /// работает неквалифицированный вызов "имя(...)" — тот же принцип,
    /// что и в v1, просто теперь вычисляется явно, а не предполагается
    /// автоматически для всех имён без исключения.
    однозначные_модульные_функции: HashMap<String, String>,
    /// "имя_функции -> манглированное_имя" — ДЛЯ ВСЕХ функций из
    /// подключённых модулей (не только коллизирующих) — используется
    /// кодогенератором, единообразно, без условной логики "коллизия или
    /// нет" на уровне LLVM-имён (тот же принцип единообразного
    /// манглирования, что уже применён для инстанциаций обобщённых
    /// структур — проще и безопаснее, чем манглировать только "при
    /// необходимости").
    манглированные_имена_функций: HashMap<(String, String), String>,
    /// "имя функции -> список ВСЕХ модулей, где она объявлена" (включая
    /// случай, когда их больше одного) — нужно ТОЛЬКО для улучшенной
    /// диагностики: когда пользователь пытается вызвать коллизирующее имя
    /// БЕЗ квалификации, сообщение "функция не объявлена" было бы
    /// вводящим в заблуждение (функция ведь объявлена, просто неоднозначно) —
    /// эта карта позволяет явно назвать модули и подсказать точный синтаксис.
    модули_для_имени_функций: HashMap<String, Vec<String>>,
    /// НОВОЕ: "имя контракта -> список требуемых сигнатур методов" — v1,
    /// только для проверки на этапе компиляции, что реализующая структура
    /// (см. ОбъявлениеСтруктуры.контракты) имеет все требуемые методы с
    /// совпадающими сигнатурами. См. ast::ОбъявлениеКонтракта.
    контракты: HashMap<String, Vec<СигнатураМетодаКонтракта>>,
    /// НОВОЕ: "русское имя внешней функции -> реальное имя символа
    /// библиотеки" (см. "внешняя функция имя(...) как "РеальноеИмя";") —
    /// нужно ТОЛЬКО кодогенератору, чтобы найти правильную LLVM-функцию
    /// при вызове (объявленную под реальным именем) по русскому имени,
    /// использованному в коде программиста.
    внешние_алиасы: HashMap<String, String>,
}

