use std::collections::HashSet;
use std::path::{Path, PathBuf};

use inkwell::context::Context;

use ast::{ВерхнийУзел, Программа};
use lexer::Лексер;
use parser::Парсер;
use semantic::СемантическийАнализатор;
use codegen::Кодогенератор;

fn main() {
    let (путь_к_файлу, только_собрать, библиотечный_режим, дополнительные_библиотеки, автономный_рантайм, целевая_платформа, android_sysroot, android_so) = разобрать_аргументы_командной_строки();

    let (программа, модули_программы, модуль_каждого_узла) = завершить_при_ошибке(
        собрать_программу_с_подключениями(Path::new(&путь_к_файлу)),
        |e| e,
    );

    let mut анализатор = СемантическийАнализатор::новый();
    завершить_при_ошибке(
        анализатор.проверить_программу(&программа, &модули_программы, &модуль_каждого_узла),
        |e| match e.строка {
            Some(строка) => format!("Ошибка семантического анализа на строке {}: {}", строка, e.сообщение),
            None => format!("Ошибка семантического анализа: {}", e.сообщение),
        },
    );

    let решения = анализатор.решения().to_vec();
    let структуры = анализатор.структуры().clone();
    let используемые_списки = анализатор.используемые_списки().clone();
    let используемые_словари = анализатор.используемые_словари().clone();
    let методы_возвращающие_структуру = анализатор.методы_возвращающие_структуру();
    let функции_возвращающие_структуру = анализатор.функции_возвращающие_структуру();
    let имена_обобщённых_структур = анализатор.имена_обобщённых_структур();
    let инстанциированные_обобщённые_структуры = анализатор.инстанциированные_обобщённые_структуры().clone();
    let решения_присваиваний_обобщённых_структур = анализатор.решения_присваиваний_обобщённых_структур().clone();
    // НОВОЕ (обобщённые функции): та же самая инфраструктура, что уже
    // используется выше для обобщённых структур.
    let имена_обобщённых_функций = анализатор.имена_обобщённых_функций();
    let инстанциированные_обобщённые_функции = анализатор.инстанциированные_обобщённые_функции().clone();
    let решения_присваиваний_обобщённых_функций = анализатор.решения_присваиваний_обобщённых_функций().clone();
    let манглированные_имена_функций = анализатор.манглированные_имена_функций().clone();
    let однозначные_модульные_функции = анализатор.однозначные_модульные_функции().clone();
    let внешние_алиасы = анализатор.внешние_алиасы().clone();
    let слабые_поля = анализатор.слабые_поля().clone();

    let контекст = Context::create();
    let mut кодогенератор = завершить_при_ошибке(
        Кодогенератор::новый(
            &контекст,
            "главный_модуль",
            решения,
            &структуры,
            &используемые_списки,
            &используемые_словари,
            &методы_возвращающие_структуру,
            &функции_возвращающие_структуру,
            &имена_обобщённых_структур,
            &имена_обобщённых_функций,
            &манглированные_имена_функций,
            &однозначные_модульные_функции,
            &внешние_алиасы,
            &слабые_поля,
        ),
        |e| format!("Ошибка инициализации кодогенератора: {}", e.сообщение),
    );

    завершить_при_ошибке(
        кодогенератор.сгенерировать_программу(&программа, библиотечный_режим, &инстанциированные_обобщённые_структуры, &решения_присваиваний_обобщённых_структур, &инстанциированные_обобщённые_функции, &решения_присваиваний_обобщённых_функций, &модуль_каждого_узла, android_so),
        |e| format!("Ошибка кодогенерации: {}", e.сообщение),
    );

    // Имя выходных файлов (.ll и исполняемый) берём из имени исходного файла,
    // а не жёстко зашитое "вывод"/"программа" — так при работе с разными
    // .код-файлами результаты не будут затирать друг друга.
    let базовое_имя = Path::new(&путь_к_файлу)
        .file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or("вывод")
        .to_string();

    // НОВОЕ (установщик для Windows): без явного ".exe" в имени, переданном
    // в "-o", реальный исполняемый файл на Windows не распознаётся системой
    // как программа (Windows требует именно это расширение, в отличие от
    // Linux/macOS) — при нативной сборке НА Windows (не кросс-компиляции
    // под Android или что-то ещё) добавляем его явно сами, а не полагаемся
    // на то, добавит ли его сам внешний clang/линковщик — это поведение
    // не задокументировано однозначно для всех вариантов вызова и не стоит
    // на него полагаться молча.
    let имя_исполняемого_файла = if cfg!(target_os = "windows") && целевая_платформа.is_none() {
        format!("{}.exe", базовое_имя)
    } else {
        базовое_имя.clone()
    };

    // .ll остаётся для удобства отладки — это ЧЕЛОВЕКОЧИТАЕМЫЙ текстовый вид
    // IR, полезно, если что-то пошло не так и нужно посмотреть, что именно
    // сгенерировал компилятор. Настоящая компиляция теперь идёт не отсюда.
    let путь_ll = format!("{}.ll", базовое_имя);
    кодогенератор
        .модуль()
        .print_to_file(&путь_ll)
        .expect("не удалось записать .ll файл");

    // Настоящая компиляция в машинный код — напрямую через LLVM API
    // (TargetMachine), без участия внешнего clang на этом этапе.
    let путь_o = format!("{}.o", базовое_имя);
    завершить_при_ошибке(
        кодогенератор.записать_объектный_файл(std::path::Path::new(&путь_o), целевая_платформа.as_deref()),
        |e| format!("Ошибка компиляции в машинный код: {}", e.сообщение),
    );

    if библиотечный_режим {
        // Библиотека не линкуется в исполняемый файл и не запускается —
        // готовый артефакт для подключения В ДРУГОЙ проект (пока вручную,
        // до появления настоящей системы пакетов) — это и есть .o файл.
        println!("Готово: {} (объектный файл библиотеки)", путь_o);
        println!("Эту библиотеку пока нужно линковать вручную в другой проект — \
                   настоящая система пакетов ещё не реализована.");
        return;
    }

    слинковать_исполняемый_файл(&путь_o, &имя_исполняемого_файла, &дополнительные_библиотеки, автономный_рантайм.as_deref(), целевая_платформа.as_deref(), android_sysroot.as_deref(), android_so);

    if только_собрать {
        println!("Готово: ./{}", имя_исполняемого_файла);
        return;
    }

    // По умолчанию — сразу запускаем результат, чтобы "запустить файл.код"
    // ощущалось одной командой, а не "сначала собери, потом отдельно запусти"
    // (в духе того, как `node файл.js` сразу и compiles-in-memory, и выполняет —
    // разница в том, что мы реально собираем нативный бинарник на диске,
    // а не интерпретируем на лету, но для пользователя ощущение то же самое).
    запустить_исполняемый_файл(&имя_исполняемого_файла);
}

/// Разбирает аргументы командной строки: ожидает путь к .код-файлу, и
/// опционально флаги --только-собрать/-c (не запускать результат сразу)
/// и --библиотека/-b (собрать как библиотеку — без точки входа "главная",
/// без линковки в исполняемый файл, без запуска; см. Кодогенератор::
/// сгенерировать_программу, параметр библиотечный_режим).
fn разобрать_аргументы_командной_строки() -> (String, bool, bool, Vec<String>, Option<String>, Option<String>, Option<String>, bool) {
    let аргументы: Vec<String> = std::env::args().collect();

    let программа = аргументы.first().cloned().unwrap_or_else(|| "запустить".to_string());
    let остальные: Vec<&String> = аргументы.iter().skip(1).collect();

    if остальные.iter().any(|а| а.as_str() == "-h" || а.as_str() == "--help") {
        вывести_подсказку(&программа);
        std::process::exit(0);
    }

    // НОВОЕ: "-с" (кириллическая "с", как в "собрать") — синоним "-c",
    // не замена. ⚠️ Важный, честный технический нюанс: кириллическая "с"
    // (U+0441) выглядит на экране АБСОЛЮТНО идентично латинской "c"
    // (U+0063), но для компьютера это два совершенно разных символа —
    // если бы кириллический вариант был единственным, человек, случайно
    // набравший привычную латинскую "-c" (мышечная память почти из
    // любого другого инструмента разработки), получил бы непонятную
    // ошибку — флаг просто не распознался бы, молча воспринялся бы как
    // имя файла. Поддержаны оба — безопаснее, чем выбирать один в ущерб
    // другому.
    let только_собрать = остальные
        .iter()
        .any(|а| а.as_str() == "-c" || а.as_str() == "-с" || а.as_str() == "--только-собрать");

    // То же самое рассуждение для "-b"/"-б" (первая буква "библиотека").
    let библиотечный_режим = остальные
        .iter()
        .any(|а| а.as_str() == "-b" || а.as_str() == "-б" || а.as_str() == "--библиотека");

    // НОВОЕ: "--линковать SDL2" — говорит линковщику добавить "-lSDL2" при
    // сборке исполняемого файла. Нужно для FFI ("внешняя функция ...;") —
    // без явного указания библиотеки линковщик не найдёт настоящую
    // реализацию внешних функций (объявление есть, а кода — нет, пока не
    // слинкуем с библиотекой, откуда он приходит). Можно указывать
    // несколько раз для нескольких библиотек сразу.
    let mut дополнительные_библиотеки: Vec<String> = Vec::new();
    // НОВОЕ: "--автономно путь/к/рантайму.o" — собирает программу БЕЗ
    // единой связи с libc ("-ffreestanding -nostdlib -static" при
    // линковке) и линкует вместо неё указанный файл — собственную,
    // написанную вручную на ассемблере замену (точка входа "_start" +
    // системные вызовы напрямую, см. минимальный_рантайм.s). Открывает
    // путь к написанию ядра ОС, загрузчика, прошивки для встраиваемых
    // систем — куда обычная libc-программа поместиться не может, ведь
    // там просто неоткуда взяться операционной системе, на которую libc
    // сама полагается.
    let mut автономный_рантайм: Option<String> = None;
    // НОВОЕ: "--целевая-платформа aarch64-linux-gnu" — компилирует НЕ под ту
    // архитектуру, на которой запущен сам компилятор ("родную"), а под
    // указанную явно. Раньше эта возможность даже не появлялась как
    // выбор — записать_объектный_файл всегда брала родную платформу
    // безусловно. Сама эта возможность УЖЕ полностью присутствовала
    // внутри LLVM (мы и так полагаемся на него для генерации кода) —
    // не хватало только явного способа её запросить, не более того.
    let mut целевая_платформа: Option<String> = None;
    // НОВОЕ: "--android-sysroot ПУТЬ" — путь к папке "sysroot" из настоящего
    // Android NDK (toolchains/llvm/prebuilt/*/sysroot/) — нужен для
    // финальной линковки под Android (своя libc — Bionic, не glibc,
    // требует настоящих системных файлов из NDK, которые компилятор сам
    // по себе никак не может ни сгенерировать, ни угадать путь к ним —
    // у каждого пользователя NDK будет лежать в своём месте).
    let mut android_sysroot: Option<String> = None;
    // НОВОЕ: "--android-so" — компилирует НЕ самостоятельную программу
    // (с обычной точкой входа "main", которую вызывает сама операционная
    // система), а подключаемую библиотеку с точкой входа "SDL_main" —
    // именно так, как ожидает готовая, официальная Java-обвязка SDL2
    // (SDLActivity.java, метод getMainFunction() — см. подробности в
    // ИСТОРИЯ_РАЗРАБОТКИ.md) — она сама находит эту функцию через dlsym()
    // внутри загруженной библиотеки, никакого JNI-кода писать не нужно.
    let mut android_so = false;
    let mut индекс = 0;
    while индекс < остальные.len() {
        if остальные[индекс].as_str() == "--линковать" {
            if let Some(имя_библиотеки) = остальные.get(индекс + 1) {
                дополнительные_библиотеки.push(имя_библиотеки.to_string());
                индекс += 2;
                continue;
            } else {
                eprintln!("Флаг --линковать требует имя библиотеки после себя (например: --линковать SDL2).\n");
                вывести_подсказку(&программа);
                std::process::exit(1);
            }
        }
        if остальные[индекс].as_str() == "--автономно" {
            if let Some(путь_рантайма) = остальные.get(индекс + 1) {
                автономный_рантайм = Some(путь_рантайма.to_string());
                индекс += 2;
                continue;
            } else {
                eprintln!("Флаг --автономно требует путь к объектному файлу рантайма (например: --автономно минимальный_рантайм.o).\n");
                вывести_подсказку(&программа);
                std::process::exit(1);
            }
        }
        if остальные[индекс].as_str() == "--целевая-платформа" {
            if let Some(тройка) = остальные.get(индекс + 1) {
                целевая_платформа = Some(тройка.to_string());
                индекс += 2;
                continue;
            } else {
                eprintln!("Флаг --целевая-платформа требует тройку целевой платформы после себя (например: --целевая-платформа aarch64-linux-gnu).\n");
                вывести_подсказку(&программа);
                std::process::exit(1);
            }
        }
        if остальные[индекс].as_str() == "--android-sysroot" {
            if let Some(путь) = остальные.get(индекс + 1) {
                android_sysroot = Some(путь.to_string());
                индекс += 2;
                continue;
            } else {
                eprintln!("Флаг --android-sysroot требует путь к sysroot из Android NDK после себя.\n");
                вывести_подсказку(&программа);
                std::process::exit(1);
            }
        }
        if остальные[индекс].as_str() == "--android-so" {
            android_so = true;
            индекс += 1;
            continue;
        }
        индекс += 1;
    }

    let пути: Vec<&&String> = остальные
        .iter()
        .enumerate()
        .filter(|(индекс, а)| {
            !matches!(
                а.as_str(),
                "-c" | "-с" | "--только-собрать" | "-b" | "-б" | "--библиотека" | "--линковать" | "--автономно" | "--целевая-платформа" | "--android-sysroot" | "--android-so"
            ) && !(*индекс > 0 && matches!(остальные[*индекс - 1].as_str(), "--линковать" | "--автономно" | "--целевая-платформа" | "--android-sysroot"))
        })
        .map(|(_, а)| а)
        .collect();

    match пути.as_slice() {
        [путь] => (путь.to_string(), только_собрать, библиотечный_режим, дополнительные_библиотеки, автономный_рантайм, целевая_платформа, android_sysroot, android_so),
        [] => {
            eprintln!("Не указан файл для компиляции.\n");
            вывести_подсказку(&программа);
            std::process::exit(1);
        }
        _ => {
            eprintln!("Слишком много аргументов — ожидается ровно один путь к .код-файлу.\n");
            вывести_подсказку(&программа);
            std::process::exit(1);
        }
    }
}

fn вывести_подсказку(имя_программы: &str) {
    eprintln!("Использование: {} путь/к/файлу.код [--только-собрать] [--библиотека] [--линковать ИМЯ] [--автономно РАНТАЙМ.o]", имя_программы);
    eprintln!("Пример:        {} привет.код", имя_программы);
    eprintln!("Пример с FFI:  {} игра.код --линковать SDL2", имя_программы);
    eprintln!();
    eprintln!("По умолчанию собранная программа сразу запускается.");
    eprintln!("Флаг --только-собрать (или -c, или -с кириллицей) — только собрать, не запускать.");
    eprintln!("Флаг --библиотека (или -b, или -б кириллицей) — собрать как библиотеку: без точки входа");
    eprintln!("  'главная', без линковки в исполняемый файл — просто .o файл,");
    eprintln!("  готовый для подключения в другой проект.");
    eprintln!("Флаг --линковать ИМЯ — добавляет '-lИМЯ' при линковке (можно несколько");
    eprintln!("  раз) — нужен для программ с 'внешняя функция ...;' (FFI), например");
    eprintln!("  '--линковать SDL2' для программ, использующих графику через SDL2.");
}

/// Последний шаг конвейера: связывает уже ГОТОВЫЙ объектный файл (машинный
/// код, полученный напрямую через LLVM TargetMachine — см. codegen.rs,
/// записать_объектный_файл) с системными библиотеками (libc, откуда приходит
/// printf/malloc/free) в единый исполняемый файл.
///
/// Раньше clang делал ДВЕ вещи: компилировал текстовый .ll в машинный код
/// И линковал результат. Теперь компиляция — наша, через настоящий LLVM API;
/// clang остался только для этого последнего шага — самой линковки, которая
/// требует платформенно-специфичного линковщика (см. подробный комментарий
/// у записать_объектный_файл о том, почему полностью убрать внешний
/// инструмент здесь — уже отдельный, больший проект).
fn слинковать_исполняемый_файл(путь_o: &str, имя_программы: &str, дополнительные_библиотеки: &[String], автономный_рантайм: Option<&str>, целевая_платформа: Option<&str>, android_sysroot: Option<&str>, android_so: bool) {
    use std::process::Command;

    // НОВОЕ: при кросс-компиляции обычный "clang" (без явного --target) не
    // подходит — линковал бы под РОДНУЮ платформу, независимо от того, под
    // какую архитектуру мы только что сгенерировали объектный файл. Проще
    // и надёжнее использовать уже настроенный кросс-компилятор для нужной
    // платформы (устанавливается отдельно, например
    // "apt install gcc-aarch64-linux-gnu") — он сам знает правильные пути
    // к системным библиотекам и линковщику для этой архитектуры, в
    // отличие от обычного clang, которому пришлось бы вручную объяснять
    // через --sysroot/-B, куда именно смотреть.
    //
    // ⚠️ НАЙДЕНО РЕАЛЬНОЙ ПРОВЕРКОЙ: "aarch64-linux-android" тоже содержит
    // подстроку "aarch64" — простая проверка ниже по ошибке линковала бы
    // такую тройку через "aarch64-linux-gnu-gcc" (обычный Linux/glibc
    // тулчейн), молча выдавая ОБЫЧНЫЙ ARM64 Linux-бинарник вместо
    // настоящего Android — тот, что выглядел бы неотличимо (ELF ARM64),
    // но не запустился бы на реальном устройстве (у Android другой
    // динамический загрузчик и своя libc — Bionic, не glibc).
    //
    // ✅ РЕШЕНО: с настоящим sysroot из Android NDK (папка
    // toolchains/llvm/prebuilt/*/sysroot/, передаётся через
    // --android-sysroot) собирается настоящий, правильный Android
    // ELF-бинарник — реально проверено: получившийся файл имеет
    // interpreter "/system/bin/linker64" (настоящий Android-загрузчик,
    // не glibc-эмуляция). Ключевые, неочевидные флаги, найденные
    // ЭКСПЕРИМЕНТАЛЬНО (не только по документации):
    //   -fuse-ld=lld    — Android NDK требует именно LLVM-линковщик,
    //                     обычный GNU ld не находит "ld.lld" сам по себе
    //   -nodefaultlibs   — без него clang ищет "-lgcc", которого нет для
    //                     Android (там свой compiler-rt, а его файлы не
    //                     входят в саму папку sysroot — честно не хватает
    //                     в этой версии, для простых программ без него
    //                     обходится)
    //   -lc -lm -ldl     — базовые системные библиотеки вместо тех, что
    //                     убрал -nodefaultlibs
    if let Some(тройка) = целевая_платформа {
        if тройка.contains("android") {
            let sysroot = match android_sysroot {
                Some(путь) => путь,
                None => {
                    eprintln!(
                        "Компиляция под Android требует флаг --android-sysroot ПУТЬ —\n\
                         путь к папке \"sysroot\" из настоящего Android NDK\n\
                         (toolchains/llvm/prebuilt/linux-x86_64/sysroot/)."
                    );
                    std::process::exit(1);
                }
            };

            let mut команда = Command::new("clang");
            команда
                .arg(format!("--target={}", тройка))
                .arg(format!("--sysroot={}", sysroot))
                .arg("-fuse-ld=lld")
                .arg("-nodefaultlibs");
            // НОВОЕ: "--android-so" — вместо самостоятельной программы
            // собираем ПОДКЛЮЧАЕМУЮ библиотеку (см. подробное объяснение
            // у сгенерировать_обёртку_main, откуда взялось имя "SDL_main")
            // — "-shared" вместо обычной точки входа операционной системы,
            // "-fPIC" обязателен для любого кода внутри shared library.
            if android_so {
                команда.arg("-shared").arg("-fPIC");
            }
            команда
                .arg(путь_o)
                .arg("-lc")
                .arg("-lm")
                .arg("-ldl")
                .arg("-o")
                .arg(имя_программы);
            let результат = команда.output();

            match результат {
                Ok(вывод) if вывод.status.success() => return,
                Ok(вывод) => {
                    eprintln!("Ошибка при линковке под Android:");
                    eprintln!("{}", String::from_utf8_lossy(&вывод.stderr));
                    std::process::exit(1);
                }
                Err(e) => {
                    eprintln!("Не удалось запустить clang для линковки под Android: {}", e);
                    std::process::exit(1);
                }
            }
        }
    }

    let имя_линковщика = match целевая_платформа {
        Some(тройка) if тройка.contains("aarch64") => "aarch64-linux-gnu-gcc",
        Some(_) => "clang", // другие платформы — честно, пока не имеют отдельного кросс-линковщика здесь
        None => "clang",
    };

    let собрать_команду = |с_no_pie: bool| {
        let mut команда = Command::new(имя_линковщика);
        команда.arg(путь_o).arg("-o").arg(имя_программы);
        if с_no_pie {
            команда.arg("-no-pie");
        }
        // НОВОЕ: "--автономно РАНТАЙМ.o" — программа собирается БЕЗ единой
        // связи с libc, вместо привычной цепочки _start -> __libc_start_main
        // -> main используется своя, написанная вручную "_start" (внутри
        // указанного файла рантайма), напрямую вызывающая уже
        // сгенерированную нами функцию "main" (см. codegen.rs,
        // сгенерировать_обёртку_main — она генерируется КАК ОБЫЧНО, этому
        // режиму не потребовалось никаких изменений в кодогенерации).
        if let Some(рантайм) = автономный_рантайм {
            команда.arg("-ffreestanding").arg("-nostdlib").arg("-static");
            команда.arg(рантайм);
        }
        // НОВОЕ: "-l<имя>" для каждой библиотеки, указанной через "--линковать"
        // — нужно для FFI ("внешняя функция ...;"), чтобы линковщик нашёл
        // настоящую реализацию внешних функций (само объявление в .код-файле
        // не содержит кода, только сигнатуру).
        for библиотека in дополнительные_библиотеки {
            команда.arg(format!("-l{}", библиотека));
        }
        команда
    };

    let результат = собрать_команду(false).output();

    match результат {
        Ok(вывод) if вывод.status.success() => {}
        Ok(вывод) => {
            // ⚠️ НАЙДЕНО ПРИ РЕАЛЬНОЙ РАБОТЕ (упаковка компилятора в .deb):
            // на некоторых конфигурациях Linux (в частности — та, на
            // которой мы всю дорогу тестировали компилятор) обычная,
            // "по умолчанию" линковка PIE-зависимым способом падает с
            // "relocation R_X86_64_32... can not be used when making a
            // PIE object" — мы раньше обходили это ВРУЧНУЮ, флагом
            // "-no-pie" при каждом ручном тестовом запуске, но КОНЕЧНЫЙ
            // пользователь компилятора (например, установившего его через
            // .deb) столкнулся бы с этой же, малопонятной ошибкой при
            // КАЖДОЙ компиляции своей программы — компилятор должен
            // справляться с этим сам, не перекладывая системную деталь
            // линковки на пользователя языка.
            let текст_ошибки = String::from_utf8_lossy(&вывод.stderr);
            if текст_ошибки.contains("PIE") || текст_ошибки.contains("R_X86_64_32") {
                let повтор = собрать_команду(true).output();
                match повтор {
                    Ok(вывод2) if вывод2.status.success() => {}
                    Ok(вывод2) => {
                        eprintln!("Ошибка при линковке:");
                        eprintln!("{}", String::from_utf8_lossy(&вывод2.stderr));
                        std::process::exit(1);
                    }
                    Err(e) => {
                        eprintln!("Не удалось повторно запустить clang: {}", e);
                        std::process::exit(1);
                    }
                }
            } else {
                eprintln!("Ошибка при линковке:");
                eprintln!("{}", текст_ошибки);
                std::process::exit(1);
            }
        }
        Err(e) => {
            eprintln!(
                "Не удалось запустить {} (нужен для линковки): {}\n\
                 Проверь, что он установлен и доступен в PATH.",
                имя_линковщика, e
            );
            std::process::exit(1);
        }
    }
}

/// Запускает уже собранный исполняемый файл и ждёт его завершения, отдавая
/// его стандартный вывод/ввод напрямую в терминал (inherit) — то есть
/// пользователь видит вывод СВОЕЙ программы на "Сфере" точно так же, как
/// если бы запустил её сам через ./имя. Код возврата программы пробрасывается
/// наружу как код возврата самого компилятора — стандартное поведение для
/// инструментов вида "собери и запусти" (аналог `go run`, `node файл.js`).
fn запустить_исполняемый_файл(имя_программы: &str) {
    use std::process::Command;

    let путь = format!("./{}", имя_программы);
    match Command::new(&путь).status() {
        Ok(статус) => {
            std::process::exit(статус.code().unwrap_or(0));
        }
        Err(e) => {
            eprintln!("Не удалось запустить '{}': {}", путь, e);
            std::process::exit(1);
        }
    }
}

/// Читает, разбирает указанный файл, и РЕКУРСИВНО разрешает все его
/// "подключить" — то есть находит подключённые файлы, разбирает их тоже,
/// и сливает ВСЕ верхнеуровневые объявления (функции, структуры) в один
/// общий список. Семантический анализ и кодогенерация ничего не знают о
/// том, что программа могла состоять из нескольких файлов — они как и
/// раньше получают один список объявлений.
///
/// Это НЕ настоящая раздельная компиляция с изоляцией пространств имён
/// между файлами (это отдельный, гораздо больший следующий шаг) — все
/// объявления из всех подключённых файлов делят ОДНО общее пространство
/// имён, как если бы весь код был написан в одном файле. Дублирующиеся
/// имена функций/структур между файлами пока не проверяются отдельно —
/// та же (уже существующая) логика, что применяется и внутри одного файла.
///
/// Циклические подключения (А подключает Б, Б подключает А) корректно
/// обрабатываются: файл, чей канонический путь уже был обработан, просто
/// молча пропускается при повторной встрече — как автоматические include
/// guards в C, без необходимости писать что-то специальное в самом языке.
fn собрать_программу_с_подключениями(входной_путь: &Path) -> Result<(Программа, std::collections::HashMap<String, HashSet<String>>, Vec<Option<String>>), String> {
    let mut обработанные_пути: HashSet<PathBuf> = HashSet::new();
    let mut итоговая_программа: Программа = Vec::new();
    // НОВОЕ: "имя модуля" (имя файла без ".код") -> множество имён
    // функций/структур, объявленных ИМЕННО в этом файле — нужно для
    // квалифицированного доступа "модуль.имя(...)" (см. семантику и
    // кодогенерацию). ГЛАВНЫЙ (входной) файл модулем не считается — его
    // объявления остаются доступны БЕЗ квалификации, как и раньше
    // (v1-упрощение, не даёт квалифицировать объявления самого входного
    // файла — честно задокументированное ограничение первой версии).
    let mut модули_программы: std::collections::HashMap<String, HashSet<String>> = std::collections::HashMap::new();
    // НОВОЕ (v2 — разрешение коллизий имён): параллельный вектор, той же
    // длины и в том же порядке, что и итоговая_программа — модуль
    // происхождения КАЖДОГО узла (None для узлов из главного файла).
    // Раньше (v1) семантика знала только "какие имена есть в каком
    // модуле" (через модули_программы) — этого хватало для распознавания
    // синтаксиса "модуль.имя(...)", но НЕ хватало для РЕГИСТРАЦИИ каждого
    // объявления под правильным модулем (нужно при разрешении коллизий —
    // семантике нужно связать САМ узел ВерхнийУзел с его происхождением,
    // не только его имя).
    let mut модуль_каждого_узла: Vec<Option<String>> = Vec::new();

    let канонический_входной_путь = входной_путь.canonicalize().map_err(|e| {
        format!(
            "Не удалось найти файл '{}': {}\nПроверь, что путь указан верно и файл существует.",
            входной_путь.display(), e
        )
    })?;
    let корень_проекта = канонический_входной_путь
        .parent()
        .unwrap_or_else(|| Path::new("."))
        .to_path_buf();

    собрать_рекурсивно(входной_путь, &корень_проекта, &mut обработанные_пути, &mut итоговая_программа, &mut модули_программы, &mut модуль_каждого_узла, true)?;
    Ok((итоговая_программа, модули_программы, модуль_каждого_узла))
}

fn собрать_рекурсивно(
    путь: &Path,
    корень_проекта: &Path,
    обработанные_пути: &mut HashSet<PathBuf>,
    итоговая_программа: &mut Программа,
    модули_программы: &mut std::collections::HashMap<String, HashSet<String>>,
    модуль_каждого_узла: &mut Vec<Option<String>>,
    это_главный_файл: bool,
) -> Result<(), String> {
    let канонический_путь = путь.canonicalize().map_err(|e| {
        format!(
            "Не удалось найти файл '{}': {}\nПроверь, что путь указан верно и файл существует.",
            путь.display(), e
        )
    })?;

    if обработанные_пути.contains(&канонический_путь) {
        // Этот файл уже был разобран раньше (либо запрошен напрямую, либо
        // через чей-то "подключить") — молча пропускаем, это не ошибка,
        // а естественная защита от циклических подключений и от повторной
        // обработки одного и того же файла, подключённого дважды из разных мест.
        return Ok(());
    }
    обработанные_пути.insert(канонический_путь.clone());

    let исходный_код = std::fs::read_to_string(путь)
        .map_err(|e| format!("Не удалось прочитать файл '{}': {}", путь.display(), e))?;

    let токены = Лексер::новый(&исходный_код)
        .токенизировать()
        .map_err(|e| format!(
            "Ошибка лексера в файле '{}' на строке {}, столбец {}: {}",
            путь.display(), e.строка, e.столбец, e.сообщение
        ))?;

    let программа_файла = Парсер::новый(токены)
        .разобрать_программу()
        .map_err(|e| format!(
            "Ошибка парсера в файле '{}' на строке {}, столбец {}: {}",
            путь.display(), e.строка, e.столбец, e.сообщение
        ))?;

    // Директория ТЕКУЩЕГО файла — все подключения внутри него разрешаются
    // относительно неё, а не относительно текущей рабочей директории терминала.
    // Иначе "подключить утилиты;" работал бы только если запускать компилятор
    // из строго определённой папки — крайне неудобно и хрупко.
    let директория = канонический_путь.parent().unwrap_or_else(|| Path::new("."));

    // НОВОЕ: имя модуля — имя файла без расширения ".код" (например,
    // "утилиты" для утилиты.код) — ТОЛЬКО для подключённых файлов, не для
    // главного (см. подробное объяснение у объявления модули_программы).
    let имя_модуля: Option<String> = if это_главный_файл {
        None
    } else {
        путь.file_stem().and_then(|s| s.to_str()).map(String::from)
    };

    for узел in программа_файла {
        match узел {
            ВерхнийУзел::Подключение(путь_подключения) => {
                let разрешённый_путь = разрешить_путь_подключения(&путь_подключения, директория, корень_проекта);
                собрать_рекурсивно(&разрешённый_путь, корень_проекта, обработанные_пути, итоговая_программа, модули_программы, модуль_каждого_узла, false)?;
            }
            other => {
                // Регистрируем имя объявления (функция/структура) под именем
                // ЭТОГО модуля — если файл не главный. Делается ДО push в
                // итоговую программу, чтобы у нас было "other" ещё доступным
                // (не перемещённым) для чтения имени.
                if let Some(имя_модуля) = &имя_модуля {
                    let имя_объявления = match &other {
                        ВерхнийУзел::Функция(ф) => Some(ф.имя.clone()),
                        ВерхнийУзел::Структура(с) => Some(с.имя.clone()),
                        ВерхнийУзел::Подключение(_) => None,
                        // Контракты не участвуют в квалифицированном доступе
                        // "модуль.имя(...)" — они используются только по
                        // имени в "структура X: ИмяКонтракта", не через
                        // точечную нотацию (v1 — см. README).
                        ВерхнийУзел::Контракт(_) => None,
                        // Внешние функции (FFI) ВСЕГДА используют буквальное
                        // LLVM-имя (должно точно совпадать с именем символа
                        // в C-библиотеке, например "SDL_Init") — не участвуют
                        // в манглировании пространств имён v2, значит и в
                        // квалифицированном доступе тоже не нуждаются.
                        ВерхнийУзел::ВнешняяФункция(_) => None,
                    };
                    if let Some(имя_объявления) = имя_объявления {
                        модули_программы
                            .entry(имя_модуля.clone())
                            .or_insert_with(HashSet::new)
                            .insert(имя_объявления);
                    }
                }
                модуль_каждого_узла.push(имя_модуля.clone());
                итоговая_программа.push(other);
            }
        }
    }

    Ok(())
}

/// Превращает строку из "подключить ...;" в реальный путь на диске.
///
/// Два случая, различаемых ПО СОДЕРЖИМОМУ строки (AST не хранит информацию
/// о том, был ли это путь в кавычках или простое имя — см. grammar.md,
/// раздел 1 — оба варианта попадают в ВерхнийУзел::Подключение(String)
/// одинаково):
/// - строка содержит "/" или уже заканчивается на ".код" — трактуем как
///   явный путь (было "подключить \"путь/файл.код\";"), ищем ТОЛЬКО рядом
///   с подключающим файлом — для явного пути "запасной" поиск в пакетах
///   не имеет смысла (человек и так указал точное расположение).
/// - иначе — трактуем как ИМЯ МОДУЛЯ (было "подключить имя;"). Сначала
///   ищем "{имя}.код" РЯДОМ с подключающим файлом (для разбиения СВОЕГО
///   ЖЕ проекта на файлы — как было и раньше). Если там не нашлось —
///   пробуем "{корень_проекта}/пакеты/{имя}.код" (простая, локальная
///   конвенция для "внешнего", не-своего кода — НЕ полноценная система
///   пакетов с публикацией/версиями/реестром, просто предсказуемое место,
///   куда можно вручную положить чужой `.код`-файл и подключить его по
///   имени, не задумываясь каждый раз о точном относительном пути).
///
/// ⚠️ ИЗВЕСТНОЕ ОГРАНИЧЕНИЕ: составные имена с точкой ("подключить
/// графика.окно;" — по грамматике должно означать "зайти в папку графика,
/// взять файл окно.код") пока не поддержаны — точка внутри имени модуля
/// сейчас просто станет частью искомого имени файла буквально
/// ("графика.окно.код"), что почти наверняка не найдётся. Явно
/// задокументировано как следующий шаг, не тихо сломано.
fn разрешить_путь_подключения(путь_подключения: &str, директория_подключающего_файла: &Path, корень_проекта: &Path) -> PathBuf {
    if путь_подключения.contains('/') || путь_подключения.ends_with(".код") {
        return директория_подключающего_файла.join(путь_подключения);
    }

    let имя_файла = format!("{}.код", путь_подключения);

    let путь_рядом = директория_подключающего_файла.join(&имя_файла);
    if путь_рядом.exists() {
        return путь_рядом;
    }

    let путь_в_пакетах = корень_проекта.join("пакеты").join(&имя_файла);
    if путь_в_пакетах.exists() {
        return путь_в_пакетах;
    }

    // Ни там, ни там не нашлось — возвращаем путь "рядом с файлом" как
    // основной вариант по умолчанию: дальше он всё равно не пройдёт
    // canonicalize() внутри собрать_рекурсивно и даст понятную ошибку
    // "не удалось найти файл", а не какую-то более странную из двух.
    путь_рядом
}


fn завершить_при_ошибке<T, E>(результат: Result<T, E>, форматировать: impl FnOnce(E) -> String) -> T {
    match результат {
        Ok(значение) => значение,
        Err(ошибка) => {
            eprintln!("{}", форматировать(ошибка));
            std::process::exit(1);
        }
    }
}

