//! Библиотечная цель пакета "sfera" — переиспользуемый ФРОНТЕНД компилятора
//! (лексер, парсер, семантический анализатор), БЕЗ кодогенерации.
//!
//! Зачем это отдельно от main.rs: языковому серверу (src/bin/сфера_lsp.rs)
//! для проверки кода в реальном времени (диагностика ошибок в редакторе)
//! не нужно РЕАЛЬНО компилировать код в машинный код — только разобрать
//! его и проверить на ошибки. Кодогенерация тянет за собой inkwell/LLVM —
//! тяжёлую зависимость, совершенно не нужную для простой проверки
//! синтаксиса и типов. Вынося именно фронтенд в library target, языковой
//! сервер может использовать ровно те же лексер/парсер/семантику, что и
//! настоящий компилятор (не дублируя логику отдельной, второй реализацией,
//! которая рисковала бы разойтись с реальным поведением компилятора), но
//! не тянуть за собой LLVM.
//!
//! main.rs (сам компилятор) НЕ использует эту библиотеку — у него
//! СВОИ собственные `mod` объявления на те же файлы. Да, это означает,
//! что token.rs/lexer.rs/ast.rs/parser.rs/semantic.rs компилируются
//! ДВАЖДЫ (один раз как часть этой библиотеки, один раз как часть
//! main.rs) — совершенно нормальная, безопасная ситуация в Cargo
//! (два разных target'а, не связанных друг с другом), а не ошибка.
//! Выбрано намеренно: изменение main.rs, чтобы он тоже использовал эту
//! библиотеку, было бы чище архитектурно, но означало бы риск задеть
//! уже проверенный, работающий код компилятора ради нового, ещё не
//! проверенного инструмента — сочли это не стоящим риска.

pub mod token;
pub mod lexer;
pub mod ast;
pub mod parser;
pub mod semantic;
#[path = "подсказки.rs"]
pub mod подсказки;
