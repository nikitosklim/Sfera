//! Числовые литералы подстраиваются под размер.
//!
//! Целый литерал сам по себе всегда 64-битное «целое». Чтобы не писать
//! `целое16(5)` на каждом шагу, этот проход (он идёт после разбора и перед
//! семантикой) подставляет явное преобразование там, где нужный размер
//! известен точно:
//!
//!   целое16 а = 5          =>  целое16 а = целое16(5)
//!   а = а + 1              =>  а = а + целое16(1)
//!   если (б == 4)          =>  если (б == беззнак8(4))
//!   аппаратная_запись8(0x24, 32)  =>  …(0x24, беззнак8(32))
//!   включить_биты(х, 1)    =>  включить_биты(х, <тип х>(1))
//!   вернуть 0 (в функции с типом целое16), аргументы вызовов, поля структур
//!
//! Правила намеренно осторожные: литерал оборачивается только когда ожидаемый
//! тип — узкое целое, а число в его пределы помещается. Во всех остальных
//! случаях ничего не меняется, и работает прежняя проверка типов.
use crate::ast::*;
use std::collections::HashMap;

const БИТОВЫЕ_ФУНКЦИИ: &[&str] = &[
    "наложить_маску", "включить_биты", "переключить_биты", "инвертировать_биты", "сдвинуть_влево", "сдвинуть_вправо",
];

fn имя_преобразования(т: &Тип) -> Option<&'static str> {
    Some(match т {
        Тип::Целое8 => "целое8",
        Тип::Целое16 => "целое16",
        Тип::Целое32 => "целое32",
        Тип::Беззнак8 => "беззнак8",
        Тип::Беззнак16 => "беззнак16",
        Тип::Беззнак32 => "беззнак32",
        Тип::Беззнак64 => "беззнак64",
        _ => return None,
    })
}

fn тип_по_имени(имя: &str) -> Option<Тип> {
    Some(match имя {
        "целое8" => Тип::Целое8,
        "целое16" => Тип::Целое16,
        "целое32" => Тип::Целое32,
        "беззнак8" => Тип::Беззнак8,
        "беззнак16" => Тип::Беззнак16,
        "беззнак32" => Тип::Беззнак32,
        "беззнак64" => Тип::Беззнак64,
        _ => return None,
    })
}

fn узкое(т: &Тип) -> bool {
    имя_преобразования(т).is_some()
}

fn помещается(т: &Тип, n: i64) -> bool {
    let (мин, макс): (i128, i128) = match т {
        Тип::Целое8 => (i8::MIN as i128, i8::MAX as i128),
        Тип::Целое16 => (i16::MIN as i128, i16::MAX as i128),
        Тип::Целое32 => (i32::MIN as i128, i32::MAX as i128),
        Тип::Беззнак8 => (0, u8::MAX as i128),
        Тип::Беззнак16 => (0, u16::MAX as i128),
        Тип::Беззнак32 => (0, u32::MAX as i128),
        Тип::Беззнак64 => (0, i64::MAX as i128),
        _ => return false,
    };
    (n as i128) >= мин && (n as i128) <= макс
}

fn обернуть(т: &Тип, е: Выражение) -> Выражение {
    Выражение::ВызовФункции { имя: имя_преобразования(т).unwrap().to_string(), типовые_параметры: Vec::new(), аргументы: vec![е] }
}

fn арифметический(о: БинарныйОператор) -> bool {
    use БинарныйОператор::*;
    matches!(о, Плюс | Минус | Умножить | Разделить | Остаток | БитИ | БитИли | БитИскл)
}

fn сравнение(о: БинарныйОператор) -> bool {
    use БинарныйОператор::*;
    matches!(о, Равно | НеРавно | Меньше | Больше | МеньшеРавно | БольшеРавно)
}

fn только_литералы(е: &Выражение) -> bool {
    match е {
        Выражение::ЦелоеЛит(_) => true,
        Выражение::Унарное { оператор: УнарныйОператор::Минус, операнд } => matches!(**операнд, Выражение::ЦелоеЛит(_)),
        Выражение::Бинарное { левое, оператор, правое } => арифметический(*оператор) && только_литералы(левое) && только_литералы(правое),
        _ => false,
    }
}

/// Подставляет преобразование в литерал (и в арифметику из одних литералов).
fn подогнать(е: &mut Выражение, т: &Тип) {
    if !узкое(т) {
        return;
    }
    match е {
        Выражение::ЦелоеЛит(n) => {
            if помещается(т, *n) {
                let старое = std::mem::replace(е, Выражение::ЦелоеЛит(0));
                *е = обернуть(т, старое);
            }
        }
        Выражение::Унарное { оператор: УнарныйОператор::Минус, операнд } => {
            if let Выражение::ЦелоеЛит(n) = **операнд {
                if n.checked_neg().map_or(false, |м| помещается(т, м)) {
                    let старое = std::mem::replace(е, Выражение::ЦелоеЛит(0));
                    *е = обернуть(т, старое);
                }
            }
        }
        Выражение::Бинарное { левое, оператор, правое } if арифметический(*оператор) => {
            if только_литералы(левое) && только_литералы(правое) {
                подогнать(левое, т);
                подогнать(правое, т);
            }
        }
        _ => {}
    }
}

struct Сигнатура {
    параметры: Vec<Тип>,
    возврат: Option<Тип>,
}

struct Проход {
    функции: HashMap<String, Option<Сигнатура>>,
    структуры: HashMap<String, Vec<(String, Тип)>>,
    методы: HashMap<(String, String), Сигнатура>,
    глобальные: HashMap<String, Тип>,
    области: Vec<HashMap<String, Option<Тип>>>,
    возврат: Option<Тип>,
}

pub fn подогнать_литералы(программа: &mut Программа) {
    let mut пр = Проход {
        функции: HashMap::new(),
        структуры: HashMap::new(),
        методы: HashMap::new(),
        глобальные: HashMap::new(),
        области: Vec::new(),
        возврат: None,
    };
    for у in programa_узлы(программа) {
        match у {
            ВерхнийУзел::Функция(ф) => {
                let с = Сигнатура { параметры: ф.параметры.iter().map(|п| п.тип.clone()).collect(), возврат: ф.тип_возврата.clone() };
                // Одинаковое имя у двух функций (из разных файлов): не угадываем.
                if пр.функции.contains_key(&ф.имя) {
                    пр.функции.insert(ф.имя.clone(), None);
                } else {
                    пр.функции.insert(ф.имя.clone(), Some(с));
                }
            }
            ВерхнийУзел::Структура(с) => {
                пр.структуры.insert(с.имя.clone(), с.поля.iter().map(|п| (п.имя.clone(), п.тип.clone())).collect());
                for м in &с.методы {
                    let сиг = Сигнатура { параметры: м.параметры.iter().map(|п| п.тип.clone()).collect(), возврат: м.тип_возврата.clone() };
                    пр.методы.insert((с.имя.clone(), м.имя.clone()), сиг);
                }
            }
            ВерхнийУзел::Глобальная { тип, имя, .. } => {
                пр.глобальные.insert(имя.clone(), тип.clone());
            }
            _ => {}
        }
    }
    for у in программа.iter_mut() {
        match у {
            ВерхнийУзел::Функция(ф) => пр.функция(ф, None),
            ВерхнийУзел::Структура(с) => {
                let имя = с.имя.clone();
                for м in с.методы.iter_mut() {
                    пр.функция(м, Some(&имя));
                }
            }
            ВерхнийУзел::Глобальная { тип, значение, .. } => {
                пр.области.clear();
                пр.возврат = None;
                пр.выражение(значение);
                let т = тип.clone();
                пр.подогнать_значение(значение, &т);
            }
            _ => {}
        }
    }
}

fn programa_узлы(п: &Программа) -> impl Iterator<Item = &ВерхнийУзел> {
    п.iter()
}

impl Проход {
    fn функция(&mut self, ф: &mut ОбъявлениеФункции, структура: Option<&str>) {
        let mut область = HashMap::new();
        if let Some(с) = структура {
            область.insert("это".to_string(), Some(Тип::Пользовательский(с.to_string())));
        }
        for п in &ф.параметры {
            область.insert(п.имя.clone(), Some(п.тип.clone()));
        }
        self.области = vec![область];
        self.возврат = ф.тип_возврата.clone();
        self.блок(&mut ф.тело);
        self.области.clear();
        self.возврат = None;
    }

    fn найти(&self, имя: &str) -> Option<Тип> {
        for о in self.области.iter().rev() {
            if let Some(т) = о.get(имя) {
                return т.clone();
            }
        }
        self.глобальные.get(имя).cloned()
    }

    fn известно_имя(&self, имя: &str) -> bool {
        self.области.iter().any(|о| о.contains_key(имя)) || self.глобальные.contains_key(имя)
    }

    fn объявить(&mut self, имя: &str, т: Option<Тип>) {
        if let Some(о) = self.области.last_mut() {
            о.insert(имя.to_string(), т);
        }
    }

    fn блок(&mut self, б: &mut Блок) {
        self.области.push(HashMap::new());
        for (о, _) in б.iter_mut() {
            self.оператор(о);
        }
        self.области.pop();
    }

    fn подогнать_значение(&self, е: &mut Выражение, т: &Тип) {
        match (т, &mut *е) {
            (Тип::Массив { элемент, .. }, Выражение::МассивЛит(элементы)) => {
                for э in элементы.iter_mut() {
                    подогнать(э, элемент);
                }
            }
            (Тип::Массив { элемент, .. }, Выражение::ВызовФункции { имя, аргументы, .. }) if имя == "массив" => {
                for а in аргументы.iter_mut() {
                    подогнать(а, элемент);
                }
            }
            _ => подогнать(е, т),
        }
    }

    fn оператор(&mut self, о: &mut Оператор) {
        match о {
            Оператор::ОбъявлениеСТипом { тип, имя, значение } | Оператор::ОбъявлениеНеизменное { тип, имя, значение } => {
                self.выражение(значение);
                let т = тип.clone();
                self.подогнать_значение(значение, &т);
                let имя = имя.clone();
                self.объявить(&имя, Some(т));
            }
            Оператор::Присваивание { место, значение } => {
                self.выражение(значение);
                self.место(место);
                match self.тип_места(место) {
                    Some(т) => self.подогнать_значение(значение, &т),
                    None => {
                        if let МестоЗаписи::Имя(и) = &*место {
                            if !self.известно_имя(и) {
                                let т = self.тип_выражения(значение);
                                let и = и.clone();
                                self.объявить(&и, т);
                            }
                        }
                    }
                }
            }
            Оператор::ВыражениеОператор(е) => self.выражение(е),
            Оператор::Если { условие, тогда, иначе } => {
                self.выражение(условие);
                self.блок(тогда);
                if let Some(и) = иначе {
                    self.блок(и);
                }
            }
            Оператор::ЦиклПока { условие, тело } => {
                self.выражение(условие);
                self.блок(тело);
            }
            Оператор::ЦиклДляКаждого { переменная, коллекция, тело } => {
                self.выражение(коллекция);
                self.области.push(HashMap::new());
                let п = переменная.clone();
                self.объявить(&п, None);
                self.блок(тело);
                self.области.pop();
            }
            Оператор::Вернуть(Some(е)) => {
                self.выражение(е);
                if let Some(т) = self.возврат.clone() {
                    подогнать(е, &т);
                }
            }
            Оператор::Параллельно(тело, _) => self.блок(тело),
            Оператор::Выбрать { .. } | Оператор::Вернуть(None) | Оператор::Прервать | Оператор::Продолжить => {}
        }
    }

    fn место(&mut self, м: &mut МестоЗаписи) {
        match м {
            МестоЗаписи::Имя(_) => {}
            МестоЗаписи::Поле { объект, .. } => self.место(объект),
            МестоЗаписи::Индекс { массив, индекс } => {
                self.место(массив);
                self.выражение(индекс);
            }
        }
    }

    fn тип_места(&self, м: &МестоЗаписи) -> Option<Тип> {
        match м {
            МестоЗаписи::Имя(и) => self.найти(и),
            МестоЗаписи::Поле { объект, поле } => match self.тип_места(объект)? {
                Тип::Пользовательский(с) => self.структуры.get(&с)?.iter().find(|(п, _)| п == поле).map(|(_, т)| т.clone()),
                _ => None,
            },
            МестоЗаписи::Индекс { массив, .. } => match self.тип_места(массив)? {
                Тип::Массив { элемент, .. } => Some(*элемент),
                _ => None,
            },
        }
    }

    /// Тип выражения, только если он известен точно (иначе None).
    fn тип_выражения(&self, е: &Выражение) -> Option<Тип> {
        match е {
            Выражение::Идентификатор(и) => self.найти(и),
            Выражение::ВызовФункции { имя, аргументы, .. } => {
                if let Some(т) = тип_по_имени(имя) {
                    return Some(т);
                }
                if let Some((вид, ширина)) = crate::semantic::разобрать_аппаратную_функцию(имя) {
                    if вид == "чтение" || вид == "ввод" {
                        return match ширина {
                            8 => Some(Тип::Беззнак8),
                            16 => Some(Тип::Беззнак16),
                            32 => Some(Тип::Беззнак32),
                            64 => Some(Тип::Беззнак64),
                            _ => None,
                        };
                    }
                    return None;
                }
                if БИТОВЫЕ_ФУНКЦИИ.contains(&имя.as_str()) {
                    return аргументы.get(0).and_then(|а| self.тип_выражения(а));
                }
                match self.функции.get(имя) {
                    Some(Some(с)) => с.возврат.clone(),
                    _ => None,
                }
            }
            Выражение::Бинарное { левое, оператор, правое } => {
                if арифметический(*оператор) {
                    self.тип_выражения(левое).or_else(|| self.тип_выражения(правое))
                } else if matches!(оператор, БинарныйОператор::СдвигВлево | БинарныйОператор::СдвигВправо) {
                    self.тип_выражения(левое)
                } else {
                    None
                }
            }
            Выражение::Унарное { оператор, операнд } if matches!(оператор, УнарныйОператор::Минус | УнарныйОператор::БитНе) => {
                self.тип_выражения(операнд)
            }
            Выражение::ДоступПоИндексу { массив, .. } => match self.тип_выражения(массив)? {
                Тип::Массив { элемент, .. } => Some(*элемент),
                _ => None,
            },
            Выражение::ДоступКПолю { объект, поле } => match self.тип_выражения(объект)? {
                Тип::Пользовательский(с) => self.структуры.get(&с)?.iter().find(|(п, _)| п == поле).map(|(_, т)| т.clone()),
                _ => None,
            },
            _ => None,
        }
    }

    fn выражение(&mut self, е: &mut Выражение) {
        match е {
            Выражение::Бинарное { левое, оператор, правое } => {
                self.выражение(левое);
                self.выражение(правое);
                let о = *оператор;
                if арифметический(о) || сравнение(о) || matches!(о, БинарныйОператор::СдвигВлево | БинарныйОператор::СдвигВправо) {
                    let лт = self.тип_выражения(левое);
                    let пт = self.тип_выражения(правое);
                    if let Some(т) = лт.filter(узкое_ссылка) {
                        подогнать(правое, &т);
                    } else if let Some(т) = пт.filter(узкое_ссылка) {
                        подогнать(левое, &т);
                    }
                }
            }
            Выражение::ВызовФункции { имя, аргументы, .. } => {
                for а in аргументы.iter_mut() {
                    self.выражение(а);
                }
                let имя = имя.clone();
                self.вызов(&имя, аргументы);
            }
            Выражение::ВызовМетода { объект, метод, аргументы, .. } => {
                self.выражение(объект);
                for а in аргументы.iter_mut() {
                    self.выражение(а);
                }
                if let Some(Тип::Пользовательский(с)) = self.тип_выражения(объект) {
                    if let Some(сиг) = self.методы.get(&(с, метод.clone())) {
                        if сиг.параметры.len() == аргументы.len() {
                            for (а, т) in аргументы.iter_mut().zip(сиг.параметры.iter()) {
                                подогнать(а, т);
                            }
                        }
                    }
                }
            }
            Выражение::МассивЛит(элементы) => {
                for э in элементы.iter_mut() {
                    self.выражение(э);
                }
            }
            Выражение::ДоступКПолю { объект, .. } => self.выражение(объект),
            Выражение::ДоступПоИндексу { массив, индекс } => {
                self.выражение(массив);
                self.выражение(индекс);
            }
            Выражение::Унарное { операнд, .. } => self.выражение(операнд),
            Выражение::Проброс(в) | Выражение::Успех(в) | Выражение::Ошибка(в) => self.выражение(в),
            Выражение::ИнтерполированныйТекст(части) => {
                for ч in части.iter_mut() {
                    if let ФрагментТекста::Выражение(в) = ч {
                        self.выражение(в);
                    }
                }
            }
            _ => {}
        }
    }

    fn вызов(&self, имя: &str, аргументы: &mut Vec<Выражение>) {
        // Аппаратная запись: значение получает ширину регистра.
        if let Some((вид, ширина)) = crate::semantic::разобрать_аппаратную_функцию(имя) {
            if (вид == "запись" || вид == "вывод") && аргументы.len() == 2 {
                let т = match ширина {
                    8 => Тип::Беззнак8,
                    16 => Тип::Беззнак16,
                    32 => Тип::Беззнак32,
                    _ => return,
                };
                подогнать(&mut аргументы[1], &т);
            }
            return;
        }
        // Битовые функции: литерал берёт тип второго операнда.
        if БИТОВЫЕ_ФУНКЦИИ.contains(&имя) && аргументы.len() == 2 {
            let лт = self.тип_выражения(&аргументы[0]);
            let пт = self.тип_выражения(&аргументы[1]);
            if let Some(т) = лт.filter(узкое_ссылка) {
                подогнать(&mut аргументы[1], &т);
            } else if let Some(т) = пт.filter(узкое_ссылка) {
                подогнать(&mut аргументы[0], &т);
            }
            return;
        }
        if тип_по_имени(имя).is_some() {
            return;
        }
        if let Some(Some(с)) = self.функции.get(имя) {
            if с.параметры.len() == аргументы.len() {
                for (а, т) in аргументы.iter_mut().zip(с.параметры.iter()) {
                    подогнать(а, т);
                }
            }
            return;
        }
        // Конструктор структуры: аргументы по порядку полей.
        if let Some(поля) = self.структуры.get(имя) {
            if поля.len() == аргументы.len() {
                for (а, (_, т)) in аргументы.iter_mut().zip(поля.iter()) {
                    подогнать(а, т);
                }
            }
        }
    }
}

fn узкое_ссылка(т: &Тип) -> bool {
    узкое(т)
}
