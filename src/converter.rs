//! Конвертер СТАРОГО синтаксиса в НОВЫЙ (под русскую раскладку клавиатуры).
//!
//! Запуск:  запустить --в-русский файл.код [ещё.код ...] [--на-месте]
//!
//! Как это устроено: парсер, разбирая старый код, по ходу записывает "правки"
//! (какой токен чем заменить — см. parser::Правка). Конвертер применяет их к
//! исходному тексту (комментарии и форматирование сохраняются), а затем
//! САМ ПРОВЕРЯЕТ результат: разбирает новый текст заново и сравнивает дерево
//! программы с деревом исходной — они обязаны совпасть. Если не совпали,
//! файл не записывается, а пользователь получает сообщение об ошибке.

use crate::ast::*;
use crate::lexer::Лексер;
use crate::parser::{Парсер, ВидПравки, Правка};
use crate::token::{Token, ТокенСПозицией};
use std::collections::HashSet;

#[derive(Clone, Copy)]
struct Опции {
    без_индексов: bool,
    /// Преобразовывать и выражения внутри "${...}" в строках.
    внутри_строк: bool,
}

struct Изменение {
    начало: usize,
    конец: usize,
    текст: String,
    класс: u8,
    ключ: i64,
}

pub fn конвертировать(исходник: &str) -> Result<String, String> {
    let (токены, правки, программа) = разобрать_с_правками(исходник)?;
    let эталон = нормализованная(программа);

    let mut последнее_расхождение = String::new();
    // Варианты по убыванию "амбициозности": индексы "числа(0)" и выражения
    // внутри строк можно по отдельности отключить, если с ними дерево не сошлось.
    for (отключить_индексы, преобразовывать_внутри_строк) in [(false, true), (true, true), (false, false), (true, false)] {
        let опции = Опции { без_индексов: отключить_индексы, внутри_строк: преобразовывать_внутри_строк };
        let результат = применить(исходник, &токены, &правки, опции);
        match разобрать_простой(&результат) {
            Ok(новая) if нормализованная(новая.clone()) == эталон => return Ok(результат),
            Ok(новая) => {
                последнее_расхождение = "дерево программы после конвертации отличается от исходного".to_string();
                if std::env::var("СФЕРА_ОТЛАДКА_КОНВЕРТЕРА").is_ok() {
                    let новая = нормализованная(новая);
                    for (а, б) in эталон.iter().zip(новая.iter()) {
                        if а != б {
                            let (са, сб) = (format!("{:?}", а), format!("{:?}", б));
                            let общий = са.chars().zip(сб.chars()).take_while(|(x, y)| x == y).count();
                            let от = общий.saturating_sub(150);
                            eprintln!("РАСХОЖДЕНИЕ:\n  было: …{}\n  стало: …{}", са.chars().skip(от).take(400).collect::<String>(), сб.chars().skip(от).take(400).collect::<String>());
                            break;
                        }
                    }
                }
            }
            Err(e) => last_error(&mut последнее_расхождение, &e),
        }
    }
    if std::env::var("СФЕРА_ОТЛАДКА_КОНВЕРТЕРА").is_ok() {
        return Ok(применить(исходник, &токены, &правки, Опции { без_индексов: false, внутри_строк: true }));
    }
    Err(format!("конвертация небезопасна: {}", последнее_расхождение))
}

fn last_error(куда: &mut String, e: &str) {
    *куда = format!("новый текст не разбирается: {}", e);
}

fn разобрать_простой(исходник: &str) -> Result<Программа, String> {
    let токены = Лексер::новый(исходник).токенизировать().map_err(|e| format!("строка {}: {}", e.строка, e.сообщение))?;
    Парсер::новый(токены)
        .разобрать_программу()
        .map_err(|e| format!("строка {}, столбец {}: {}", e.строка, e.столбец, e.сообщение))
}

fn разобрать_с_правками(исходник: &str) -> Result<(Vec<ТокенСПозицией>, Vec<Правка>, Программа), String> {
    let токены = Лексер::новый(исходник).токенизировать().map_err(|e| format!("строка {}: {}", e.строка, e.сообщение))?;
    let mut парсер = Парсер::новый(токены.clone());
    парсер.записывать_правки = true;
    let программа = парсер
        .разобрать_программу()
        .map_err(|e| format!("строка {}, столбец {}: {}", e.строка, e.столбец, e.сообщение))?;
    Ok((токены, парсер.правки, программа))
}

// ---------- нормализация дерева для сравнения (номера строк не важны) ----------

fn нормализованная(mut п: Программа) -> Программа {
    for узел in п.iter_mut() {
        match узел {
            ВерхнийУзел::Функция(ф) => нормализовать_функцию(ф),
            ВерхнийУзел::Структура(с) => {
                с.позиция = None;
                for м in &mut с.методы {
                    нормализовать_функцию(м);
                }
            }
            _ => {}
        }
    }
    п
}

fn нормализовать_функцию(ф: &mut ОбъявлениеФункции) {
    ф.позиция = None;
    нормализовать_блок(&mut ф.тело);
}

fn нормализовать_блок(б: &mut Блок) {
    for (о, строка) in б.iter_mut() {
        *строка = 0;
        match о {
            Оператор::Если { тогда, иначе, .. } => {
                нормализовать_блок(тогда);
                if let Some(и) = иначе {
                    нормализовать_блок(и);
                }
            }
            Оператор::ЦиклДляКаждого { тело, .. } | Оператор::ЦиклПока { тело, .. } => нормализовать_блок(тело),
            Оператор::Параллельно(тело, _) => нормализовать_блок(тело),
            _ => {}
        }
    }
}

// ---------- применение правок ----------

fn применить(исходник: &str, токены: &[ТокенСПозицией], правки: &[Правка], опции: Опции) -> String {
    let без_индексов = опции.без_индексов;
    let текст: Vec<char> = исходник.chars().collect();
    let mut изменения: Vec<Изменение> = Vec::new();
    let mut тронутые: HashSet<usize> = HashSet::new();

    let пробел = |c: char| c == ' ' || c == '\t';
    // Начало диапазона после отбрасывания пробелов слева — но только если
    // перед пробелами что-то есть на этой же строке (отступ не трогаем).
    let без_пробелов_слева = |начало: usize| -> usize {
        let mut к = начало;
        while к > 0 && пробел(текст[к - 1]) {
            к -= 1;
        }
        if к == 0 || текст[к - 1] == '\n' {
            начало
        } else {
            к
        }
    };

    // --- группы угловых скобок: определить безопасные ---
    let группы: Vec<(usize, &Vec<usize>, usize, bool)> = правки
        .iter()
        .filter_map(|п| match п {
            Правка::Группа { откр, запятые, закр, объявление } => Some((*откр, запятые, *закр, *объявление)),
            _ => None,
        })
        .collect();
    let откр_групп: Vec<usize> = группы.iter().map(|г| г.0).collect();
    let безопасна = |г: &(usize, &Vec<usize>, usize, bool)| -> bool {
        // Если не последний аргумент сам обобщённый, "и" станет неоднозначным.
        let (откр, запятые, _, _) = *г;
        let mut начало = откр + 1;
        for &з in запятые.iter() {
            if откр_групп.iter().any(|&о| о >= начало && о < з) {
                return false;
            }
            начало = з + 1;
        }
        true
    };

    for п in правки {
        match п {
            Правка::Заменить { токен, текст: новый, прижать, окружить, вид } => {
                if без_индексов && *вид == ВидПравки::Индекс {
                    continue;
                }
                тронутые.insert(*токен);
                let т = &токены[*токен];
                let начало = if *прижать { без_пробелов_слева(т.начало) } else { т.начало };
                let mut новый_текст = новый.clone();
                if *окружить && т.конец < текст.len() && !текст[т.конец].is_whitespace() {
                    новый_текст.push(' ');
                }
                изменения.push(Изменение { начало, конец: т.конец, текст: новый_текст, класс: 2, ключ: 0 });
            }
            Правка::Удалить { токен, и_справа } => {
                тронутые.insert(*токен);
                изменения.push(удаление(&текст, &токены[*токен], *и_справа, &без_пробелов_слева));
            }
            Правка::ВставитьПеред { токен, текст: новый, ключ } => {
                let т = &токены[*токен];
                изменения.push(Изменение { начало: т.начало, конец: т.начало, текст: новый.clone(), класс: 1, ключ: -(*ключ as i64) });
            }
            Правка::ВставитьПосле { токен, текст: новый, ключ } => {
                let т = &токены[*токен];
                изменения.push(Изменение { начало: т.конец, конец: т.конец, текст: новый.clone(), класс: 0, ключ: *ключ as i64 });
            }
            Правка::Склеить { токен } => {
                let т = &токены[*токен];
                let следующий = &токены[*токен + 1];
                if текст[т.конец..следующий.начало].iter().all(|c| c.is_whitespace()) {
                    изменения.push(Изменение { начало: т.конец, конец: следующий.начало, текст: " ".to_string(), класс: 2, ключ: 0 });
                }
            }
            Правка::Группа { .. } => {}
        }
    }

    for г in &группы {
        let (откр, запятые, закр, объявление) = (г.0, г.1, г.2, г.3);
        тронутые.insert(откр);
        тронутые.insert(закр);
        for &з in запятые.iter() {
            тронутые.insert(з);
        }
        if !безопасна(г) {
            continue;
        }
        let т = &токены[откр];
        изменения.push(Изменение { начало: без_пробелов_слева(т.начало), конец: т.конец, текст: " из ".to_string(), класс: 2, ключ: 0 });
        for &з in запятые.iter() {
            let т = &токены[з];
            let mut новый = " и".to_string();
            if т.конец < текст.len() && !текст[т.конец].is_whitespace() {
                новый.push(' ');
            }
            изменения.push(Изменение { начало: без_пробелов_слева(т.начало), конец: т.конец, текст: новый, класс: 2, ключ: 0 });
        }
        let т = &токены[закр];
        let после_скобкой = т.конец < текст.len() && текст[т.конец] == '(';
        изменения.push(Изменение {
            начало: без_пробелов_слева(т.начало),
            конец: т.конец,
            текст: if объявление && после_скобкой { " ".to_string() } else { String::new() },
            класс: 2,
            ключ: 0,
        });
    }

    // --- токены-операторы и строки ---
    for (номер, т) in токены.iter().enumerate() {
        if тронутые.contains(&номер) {
            continue;
        }
        let исходный_символ = текст.get(т.начало).copied().unwrap_or(' ');
        let слово = match &т.токен {
            Token::И if исходный_символ == '&' => Some("и"),
            Token::Или if исходный_символ == '|' => Some("или"),
            Token::Не if исходный_символ == '!' => Some("не"),
            Token::МеньшеРавно => Some("не больше"),
            Token::БольшеРавно => Some("не меньше"),
            Token::Меньше if исходный_символ == '<' => Some("меньше"),
            Token::Больше if исходный_символ == '>' => Some("больше"),
            _ => None,
        };
        if let Some(слово) = слово {
            let mut новый = String::new();
            if т.начало > 0 && !текст[т.начало - 1].is_whitespace() {
                новый.push(' ');
            }
            новый.push_str(слово);
            if т.конец < текст.len() && !текст[т.конец].is_whitespace() {
                новый.push(' ');
            }
            изменения.push(Изменение { начало: т.начало, конец: т.конец, текст: новый, класс: 2, ключ: 0 });
        }
        if let Token::ТекстЛит(_) = &т.токен {
            let сырой: Vec<char> = текст[т.начало + 1..т.конец - 1].to_vec();
            if сырой.iter().any(|&c| c == '$') {
                let новый = преобразовать_строку(&сырой, опции);
                изменения.push(Изменение { начало: т.начало + 1, конец: т.конец - 1, текст: новый, класс: 2, ключ: 0 });
            }
        }
    }

    // --- применить ---
    изменения.sort_by(|a, b| (a.начало, a.класс, a.ключ).cmp(&(b.начало, b.класс, b.ключ)));
    let mut вывод = String::new();
    let mut курсор = 0usize;
    for и in &изменения {
        let начало = и.начало.max(курсор);
        if начало > курсор {
            вывод.extend(&текст[курсор..начало]);
        }
        вывод.push_str(&и.текст);
        курсор = и.конец.max(курсор);
    }
    вывод.extend(&текст[курсор.min(текст.len())..]);
    вывод
}

fn удаление(
    текст: &[char],
    т: &ТокенСПозицией,
    и_справа: bool,
    без_пробелов_слева: &dyn Fn(usize) -> usize,
) -> Изменение {
    let пробел = |c: char| c == ' ' || c == '\t';
    if и_справа {
        let mut к = т.конец;
        while к < текст.len() && пробел(текст[к]) {
            к += 1;
        }
        return Изменение { начало: т.начало, конец: к, текст: String::new(), класс: 2, ключ: 0 };
    }
    let начало = без_пробелов_слева(т.начало);
    // токен — единственное на своей строке: убираем строку целиком
    let mut левый_край = т.начало;
    while левый_край > 0 && пробел(текст[левый_край - 1]) {
        левый_край -= 1;
    }
    let на_начале_строки = левый_край == 0 || текст[левый_край - 1] == '\n';
    let mut правый_край = т.конец;
    while правый_край < текст.len() && пробел(текст[правый_край]) {
        правый_край += 1;
    }
    let до_конца_строки = правый_край >= текст.len() || текст[правый_край] == '\n' || текст[правый_край] == '\r';
    if на_начале_строки && до_конца_строки {
        let mut конец = правый_край;
        if конец < текст.len() && текст[конец] == '\r' {
            конец += 1;
        }
        if конец < текст.len() && текст[конец] == '\n' {
            конец += 1;
        }
        return Изменение { начало: левый_край, конец, текст: String::new(), класс: 2, ключ: 0 };
    }
    Изменение { начало, конец: т.конец, текст: String::new(), класс: 2, ключ: 0 }
}

/// "$имя" -> "%имя%", "${выражение}" -> "%(выражение)%". Знаки "%" не трогаем:
/// правила "%" действуют в компиляторе для любого кода, и старого тоже.
fn преобразовать_строку(сырой: &[char], опции: Опции) -> String {
    let начало_имени = |c: char| c.is_alphabetic() || c == '_';
    let часть_имени = |c: char| c.is_alphanumeric() || c == '_';
    let mut вывод = String::new();
    let mut и = 0;
    while и < сырой.len() {
        let c = сырой[и];
        if c == '\\' && и + 1 < сырой.len() {
            вывод.push(c);
            вывод.push(сырой[и + 1]);
            и += 2;
        } else if c == '$' && и + 1 < сырой.len() && сырой[и + 1] == '{' {
            let mut глубина = 1usize;
            let mut к = и + 2;
            while к < сырой.len() && глубина > 0 {
                match сырой[к] {
                    '{' => глубина += 1,
                    '}' => глубина -= 1,
                    _ => {}
                }
                if глубина > 0 {
                    к += 1;
                }
            }
            if глубина > 0 {
                вывод.push(c);
                и += 1;
            } else {
                вывод.push_str("%(");
                let внутри: String = сырой[и + 2..к].iter().collect();
                if опции.внутри_строк {
                    вывод.push_str(&конвертировать_выражение(&внутри, опции).unwrap_or(внутри));
                } else {
                    вывод.push_str(&внутри);
                }
                вывод.push_str(")%");
                и = к + 1;
            }
        } else if c == '$' && и + 1 < сырой.len() && начало_имени(сырой[и + 1]) {
            let mut к = и + 1;
            while к < сырой.len() && часть_имени(сырой[к]) {
                к += 1;
            }
            вывод.push('%');
            вывод.extend(&сырой[и + 1..к]);
            вывод.push('%');
            и = к;
        } else {
            вывод.push(c);
            и += 1;
        }
    }
    вывод
}

/// Конвертирует одиночное выражение (из "${...}"): заворачивает в
/// временную функцию, применяет правки и достаёт выражение обратно.
fn конвертировать_выражение(выражение: &str, опции: Опции) -> Option<String> {
    let обёртка = format!("функция _в() {{ вернуть {}; }}", выражение);
    let (токены, правки, _) = разобрать_с_правками(&обёртка).ok()?;
    let результат = применить(&обёртка, &токены, &правки, опции);
    let от = результат.find("вернуть ")? + "вернуть ".len();
    let до = результат.rfind("; конец")?;
    if до < от {
        return None;
    }
    Some(результат[от..до].to_string())
}
