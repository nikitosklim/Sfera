//! Лексер — первый этап компиляции. Читает исходный код как обычный текст
//! и превращает его в последовательность токенов, понятную парсеру.
//!
//! Мы работаем с Vec<char>, а не с байтами напрямую — потому что кириллица
//! в UTF-8 занимает 2 байта на символ, и если наивно индексировать по байтам,
//! легко разрезать символ пополам и получить мусор. Vec<char> избавляет
//! от этой головной боли: один char = один символ, независимо от алфавита.

use crate::token::{Token, ТокенСПозицией};

pub struct Лексер {
    символы: Vec<char>,
    позиция: usize,
    строка: usize,
    столбец: usize,
}

#[derive(Debug)]
pub struct ОшибкаЛексера {
    pub сообщение: String,
    pub строка: usize,
    pub столбец: usize,
}

impl Лексер {
    pub fn новый(исходный_код: &str) -> Self {
        Лексер {
            символы: исходный_код.chars().collect(),
            позиция: 0,
            строка: 1,
            столбец: 1,
        }
    }

    /// Главный метод — прогоняет весь текст и возвращает список токенов
    /// либо первую встреченную ошибку.
    pub fn токенизировать(&mut self) -> Result<Vec<ТокенСПозицией>, ОшибкаЛексера> {
        let mut токены = Vec::new();

        loop {
            self.пропустить_пробелы_и_комментарии();

            let строка = self.строка;
            let столбец = self.столбец;

            let символ = match self.текущий() {
                Some(c) => c,
                None => {
                    токены.push(ТокенСПозицией {
                        токен: Token::КонецФайла,
                        строка,
                        столбец,
                    });
                    break;
                }
            };

            let токен = if символ.is_ascii_digit() {
                self.читать_число()?
            } else if символ == '"' {
                self.читать_текст()?
            } else if является_началом_идентификатора(символ) {
                self.читать_идентификатор_или_ключевое_слово()
            } else {
                self.читать_оператор_или_разделитель()?
            };

            токены.push(ТокенСПозицией {
                токен,
                строка,
                столбец,
            });
        }

        Ok(токены)
    }

    // --- Вспомогательные методы навигации по символам ---

    fn текущий(&self) -> Option<char> {
        self.символы.get(self.позиция).copied()
    }

    fn заглянуть_вперёд(&self, смещение: usize) -> Option<char> {
        self.символы.get(self.позиция + смещение).copied()
    }

    fn продвинуться(&mut self) -> Option<char> {
        let символ = self.текущий();
        if let Some(c) = символ {
            self.позиция += 1;
            if c == '\n' {
                self.строка += 1;
                self.столбец = 1;
            } else {
                self.столбец += 1;
            }
        }
        символ
    }

    fn пропустить_пробелы_и_комментарии(&mut self) {
        loop {
            match self.текущий() {
                Some(c) if c.is_whitespace() => {
                    self.продвинуться();
                }
                Some('/') if self.заглянуть_вперёд(1) == Some('/') => {
                    // однострочный комментарий — до конца строки
                    while let Some(c) = self.текущий() {
                        if c == '\n' {
                            break;
                        }
                        self.продвинуться();
                    }
                }
                Some('/') if self.заглянуть_вперёд(1) == Some('*') => {
                    // многострочный комментарий — до */
                    self.продвинуться(); // /
                    self.продвинуться(); // *
                    loop {
                        match self.текущий() {
                            None => break, // TODO: незакрытый комментарий — сейчас молча обрываем
                            Some('*') if self.заглянуть_вперёд(1) == Some('/') => {
                                self.продвинуться();
                                self.продвинуться();
                                break;
                            }
                            _ => {
                                self.продвинуться();
                            }
                        }
                    }
                }
                _ => break,
            }
        }
    }

    // --- Разбор чисел (целое_литерал / дробное_литерал из грамматики) ---

    fn читать_число(&mut self) -> Result<Token, ОшибкаЛексера> {
        let mut текст = String::new();
        let mut дробное = false;

        while let Some(c) = self.текущий() {
            if c.is_ascii_digit() {
                текст.push(c);
                self.продвинуться();
            } else if c == '.' && !дробное && self.заглянуть_вперёд(1).map_or(false, |n| n.is_ascii_digit()) {
                // точка — часть числа, только если после неё цифра
                // (иначе это могло бы быть, например, "5.метод()" в будущем)
                дробное = true;
                текст.push(c);
                self.продвинуться();
            } else {
                break;
            }
        }

        if дробное {
            текст.parse::<f64>()
                .map(Token::ДробноеЛит)
                .map_err(|_| ОшибкаЛексера {
                    сообщение: format!("не удалось разобрать дробное число: {}", текст),
                    строка: self.строка,
                    столбец: self.столбец,
                })
        } else {
            текст.parse::<i64>()
                .map(Token::ЦелоеЛит)
                .map_err(|_| ОшибкаЛексера {
                    сообщение: format!("не удалось разобрать целое число: {}", текст),
                    строка: self.строка,
                    столбец: self.столбец,
                })
        }
    }

    // --- Разбор текстовых литералов ---
    // Пока без интерполяции на уровне лексера — $имя и ${выражение} внутри строки
    // сохраняем как есть, разбирать их будем на этапе парсера/семантического анализа.
    // Так проще: лексер не должен знать о выражениях, это его нарушало бы однослойность.

    fn читать_текст(&mut self) -> Result<Token, ОшибкаЛексера> {
        let начальная_строка = self.строка;
        let начальный_столбец = self.столбец;

        self.продвинуться(); // открывающая "

        let mut текст = String::new();
        loop {
            match self.текущий() {
                None => {
                    return Err(ОшибкаЛексера {
                        сообщение: "незакрытый текстовый литерал".to_string(),
                        строка: начальная_строка,
                        столбец: начальный_столбец,
                    });
                }
                Some('"') => {
                    self.продвинуться();
                    break;
                }
                Some('\\') => {
                    // экранированные последовательности
                    self.продвинуться();
                    match self.текущий() {
                        Some('n') => { текст.push('\n'); self.продвинуться(); }
                        Some('t') => { текст.push('\t'); self.продвинуться(); }
                        Some('"') => { текст.push('"'); self.продвинуться(); }
                        Some('\\') => { текст.push('\\'); self.продвинуться(); }
                        Some('$') => { текст.push('$'); self.продвинуться(); }
                        Some(other) => {
                            // неизвестный escape — сохраняем как есть, не считаем фатальной ошибкой
                            текст.push('\\');
                            текст.push(other);
                            self.продвинуться();
                        }
                        None => {
                            return Err(ОшибкаЛексера {
                                сообщение: "незакрытый текстовый литерал (обрыв после \\)".to_string(),
                                строка: начальная_строка,
                                столбец: начальный_столбец,
                            });
                        }
                    }
                }
                Some(c) => {
                    текст.push(c);
                    self.продвинуться();
                }
            }
        }

        Ok(Token::ТекстЛит(текст))
    }

    // --- Разбор идентификаторов и ключевых слов ---

    fn читать_идентификатор_или_ключевое_слово(&mut self) -> Token {
        let mut текст = String::new();

        while let Some(c) = self.текущий() {
            if является_частью_идентификатора(c) {
                текст.push(c);
                self.продвинуться();
            } else {
                break;
            }
        }

        сопоставить_ключевое_слово(&текст)
    }

    // --- Операторы и разделители ---

    fn читать_оператор_или_разделитель(&mut self) -> Result<Token, ОшибкаЛексера> {
        let строка = self.строка;
        let столбец = self.столбец;
        let c = self.продвинуться().unwrap();

        let токен = match c {
            '+' => Token::Плюс,
            '-' => {
                if self.текущий() == Some('>') {
                    self.продвинуться();
                    Token::Стрелка
                } else {
                    Token::Минус
                }
            }
            '*' => Token::Звёздочка,
            '/' => Token::Слэш, // деление; // и /* уже отфильтрованы как комментарии выше
            '%' => Token::Процент,
            '=' => {
                if self.текущий() == Some('=') {
                    self.продвинуться();
                    Token::РавноРавно
                } else {
                    Token::Равно
                }
            }
            '!' => {
                if self.текущий() == Some('=') {
                    self.продвинуться();
                    Token::НеРавно
                } else {
                    Token::Не
                }
            }
            '<' => {
                if self.текущий() == Some('=') {
                    self.продвинуться();
                    Token::МеньшеРавно
                } else {
                    Token::Меньше
                }
            }
            '>' => {
                if self.текущий() == Some('=') {
                    self.продвинуться();
                    Token::БольшеРавно
                } else {
                    Token::Больше
                }
            }
            '&' => {
                if self.текущий() == Some('&') {
                    self.продвинуться();
                    Token::И
                } else {
                    return Err(ОшибкаЛексера {
                        сообщение: "ожидался '&&', одиночный '&' пока не поддерживается".to_string(),
                        строка,
                        столбец,
                    });
                }
            }
            '|' => {
                if self.текущий() == Some('|') {
                    self.продвинуться();
                    Token::Или
                } else {
                    return Err(ОшибкаЛексера {
                        сообщение: "ожидался '||', одиночный '|' пока не поддерживается".to_string(),
                        строка,
                        столбец,
                    });
                }
            }
            '?' => Token::Вопрос,
            '$' => Token::Доллар,
            '{' => Token::ОткрФигурная,
            '}' => Token::ЗакрФигурная,
            '(' => Token::ОткрКруглая,
            ')' => Token::ЗакрКруглая,
            '[' => Token::ОткрКвадратная,
            ']' => Token::ЗакрКвадратная,
            '.' => Token::Точка,
            ',' => Token::Запятая,
            ';' => Token::ТочкаЗапятой,
            ':' => Token::Двоеточие,
            other => {
                return Err(ОшибкаЛексера {
                    сообщение: format!("неожиданный символ: '{}'", other),
                    строка,
                    столбец,
                });
            }
        };

        Ok(токен)
    }
}

/// Может ли символ быть ПЕРВЫМ символом идентификатора.
/// Разрешаем русские и латинские буквы, а также подчёркивание.
/// Цифра не может начинать идентификатор (грамматика, раздел 2).
fn является_началом_идентификатора(c: char) -> bool {
    c.is_alphabetic() || c == '_'
}

/// Может ли символ быть частью идентификатора (не первым).
fn является_частью_идентификатора(c: char) -> bool {
    c.is_alphanumeric() || c == '_'
}

/// Сопоставляет прочитанное слово с ключевым словом языка,
/// либо возвращает его как обычный идентификатор, если совпадений нет.
fn сопоставить_ключевое_слово(текст: &str) -> Token {
    match текст {
        "функция" => Token::Функция,
        "структура" => Token::Структура,
        "внешняя" => Token::Внешняя,
        "как" => Token::Как,
        "контракт" => Token::Контракт,
        "подключить" => Token::Подключить,
        "если" => Token::Если,
        "иначе" => Token::Иначе,
        "для" => Token::Для,
        "каждого" => Token::Каждого,
        "в" => Token::В,
        "пока" => Token::Пока,
        "вернуть" => Token::Вернуть,
        "публично" => Token::Публично,
        "приватно" => Token::Приватно,
        "результат" => Token::Результат,
        "успех" => Token::Успех,
        "ошибка" => Token::Ошибка,
        "слабая" => Token::Слабая,
        "неизменно" => Token::Неизменно,
        "ссылка" => Token::Ссылка,
        "параллельно" => Token::Параллельно,
        "канал" => Token::Канал,
        "это" => Token::Это,

        "целое" => Token::Целое,
        "целое8" => Token::Целое8,
        "целое16" => Token::Целое16,
        "целое32" => Token::Целое32,
        "целое64" => Token::Целое64,
        "беззнак8" => Token::Беззнак8,
        "беззнак16" => Token::Беззнак16,
        "беззнак32" => Token::Беззнак32,
        "беззнак64" => Token::Беззнак64,
        "дробное" => Token::Дробное,
        "дробное32" => Token::Дробное32,
        "дробное64" => Token::Дробное64,
        "текст" => Token::Текст,
        "верно" => Token::Верно,

        "да" => Token::ВерноЛит(true),
        "нет" => Token::ВерноЛит(false),
        "неуказано" => Token::НеуказаноЛит,

        other => Token::Идентификатор(other.to_string()),
    }
}
