    println!("сфера_пакеты — управление зависимостями языка «Сфера»");
    println!();
    println!("Команды:");
    println!("  установить   Читает 'сфера.зависимости' в текущей папке, клонирует");
    println!("               и устанавливает все перечисленные пакеты в 'пакеты/'.");
    println!("  список       Показывает уже установленные пакеты (файлы в 'пакеты/').");
    println!("  удалить ИМЯ  Убирает файл пакета и его метаданные из 'пакеты/'.");
