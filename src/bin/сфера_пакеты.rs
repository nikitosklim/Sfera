/// Домашняя папка пользователя — где хранится ЛИЧНАЯ, не-проектная
/// настройка (адрес индекса) и локальный кэш индекса. Не "пакеты/" (та
/// папка — для зависимостей ОДНОГО проекта) и не переменная окружения
/// (чтобы не приходилось выставлять её в каждом новом терминале) — один
/// раз настроил командой "индекс-настроить", и оно запоминается.
/// Кроссплатформенно: $HOME на macOS/Linux, %USERPROFILE% на Windows —
/// тот же самый разработчик уже работает и там, и там (см. профиль).
fn домашняя_папка() -> Result<PathBuf, String> {
    std::env::var("HOME")
        .or_else(|_| std::env::var("USERPROFILE"))
        .map(PathBuf::from)
        .map_err(|_| "не удалось определить домашнюю папку (нет ни HOME, ни USERPROFILE)".to_string())
}

fn папка_настроек_сферы() -> Result<PathBuf, String> {
    Ok(домашняя_папка()?.join(".сфера"))
}

fn путь_файла_с_адресом_индекса() -> Result<PathBuf, String> {
    Ok(папка_настроек_сферы()?.join("индекс_url.txt"))
}

fn путь_кэша_индекса() -> Result<PathBuf, String> {
    Ok(папка_настроек_сферы()?.join("индекс"))
}

/// НОВОЕ: "сфера_пакеты индекс-настроить URL" — запоминает git-адрес
/// публичного индекса один раз на машину. Явно валидирует, что URL хоть
/// что-то похожее на адрес (не пустая строка) — дальше git сам честно
/// пожалуется, если адрес неверный, при первом "индекс-обновить".
fn настроить_индекс(url: Option<&str>) -> Result<(), String> {
    let url = url
        .filter(|s| !s.trim().is_empty())
        .ok_or_else(|| "укажи адрес индекса: сфера_пакеты индекс-настроить URL_ИНДЕКСА".to_string())?;

    let папка_настроек = папка_настроек_сферы()?;
    fs::create_dir_all(&папка_настроек)
        .map_err(|e| format!("не удалось создать '{}': {}", папка_настроек.display(), e))?;

    fs::write(путь_файла_с_адресом_индекса()?, url)
        .map_err(|e| format!("не удалось сохранить адрес индекса: {}", e))?;

    println!("Индекс настроен: {}", url);
    println!("Дальше — 'сфера_пакеты индекс-обновить', чтобы скачать его локально.");
    Ok(())
}

/// Читает сохранённый ранее адрес индекса — с честной, конкретной
/// ошибкой (что именно сделать), если он ещё не настроен, а не просто
/// "файл не найден".
fn прочитать_url_индекса() -> Result<String, String> {
    let путь = путь_файла_с_адресом_индекса()?;
    fs::read_to_string(&путь)
        .map(|s| s.trim().to_string())
        .map_err(|_| {
            "адрес индекса ещё не настроен — сначала: сфера_пакеты индекс-настроить URL_ИНДЕКСА"
                .to_string()
        })
}

/// НОВОЕ: "сфера_пакеты индекс-обновить" — клонирует (в первый раз) или
/// обновляет (git pull, если уже клонирован) локальную копию индекса.
/// Тот же приём "клонировать во временную папку", что и установка
/// обычного пакета, но здесь результат — не "пакеты/", а постоянный,
/// переиспользуемый локальный кэш (~/.сфера/индекс/), потому что индекс
/// один и тот же для ВСЕХ проектов на этой машине, а не для одного.
fn обновить_индекс() -> Result<(), String> {
    let url = прочитать_url_индекса()?;
    let путь_кэша = путь_кэша_индекса()?;

    if путь_кэша.join(".git").exists() {
        println!("Обновляю локальную копию индекса ({})...", url);
        let вывод = Command::new("git")
            .arg("-C")
            .arg(&путь_кэша)
            .arg("pull")
            .arg("--ff-only")
            .output()
            .map_err(|e| format!("не удалось запустить git: {}", e))?;
        if !вывод.status.success() {
            return Err(format!(
                "git pull не удался: {}",
                String::from_utf8_lossy(&вывод.stderr)
            ));
        }
    } else {
        println!("Скачиваю индекс впервые ({})...", url);
        if путь_кэша.exists() {
            fs::remove_dir_all(&путь_кэша).ok();
        }
        fs::create_dir_all(путь_кэша.parent().unwrap_or(Path::new(".")))
            .map_err(|e| format!("не удалось создать папку настроек: {}", e))?;
        let вывод = Command::new("git")
            .arg("clone")
            .arg("--depth")
            .arg("1")
            .arg(&url)
            .arg(&путь_кэша)
            .output()
            .map_err(|e| format!("не удалось запустить git (установлен ли он?): {}", e))?;
        if !вывод.status.success() {
            return Err(format!(
                "git clone индекса не удался: {}",
                String::from_utf8_lossy(&вывод.stderr)
            ));
        }
    }

    let число_пакетов = прочитать_каталог_индекса(&путь_кэша)?.len();
    println!("Готово: в индексе {} пакет(ов).", число_пакетов);
    Ok(())
}

/// Единственный файл каталога внутри репозитория индекса — тот же
/// формат строк, что и у "сфера.зависимости" самого проекта (см.
/// разобрать_манифест) — сознательно один и тот же парсер на оба
/// случая: это один и тот же по сути список "имя -> откуда брать", просто
/// один — общий, для поиска, другой — для одного конкретного проекта.
const ИМЯ_ФАЙЛА_КАТАЛОГА: &str = "каталог.пакеты";

fn прочитать_каталог_индекса(путь_кэша: &Path) -> Result<Vec<Зависимость>, String> {
    let путь_каталога = путь_кэша.join(ИМЯ_ФАЙЛА_КАТАЛОГА);
    if !путь_каталога.exists() {
        return Err(format!(
            "в индексе не найден файл каталога '{}' — это не тот репозиторий, или его формат ещё не готов",
            ИМЯ_ФАЙЛА_КАТАЛОГА
        ));
    }
    let содержимое = fs::read_to_string(&путь_каталога)
        .map_err(|e| format!("не удалось прочитать '{}': {}", путь_каталога.display(), e))?;
    разобрать_манифест(&содержимое)
}

/// Загружает каталог, автоматически скачивая индекс в первый раз, если
/// локального кэша ещё нет — так "искать"/"добавить" работают сразу
/// после "индекс-настроить", без обязательного отдельного шага.
fn загрузить_каталог_с_автообновлением() -> Result<Vec<Зависимость>, String> {
    let путь_кэша = путь_кэша_индекса()?;
    if !путь_кэша.join(ИМЯ_ФАЙЛА_КАТАЛОГА).exists() {
        обновить_индекс()?;
    }
    прочитать_каталог_индекса(&путь_кэша)
}

/// НОВОЕ: "сфера_пакеты искать ЗАПРОС" — простой, регистронезависимый
/// поиск подстроки по имени пакета и по его описанию (не по URL — искать
/// по ссылке всё равно бессмысленно, её и так не подберёшь по памяти).
fn искать_в_индексе(запрос: Option<&str>) -> Result<(), String> {
    let запрос = запрос.ok_or_else(|| {
        "укажи, что искать: сфера_пакеты искать ЗАПРОС".to_string()
    })?;
    let запрос_нижний = запрос.to_lowercase();

    let каталог = загрузить_каталог_с_автообновлением()?;
    let найдено: Vec<&Зависимость> = каталог
        .iter()
        .filter(|з| {
            з.имя.to_lowercase().contains(&запрос_нижний)
                || з
                    .описание
                    .as_ref()
                    .map(|о| о.to_lowercase().contains(&запрос_нижний))
                    .unwrap_or(false)
        })
        .collect();

    if найдено.is_empty() {
        println!("Ничего не найдено по запросу '{}'.", запрос);
        return Ok(());
    }

    println!("Найдено ({}):", найдено.len());
    for з in найдено {
        println!("  {}", з.имя);
        println!("    {}", з.url);
        if let Some(описание) = &з.описание {
            println!("    {}", описание);
        }
        println!();
    }
    println!("Установить: добавь в 'сфера.зависимости' командой 'сфера_пакеты добавить ИМЯ'.");
    Ok(())
}

/// НОВОЕ: "сфера_пакеты добавить ИМЯ" — находит ИМЯ в индексе (точное
/// совпадение, не поиск по подстроке — в отличие от "искать", здесь
/// нужен ровно один, однозначный пакет) и дописывает готовую строку
/// зависимости в "сфера.зависимости" текущего проекта, создавая файл,
/// если его ещё не было. Не устанавливает сам пакет — специально: между
/// "добавить в манифест" и "реально накатить в пакеты/" всегда остаётся
/// отдельный, явный шаг "сфера_пакеты установить" (тот же принцип
/// "явное лучше неявного", что и у cargo add/npm install без --save
/// в некоторых версиях — проще понимать, что произошло, по одной команде
/// за раз, чем гадать, что именно сделала одна всё-в-одном команда).
fn добавить_из_индекса(имя: Option<&str>) -> Result<(), String> {
    let имя = имя.ok_or_else(|| {
        "укажи имя пакета: сфера_пакеты добавить ИМЯ".to_string()
    })?;

    let каталог = загрузить_каталог_с_автообновлением()?;
    let найденные: Vec<&Зависимость> = каталог.iter().filter(|з| з.имя == имя).collect();

    let зависимость = match найденные.as_slice() {
        [] => {
            return Err(format!(
                "пакет '{}' не найден в индексе — проверь имя ('сфера_пакеты искать {}') или обнови индекс ('сфера_пакеты индекс-обновить')",
                имя, имя
            ))
        }
        [единственная] => единственная,
        несколько => {
            return Err(format!(
                "в индексе {} записей с именем '{}' — сообщите об этом ведущему индекса, это ошибка каталога, не должно происходить",
                несколько.len(), имя
            ))
        }
    };

    let манифест_путь = Path::new("сфера.зависимости");
    let существующее_содержимое = fs::read_to_string(манифест_путь).unwrap_or_default();

    // Не дублируем — если зависимость с таким именем уже есть в
    // манифесте (неважно, установлена она уже или нет), не трогаем
    // файл, а честно об этом сообщаем, вместо тихого дублирования строк.
    let уже_есть = существующее_содержимое
        .lines()
        .any(|строка| строка.trim().split('=').next().map(str::trim) == Some(имя));
    if уже_есть {
        println!(
            "'{}' уже есть в 'сфера.зависимости' — ничего не меняю.",
            имя
        );
        return Ok(());
    }

    let mut новая_строка = format!("{} = git {}", зависимость.имя, зависимость.url);
    if let Some(ветка) = &зависимость.ветка {
        новая_строка.push_str(&format!(" ветка={}", ветка));
    }
    if let Some(версия) = &зависимость.версия {
        новая_строка.push_str(&format!(" версия={}", версия));
    }
    if let Some(описание) = &зависимость.описание {
        новая_строка.push_str(&format!(" описание=\"{}\"", описание));
    }

    let новое_содержимое = if существующее_содержимое.is_empty() {
        format!("{}\n", новая_строка)
    } else if существующее_содержимое.ends_with('\n') {
        format!("{}{}\n", существующее_содержимое, новая_строка)
    } else {
        format!("{}\n{}\n", существующее_содержимое, новая_строка)
    };

    fs::write(манифест_путь, новое_содержимое)
        .map_err(|e| format!("не удалось записать 'сфера.зависимости': {}", e))?;

    println!("Добавлено в 'сфера.зависимости': {}", новая_строка);
    println!("Дальше — 'сфера_пакеты установить', чтобы реально его поставить.");
    Ok(())
}
