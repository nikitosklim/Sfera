/// Одна зависимость, разобранная из файла манифеста.
#[derive(Clone)]
struct Зависимость {
    имя: String,
    url: String,
    ветка: Option<String>,
    /// НОВОЕ: "версия=X.Y.Z" (точная версия — она же имя git-тега,
    /// передаётся в `git clone --branch` НАПРЯМУЮ) ИЛИ "версия=^X.Y.Z" /
    /// "версия=~X.Y.Z" (ДИАПАЗОН — не имя тега, а требование, которое
    /// нужно РАЗРЕШИТЬ в конкретный тег через `git ls-remote --tags`
    /// перед клонированием, см. разрешить_диапазон_версии). В обоих
    /// случаях дополнительно участвует в разрешении конфликтов при
    /// транзитивных зависимостях (см. установить_зависимости) — если
    /// два места в дереве зависимостей просят один и тот же пакет с
    /// одного и того же адреса, но разных версий — требования ПЕРЕСЕКАЮТСЯ
    /// как диапазоны (настоящий constraint solving, см. Диапазон,
    /// пересечь_диапазоны), а не просто "большая побеждает".
    /// Взаимоисключает `ветка` на одной строке манифеста — семантика
    /// "какая версия" и "какая ветка" разные вещи, смешивать их в одном
    /// поле было бы нечестно.
    версия: Option<String>,
    /// НОВОЕ: необязательное человекочитаемое описание пакета — если
    /// указано в манифесте, сохраняется в метаданные при установке и
    /// показывается командой "список" — раньше список показывал только
    /// голые имена файлов, без единого слова о том, что пакет вообще
    /// делает.
    описание: Option<String>,
}

/// Разбирает файл "сфера.зависимости" — простой, построчный формат
/// (не JSON/TOML — намеренно: минимум кода, полный контроль, без новых
/// зависимостей в Cargo.toml, соответствует общей философии проекта
/// "строить самим и понимать каждую часть").
fn разобрать_манифест(содержимое: &str) -> Result<Vec<Зависимость>, String> {
    let mut зависимости = Vec::new();

    for (номер_строки, строка) in содержимое.lines().enumerate() {
        let строка = строка.trim();
        if строка.is_empty() || строка.starts_with('#') {
            continue;
        }

        let (имя, остальное) = строка.split_once('=').ok_or_else(|| {
            format!(
                "строка {}: ожидался формат 'имя = git URL [ветка=ИМЯ] [описание=\"текст\"]', получено: '{}'",
                номер_строки + 1,
                строка
            )
        })?;
        let имя = имя.trim().to_string();
        let остальное = остальное.trim();

        // НОВОЕ: "описание=\"...\"" может содержать пробелы внутри кавычек
        // — извлекаем его ДО обычного разбиения по пробелам, иначе
        // split_whitespace ниже разорвал бы описание на куски.
        let (остальное_без_описания, описание) = извлечь_описание(остальное, номер_строки + 1)?;

        let части: Vec<&str> = остальное_без_описания.split_whitespace().collect();
        if части.len() < 2 || части[0] != "git" {
            return Err(format!(
                "строка {}: пока поддерживается только 'git URL' (другие источники — следующий шаг), получено: '{}'",
                номер_строки + 1,
                остальное
            ));
        }
        let url = части[1].to_string();

        let mut ветка = None;
        let mut версия = None;
        for часть in &части[2..] {
            if let Some(значение) = часть.strip_prefix("ветка=") {
                ветка = Some(значение.to_string());
            } else if let Some(значение) = часть.strip_prefix("версия=") {
                версия = Some(значение.to_string());
            }
        }
        if ветка.is_some() && версия.is_some() {
            return Err(format!(
                "строка {}: 'ветка=' и 'версия=' взаимоисключающие — укажи только одно ('версия' — если это семантическая версия вида X.Y.Z, для разрешения конфликтов; 'ветка' — для произвольного git-рефа)",
                номер_строки + 1
            ));
        }

        зависимости.push(Зависимость { имя, url, ветка, версия, описание });
    }

    Ok(зависимости)
}

/// Ищет "описание=\"текст внутри кавычек\"" где-то в строке — возвращает
/// (остаток строки без этого куска, найденное описание). Простой, ручной
/// разбор — та же философия, что и у всего формата манифеста: минимум
/// кода, полный контроль, без библиотек для парсинга строк в кавычках.
fn извлечь_описание(остальное: &str, номер_строки: usize) -> Result<(String, Option<String>), String> {
    let маркер = "описание=\"";
    if let Some(начало_маркера) = остальное.find(маркер) {
        let после_маркера = &остальное[начало_маркера + маркер.len()..];
        let конец_кавычки = после_маркера.find('"').ok_or_else(|| {
            format!(
                "строка {}: не найдена закрывающая кавычка у 'описание=\"...'",
                номер_строки
            )
        })?;
        let текст_описания = после_маркера[..конец_кавычки].to_string();
        let до = &остальное[..начало_маркера];
        let после = &после_маркера[конец_кавычки + 1..];
        let без_описания = format!("{} {}", до, после);
        Ok((без_описания, Some(текст_описания)))
    } else {
        Ok((остальное.to_string(), None))
    }
}

fn установить_зависимости(обновить_блокировку: bool) -> Result<(), String> {
    let манифест_путь = Path::new("сфера.зависимости");
    if !манифест_путь.exists() {
        return Err(
            "файл 'сфера.зависимости' не найден в текущей папке — создайте его \
             (см. 'сфера_пакеты' без аргументов для примера формата)"
                .to_string(),
        );
    }

    let содержимое = fs::read_to_string(манифест_путь)
        .map_err(|e| format!("не удалось прочитать 'сфера.зависимости': {}", e))?;
    let корневые_зависимости = разобрать_манифест(&содержимое)?;

    if корневые_зависимости.is_empty() {
        println!("Файл 'сфера.зависимости' не содержит ни одной зависимости.");
        // Пустой манифест — значит и блокировать нечего; убираем файл
        // блокировки, если он остался от предыдущего, непустого манифеста
        // (иначе он бы честно не отражал текущее состояние проекта).
        let путь_блокировки = Path::new("сфера.блокировка");
        if путь_блокировки.exists() {
            fs::remove_file(путь_блокировки).ok();
        }
        return Ok(());
    }

    // НОВОЕ — файл блокировки ("сфера.блокировка"): тот же формат, что и у
    // манифеста (переиспользуем разобрать_манифест — отдельного парсера не
    // нужно), но каждая строка здесь всегда уже разрешённая, конкретная
    // версия (никогда ^/~), записанная предыдущим успешным "установить".
    // Цель — воспроизводимость: повторная установка на другой машине (или
    // через время, когда в репозитории пакета появились новые теги)
    // должна ставить ТЕ ЖЕ версии, а не тихо "уехать" на более новые внутри
    // того же диапазона. Отсутствие файла или ошибка его разбора —
    // НЕ фатальны: честное предупреждение и обычная работа без блокировки
    // (файл будет создан/пересоздан заново в конце этой же установки).
    let путь_блокировки = Path::new("сфера.блокировка");
    let блокировка: HashMap<String, Зависимость> = if обновить_блокировку {
        HashMap::new()
    } else if путь_блокировки.exists() {
        match fs::read_to_string(путь_блокировки)
            .map_err(|e| e.to_string())
            .and_then(|содержимое| разобрать_манифест(&содержимое))
        {
            Ok(записи) => записи.into_iter().map(|з| (з.имя.clone(), з)).collect(),
            Err(ошибка) => {
                println!(
                    "⚠️  не удалось прочитать 'сфера.блокировка' ({}) — игнорирую её и \
                     разрешаю версии заново (файл будет пересоздан по итогам этой установки).",
                    ошибка
                );
                HashMap::new()
            }
        }
    } else {
        HashMap::new()
    };

    let папка_пакетов = Path::new("пакеты");
    fs::create_dir_all(папка_пакетов)
        .map_err(|e| format!("не удалось создать папку 'пакеты/': {}", e))?;

    // BFS по дереву зависимостей — см. объяснение в архитектурном
    // комментарии в самом верху файла. Очередь хранит саму зависимость и,
    // необязательно, имя пакета, ЧЕРЕЗ который она была обнаружена (None
    // — зависимость объявлена прямо в корневом "сфера.зависимости").
    let mut очередь: VecDeque<(Зависимость, Option<String>)> =
        корневые_зависимости.into_iter().map(|з| (з, None)).collect();
    // имя_пакета -> уже выбранный источник (URL + версия, если удалось её
    // разобрать как семвер) — единственный источник истины для обнаружения
    // повторов, конфликтов и решения "нужно ли обновить уже установленный
    // пакет до более новой запрошенной версии".
    let mut известные: HashMap<String, ВыбранныйПакет> = HashMap::new();
    // НОВОЕ — защита при удалении: имя_пакета -> имена ВСЕХ пакетов,
    // которые в ходе ЭТОГО обхода хоть раз объявили его своей
    // зависимостью — не только первого (в отличие от одиночного
    // "транзитивная_через" в метаданных, см. установить_одну_зависимость).
    // Копится независимо от того, привёл ли конкретный запрос к
    // (пере)установке или был тихо пропущен как дубликат — иначе второй и
    // последующие требователи одного и того же пакета были бы невидимы.
    // Записывается в метаданные отдельным проходом после обхода (см.
    // ниже) и используется командой "удалить" для честного предупреждения.
    let mut требуется_кем: HashMap<String, Vec<String>> = HashMap::new();

    let mut счётчик_прямых = 0;
    let mut счётчик_транзитивных = 0;
    let mut счётчик_обновлений = 0;

    while let Some((исходная_зависимость, через)) = очередь.pop_front() {
        // Записываем требователя ДО любых match/continue ниже — даже если
        // этот конкретный запрос окажется дубликатом и будет пропущен, сам
        // факт "родитель просит этот пакет" должен остаться зафиксирован.
        if let Some(родитель) = &через {
            let список = требуется_кем.entry(исходная_зависимость.имя.clone()).or_default();
            if !список.contains(родитель) {
                список.push(родитель.clone());
            }
        }

        // Требование ЭТОГО конкретного запроса — разбирается без похода в
        // сеть. Голая "версия=X.Y.Z" (без ^/~), "ветка=..." или отсутствие
        // версии вовсе дают None у диапазона — тогда, как и раньше,
        // пересекать нечего, сравниваем как умеем (см. ветку "_" ниже).
        let новое_требование = исходная_зависимость
            .версия
            .as_deref()
            .and_then(разобрать_требование_версии);
        let новый_диапазон = новое_требование.as_ref().map(диапазон_из_требования);

        // Клонируем нужные поля уже известной записи ДО дальнейшей работы —
        // разрешить_версию_пакета (сетевой поход) и последующая вставка в
        // "известные" не могут держать заимствование известные.get(...).
        let существующая_запись = известные.get(&исходная_зависимость.имя).map(|п| {
            (
                п.url.clone(),
                п.диапазон,
                п.семвер,
                п.версия_строка.clone(),
                п.через.clone(),
            )
        });

        if let Some((текущий_url, _, _, _, текущий_через)) = &существующая_запись {
            if *текущий_url != исходная_зависимость.url {
                // НОВОЕ — конфликт РАЗНЫХ АДРЕСОВ под одним именем пакета
                // (в отличие от версионного конфликта ниже) больше не
                // тихо разрешается "первый встреченный побеждает" — это
                // не версия одного и того же кода, а буквально разные
                // репозитории, и молча выбрать один означало бы, что
                // проект соберётся не с тем кодом, который кто-то из
                // авторов дерева зависимостей на самом деле имел в виду,
                // без единого шанса это заметить. Честно проваливаем ВСЮ
                // установку с понятной ошибкой, называющей оба адреса и
                // через каких пакетов каждый из них был запрошен —
                // разработчик должен разрешить это САМ (переименовать
                // один из пакетов в своём сфера.зависимости, или
                // убедиться, что оба места дерева действительно должны
                // ссылаться на один и тот же репозиторий).
                return Err(format!(
                    "пакет '{}' запрошен из двух РАЗНЫХ адресов в дереве зависимостей — это не \
                     версионный конфликт (тот разрешается автоматически, см. 'версия='), а буквально \
                     разный код, и сфера_пакеты не может честно выбрать один из них сама:\n\
                     \x20 - {}{}\n\
                     \x20 - {}{}\n\
                     Разрешите это вручную — например, дайте одному из пакетов другое имя в том \
                     'сфера.зависимости', где он объявлен, или убедитесь, что оба места дерева \
                     действительно должны указывать на один и тот же репозиторий.",
                    исходная_зависимость.имя,
                    текущий_url,
                    текущий_через
                        .as_ref()
                        .map(|р| format!(" (запрошен через пакет '{}')", р))
                        .unwrap_or_else(|| " (запрошен напрямую в корневом сфера.зависимости)".to_string()),
                    исходная_зависимость.url,
                    через
                        .as_ref()
                        .map(|р| format!(" (запрошен через пакет '{}')", р))
                        .unwrap_or_else(|| " (запрошен напрямую в корневом сфера.зависимости)".to_string()),
                ));
            }
        }

        let mut является_обновлением = false;

        let (зависимость, новый_семвер, диапазон_для_записи) = match &существующая_запись {
            None => {
                // Пакет встречается впервые в этом обходе — разрешать
                // диапазон против чего-либо ещё не нужно, пересекать не с
                // чем. Точная версия по-прежнему используется как имя
                // git-тега напрямую, без похода в сеть — поведение не
                // изменилось.
                match &новое_требование {
                    Some(ТребованиеВерсии::Точная(семвер)) => {
                        (исходная_зависимость.clone(), Some(*семвер), новый_диапазон)
                    }
                    Some(ТребованиеВерсии::Каре(_)) | Some(ТребованиеВерсии::Тильда(_)) => {
                        let интервал = новый_диапазон.unwrap();
                        let исходный_текст = исходная_зависимость.версия.clone().unwrap();
                        let (тег, семвер) = разрешить_версию_пакета(
                            &исходная_зависимость.имя,
                            &исходная_зависимость.url,
                            &исходный_текст,
                            &интервал,
                            &блокировка,
                        )?;
                        let мут_зависимость = Зависимость {
                            версия: Some(тег),
                            ..исходная_зависимость.clone()
                        };
                        (мут_зависимость, Some(семвер), Some(интервал))
                    }
                    None => (исходная_зависимость.clone(), None, None),
                }
            }
            Some((_, текущий_диапазон, текущий_семвер, текущая_версия_строка, _)) => {
                match (текущий_диапазон, &новый_диапазон) {
                    (Some(старый), Some(новый)) => {
                        // НАСТОЯЩЕЕ пересечение диапазонов версий — сердце
                        // constraint solving. Если требования из разных мест
                        // дерева зависимостей не пересекаются вовсе, это
                        // доказуемый конфликт: не существует версии,
                        // удовлетворяющей ОБОИМ требованиям одновременно —
                        // и установка честно проваливается, вместо того
                        // чтобы молча выбрать бОльшую версию (как было
                        // раньше).
                        let итог = пересечь_диапазоны(старый, новый).ok_or_else(|| {
                            format!(
                                "настоящий конфликт версий пакета '{}': требования из разных мест \
                                 дерева зависимостей не пересекаются — уже выбран интервал {} (версия \
                                 {}){}, а новый запрос требует интервал {}{} — не существует версии, \
                                 удовлетворяющей ОБОИМ требованиям одновременно. Разрешите это \
                                 вручную — ослабьте одно из требований версии в 'сфера.зависимости', \
                                 или явно зафиксируйте нужную версию.",
                                исходная_зависимость.имя,
                                диапазон_в_текст(старый),
                                текущая_версия_строка.as_deref().unwrap_or("?"),
                                существующая_запись
                                    .as_ref()
                                    .and_then(|(_, _, _, _, ч)| ч.clone())
                                    .map(|р| format!(" (запрошен через пакет '{}')", р))
                                    .unwrap_or_else(|| " (запрошен напрямую в корневом сфера.зависимости)".to_string()),
                                диапазон_в_текст(новый),
                                через
                                    .as_ref()
                                    .map(|р| format!(" (запрошен транзитивно через пакет '{}')", р))
                                    .unwrap_or_else(|| " (запрошен напрямую в корневом сфера.зависимости)".to_string()),
                            )
                        })?;

                        if текущий_семвер.map_or(false, |в| диапазон_содержит(&итог, в)) {
                            // Уже выбранная версия по-прежнему подходит под
                            // СУЖЕННЫЙ (пересечённый) интервал —
                            // переустанавливать не нужно, только запоминаем
                            // более узкий диапазон на будущее (следующие
                            // требования будут пересекаться уже с ним, а не
                            // с исходным, более широким).
                            известные.insert(
                                исходная_зависимость.имя.clone(),
                                ВыбранныйПакет {
                                    url: исходная_зависимость.url.clone(),
                                    версия_строка: текущая_версия_строка.clone(),
                                    семвер: *текущий_семвер,
                                    диапазон: Some(итог),
                                    через: существующая_запись.as_ref().and_then(|(_, _, _, _, ч)| ч.clone()),
                                },
                            );
                            continue;
                        }

                        // Диапазон сузился так, что уже выбранная версия
                        // больше не подходит — разрешаем заново, в пределах
                        // ИТОГОВОГО (пересечённого) интервала.
                        println!(
                            "'{}' — пересечение диапазонов версий сузило допустимый интервал до {} — \
                             уже выбранная версия ({}) больше не подходит, разрешаю заново.",
                            исходная_зависимость.имя,
                            диапазон_в_текст(&итог),
                            текущая_версия_строка.as_deref().unwrap_or("?"),
                        );
                        let текст_для_сообщений = format!("пересечение диапазонов {}", диапазон_в_текст(&итог));
                        let (тег, семвер) = разрешить_версию_пакета(
                            &исходная_зависимость.имя,
                            &исходная_зависимость.url,
                            &текст_для_сообщений,
                            &итог,
                            &блокировка,
                        )?;
                        является_обновлением = true;
                        let мут_зависимость = Зависимость {
                            версия: Some(тег),
                            ..исходная_зависимость.clone()
                        };
                        (мут_зависимость, Some(семвер), Some(итог))
                    }
                    _ => {
                        // Хотя бы одно из требований (старое или новое) не
                        // сравнимо как семвер (ветка, отсутствие версии, или
                        // нераспознаваемая строка) — пересекать нечего, как
                        // и раньше: честно сообщаем и оставляем уже
                        // выбранную версию.
                        if *текущая_версия_строка == исходная_зависимость.версия {
                            // Буквально тот же запрос повторно — обычный,
                            // тихий повтор, не о чем предупреждать.
                            continue;
                        }
                        println!(
                            "⚠️  '{}' запрошен снова{}, но версии нельзя однозначно сравнить ('{}' и '{}') — \
                             оставляю уже выбранную; автоматическое пересечение диапазонов работает только \
                             для версий вида X.Y.Z (и диапазонов ^/~ от них) у пакетов с одного и того же \
                             адреса.",
                            исходная_зависимость.имя,
                            через.as_ref().map(|р| format!(" (транзитивно, через '{}')", р)).unwrap_or_default(),
                            исходная_зависимость.версия.as_deref().unwrap_or("(без версии)"),
                            текущая_версия_строка.as_deref().unwrap_or("(без версии)"),
                        );
                        continue;
                    }
                }
            }
        };

        известные.insert(
            зависимость.имя.clone(),
            ВыбранныйПакет {
                url: зависимость.url.clone(),
                версия_строка: зависимость.версия.clone(),
                семвер: новый_семвер,
                диапазон: диапазон_для_записи,
                через: через.clone(),
            },
        );

        if является_обновлением {
            счётчик_обновлений += 1;
        } else {
            match &через {
                Some(_) => счётчик_транзитивных += 1,
                None => счётчик_прямых += 1,
            }
        }

        match &через {
            Some(родитель) => {
                println!(
                    "Устанавливаю '{}' из {}... (транзитивная зависимость пакета '{}')",
                    зависимость.имя, зависимость.url, родитель
                );
            }
            None => {
                println!("Устанавливаю '{}' из {}...", зависимость.имя, зависимость.url);
            }
        }

        let транзитивные_зависимости =
            установить_одну_зависимость(&зависимость, папка_пакетов, через.as_deref())?;
        for транз in транзитивные_зависимости {
            очередь.push_back((транз, Some(зависимость.имя.clone())));
        }
    }

    // НОВОЕ — защита при удалении: отдельным проходом ПОСЛЕ всего обхода
    // (не по ходу установки каждого пакета — см. комментарий у объявления
    // требуется_кем выше) дописываем в метаданные каждого пакета полный,
    // накопленный список требователей. Патчим существующий файл метаданных
    // (написанный установить_одну_зависимость чуть раньше), а не
    // перезаписываем его целиком — остальные поля (источник, версия,
    // описание, транзитивная_через) должны остаться нетронутыми.
    for (имя_пакета, требователи) in &требуется_кем {
        if требователи.is_empty() || !известные.contains_key(имя_пакета) {
            continue;
        }
        let путь_метаданных = папка_пакетов.join(имя_пакета).join(".метаданные");
        let существующее = fs::read_to_string(&путь_метаданных).unwrap_or_default();
        let без_старого_поля: String = существующее
            .lines()
            .filter(|строка| !строка.starts_with("требуется_пакетами="))
            .map(|строка| format!("{}\n", строка))
            .collect();
        let новое_содержимое = format!(
            "{}требуется_пакетами={}\n",
            без_старого_поля,
            требователи.join(",")
        );
        fs::write(&путь_метаданных, новое_содержимое)
            .map_err(|e| format!("не удалось обновить метаданные '{}': {}", имя_пакета, e))?;
    }

    // НОВОЕ — файл блокировки: перезаписываем "сфера.блокировка" целиком
    // из ИТОГОВОЙ карты "известные" — тот же формат, что и у манифеста
    // (разобрать_манифест умеет читать его обратно без отдельного
    // парсера), но только для пакетов, у которых удалось разобрать
    // семвер (версия= — точная или диапазон, разрешённый в тег). Пакеты
    // на "ветка=" или вовсе без версии сюда не попадают — зафиксировать
    // ветку "как версию" было бы нечестно (ветки двигаются, это не
    // семвер, и git clone --branch и так всегда берёт её текущую голову).
    // Полная перезапись (а не патч построчно) означает, что пакет,
    // убранный из "сфера.зависимости", естественно пропадает из
    // блокировки на следующей же установке — без отдельной чистки.
    let замки: Vec<(&String, &ВыбранныйПакет)> = известные
        .iter()
        .filter(|(_, пакет)| пакет.семвер.is_some() && пакет.версия_строка.is_some())
        .collect();
    if замки.is_empty() {
        if путь_блокировки.exists() {
            fs::remove_file(путь_блокировки).ok();
        }
    } else {
        let mut имена: Vec<&String> = замки.iter().map(|(имя, _)| *имя).collect();
        имена.sort();
        let mut содержимое_блокировки = String::from(
            "# Автоматически создано и перезаписывается командой 'установить' — не редактировать \
             руками (следующая установка перезапишет). Формат тот же, что и у 'сфера.зависимости',\n\
             # но версии здесь ВСЕГДА уже разрешённые, конкретные теги (никогда ^/~) — так повторная \
             установка (на любой машине) ставит ТЕ ЖЕ версии, а не тихо более новые внутри диапазона.\n\
             # Чтобы сознательно обновиться до новейших версий, удовлетворяющих диапазонам манифеста,\n\
             # запусти 'сфера_пакеты установить --обновить-блокировку'.\n",
        );
        for имя in имена {
            let (_, пакет) = замки.iter().find(|(и, _)| *и == имя).unwrap();
            содержимое_блокировки.push_str(&format!(
                "{} = git {} версия={}\n",
                имя,
                пакет.url,
                пакет.версия_строка.as_deref().unwrap()
            ));
        }
        fs::write(путь_блокировки, содержимое_блокировки)
            .map_err(|e| format!("не удалось записать 'сфера.блокировка': {}", e))?;
    }

    println!(
        "\nГотово: установлено пакетов — {} (из них {} — транзитивно, {} — обновлено до более новой запрошенной версии).",
        счётчик_прямых + счётчик_транзитивных,
        счётчик_транзитивных,
        счётчик_обновлений
    );
    Ok(())
}

/// Уже выбранный (для текущего запуска "установить") источник одного
/// имени пакета — см. установить_зависимости.
struct ВыбранныйПакет {
    url: String,
    версия_строка: Option<String>,
    семвер: Option<СемВер>,
    /// НОВОЕ — настоящее пересечение диапазонов версий (constraint
    /// solving): накопленный интервал версий, удовлетворяющий ВСЕМ
    /// требованиям, встреченным для этого пакета до сих пор (не только
    /// самому первому) — каждое новое требование ПЕРЕСЕКАЕТСЯ с этим
    /// интервалом (см. пересечь_диапазоны), сужая его. None — версия
    /// этого пакета не сравнима вообще (ветка или неразборчивая строка) —
    /// тогда сравнение не производится, как и раньше.
    диапазон: Option<Диапазон>,
    /// НОВОЕ — для честного сообщения об ошибке при конфликте разных
    /// адресов под одним именем (см. установить_зависимости): через какой
    /// пакет была обнаружена ИМЕННО эта, выбранная запись (None — прямо
    /// из корневого "сфера.зависимости").
    через: Option<String>,
}

/// Простая семантическая версия (major.minor.patch) — ровно то, что нужно
/// для сравнения "какая версия новее", без внешних библиотек (та же
/// философия минимального кода без новых зависимостей в Cargo.toml, что и
/// у остального сфера_пакеты). НЕ полный семвер по спецификации semver.org
/// — сознательно не различает пререлизы/build-метаданные (`-rc1`, `+build5`
/// отбрасываются целиком перед сравнением) — честное упрощение, а не
/// незамеченный пробел.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
struct СемВер(u64, u64, u64);

/// Разбирает строку вида "1.2.3" или "v1.2.3" в СемВер. Возвращает None,
/// если строка не в этом формате (тогда версии из манифеста нельзя
/// использовать для автоматического сравнения — см. вызывающий код).
fn разобрать_семвер(текст: &str) -> Option<СемВер> {
    let без_v = текст.strip_prefix('v').unwrap_or(текст);
    // Отбрасываем пререлиз/build-метаданные ("1.2.3-rc1", "1.2.3+build5")
    // — сравниваем только основную тройку чисел.
    let основная_часть = без_v.split(['-', '+']).next().unwrap_or(без_v);
    let части: Vec<&str> = основная_часть.split('.').collect();
    if части.len() != 3 {
        return None;
    }
    let большая = части[0].parse::<u64>().ok()?;
    let малая = части[1].parse::<u64>().ok()?;
    let патч = части[2].parse::<u64>().ok()?;
    Some(СемВер(большая, малая, патч))
}

/// НОВОЕ — диапазоны версий: требование к версии из манифеста, не только
/// точное совпадение. `^X.Y.Z` (каре, как в npm/cargo) и `~X.Y.Z`
/// (тильда) — не имена git-тегов сами по себе, а требования, которые
/// нужно РАЗРЕШИТЬ в конкретный тег через git ls-remote (см.
/// разрешить_диапазон_версии), в отличие от голого `X.Y.Z`, которое
/// по-прежнему используется как имя тега напрямую.
#[derive(Clone, Copy)]
enum ТребованиеВерсии {
    Точная(СемВер),
    /// `^X.Y.Z` — совместимые версии в духе npm/cargo: если major > 0,
    /// разрешено `>=X.Y.Z` при том же major; если major == 0 и minor > 0
    /// — `>=0.Y.Z` при том же minor; если major == 0 и minor == 0 —
    /// разрешён только точно тот же patch (после 0.0.Z менять нечего,
    /// не считается совместимым ничего, кроме самого Z).
    Каре(СемВер),
    /// `~X.Y.Z` — только патч-версии внутри того же major.minor:
    /// `>=X.Y.Z`, `<X.(Y+1).0`.
    Тильда(СемВер),
}

/// Разбирает поле "версия=..." из манифеста в требование — точную версию
/// или диапазон. None, если это не распознаваемый семвер вообще (тогда
/// поле используется как есть, как имя git-рефа, без всякого сравнения —
/// см. установить_зависимости).
fn разобрать_требование_версии(текст: &str) -> Option<ТребованиеВерсии> {
    if let Some(остаток) = текст.strip_prefix('^') {
        разобрать_семвер(остаток).map(ТребованиеВерсии::Каре)
    } else if let Some(остаток) = текст.strip_prefix('~') {
        разобрать_семвер(остаток).map(ТребованиеВерсии::Тильда)
    } else {
        разобрать_семвер(текст).map(ТребованиеВерсии::Точная)
    }
}

/// НОВОЕ — настоящее пересечение диапазонов версий (constraint solving),
/// а не просто "выбирается большая версия, с предупреждением, если она на
/// самом деле не подходит" (см. архитектурный комментарий про разрешение
/// версионных конфликтов в начале файла — так было ДО этого изменения).
///
/// Единое представление: полуоткрытый интервал версий [ниж, верх) — нижняя
/// граница ВКЛЮЧЕНА, верхняя ИСКЛЮЧЕНА (None у верхней — "и выше", без
/// потолка). Любое ТребованиеВерсии (точное/каре/тильда) конвертируется в
/// такой интервал через диапазон_из_требования — и дальше ВСЕ требования к
/// одному и тому же пакету, встреченные в дереве зависимостей, ПЕРЕСЕКАЮТСЯ
/// друг с другом (пересечь_диапазоны), а не просто сравниваются "какая
/// версия больше". Если пересечение оказывается пустым — это НАСТОЯЩИЙ,
/// доказуемый конфликт (два места дерева просят версий, которых не
/// существует одновременно), и установка честно проваливается с ошибкой,
/// а не выбирает большую версию вслепую.
#[derive(Clone, Copy, Debug)]
struct Диапазон {
    ниж: СемВер,
    /// Верхняя граница, ИСКЛЮЧЕНА. None — верхней границы нет вообще (в
    /// этой кодовой базе ни одно текущее ТребованиеВерсии такого не
    /// порождает — у точного/каре/тильды всегда есть потолок — но
    /// представление оставлено общим на случай будущих требований вида
    /// ">=X.Y.Z" без верхней границы).
    верх: Option<СемВер>,
}

/// Версия, идущая сразу за данной по patch — используется как ИСКЛЮЧЁННАЯ
/// верхняя граница точного требования "=X.Y.Z": интервал [v, v+1патч)
/// содержит РОВНО одну версию v, поскольку версии здесь дискретны
/// (целочисленная тройка), а не непрерывны.
fn следующий_патч(в: СемВер) -> СемВер {
    СемВер(в.0, в.1, в.2 + 1)
}

/// Конвертирует одно требование версии (из ОДНОГО места дерева
/// зависимостей) в интервал — та же арифметика границ, что раньше жила
/// внутри удовлетворяет(...), только выражена как границы интервала, а не
/// как предикат "подходит/не подходит" одной конкретной версии.
fn диапазон_из_требования(т: &ТребованиеВерсии) -> Диапазон {
    match т {
        ТребованиеВерсии::Точная(в) => Диапазон { ниж: *в, верх: Some(следующий_патч(*в)) },
        ТребованиеВерсии::Каре(в) => {
            let верх = if в.0 > 0 {
                СемВер(в.0 + 1, 0, 0)
            } else if в.1 > 0 {
                СемВер(0, в.1 + 1, 0)
            } else {
                следующий_патч(*в)
            };
            Диапазон { ниж: *в, верх: Some(верх) }
        }
        ТребованиеВерсии::Тильда(в) => Диапазон { ниж: *в, верх: Some(СемВер(в.0, в.1 + 1, 0)) },
    }
}

/// Проверяет, попадает ли конкретная версия (например, версия реально
/// существующего git-тега) в интервал.
fn диапазон_содержит(д: &Диапазон, кандидат: СемВер) -> bool {
    кандидат >= д.ниж && д.верх.map_or(true, |в| кандидат < в)
}

/// Пересечение двух интервалов версий — сердце настоящего constraint
/// solving. None означает, что интервалы НЕ пересекаются вовсе — то есть
/// не существует версии, удовлетворяющей ОБОИМ требованиям одновременно
/// (настоящий, доказуемый конфликт, а не "выбираем большую и
/// предупреждаем", как было раньше).
fn пересечь_диапазоны(а: &Диапазон, б: &Диапазон) -> Option<Диапазон> {
    let ниж = а.ниж.max(б.ниж);
    let верх = match (а.верх, б.верх) {
        (Some(x), Some(y)) => Some(x.min(y)),
        (Some(x), None) => Some(x),
        (None, Some(y)) => Some(y),
        (None, None) => None,
    };
    if let Some(в) = верх {
        if ниж >= в {
            return None; // пустое пересечение — конфликт
        }
    }
    Some(Диапазон { ниж, верх })
}

/// Человекочитаемое представление интервала для сообщений об ошибках и
/// логов, например ">=1.2.0, <2.0.0".
fn диапазон_в_текст(д: &Диапазон) -> String {
    match д.верх {
        Some(в) => format!(">={}.{}.{}, <{}.{}.{}", д.ниж.0, д.ниж.1, д.ниж.2, в.0, в.1, в.2),
        None => format!(">={}.{}.{}", д.ниж.0, д.ниж.1, д.ниж.2),
    }
}

/// НОВОЕ — разрешает версию пакета для ИНТЕРВАЛА (не для одного исходного
/// ТребованиеВерсии): сначала пробует переиспользовать зафиксированный в
/// "сфера.блокировка" тег (если он для того же адреса и его версия всё ещё
/// попадает в интервал), иначе идёт в сеть через разрешить_диапазон_версии.
/// Единая точка входа, используемая и при первом появлении пакета в обходе
/// (интервал — диапазон его собственного, единственного требования), и при
/// повторном разрешении после того, как пересечение с другим требованием из
/// дерева зависимостей сузило интервал и уже выбранная версия перестала в
/// него попадать (интервал — уже ПЕРЕСЕЧЁННЫЙ результат, см.
/// пересечь_диапазоны и установить_зависимости).
fn разрешить_версию_пакета(
    имя_пакета: &str,
    url: &str,
    текст_требования: &str,
    интервал: &Диапазон,
    блокировка: &HashMap<String, Зависимость>,
) -> Result<(String, СемВер), String> {
    // Диапазон в манифесте мог с тех пор ужесточиться, или у пакета мог
    // появиться более новый тег (не участвующий тут намеренно — блокировка
    // для того и существует, чтобы такие новые теги НЕ подхватывались сами
    // по себе) — если зафиксированный тег БОЛЬШЕ не попадает в интервал
    // (например, интервал сузили пересечением с новым требованием),
    // разрешаем заново и позже перезапишем блокировку актуальным
    // результатом.
    let из_блокировки = блокировка.get(имя_пакета).and_then(|зафиксированный| {
        if зафиксированный.url != url {
            return None;
        }
        let семвер_зафиксированного = зафиксированный.версия.as_deref().and_then(разобрать_семвер)?;
        if диапазон_содержит(интервал, семвер_зафиксированного) {
            Some((зафиксированный.версия.clone().unwrap(), семвер_зафиксированного))
        } else {
            None
        }
    });

    match из_блокировки {
        Some((тег, семвер)) => {
            println!(
                "'{}' — {} взято из 'сфера.блокировка': тег '{}' (без обращения к git ls-remote).",
                имя_пакета, текст_требования, тег
            );
            Ok((тег, семвер))
        }
        None => {
            let (тег, семвер) = разрешить_диапазон_версии(url, текст_требования, интервал)?;
            println!("'{}' — {} разрешено в тег '{}'.", имя_пакета, текст_требования, тег);
            Ok((тег, семвер))
        }
    }
}

/// НОВОЕ — разрешает диапазон версии (`^X.Y.Z`/`~X.Y.Z`) в конкретный,
/// реально существующий git-тег: спрашивает у удалённого репозитория
/// список тегов (`git ls-remote --tags`, БЕЗ полного клонирования — это
/// быстрая, лёгкая сетевая операция, не скачивание всего репозитория),
/// разбирает имена тегов как семвер (тот же разобрать_семвер, с
/// необязательным ведущим "v" — "v1.2.3" и "1.2.3" оба распознаются) и
/// выбирает НАИБОЛЬШУЮ версию, удовлетворяющую требованию. Возвращает имя
/// тега (для клонирования) и его разобранную версию (для дальнейшего
/// сравнения при разрешении конфликтов).
fn разрешить_диапазон_версии(
    url: &str,
    исходное_требование: &str,
    диапазон: &Диапазон,
) -> Result<(String, СемВер), String> {
    let вывод = Command::new("git")
        .arg("ls-remote")
        .arg("--tags")
        .arg(url)
        .output()
        .map_err(|e| format!("не удалось запустить git (установлен ли он?): {}", e))?;
    if !вывод.status.success() {
        return Err(format!(
            "git ls-remote не удался для '{}': {}",
            url,
            String::from_utf8_lossy(&вывод.stderr)
        ));
    }

    let текст = String::from_utf8_lossy(&вывод.stdout);
    let mut лучший: Option<(String, СемВер)> = None;
    for строка in текст.lines() {
        let Some((_sha, реф)) = строка.split_once('\t') else {
            continue;
        };
        let Some(имя_тега) = реф.strip_prefix("refs/tags/") else {
            continue;
        };
        // Аннотированные теги git отдаёт ДВАЖДЫ — сам тег и
        // "разыменованный" `имя^{}`, указывающий на тот же коммит.
        // Отрезаем суффикс, иначе один и тот же тег попал бы в список
        // дважды (не влияет на выбор максимума, но задваивает работу).
        let имя_тега = имя_тега.strip_suffix("^{}").unwrap_or(имя_тега);

        if let Some(версия_тега) = разобрать_семвер(имя_тега) {
            if диапазон_содержит(диапазон, версия_тега) {
                let это_новый_максимум = лучший
                    .as_ref()
                    .map(|(_, текущая)| версия_тега > *текущая)
                    .unwrap_or(true);
                if это_новый_максимум {
                    лучший = Some((имя_тега.to_string(), версия_тега));
                }
            }
        }
    }

    лучший.ok_or_else(|| {
        format!(
            "не найден ни один git-тег в '{}', удовлетворяющий требованию версии '{}' (интервал {}) — \
             проверь, что у пакета вообще есть теги в формате semver ('X.Y.Z' или 'vX.Y.Z')",
            url, исходное_требование, диапазон_в_текст(диапазон)
        )
    })
}

/// Устанавливает один пакет и возвращает список ЕГО СОБСТВЕННЫХ
/// зависимостей (пустой, если у пакета нет своего "сфера.зависимости") —
/// вызывающая сторона (установить_зависимости) решает, что с ними делать
/// дальше (обход в ширину), эта функция знает только про один, текущий
/// пакет. "родитель" — только для записи в метаданные (см. ниже), на
/// логику установки не влияет.
fn установить_одну_зависимость(
    зависимость: &Зависимость,
    папка_пакетов: &Path,
    родитель: Option<&str>,
) -> Result<Vec<Зависимость>, String> {
    let временная_папка = std::env::temp_dir().join(format!("сфера_пакет_{}", std::process::id()));
    if временная_папка.exists() {
        fs::remove_dir_all(&временная_папка).ok();
    }

    let mut команда = Command::new("git");
    команда.arg("clone").arg("--depth").arg("1");
    // "версия=X.Y.Z" технически — то же самое, что и "ветка=..." для git
    // (передаётся в --branch, git не различает ветки/теги на этом
    // уровне) — просто ДОПОЛНИТЕЛЬНО разбирается как семвер для
    // разрешения конфликтов (см. установить_зависимости). Само поле
    // "версия" должно совпадать с точным именем git-тега в репозитории
    // пакета — сфера_пакеты не угадывает и не перебирает варианты вроде
    // "с 'v' или без" (см. честное ограничение ниже).
    if let Some(реф) = зависимость.ветка.as_ref().or(зависимость.версия.as_ref()) {
        команда.arg("--branch").arg(реф);
    }
    команда.arg(&зависимость.url).arg(&временная_папка);

    let вывод = команда
        .output()
        .map_err(|e| format!("не удалось запустить git (установлен ли он?): {}", e))?;

    if !вывод.status.success() {
        return Err(format!(
            "git clone не удался для '{}': {}",
            зависимость.имя,
            String::from_utf8_lossy(&вывод.stderr)
        ));
    }

    // НОВОЕ — изоляция пространства имён: каждый пакет получает СВОЮ
    // подпапку "пакеты/ИМЯ_ПАКЕТА/", а не сваливается плоско вместе со
    // всеми остальными пакетами в общую "пакеты/". Раньше, если два
    // разных пакета содержали файл с одинаковым именем (например, оба —
    // "утилиты.код"), один молча перезаписывал другой при установке —
    // самый серьёзный, честно названный недостаток v1. Теперь коллизия
    // невозможна: файлы разных пакетов физически лежат в разных папках.
    // Компилятор находит их через составное имя "подключить пакет.файл;"
    // (main.rs, разрешить_путь_подключения — тот же механизм, что уже
    // был в грамматике языка для "имя.подимя", просто раньше не
    // интерпретировался как путь).
    let папка_этого_пакета = папка_пакетов.join(&зависимость.имя);
    // Переустановка — начинаем с чистой папки, а не с добавления поверх
    // старых файлов: если из пакета убрали файл в новой версии, старая,
    // осиротевшая копия не должна остаться и продолжать находиться.
    if папка_этого_пакета.exists() {
        fs::remove_dir_all(&папка_этого_пакета)
            .map_err(|e| format!("не удалось очистить старую версию пакета '{}': {}", зависимость.имя, e))?;
    }
    fs::create_dir_all(&папка_этого_пакета)
        .map_err(|e| format!("не удалось создать папку пакета '{}': {}", зависимость.имя, e))?;

    // Копируем ВСЕ .код файлы из КОРНЯ клонированного репозитория в
    // папку ЭТОГО пакета (не в общую "пакеты/" — см. выше).
    let записи = fs::read_dir(&временная_папка)
        .map_err(|e| format!("не удалось прочитать клонированный репозиторий '{}': {}", зависимость.имя, e))?;

    let mut скопировано = 0;
    for запись in записи {
        let запись = запись.map_err(|e| format!("ошибка чтения записи каталога: {}", e))?;
        let путь = запись.path();
        if путь.extension().and_then(|s| s.to_str()) == Some("код") {
            let имя_файла = путь.file_name().ok_or("файл без имени")?;
            let назначение = папка_этого_пакета.join(имя_файла);
            fs::copy(&путь, &назначение)
                .map_err(|e| format!("не удалось скопировать '{}': {}", путь.display(), e))?;
            println!("  -> пакеты/{}/{}", зависимость.имя, имя_файла.to_string_lossy());
            скопировано += 1;
        }
    }

    if скопировано == 0 {
        fs::remove_dir_all(&временная_папка).ok();
        return Err(format!(
            "в репозитории '{}' не найдено ни одного .код файла в корне",
            зависимость.имя
        ));
    }

    // НОВОЕ — транзитивные зависимости: если у САМОГО пакета внутри его
    // репозитория есть свой "сфера.зависимости", читаем и его — тем же
    // разбором (разобрать_манифест), что и для манифеста корневого
    // проекта. Обязательно ДО удаления временной папки — это единственное
    // место, где содержимое клонированного репозитория ещё доступно.
    // Возвращаем список вызывающей стороне — она решает, устанавливать ли
    // их и в каком порядке (обход в ширину, обнаружение конфликтов имён и
    // циклов — см. установить_зависимости), эта функция сама по себе
    // рекурсию не делает.
    let путь_манифеста_пакета = временная_папка.join("сфера.зависимости");
    let транзитивные_зависимости = if путь_манифеста_пакета.exists() {
        let содержимое_манифеста = fs::read_to_string(&путь_манифеста_пакета).map_err(|e| {
            format!(
                "не удалось прочитать 'сфера.зависимости' внутри пакета '{}': {}",
                зависимость.имя, e
            )
        })?;
        разобрать_манифест(&содержимое_манифеста).map_err(|e| {
            format!(
                "у пакета '{}' некорректный собственный 'сфера.зависимости': {}",
                зависимость.имя, e
            )
        })?
    } else {
        Vec::new()
    };

    fs::remove_dir_all(&временная_папка).ok();

    // Метаданные (источник, ветка, описание, и — новое — через какой
    // пакет эта зависимость была подтянута, если она не из корневого
    // манифеста) теперь тоже внутри папки самого пакета — отдельная
    // центральная "пакеты/.метаданные/" со своим файлом на каждый пакет
    // больше не нужна: раз у пакета уже есть собственная папка, класть
    // его метаданные куда-то ещё — лишнее косвенное разбиение без выгоды.
    let mut содержимое_метаданных = format!("имя={}\nисточник={}\n", зависимость.имя, зависимость.url);
    if let Some(ветка) = &зависимость.ветка {
        содержимое_метаданных.push_str(&format!("ветка={}\n", ветка));
    }
    if let Some(версия) = &зависимость.версия {
        содержимое_метаданных.push_str(&format!("версия={}\n", версия));
    }
    if let Some(описание) = &зависимость.описание {
        содержимое_метаданных.push_str(&format!("описание={}\n", описание));
    }
    if let Some(родитель) = родитель {
        содержимое_метаданных.push_str(&format!("транзитивная_через={}\n", родитель));
    }
    if !транзитивные_зависимости.is_empty() {
        содержимое_метаданных.push_str(&format!(
            "собственных_зависимостей={}\n",
            транзитивные_зависимости.len()
        ));
    }

    let путь_метаданных = папка_этого_пакета.join(".метаданные");
    fs::write(&путь_метаданных, содержимое_метаданных)
        .map_err(|e| format!("не удалось записать метаданные для '{}': {}", зависимость.имя, e))?;

    Ok(транзитивные_зависимости)
}

fn показать_список() -> Result<(), String> {
    let папка_пакетов = Path::new("пакеты");
    if !папка_пакетов.exists() {
        println!("Папка 'пакеты/' не найдена — ничего не установлено.");
        return Ok(());
    }

    let записи = fs::read_dir(папка_пакетов)
        .map_err(|e| format!("не удалось прочитать 'пакеты/': {}", e))?;

    // НОВОЕ (изоляция пространства имён): каждый ПОДКАТАЛОГ "пакеты/" —
    // это один установленный (через "установить") пакет со своими
    // файлами внутри. Голые ".код"-файлы прямо в "пакеты/" по-прежнему
    // поддерживаются (для файла, положенного туда вручную, без
    // сфера_пакеты) — но также это СЛЕД старого, дособачного формата
    // установки (плоский, без изоляции) — на всякий случай, если кто-то
    // обновил компилятор, но ещё не переустановил зависимости заново,
    // они показываются отдельно, с честным предупреждением, а не молча.
    let mut папки_пакетов: Vec<PathBuf> = Vec::new();
    let mut голые_код_файлы: Vec<PathBuf> = Vec::new();
    for запись in записи {
        let запись = запись.map_err(|e| format!("ошибка чтения записи каталога: {}", e))?;
        let путь = запись.path();
        // ".метаданные" — старая, ЦЕНТРАЛЬНАЯ папка метаданных (до
        // изоляции пространств имён, см. установить_одну_зависимость) —
        // это не пакет, пропускаем, иначе она сама попала бы в список
        // "установленных пакетов".
        let это_старая_папка_метаданных = путь.file_name().and_then(|s| s.to_str()) == Some(".метаданные");
        if путь.is_dir() && !это_старая_папка_метаданных {
            папки_пакетов.push(путь);
        } else if путь.extension().and_then(|s| s.to_str()) == Some("код") {
            голые_код_файлы.push(путь);
        }
    }
    папки_пакетов.sort();
    голые_код_файлы.sort();

    if папки_пакетов.is_empty() && голые_код_файлы.is_empty() {
        println!("В 'пакеты/' ничего не установлено.");
        return Ok(());
    }

    if !папки_пакетов.is_empty() {
        println!("Установленные пакеты ({}):", папки_пакетов.len());
        for папка_пакета in &папки_пакетов {
            let имя_пакета = папка_пакета
                .file_name()
                .map(|s| s.to_string_lossy().to_string())
                .unwrap_or_default();
            println!("  {}", имя_пакета);

            let полный_путь = fs::canonicalize(папка_пакета).unwrap_or_else(|_| папка_пакета.clone());
            println!("    расположение: {}", полный_путь.display());

            // Метаданные (если пакет ставился через "установить", а не
            // руками) лежат прямо внутри его же папки — см.
            // установить_одну_зависимость.
            let путь_метаданных = папка_пакета.join(".метаданные");
            if let Ok(содержимое) = fs::read_to_string(&путь_метаданных) {
                for строка_метаданных in содержимое.lines() {
                    if let Some(значение) = строка_метаданных.strip_prefix("описание=") {
                        println!("    описание: {}", значение);
                    } else if let Some(значение) = строка_метаданных.strip_prefix("источник=") {
                        println!("    источник: {}", значение);
                    } else if let Some(значение) = строка_метаданных.strip_prefix("версия=") {
                        println!("    версия: {}", значение);
                    } else if let Some(значение) = строка_метаданных.strip_prefix("транзитивная_через=") {
                        // НОВОЕ (транзитивные зависимости): этот пакет не
                        // объявлен напрямую в "сфера.зависимости" проекта —
                        // его подтянул другой пакет как СВОЮ зависимость.
                        println!("    поставлен как зависимость пакета: {}", значение);
                    } else if let Some(значение) = строка_метаданных.strip_prefix("собственных_зависимостей=") {
                        println!("    у самого пакета собственных зависимостей: {}", значение);
                    } else if let Some(значение) = строка_метаданных.strip_prefix("требуется_пакетами=") {
                        // НОВОЕ (защита при удалении): полный список
                        // пакетов, накопленный за последний "установить" —
                        // именно ЭТИ данные использует "удалить" для
                        // предупреждения (см. удалить_пакет).
                        println!(
                            "    требуется установленным пакетам: {}",
                            значение.replace(',', ", ")
                        );
                    }
                }
            }

            // Файлы пакета — то, что реальному разработчику нужно знать,
            // ЧТО именно из этого пакета доступно и под каким составным
            // именем его подключать ("подключить ИМЯ_ПАКЕТА.ИМЯ_ФАЙЛА;").
            if let Ok(файлы_пакета) = fs::read_dir(папка_пакета) {
                let mut имена_файлов: Vec<String> = файлы_пакета
                    .filter_map(|з| з.ok())
                    .map(|з| з.path())
                    .filter(|п| п.extension().and_then(|s| s.to_str()) == Some("код"))
                    .filter_map(|п| п.file_stem().map(|s| s.to_string_lossy().to_string()))
                    .collect();
                имена_файлов.sort();
                for имя_файла in &имена_файлов {
                    if имя_файла == &имя_пакета {
                        println!("    подключить {};", имя_пакета);
                    } else {
                        println!("    подключить {}.{};", имя_пакета, имя_файла);
                    }
                }
            }
            println!();
        }
    }

    if !голые_код_файлы.is_empty() {
        println!(
            "⚠️ Файлы напрямую в 'пакеты/' (не в подпапке, {}):",
            голые_код_файлы.len()
        );
        println!(
            "   Такие файлы либо положены вручную (не через 'установить'), либо остались от\n   старой, дособачной установки без изоляции пространства имён — переустанови\n   зависимость ('сфера_пакеты установить'), чтобы получить изолированную папку."
        );
        for путь in &голые_код_файлы {
            if let Some(имя_файла) = путь.file_name() {
                println!("  {}", имя_файла.to_string_lossy());
            }
        }
        println!();
    }

    Ok(())
}

/// Убирает один пакет — целиком его папку "пакеты/ИМЯ/" (файлы и
/// метаданные внутри неё). Для обратной совместимости со старым, плоским
/// форматом установки (до изоляции пространств имён) также по-прежнему
/// понимает голый "пакеты/ИМЯ.код" — на случай если пакет ещё не был
/// переустановлен в новом формате.
///
/// НОВОЕ — защита при удалении: если метаданные пакета говорят, что он
/// "требуется_пакетами=..." (см. установить_зависимости), и хотя бы один
/// из этих требователей всё ещё установлен рядом (у него тоже есть своя
/// папка в "пакеты/") — удаление отклоняется с честным предупреждением,
/// если не передан флаг "--force". Честная граница: список требователей —
/// это НЕ живой, постоянно обновляемый граф зависимостей (сфера_пакеты
/// вообще не хранит такого между запусками) — только снимок, сделанный во
/// время ПОСЛЕДНЕГО "установить"; если зависимости с тех пор поменяли
/// вручную, список может быть неточным.
fn удалить_пакет(имя: Option<&str>, форсировать: bool) -> Result<(), String> {
    let имя = имя.ok_or_else(|| {
        "укажи имя пакета для удаления: сфера_пакеты удалить ИМЯ [--force]".to_string()
    })?;

    let папка_пакетов = Path::new("пакеты");
    let папка_этого_пакета = папка_пакетов.join(имя);

    if папка_этого_пакета.is_dir() {
        let путь_метаданных = папка_этого_пакета.join(".метаданные");
        if let Ok(содержимое) = fs::read_to_string(&путь_метаданных) {
            for строка in содержимое.lines() {
                let Some(значение) = строка.strip_prefix("требуется_пакетами=") else {
                    continue;
                };
                let живые_требователи: Vec<&str> = значение
                    .split(',')
                    .filter(|s| !s.is_empty())
                    .filter(|требователь| папка_пакетов.join(требователь).is_dir())
                    .collect();
                if живые_требователи.is_empty() {
                    continue;
                }
                if !форсировать {
                    return Err(format!(
                        "пакет '{}' требуется другим установленным пакетам: {} — удаление может их \
                         сломать (они не найдут его файлы при следующей компиляции). Если это \
                         осознанный выбор — сам поправишь или переустановишь их зависимости — повтори \
                         команду с флагом --force. (Список основан на данных последнего 'установить', \
                         а не на живом графе зависимостей — если зависимости с тех пор менялись вручную, \
                         он может быть неточным.)",
                        имя,
                        живые_требователи.join(", ")
                    ));
                }
                println!(
                    "⚠️  '{}' всё ещё требуется пакетам: {} — удаляю принудительно (--force).",
                    имя,
                    живые_требователи.join(", ")
                );
            }
        }

        fs::remove_dir_all(&папка_этого_пакета)
            .map_err(|e| format!("не удалось удалить '{}': {}", папка_этого_пакета.display(), e))?;
        println!("Удалено: {}", папка_этого_пакета.display());
        return Ok(());
    }

    // Старый, плоский формат (до изоляции пространств имён) — голый
    // ".код" файл прямо в "пакеты/", плюс метаданные в отдельной,
    // центральной "пакеты/.метаданные/" (как их писали ДО этого
    // изменения).
    let путь_файла = папка_пакетов.join(format!("{}.код", имя));
    if !путь_файла.exists() {
        return Err(format!("пакет '{}' не найден в 'пакеты/'", имя));
    }

    fs::remove_file(&путь_файла)
        .map_err(|e| format!("не удалось удалить '{}': {}", путь_файла.display(), e))?;
    println!("Удалено: {}", путь_файла.display());

    let путь_метаданных = папка_пакетов.join(".метаданные").join(format!("{}.метаданные", имя));
    if путь_метаданных.exists() {
        fs::remove_file(&путь_метаданных)
            .map_err(|e| format!("не удалось удалить метаданные '{}': {}", путь_метаданных.display(), e))?;
        println!("Удалены метаданные: {}", путь_метаданных.display());
    }

    Ok(())
}

