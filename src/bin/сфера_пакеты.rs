// сфера_пакеты — инструмент управления зависимостями языка «Сфера».
//
// АРХИТЕКТУРНОЕ РЕШЕНИЕ: нет и не будет своего центрального реестра
// пакетов (как crates.io/npm) — содержать такую инфраструктуру
// нереалистично для проекта такого масштаба. Вместо этого — GIT КАК
// РЕЕСТР: зависимость это просто ссылка на git-репозиторий (тот же
// подход, с которого начинались Go modules и ранний Cargo, до появления
// crates.io) — полностью децентрализованно, не требует ни одного
// сервера, которым нужно было бы владеть.
//
// Пакет — это git-репозиторий, содержащий один или несколько .код файлов
// в своём корне. Установка клонирует репозиторий во временную папку и
// копирует ИЗ НЕЁ все .код файлы прямо в "пакеты/" проекта — тот же,
// уже существующий и работающий механизм разрешения "подключить" (см.
// main.rs, разрешить_путь_подключения) используется БЕЗ ИЗМЕНЕНИЙ.
//
// ⚠️ ЧЕСТНЫЕ ОГРАНИЧЕНИЯ v1 (см. подробности в README):
// - Нет разрешения версионных конфликтов (semver и подобное) — только
//   "какую ветку/тег/коммит git взять", простое сопоставление имени с
//   URL, без графа транзитивных зависимостей.
// - Плоское копирование .код файлов в "пакеты/" — если два разных пакета
//   содержат файл с одинаковым именем, один перезапишет другой (нет
//   изоляции пространства имён между пакетами на уровне файлов).

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
    let аргументы: Vec<String> = std::env::args().collect();
    let команда = аргументы.get(1).map(String::as_str).unwrap_or("");

    let результат = match команда {
        "установить" => установить_зависимости(),
        "список" => показать_список(),
        "удалить" => удалить_пакет(аргументы.get(2).map(String::as_str)),
        _ => {
            вывести_подсказку();
            std::process::exit(if команда.is_empty() { 0 } else { 1 });
        }
    };

    if let Err(сообщение) = результат {
        eprintln!("Ошибка: {}", сообщение);
        std::process::exit(1);
    }
}

