// сфера_пакеты — инструмент управления зависимостями языка «Сфера».
//
// АРХИТЕКТУРНОЕ РЕШЕНИЕ: GIT КАК РЕЕСТР — зависимость это просто ссылка
// на git-репозиторий (тот же подход, с которого начинались Go modules и
// ранний Cargo, до появления crates.io) — полностью децентрализованно,
// не требует ни одного сервера, которым нужно было бы владеть.
//
// Пакет — это git-репозиторий, содержащий один или несколько .код файлов
// в своём корне. Установка клонирует репозиторий во временную папку и
// копирует ИЗ НЕЁ все .код файлы в "пакеты/ИМЯ_ПАКЕТА/" проекта (см.
// изоляцию пространства имён ниже) — тот же, уже существующий и
// работающий механизм разрешения "подключить" (см. main.rs,
// разрешить_путь_подключения) используется БЕЗ ИЗМЕНЕНИЙ.
//
// НОВОЕ — ПУБЛИЧНЫЙ ИНДЕКС ПАКЕТОВ ("искать"/"добавить"/"индекс-*"):
// та же философия "git как реестр", доведённая до централизованного
// СПИСКА, а не инфраструктуры. Раньше, чтобы поставить чужой пакет,
// нужно было заранее знать его git URL — взять его было решительно
// неоткуда. Индекс — это ОДИН git-репозиторий с одним каталог-файлом
// внутри (тот же формат "имя = git URL описание=..."), который каждый
// желающий может клонировать/обновлять (сфера_пакеты индекс-обновить),
// искать по нему (сфера_пакеты искать ЗАПРОС) и добавлять найденное в
// свой сфера.зависимости одной командой (сфера_пакеты добавить ИМЯ).
// Публикация пакета — это pull request в индекс (или прямое
// редактирование файла, если репозиторий свой), а не загрузка на
// какой-то сервер: НИКАКОЙ новой инфраструктуры сфера_пакеты не
// содержит и не запускает — только git, который уже был нужен для
// самих пакетов.
//
// ⚠️ ЧЕСТНО, СОЗНАТЕЛЬНО ВРЕМЕННОЕ РЕШЕНИЕ, НЕ ФИНАЛЬНОЕ: это первый,
// самый лёгкий шаг к полноценному публичному реестру. Следующий,
// намного больший шаг (когда будет куплен домен и сервер) — настоящий
// веб-сервис с базой данных и HTTP API для поиска/публикации, полностью
// заменяющий этот git-индекс, а не дополняющий его.
//
// РАЗРЕШЕНИЕ ВЕРСИОННЫХ КОНФЛИКТОВ — НАСТОЯЩЕЕ ПЕРЕСЕЧЕНИЕ ДИАПАЗОНОВ
// (constraint solving): необязательное поле "версия=X.Y.Z" в манифесте
// (взаимоисключает "ветка=") — это по-прежнему просто имя git-тега для
// клонирования (для точной версии) или требование к диапазону версий
// ("^X.Y.Z"/"~X.Y.Z"), но ДОПОЛНИТЕЛЬНО разбирается как простой семвер
// (major.minor.patch, без пререлизов/build-метаданных) и конвертируется в
// полуоткрытый интервал версий [ниж, верх) (см. Диапазон,
// диапазон_из_требования). Если один и тот же пакет (тот же URL) запрошен
// из РАЗНЫХ мест дерева зависимостей — каждое новое требование
// ПЕРЕСЕКАЕТСЯ (см. пересечь_диапазоны) с уже накопленным интервалом для
// этого пакета, а не просто сравнивается "какая версия больше": итоговый
// интервал — это версии, удовлетворяющие ВСЕМ требованиям сразу. Если уже
// выбранная версия попадает в новый, суженный интервал — переустановка не
// нужна. Если нет — пакет разрешается заново, но уже в пределах суженного
// интервала (см. разрешить_версию_пакета). Если пересечение оказывается
// ПУСТЫМ — это доказуемый, настоящий конфликт (два места дерева требуют
// версий, которых не существует одновременно), и "установить" честно
// проваливается с ошибкой, называющей оба требования и через какие пакеты
// каждое из них было запрошено — НЕ выбирает большую версию вслепую, как
// было раньше. Если версии сравнить вообще нельзя (не указаны, не в
// формате X.Y.Z, или запрошен другой URL под тем же именем) — честное
// предупреждение в консоль и сохранение первого выбора, без падения и без
// угадывания — как и раньше.
//
// ТРАНЗИТИВНЫЕ ЗАВИСИМОСТИ: если у устанавливаемого пакета внутри его
// собственного репозитория тоже есть файл "сфера.зависимости", он
// подхватывается автоматически — "установить" обходит граф зависимостей
// в ширину (BFS), а не только один уровень корневого манифеста. Имя
// пакета уникально в рамках всего дерева: версии одного и того же адреса
// разрешаются автоматически (см. РАЗРЕШЕНИЕ ВЕРСИОННЫХ КОНФЛИКТОВ выше) —
// но столкновение с ДРУГИМ АДРЕСОМ под тем же именем это принципиально не
// версия, а разный код, и сфера_пакеты не выбирает молча: вся установка
// честно проваливается с ошибкой, называющей оба адреса и через какие
// пакеты каждый был запрошен (см. установить_зависимости) — разработчик
// разрешает это сам (переименование одного из пакетов в его манифесте).
// Циклы (А зависит от Б, Б — от А) корректно обрываются тем же самым
// множеством уже обработанных имён.
//
// ЗАЩИТА ПРИ УДАЛЕНИИ: во время "установить" накапливается (не только
// первый, а ВСЕ встреченные за обход требователи — см. требуется_кем в
// установить_зависимости) список "какие установленные пакеты требуют
// этот", записывается в метаданные пакета отдельным проходом после BFS.
// "удалить ИМЯ" читает этот список и, если хотя бы один из требователей
// всё ещё установлен рядом, отказывает с предупреждением, пока не передан
// флаг "--force". Честная граница: это снимок на момент последнего
// "установить", не живой граф — если зависимости с тех пор поменяли
// вручную (не через сфера_пакеты), список может быть неточным.
//
// ФАЙЛ БЛОКИРОВКИ ("сфера.блокировка"): после каждого успешного
// "установить" перезаписывается целиком из итоговой карты выбранных
// пакетов — тот же построчный формат, что и у манифеста (переиспользуем
// разобрать_манифест), но версия там ВСЕГДА уже разрешённый конкретный
// тег, никогда ^/~. При следующем "установить" диапазон версии сперва
// проверяется против блокировки (если тег оттуда всё ещё удовлетворяет
// диапазону — берём его напрямую, без обращения к git ls-remote) — это
// и есть воспроизводимость: та же команда на другой машине (или через
// время) ставит ТЕ ЖЕ версии, а не тихо более новые внутри того же
// диапазона. Флаг "--обновить-блокировку" игнорирует файл и разрешает
// все диапазоны заново. Пакеты на "ветка=" (или вовсе без версии) в
// блокировку не попадают — ветки не семвер, фиксировать их как версию
// было бы нечестно.

use std::collections::{HashMap, VecDeque};
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
    let аргументы: Vec<String> = std::env::args().collect();
    let команда = аргументы.get(1).map(String::as_str).unwrap_or("");

    let результат = match команда {
        "установить" => установить_зависимости(аргументы.iter().any(|а| а == "--обновить-блокировку")),
        "список" => показать_список(),
        "удалить" => удалить_пакет(
            аргументы.get(2).map(String::as_str),
            аргументы.iter().any(|а| а == "--force"),
        ),
        "искать" => искать_в_индексе(аргументы.get(2).map(String::as_str)),
        "добавить" => добавить_из_индекса(аргументы.get(2).map(String::as_str)),
        "индекс-настроить" => настроить_индекс(аргументы.get(2).map(String::as_str)),
        "индекс-обновить" => обновить_индекс(),
        _ => {
            вывести_подсказку();
            std::process::exit(if команда.is_empty() { 0 } else { 1 });
        }
    };

    if let Err(сообщение) = результат {
        eprintln!("Ошибка: {}", сообщение);
        std::process::exit(1);
    }
}

