//! Парсер — второй этап компиляции. Превращает плоский список токенов
//! в дерево (AST), отражающее реальную вложенность программы.
//!
//! Используем классический метод "рекурсивный спуск" (recursive descent):
//! на каждую грамматическую конструкцию — свой метод, методы вызывают
//! друг друга по мере необходимости. Это самый читаемый подход для
//! компилятора, который пишется и поддерживается одним человеком —
//! чуть менее гибкий, чем генератор парсеров, зато код парсера почти
//! дословно повторяет структуру грамматики (grammar.md), и любую строчку
//! легко сопоставить с конкретным правилом оттуда.

use crate::ast::*;
use crate::token::{Token, ТокенСПозицией};

pub struct Парсер {
    токены: Vec<ТокенСПозицией>,
    позиция: usize,
}

#[derive(Debug)]
pub struct ОшибкаПарсера {
    pub сообщение: String,
    pub строка: usize,
    pub столбец: usize,
}

impl Парсер {
    pub fn новый(токены: Vec<ТокенСПозицией>) -> Self {
        Парсер { токены, позиция: 0 }
    }

    /// Главный метод — разбирает всю программу целиком (раздел 1 грамматики)
    pub fn разобрать_программу(&mut self) -> Result<Программа, ОшибкаПарсера> {
        let mut узлы = Vec::new();

        while !self.на_конце() {
            узлы.push(self.разобрать_верхний_узел()?);
        }

        Ok(узлы)
    }

    // ================== Навигация по токенам ==================

    fn текущий(&self) -> &Token {
        &self.токены[self.позиция].токен
    }

    /// Смотрит на токен на "смещение" позиций вперёд, не сдвигая саму позицию
    /// парсера. Нужен для разрешения неоднозначностей, которые нельзя решить,
    /// глядя только на текущий токен — например, "Идентификатор Идентификатор"
    /// (имя пользовательского типа + имя переменной, объявление) отличается
    /// от "Идентификатор =" (присваивание) только тем, что идёт ВТОРЫМ токеном.
    fn заглянуть_вперёд(&self, смещение: usize) -> &Token {
        let индекс = (self.позиция + смещение).min(self.токены.len() - 1);
        &self.токены[индекс].токен
    }

    fn текущая_позиция(&self) -> (usize, usize) {
        let т = &self.токены[self.позиция];
        (т.строка, т.столбец)
    }

    fn на_конце(&self) -> bool {
        matches!(self.текущий(), Token::КонецФайла)
    }

    fn продвинуться(&mut self) -> Token {
        let токен = self.токены[self.позиция].токен.clone();
        if !self.на_конце() {
            self.позиция += 1;
        }
        токен
    }

    fn проверить(&self, ожидаемый: &Token) -> bool {
        self.текущий() == ожидаемый
    }

    /// Если текущий токен совпадает с ожидаемым — съедаем его и возвращаем true.
    /// Иначе не трогаем позицию и возвращаем false.
    fn совпадает(&mut self, ожидаемый: &Token) -> bool {
        if self.проверить(ожидаемый) {
            self.продвинуться();
            true
        } else {
            false
        }
    }

    /// Требуем конкретный токен — если его нет, это ошибка синтаксиса.
    fn ожидать(&mut self, ожидаемый: Token, контекст: &str) -> Result<(), ОшибкаПарсера> {
        if self.проверить(&ожидаемый) {
            self.продвинуться();
            Ok(())
        } else {
            let (строка, столбец) = self.текущая_позиция();
            Err(ОшибкаПарсера {
                сообщение: format!(
                    "{}: ожидался {:?}, но встретился {:?}",
                    контекст,
                    ожидаемый,
                    self.текущий()
                ),
                строка,
                столбец,
            })
        }
    }

    fn ошибка(&self, сообщение: impl Into<String>) -> ОшибкаПарсера {
        let (строка, столбец) = self.текущая_позиция();
        ОшибкаПарсера {
            сообщение: сообщение.into(),
            строка,
            столбец,
        }
    }

    /// Читаем идентификатор (имя переменной/функции/типа) и возвращаем его текст.
    fn ожидать_идентификатор(&mut self, контекст: &str) -> Result<String, ОшибкаПарсера> {
        match self.текущий().clone() {
            Token::Идентификатор(имя) => {
                self.продвинуться();
                Ok(имя)
            }
            other => {
                let (строка, столбец) = self.текущая_позиция();
                Err(ОшибкаПарсера {
                    сообщение: format!("{}: ожидался идентификатор, встретился {:?}", контекст, other),
                    строка,
                    столбец,
                })
            }
        }
    }

    // ================== Верхний уровень (раздел 1) ==================

    fn разобрать_верхний_узел(&mut self) -> Result<ВерхнийУзел, ОшибкаПарсера> {
        match self.текущий() {
            Token::Подключить => self.разобрать_подключение(),
            Token::Структура => Ok(ВерхнийУзел::Структура(self.разобрать_структуру()?)),
            Token::Функция => Ok(ВерхнийУзел::Функция(self.разобрать_функцию()?)),
            Token::Контракт => Ok(ВерхнийУзел::Контракт(self.разобрать_контракт()?)),
            Token::Внешняя => Ok(ВерхнийУзел::ВнешняяФункция(self.разобрать_внешнюю_функцию()?)),
            other => Err(self.ошибка(format!(
                "на верхнем уровне ожидалось 'подключить', 'структура', 'функция', 'контракт' или 'внешняя', встретилось {:?}",
                other
            ))),
        }
    }

    /// "внешняя функция SDL_Init(целое флаги) -> целое;" — та же форма, что
    /// и метод контракта (сигнатура без тела, завершается ";"), но на
    /// верхнем уровне — привязка к функции ИЗ ВНЕШНЕЙ C-БИБЛИОТЕКИ.
    fn разобрать_внешнюю_функцию(&mut self) -> Result<ОбъявлениеВнешнейФункции, ОшибкаПарсера> {
        self.ожидать(Token::Внешняя, "объявление внешней функции")?;
        self.ожидать(Token::Функция, "'функция' после 'внешняя'")?;
        let имя = self.ожидать_идентификатор("имя внешней функции")?;
        self.ожидать(Token::ОткрКруглая, "начало списка параметров внешней функции")?;
        let параметры = self.разобрать_параметры()?;
        self.ожидать(Token::ЗакрКруглая, "конец списка параметров внешней функции")?;
        let тип_возврата = if self.совпадает(&Token::Стрелка) {
            Some(self.разобрать_тип()?)
        } else {
            None
        };

        // НОВОЕ: "как "SDL_Init"" — необязательный алиас реального имени
        // символа библиотеки, отдельный от того, как функция называется
        // в коде программиста (см. подробное объяснение у поля
        // ОбъявлениеВнешнейФункции.реальное_имя).
        let реальное_имя = if self.совпадает(&Token::Как) {
            match self.текущий().clone() {
                Token::ТекстЛит(текст) => {
                    self.продвинуться();
                    Some(текст)
                }
                other => {
                    return Err(self.ошибка(format!(
                        "после 'как' ожидалась текстовая строка с реальным именем символа библиотеки, встретилось {:?}",
                        other
                    )));
                }
            }
        } else {
            None
        };

        self.ожидать(Token::ТочкаЗапятой, "конец объявления внешней функции (без тела — только ';')")?;

        Ok(ОбъявлениеВнешнейФункции { имя, параметры, тип_возврата, реальное_имя })
    }

    /// "контракт Печатаемый { функция напечатать() -> текст; }" — методы
    /// контракта имеют ТОЛЬКО сигнатуру, без тела (сразу ";" вместо "{ ... }") —
    /// контракт заявляет ТРЕБОВАНИЕ, не даёт реализацию.
    fn разобрать_контракт(&mut self) -> Result<ОбъявлениеКонтракта, ОшибкаПарсера> {
        self.ожидать(Token::Контракт, "объявление контракта")?;
        let имя = self.ожидать_идентификатор("имя контракта")?;
        self.ожидать(Token::ОткрФигурная, "тело контракта")?;

        let mut методы = Vec::new();
        while !self.проверить(&Token::ЗакрФигурная) {
            self.ожидать(Token::Функция, "объявление метода контракта")?;
            let имя_метода = self.ожидать_идентификатор("имя метода контракта")?;
            self.ожидать(Token::ОткрКруглая, "начало списка параметров метода контракта")?;
            let параметры = self.разобрать_параметры()?;
            self.ожидать(Token::ЗакрКруглая, "конец списка параметров метода контракта")?;
            let тип_возврата = if self.совпадает(&Token::Стрелка) {
                Some(self.разобрать_тип()?)
            } else {
                None
            };
            self.ожидать(Token::ТочкаЗапятой, "конец сигнатуры метода контракта (без тела — только ';')")?;
            методы.push(СигнатураМетодаКонтракта { имя: имя_метода, параметры, тип_возврата });
        }
        self.ожидать(Token::ЗакрФигурная, "конец тела контракта")?;

        Ok(ОбъявлениеКонтракта { имя, методы })
    }

    fn разобрать_подключение(&mut self) -> Result<ВерхнийУзел, ОшибкаПарсера> {
        self.ожидать(Token::Подключить, "подключение модуля")?;

        let путь = match self.текущий().clone() {
            Token::ТекстЛит(текст) => {
                // подключить "путь/к/файлу.код";
                self.продвинуться();
                текст
            }
            Token::Идентификатор(_) => {
                // подключить имя.подимя;
                let mut части = vec![self.ожидать_идентификатор("имя модуля")?];
                while self.совпадает(&Token::Точка) {
                    части.push(self.ожидать_идентификатор("имя вложенного модуля")?);
                }
                части.join(".")
            }
            other => {
                return Err(self.ошибка(format!(
                    "после 'подключить' ожидалось имя модуля или строка с путём, встретилось {:?}",
                    other
                )))
            }
        };

        self.ожидать(Token::ТочкаЗапятой, "конец подключения модуля")?;
        Ok(ВерхнийУзел::Подключение(путь))
    }

    // ================== Структуры (раздел 5) ==================

    fn разобрать_структуру(&mut self) -> Result<ОбъявлениеСтруктуры, ОшибкаПарсера> {
        // Захватываем позицию ДО продвижения — это позиция самого ключевого
        // слова "структура", нужна только языковому серверу для "перейти
        // к определению" (компилятору при генерации кода не нужна).
        let позиция = self.текущая_позиция();
        self.ожидать(Token::Структура, "объявление структуры")?;
        let имя = self.ожидать_идентификатор("имя структуры")?;

        // "структура Коробка<тип> { ... }" — переиспользуем ту же функцию
        // разбора обобщённых параметров, что уже написана для функций
        // (сама функция не съедает закрывающую ">", это нужно сделать явно
        // здесь — тот же паттерн, что и в разобрать_функцию).
        let обобщённые_параметры = if self.совпадает(&Token::Меньше) {
            let параметры = self.разобрать_обобщённые_параметры()?;
            self.ожидать(Token::Больше, "конец списка обобщённых параметров структуры")?;
            параметры
        } else {
            Vec::new()
        };

        let mut контракты = Vec::new();
        if self.совпадает(&Token::Двоеточие) {
            контракты.push(self.ожидать_идентификатор("имя контракта")?);
            while self.совпадает(&Token::Запятая) {
                контракты.push(self.ожидать_идентификатор("имя контракта")?);
            }
        }

        self.ожидать(Token::ОткрФигурная, "тело структуры")?;

        let mut поля = Vec::new();
        let mut методы = Vec::new();

        while !self.проверить(&Token::ЗакрФигурная) {
            let видимость = self.разобрать_необязательную_видимость();
            let слабая = self.совпадает(&Token::Слабая);

            if self.проверить(&Token::Функция) {
                // "это" внутри метода — неявное имя, не объявляется в списке
                // параметров (см. Token::Это в лексере/парсере выражений).
                // "слабая" для методов не имеет смысла (осмысленно только
                // для полей) — просто съедена выше и молча игнорируется.
                let mut метод = self.разобрать_функцию()?;
                метод.видимость = видимость;
                методы.push(метод);
            } else {
                let тип = self.разобрать_тип()?;
                let имя_поля = self.ожидать_идентификатор("имя поля структуры")?;
                self.ожидать(Token::ТочкаЗапятой, "конец объявления поля")?;
                поля.push(ПолеСтруктуры {
                    видимость,
                    слабая,
                    тип,
                    имя: имя_поля,
                });
            }
        }

        self.ожидать(Token::ЗакрФигурная, "конец тела структуры")?;

        Ok(ОбъявлениеСтруктуры {
            имя,
            обобщённые_параметры,
            контракты,
            поля,
            методы,
            позиция: Some(позиция),
        })
    }

    fn разобрать_необязательную_видимость(&mut self) -> Option<Видимость> {
        if self.совпадает(&Token::Публично) {
            Some(Видимость::Публично)
        } else if self.совпадает(&Token::Приватно) {
            Some(Видимость::Приватно)
        } else {
            None
        }
    }

    // ================== Функции (раздел 6) ==================

    fn разобрать_функцию(&mut self) -> Result<ОбъявлениеФункции, ОшибкаПарсера> {
        // Та же логика, что и в разобрать_структуру — позиция ключевого
        // слова "функция", нужна только языковому серверу.
        let позиция = self.текущая_позиция();
        self.ожидать(Token::Функция, "объявление функции")?;
        let имя = self.ожидать_идентификатор("имя функции")?;

        let обобщённые_параметры = if self.совпадает(&Token::Меньше) {
            let параметры = self.разобрать_обобщённые_параметры()?;
            self.ожидать(Token::Больше, "конец списка обобщённых параметров")?;
            параметры
        } else {
            Vec::new()
        };

        self.ожидать(Token::ОткрКруглая, "начало списка параметров функции")?;
        let параметры = self.разобрать_параметры()?;
        self.ожидать(Token::ЗакрКруглая, "конец списка параметров функции")?;

        let тип_возврата = if self.совпадает(&Token::Стрелка) {
            Some(self.разобрать_тип()?)
        } else {
            None
        };

        let тело = self.разобрать_блок()?;

        Ok(ОбъявлениеФункции {
            имя,
            видимость: None,
            обобщённые_параметры,
            параметры,
            тип_возврата,
            тело,
            позиция: Some(позиция),
        })
    }

    fn разобрать_обобщённые_параметры(&mut self) -> Result<Vec<ОбобщённыйПараметр>, ОшибкаПарсера> {
        let mut параметры = vec![self.разобрать_один_обобщённый_параметр()?];
        while self.совпадает(&Token::Запятая) {
            параметры.push(self.разобрать_один_обобщённый_параметр()?);
        }
        Ok(параметры)
    }

    fn разобрать_один_обобщённый_параметр(&mut self) -> Result<ОбобщённыйПараметр, ОшибкаПарсера> {
        // По грамматике параметр типа пишется как ключевое слово "тип" (Token::Идентификатор("тип"))
        // либо как произвольное имя (Ключ, Значение) — оба случая приходят как Идентификатор,
        // потому что "тип" здесь используется не как встроенный базовый тип, а как имя параметра.
        let имя = self.ожидать_идентификатор("имя параметра типа (например, тип / Ключ / Значение)")?;

        let mut ограничения = Vec::new();
        if self.совпадает(&Token::Двоеточие) {
            ограничения.push(self.ожидать_идентификатор("имя ограничения (контракта)")?);
            while self.совпадает(&Token::Запятая) {
                ограничения.push(self.ожидать_идентификатор("имя ограничения (контракта)")?);
            }
        }

        Ok(ОбобщённыйПараметр { имя, ограничения })
    }

    fn разобрать_параметры(&mut self) -> Result<Vec<Параметр>, ОшибкаПарсера> {
        let mut параметры = Vec::new();

        if self.проверить(&Token::ЗакрКруглая) {
            return Ok(параметры); // пустой список параметров
        }

        параметры.push(self.разобрать_один_параметр()?);
        while self.совпадает(&Token::Запятая) {
            параметры.push(self.разобрать_один_параметр()?);
        }

        Ok(параметры)
    }

    fn разобрать_один_параметр(&mut self) -> Result<Параметр, ОшибкаПарсера> {
        let по_ссылке = self.совпадает(&Token::Ссылка);
        let тип = self.разобрать_тип()?;
        let имя = self.ожидать_идентификатор("имя параметра")?;
        Ok(Параметр { тип, имя, по_ссылке })
    }

    // ================== Типы (раздел 3) ==================

    fn разобрать_тип(&mut self) -> Result<Тип, ОшибкаПарсера> {
        let базовый = self.разобрать_базовый_или_пользовательский_тип()?;

        // тип[N] или тип[] — массив
        let с_массивом = if self.совпадает(&Token::ОткрКвадратная) {
            let размер = if let Token::ЦелоеЛит(n) = self.текущий().clone() {
                self.продвинуться();
                Some(n)
            } else {
                None
            };
            self.ожидать(Token::ЗакрКвадратная, "конец объявления массива")?;
            Тип::Массив {
                элемент: Box::new(базовый),
                размер,
            }
        } else {
            базовый
        };

        // тип? — опциональный
        if self.совпадает(&Token::Вопрос) {
            Ok(Тип::Опциональный(Box::new(с_массивом)))
        } else {
            Ok(с_массивом)
        }
    }

    fn разобрать_базовый_или_пользовательский_тип(&mut self) -> Result<Тип, ОшибкаПарсера> {
        let тип = match self.текущий().clone() {
            Token::Целое => { self.продвинуться(); Тип::Целое }
            Token::Целое8 => { self.продвинуться(); Тип::Целое8 }
            Token::Целое16 => { self.продвинуться(); Тип::Целое16 }
            Token::Целое32 => { self.продвинуться(); Тип::Целое32 }
            Token::Целое64 => { self.продвинуться(); Тип::Целое64 }
            Token::Беззнак8 => { self.продвинуться(); Тип::Беззнак8 }
            Token::Беззнак16 => { self.продвинуться(); Тип::Беззнак16 }
            Token::Беззнак32 => { self.продвинуться(); Тип::Беззнак32 }
            Token::Беззнак64 => { self.продвинуться(); Тип::Беззнак64 }
            Token::Дробное => { self.продвинуться(); Тип::Дробное }
            Token::Дробное32 => { self.продвинуться(); Тип::Дробное32 }
            Token::Дробное64 => { self.продвинуться(); Тип::Дробное64 }
            Token::Текст => { self.продвинуться(); Тип::Текст }
            Token::Верно => { self.продвинуться(); Тип::Верно }
            Token::Результат => {
                self.продвинуться();
                self.ожидать(Token::Меньше, "результат<тип>")?;
                let внутренний = self.разобрать_тип()?;
                self.ожидать(Token::Больше, "результат<тип>")?;
                Тип::Результат(Box::new(внутренний))
            }
            Token::Канал => {
                self.продвинуться();
                self.ожидать(Token::Меньше, "канал<тип>")?;
                let внутренний = self.разобрать_тип()?;
                self.ожидать(Token::Больше, "канал<тип>")?;
                Тип::Канал(Box::new(внутренний))
            }
            Token::Идентификатор(имя) => {
                self.продвинуться();
                if self.совпадает(&Token::Меньше) {
                    // Обобщённый тип: Список<целое>, Словарь<текст, целое>
                    let mut параметры = vec![self.разобрать_тип()?];
                    while self.совпадает(&Token::Запятая) {
                        параметры.push(self.разобрать_тип()?);
                    }
                    self.ожидать(Token::Больше, "конец списка типовых параметров")?;
                    Тип::Обобщённый { имя, параметры }
                } else {
                    Тип::Пользовательский(имя)
                }
            }
            other => {
                return Err(self.ошибка(format!("ожидался тип, встретилось {:?}", other)));
            }
        };
        Ok(тип)
    }

    // ================== Блоки и операторы (раздел 7) ==================

    fn разобрать_блок(&mut self) -> Result<Блок, ОшибкаПарсера> {
        self.ожидать(Token::ОткрФигурная, "начало блока")?;
        let mut операторы = Vec::new();
        while !self.проверить(&Token::ЗакрФигурная) {
            let строка = self.токены[self.позиция].строка;
            операторы.push((self.разобрать_оператор()?, строка));
        }
        self.ожидать(Token::ЗакрФигурная, "конец блока")?;
        Ok(операторы)
    }

    fn разобрать_оператор(&mut self) -> Result<Оператор, ОшибкаПарсера> {
        match self.текущий().clone() {
            Token::Если => self.разобрать_если(),
            Token::Для => self.разобрать_цикл_для_каждого(),
            Token::Пока => self.разобрать_цикл_пока(),
            Token::Вернуть => self.разобрать_вернуть(),
            Token::Параллельно => {
                self.продвинуться();
                Ok(Оператор::Параллельно(self.разобрать_блок()?))
            }
            Token::Неизменно => self.разобрать_неизменное_объявление(),

            // Начинается с типа => объявление с явным типом.
            // Начинается с идентификатора => присваивание ИЛИ объявление с выводом типа
            // ИЛИ вызов функции/другое выражение-оператор
            // ИЛИ объявление с ПОЛЬЗОВАТЕЛЬСКИМ типом (структурой) — этот случай
            // неотличим от присваивания по одному только текущему токену, оба
            // начинаются с Идентификатор. Различаем по СЛЕДУЮЩЕМУ токену:
            // "Идентификатор Идентификатор" (два подряд) — это "ИмяТипа имя = ...;",
            // тогда как "Идентификатор =" — присваивание, а "Идентификатор ("
            // — вызов функции. Классический lookahead(1) для разрешения
            // неоднозначности, которую нельзя увидеть по одному токену.
            _ if является_началом_типа(self.текущий()) => self.разобрать_объявление_с_типом(),

            Token::Идентификатор(_) if matches!(self.заглянуть_вперёд(1), Token::Идентификатор(_)) => {
                self.разобрать_объявление_с_типом()
            }

            // Обобщённый тип перед объявлением: "Список<целое> очки = ...;".
            // Похожая неоднозначность, что и с генерик-вызовом (см.
            // попробовать_генерик_вызов) — здесь тоже нужен откат позиции,
            // потому что "Идентификатор < ... >" может оказаться и началом
            // обычного выражения со сравнением ("а < б"), а не типом.
            Token::Идентификатор(_) if self.похоже_на_обобщённое_объявление() => {
                self.разобрать_объявление_с_типом()
            }

            Token::Идентификатор(_) => self.разобрать_идентификатор_как_оператор(),

            // "это.поле = значение;" — тот же путь, что и обычное присваивание
            // через идентификатор (см. разобрать_идентификатор_как_оператор,
            // куда добавлена явная обработка Token::Это).
            Token::Это => self.разобрать_идентификатор_как_оператор(),

            _ => {
                // произвольное выражение как оператор (например, вызов функции без результата)
                let выражение = self.разобрать_выражение()?;
                self.ожидать(Token::ТочкаЗапятой, "конец оператора-выражения")?;
                Ok(Оператор::ВыражениеОператор(выражение))
            }
        }
    }

    fn разобрать_если(&mut self) -> Result<Оператор, ОшибкаПарсера> {
        self.ожидать(Token::Если, "условный оператор")?;
        self.ожидать(Token::ОткрКруглая, "условие в скобках")?;
        let условие = self.разобрать_выражение()?;
        self.ожидать(Token::ЗакрКруглая, "условие в скобках")?;
        let тогда = self.разобрать_блок()?;

        let иначе = if self.совпадает(&Token::Иначе) {
            if self.проверить(&Token::Если) {
                // "иначе если" — представляем как вложенный если внутри блока-иначе
                let строка = self.токены[self.позиция].строка;
                Some(vec![(self.разобрать_если()?, строка)])
            } else {
                Some(self.разобрать_блок()?)
            }
        } else {
            None
        };

        Ok(Оператор::Если { условие, тогда, иначе })
    }

    fn разобрать_цикл_для_каждого(&mut self) -> Result<Оператор, ОшибкаПарсера> {
        self.ожидать(Token::Для, "цикл для каждого")?;
        self.ожидать(Token::Каждого, "цикл для каждого (ожидалось 'каждого')")?;
        let переменная = self.ожидать_идентификатор("имя переменной цикла")?;
        self.ожидать(Token::В, "цикл для каждого (ожидалось 'в')")?;
        let коллекция = self.разобрать_выражение()?;
        let тело = self.разобрать_блок()?;
        Ok(Оператор::ЦиклДляКаждого { переменная, коллекция, тело })
    }

    fn разобрать_цикл_пока(&mut self) -> Result<Оператор, ОшибкаПарсера> {
        self.ожидать(Token::Пока, "цикл пока")?;
        self.ожидать(Token::ОткрКруглая, "условие в скобках")?;
        let условие = self.разобрать_выражение()?;
        self.ожидать(Token::ЗакрКруглая, "условие в скобках")?;
        let тело = self.разобрать_блок()?;
        Ok(Оператор::ЦиклПока { условие, тело })
    }

    fn разобрать_вернуть(&mut self) -> Result<Оператор, ОшибкаПарсера> {
        self.ожидать(Token::Вернуть, "оператор возврата")?;
        let значение = if self.проверить(&Token::ТочкаЗапятой) {
            None
        } else {
            Some(self.разобрать_выражение()?)
        };
        self.ожидать(Token::ТочкаЗапятой, "конец оператора возврата")?;
        Ok(Оператор::Вернуть(значение))
    }

    fn разобрать_неизменное_объявление(&mut self) -> Result<Оператор, ОшибкаПарсера> {
        self.ожидать(Token::Неизменно, "неизменяемое объявление")?;
        let тип = self.разобрать_тип()?;
        let имя = self.ожидать_идентификатор("имя неизменяемой переменной")?;
        self.ожидать(Token::Равно, "инициализация неизменяемой переменной")?;
        let значение = self.разобрать_выражение()?;
        self.ожидать(Token::ТочкаЗапятой, "конец объявления")?;
        Ok(Оператор::ОбъявлениеНеизменное { тип, имя, значение })
    }

    fn разобрать_объявление_с_типом(&mut self) -> Result<Оператор, ОшибкаПарсера> {
        let тип = self.разобрать_тип()?;
        let имя = self.ожидать_идентификатор("имя переменной")?;
        self.ожидать(Token::Равно, "инициализация переменной")?;
        let значение = self.разобрать_выражение()?;
        self.ожидать(Token::ТочкаЗапятой, "конец объявления")?;
        Ok(Оператор::ОбъявлениеСТипом { тип, имя, значение })
    }

    /// Идентификатор в начале оператора неоднозначен без заглядывания вперёд:
    /// это может быть "имя = значение;" / "объект.поле = значение;"
    /// (присваивание/объявление с выводом типа) или просто выражение-оператор
    /// вроде вызова функции "вывести(...);".
    ///
    /// Стратегия: сначала собираем цепочку постфиксных операций (.поле, .поле.поле,
    /// вызов и т.д.) — то есть разбираем как обычное выражение. Затем смотрим,
    /// не идёт ли сразу после этого "=". Если да — это присваивание, и нужно
    /// проверить, что то, что мы собрали, вообще годится как МЕСТО ЗАПИСИ
    /// (простое имя или цепочка .поле — не вызов функции, не литерал).
    fn разобрать_идентификатор_как_оператор(&mut self) -> Result<Оператор, ОшибкаПарсера> {
        // "это" (Token::Это, не Token::Идентификатор) — отдельный токен в
        // лексере, но ведёт себя как обычный идентификатор для целей
        // присваивания в поле ("это.значение = ...;" — сеттер внутри
        // метода, самый обычный паттерн ООП). НАЙДЕННЫЙ ПРИ ТЕСТИРОВАНИИ
        // ПРОБЕЛ: раньше эта функция вызывалась ТОЛЬКО для Token::Идентификатор
        // (см. разобрать_оператор) — "это.поле = значение;" никогда не
        // работал в языке вообще, независимо от generics, просто это
        // обнаружилось только сейчас, при первой попытке написать метод-сеттер.
        let имя = if self.проверить(&Token::Это) {
            self.продвинуться();
            "это".to_string()
        } else {
            self.ожидать_идентификатор("оператор")?
        };
        let базовое = Выражение::Идентификатор(имя);
        let выражение = self.дособрать_постфиксные_операции(базовое)?;

        if self.совпадает(&Token::Равно) {
            let место = выражение_в_место_записи(выражение).map_err(|сообщение| self.ошибка(сообщение))?;
            let значение = self.разобрать_выражение()?;
            self.ожидать(Token::ТочкаЗапятой, "конец присваивания")?;
            Ok(Оператор::Присваивание { место, значение })
        } else {
            // это не присваивание — довершаем как обычное выражение-оператор
            // (вызов функции, доступ к полю без присваивания и т.д.)
            let выражение = self.дособрать_бинарные_операции(выражение, 0)?;
            self.ожидать(Token::ТочкаЗапятой, "конец оператора-выражения")?;
            Ok(Оператор::ВыражениеОператор(выражение))
        }
    }

    // ================== Выражения (раздел 8) — разбор с приоритетом операторов ==================
    //
    // Используем классическую технику "precedence climbing" (восхождение по приоритету):
    // каждый уровень приоритета — свой метод, от самого низкого (||) до самого высокого
    // (вызовы, доступ к полю, индексация). Это прямое отражение таблицы приоритетов
    // из грамматики, раздел 8.

    fn разобрать_выражение(&mut self) -> Result<Выражение, ОшибкаПарсера> {
        self.разобрать_или()
    }

    fn разобрать_или(&mut self) -> Result<Выражение, ОшибкаПарсера> {
        let mut левое = self.разобрать_и()?;
        while self.совпадает(&Token::Или) {
            let правое = self.разобрать_и()?;
            левое = Выражение::Бинарное {
                левое: Box::new(левое),
                оператор: БинарныйОператор::Или,
                правое: Box::new(правое),
            };
        }
        Ok(левое)
    }

    fn разобрать_и(&mut self) -> Result<Выражение, ОшибкаПарсера> {
        let mut левое = self.разобрать_битовое_или()?;
        while self.совпадает(&Token::И) {
            let правое = self.разобрать_битовое_или()?;
            левое = Выражение::Бинарное {
                левое: Box::new(левое),
                оператор: БинарныйОператор::И,
                правое: Box::new(правое),
            };
        }
        Ok(левое)
    }

    // НОВОЕ: настоящие побитовые операторы — приоритет между логическими
    // (&&/||, самый низкий) и обычным сравнением (==/!=, выше) — тот же
    // порядок, что в C/Rust: | ниже, чем ^, тот ниже, чем &.
    fn разобрать_битовое_или(&mut self) -> Result<Выражение, ОшибкаПарсера> {
        let mut левое = self.разобрать_битовое_искл()?;
        while self.совпадает(&Token::БитИли) {
            let правое = self.разобрать_битовое_искл()?;
            левое = Выражение::Бинарное {
                левое: Box::new(левое),
                оператор: БинарныйОператор::БитИли,
                правое: Box::new(правое),
            };
        }
        Ok(левое)
    }

    fn разобрать_битовое_искл(&mut self) -> Result<Выражение, ОшибкаПарсера> {
        let mut левое = self.разобрать_битовое_и()?;
        while self.совпадает(&Token::БитИскл) {
            let правое = self.разобрать_битовое_и()?;
            левое = Выражение::Бинарное {
                левое: Box::new(левое),
                оператор: БинарныйОператор::БитИскл,
                правое: Box::new(правое),
            };
        }
        Ok(левое)
    }

    fn разобрать_битовое_и(&mut self) -> Result<Выражение, ОшибкаПарсера> {
        let mut левое = self.разобрать_равенство()?;
        while self.совпадает(&Token::БитИ) {
            let правое = self.разобрать_равенство()?;
            левое = Выражение::Бинарное {
                левое: Box::new(левое),
                оператор: БинарныйОператор::БитИ,
                правое: Box::new(правое),
            };
        }
        Ok(левое)
    }

    fn разобрать_равенство(&mut self) -> Result<Выражение, ОшибкаПарсера> {
        let mut левое = self.разобрать_сравнение()?;
        loop {
            let оператор = if self.совпадает(&Token::РавноРавно) {
                БинарныйОператор::Равно
            } else if self.совпадает(&Token::НеРавно) {
                БинарныйОператор::НеРавно
            } else {
                break;
            };
            let правое = self.разобрать_сравнение()?;
            левое = Выражение::Бинарное {
                левое: Box::new(левое),
                оператор,
                правое: Box::new(правое),
            };
        }
        Ok(левое)
    }

    fn разобрать_сравнение(&mut self) -> Result<Выражение, ОшибкаПарсера> {
        let mut левое = self.разобрать_слагаемое()?;
        loop {
            let оператор = if self.совпадает(&Token::Меньше) {
                БинарныйОператор::Меньше
            } else if self.совпадает(&Token::Больше) {
                БинарныйОператор::Больше
            } else if self.совпадает(&Token::МеньшеРавно) {
                БинарныйОператор::МеньшеРавно
            } else if self.совпадает(&Token::БольшеРавно) {
                БинарныйОператор::БольшеРавно
            } else {
                break;
            };
            let правое = self.разобрать_слагаемое()?;
            левое = Выражение::Бинарное {
                левое: Box::new(левое),
                оператор,
                правое: Box::new(правое),
            };
        }
        Ok(левое)
    }

    fn разобрать_слагаемое(&mut self) -> Result<Выражение, ОшибкаПарсера> {
        let mut левое = self.разобрать_множитель()?;
        loop {
            let оператор = if self.совпадает(&Token::Плюс) {
                БинарныйОператор::Плюс
            } else if self.совпадает(&Token::Минус) {
                БинарныйОператор::Минус
            } else {
                break;
            };
            let правое = self.разобрать_множитель()?;
            левое = Выражение::Бинарное {
                левое: Box::new(левое),
                оператор,
                правое: Box::new(правое),
            };
        }
        Ok(левое)
    }

    fn разобрать_множитель(&mut self) -> Result<Выражение, ОшибкаПарсера> {
        let mut левое = self.разобрать_унарное()?;
        loop {
            let оператор = if self.совпадает(&Token::Звёздочка) {
                БинарныйОператор::Умножить
            } else if self.совпадает(&Token::Слэш) {
                БинарныйОператор::Разделить
            } else if self.совпадает(&Token::Процент) {
                БинарныйОператор::Остаток
            } else {
                break;
            };
            let правое = self.разобрать_унарное()?;
            левое = Выражение::Бинарное {
                левое: Box::new(левое),
                оператор,
                правое: Box::new(правое),
            };
        }
        Ok(левое)
    }

    fn разобрать_унарное(&mut self) -> Result<Выражение, ОшибкаПарсера> {
        if self.совпадает(&Token::Минус) {
            let операнд = self.разобрать_унарное()?;
            return Ok(Выражение::Унарное {
                оператор: УнарныйОператор::Минус,
                операнд: Box::new(операнд),
            });
        }
        if self.совпадает(&Token::Не) {
            let операнд = self.разобрать_унарное()?;
            return Ok(Выражение::Унарное {
                оператор: УнарныйОператор::Не,
                операнд: Box::new(операнд),
            });
        }
        // НОВОЕ: побитовое отрицание — переворачивает каждый бит числа.
        if self.совпадает(&Token::БитНе) {
            let операнд = self.разобрать_унарное()?;
            return Ok(Выражение::Унарное {
                оператор: УнарныйОператор::БитНе,
                операнд: Box::new(операнд),
            });
        }
        self.разобрать_постфиксное()
    }

    /// Постфиксные операции — то, что идёт СРАЗУ ПОСЛЕ базового выражения:
    /// вызов (), доступ .поле, индексация [i], проброс ошибки ?
    fn разобрать_постфиксное(&mut self) -> Result<Выражение, ОшибкаПарсера> {
        let базовое = self.разобрать_первичное()?;
        self.дособрать_постфиксные_операции(базовое)
    }

    fn дособрать_постфиксные_операции(&mut self, начальное: Выражение) -> Result<Выражение, ОшибкаПарсера> {
        let mut выражение = начальное;
        loop {
            if self.совпадает(&Token::Точка) {
                let имя_после_точки = self.ожидать_идентификатор("имя поля или метода после '.'")?;

                if self.проверить(&Token::ОткрКруглая) {
                    // объект.метод(аргументы) — вызов метода, отличается от
                    // обычного вызова функции тем, что "метод" принадлежит
                    // конкретному объекту слева, а не является свободным именем.
                    self.продвинуться(); // (
                    let аргументы = self.разобрать_аргументы()?;
                    self.ожидать(Token::ЗакрКруглая, "конец списка аргументов вызова метода")?;
                    выражение = Выражение::ВызовМетода {
                        объект: Box::new(выражение),
                        метод: имя_после_точки,
                        аргументы,
                    };
                } else {
                    выражение = Выражение::ДоступКПолю {
                        объект: Box::new(выражение),
                        поле: имя_после_точки,
                    };
                }
            } else if self.совпадает(&Token::ОткрКвадратная) {
                let индекс = self.разобрать_выражение()?;
                self.ожидать(Token::ЗакрКвадратная, "конец индексации")?;
                выражение = Выражение::ДоступПоИндексу {
                    массив: Box::new(выражение),
                    индекс: Box::new(индекс),
                };
            } else if self.проверить(&Token::ОткрКруглая) {
                // Вызов функции: имя(аргументы). Годится только когда "выражение"
                // на самом деле было простым именем — синтаксически f()() (вызов
                // результата вызова) в языке пока не предусмотрен, поэтому здесь
                // достаточно вытащить имя из Идентификатор, если оно есть.
                let имя = match &выражение {
                    Выражение::Идентификатор(имя) => имя.clone(),
                    other => {
                        return Err(self.ошибка(format!(
                            "нельзя вызвать как функцию выражение {:?} — вызов возможен только по простому имени",
                            other
                        )));
                    }
                };
                self.продвинуться(); // (
                let аргументы = self.разобрать_аргументы()?;
                self.ожидать(Token::ЗакрКруглая, "конец списка аргументов вызова")?;
                выражение = Выражение::ВызовФункции {
                    имя,
                    типовые_параметры: Vec::new(),
                    аргументы,
                };
            } else if self.совпадает(&Token::Вопрос) {
                выражение = Выражение::Проброс(Box::new(выражение));
            } else {
                break;
            }
        }
        Ok(выражение)
    }

    /// Используется, когда часть выражения уже разобрана вручную (см.
    /// разобрать_идентификатор_как_оператор) и нужно доразобрать возможные
    /// бинарные операции после неё. min_приоритет пока не используется для
    /// разных уровней (упрощённая версия) — полноценный разбор с нуля всегда
    /// идёт через разобрать_выражение(); этот метод — узкий случай для
    /// операторов верхнего уровня, начинающихся с идентификатора.
    fn дособрать_бинарные_операции(
        &mut self,
        левое: Выражение,
        _min_приоритет: u8,
    ) -> Result<Выражение, ОшибкаПарсера> {
        // Простая реализация: если после базового выражения идёт бинарный оператор,
        // разбираем правую часть полноценным разбором выражения. Вложенность приоритетов
        // внутри правой части обрабатывается рекурсивно самим разобрать_выражение().
        if есть_бинарный_оператор(self.текущий()) {
            let оператор = токен_в_бинарный_оператор(&self.продвинуться()).unwrap();
            let правое = self.разобрать_выражение()?;
            Ok(Выражение::Бинарное {
                левое: Box::new(левое),
                оператор,
                правое: Box::new(правое),
            })
        } else {
            Ok(левое)
        }
    }

    fn разобрать_первичное(&mut self) -> Result<Выражение, ОшибкаПарсера> {
        match self.текущий().clone() {
            Token::ЦелоеЛит(n) => { self.продвинуться(); Ok(Выражение::ЦелоеЛит(n)) }
            Token::ДробноеЛит(n) => { self.продвинуться(); Ok(Выражение::ДробноеЛит(n)) }
            Token::ТекстЛит(s) => { self.продвинуться(); Ok(разобрать_текстовый_литерал(s)) }
            Token::ВерноЛит(b) => { self.продвинуться(); Ok(Выражение::ВерноЛит(b)) }
            Token::НеуказаноЛит => { self.продвинуться(); Ok(Выражение::НеуказаноЛит) }

            Token::ОткрКруглая => {
                self.продвинуться();
                let внутреннее = self.разобрать_выражение()?;
                self.ожидать(Token::ЗакрКруглая, "закрывающая скобка выражения")?;
                Ok(внутреннее)
            }

            Token::ОткрКвадратная => {
                self.продвинуться();
                let mut элементы = Vec::new();
                if !self.проверить(&Token::ЗакрКвадратная) {
                    элементы.push(self.разобрать_выражение()?);
                    while self.совпадает(&Token::Запятая) {
                        элементы.push(self.разобрать_выражение()?);
                    }
                }
                self.ожидать(Token::ЗакрКвадратная, "конец литерала массива")?;
                Ok(Выражение::МассивЛит(элементы))
            }

            Token::Успех => {
                self.продвинуться();
                self.ожидать(Token::ОткрКруглая, "успех(значение)")?;
                let внутреннее = self.разобрать_выражение()?;
                self.ожидать(Token::ЗакрКруглая, "успех(значение)")?;
                Ok(Выражение::Успех(Box::new(внутреннее)))
            }

            Token::Ошибка => {
                self.продвинуться();
                self.ожидать(Token::ОткрКруглая, "ошибка(значение)")?;
                let внутреннее = self.разобрать_выражение()?;
                self.ожидать(Token::ЗакрКруглая, "ошибка(значение)")?;
                Ok(Выражение::Ошибка(Box::new(внутреннее)))
            }

            Token::Это => {
                self.продвинуться();
                Ok(Выражение::Идентификатор("это".to_string()))
            }

            // НОВОЕ: явное приведение типа — "целое32(значение)" и подобные
            // (см. подробное объяснение в semantic.rs, у функции
            // имя_числового_типа_в_решённый_тип). Встроенные числовые типы —
            // ОТДЕЛЬНЫЕ токены (не Token::Идентификатор), значит без этой
            // ветки парсер вообще не распознал бы "целое(...)" как начало
            // выражения — падал бы с "ожидалось выражение".
            токен @ (Token::Целое | Token::Целое8 | Token::Целое16 | Token::Целое32 | Token::Целое64
                | Token::Беззнак8 | Token::Беззнак16 | Token::Беззнак32 | Token::Беззнак64
                | Token::Дробное | Token::Дробное32 | Token::Дробное64)
                if matches!(self.токены.get(self.позиция + 1).map(|т| &т.токен), Some(Token::ОткрКруглая)) =>
            {
                let имя_типа = имя_токена_типа(&токен);
                self.продвинуться();
                self.продвинуться();
                let значение = self.разобрать_выражение()?;
                self.ожидать(Token::ЗакрКруглая, "конец приведения типа")?;
                Ok(Выражение::ВызовФункции {
                    имя: имя_типа,
                    типовые_параметры: Vec::new(),
                    аргументы: vec![значение],
                })
            }

            Token::Идентификатор(имя) => {
                self.продвинуться();

                // Возможен вызов с явными типовыми параметрами: Список<целое>(...).
                // "<" неоднозначен — это может быть и оператор "меньше". Разрешаем
                // это ПОПЫТКОЙ разбора с откатом позиции: пробуем прочитать
                // "<тип, тип, ...>(" — если где-то не сошлось, откатываемся и
                // читаем "<" как обычный оператор сравнения дальше по цепочке.
                // Та же принципиальная неоднозначность, что и знаменитая
                // "a<b>(c)" в C++ — полностью безопасного решения без отката
                // здесь не существует ни в одном языке с похожим синтаксисом.
                if self.проверить(&Token::Меньше) {
                    let сохранённая_позиция = self.позиция;
                    if let Some(выражение) = self.попробовать_генерик_вызов(&имя) {
                        return Ok(выражение);
                    }
                    self.позиция = сохранённая_позиция;
                }

                if self.проверить(&Token::ОткрКруглая) {
                    self.продвинуться();
                    let аргументы = self.разобрать_аргументы()?;
                    self.ожидать(Token::ЗакрКруглая, "конец списка аргументов вызова")?;
                    Ok(Выражение::ВызовФункции {
                        имя,
                        типовые_параметры: Vec::new(),
                        аргументы,
                    })
                } else {
                    Ok(Выражение::Идентификатор(имя))
                }
            }

            other => Err(self.ошибка(format!("ожидалось выражение, встретилось {:?}", other))),
        }
    }

    /// Проверяет (с полным откатом позиции — этот метод НИКОГДА не оставляет
    /// парсер сдвинутым, вне зависимости от результата), похоже ли то, что
    /// сейчас впереди, на "Тип<параметры> имя" — начало объявления переменной
    /// с обобщённым типом ("Список<целое> очки = ...;"). Быстрая проверка
    /// следующего токена (сразу "<") — чтобы не запускать полноценную (хоть
    /// и безопасную) попытку разбора типа на КАЖДОМ операторе, начинающемся
    /// с идентификатора, а только на тех, где это вообще может иметь смысл.
    fn похоже_на_обобщённое_объявление(&mut self) -> bool {
        if !matches!(self.заглянуть_вперёд(1), Token::Меньше) {
            return false;
        }

        let сохранённая_позиция = self.позиция;
        let результат = match self.разобрать_тип() {
            Ok(_) => matches!(self.текущий(), Token::Идентификатор(_)),
            Err(_) => false,
        };
        self.позиция = сохранённая_позиция;
        результат
    }

    /// Пытается разобрать "<тип, тип, ...>(аргументы)" — синтаксис явного
    /// вызова с типовыми параметрами (Список<целое>(), Словарь<текст, целое>()).
    /// Возвращает None при ЛЮБОЙ неудаче на любом шаге (не пробрасывает
    /// ошибку наружу) — вызывающий код (разобрать_первичное) в этом случае
    /// откатывает позицию парсера и разбирает "<" как обычный оператор
    /// сравнения. Позицию парсера НЕ трогаем при неудаче — откат делает
    /// вызывающий код, у которого сохранена позиция "до" вызова этого метода.
    fn попробовать_генерик_вызов(&mut self, имя: &str) -> Option<Выражение> {
        self.продвинуться(); // '<' — уже проверен вызывающим кодом (self.проверить)

        let mut типы = Vec::new();
        типы.push(self.разобрать_тип().ok()?);
        while self.проверить(&Token::Запятая) {
            self.продвинуться();
            типы.push(self.разобрать_тип().ok()?);
        }

        if !self.совпадает(&Token::Больше) {
            return None;
        }
        if !self.проверить(&Token::ОткрКруглая) {
            return None;
        }
        self.продвинуться(); // '('

        let аргументы = self.разобрать_аргументы().ok()?;

        if !self.совпадает(&Token::ЗакрКруглая) {
            return None;
        }

        Some(Выражение::ВызовФункции {
            имя: имя.to_string(),
            типовые_параметры: типы,
            аргументы,
        })
    }

    fn разобрать_аргументы(&mut self) -> Result<Vec<Выражение>, ОшибкаПарсера> {
        let mut аргументы = Vec::new();
        if self.проверить(&Token::ЗакрКруглая) {
            return Ok(аргументы);
        }
        аргументы.push(self.разобрать_выражение()?);
        while self.совпадает(&Token::Запятая) {
            аргументы.push(self.разобрать_выражение()?);
        }
        Ok(аргументы)
    }
}

