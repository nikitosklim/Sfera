/// Проверяет, что разобранное выражение годится как "место записи" (lvalue) —
/// то есть в него в принципе можно что-то присвоить — и превращает его в
/// МестоЗаписи. Годятся только простые имена и цепочки доступа к полю
/// (.поле.поле...); вызовы функций, литералы, арифметические выражения
/// и так далее — не годятся, присвоить в них ничего нельзя.
/// Сканирует содержимое текстового литерала на предмет интерполяции ($имя)
/// и превращает его либо в простой Выражение::ТекстЛит (если интерполяции
/// нет — подавляющее большинство строк в реальном коде), либо в
/// Выражение::ИнтерполированныйТекст с разбивкой на фрагменты.
///
/// Правило распознавания идентификатора после "$": та же самая логика, что
/// и в лексере для обычных идентификаторов (буквы любого алфавита, цифры,
/// подчёркивание, не может начинаться с цифры) — см. lexer.rs. Дублирование
/// этого небольшого куска логики между лексером и этой функцией осознанное:
/// лексер работает с ПОТОКОМ токенов всего файла, а эта функция — с уже
/// готовой строкой текстового литерала, извлечённой лексером как единое
/// целое; пропускать через полноценный лексер ещё раз ради пары символов
/// было бы избыточным усложнением.
///
/// ОГРАНИЧЕНИЕ ЭТОЙ ВЕРСИИ: поддерживается только "$имя", НЕ "${выражение}"
/// — см. комментарий у Выражение::ИнтерполированныйТекст в ast.rs.
/// Превращает токен встроенного числового типа обратно в его текстовое
/// имя (как оно пишется в коде) — нужно для разбора явного приведения
/// типа ("целое32(значение)"), см. разобрать_первичное.
fn имя_токена_типа(токен: &Token) -> String {
    match токен {
        Token::Целое => "целое",
        Token::Целое8 => "целое8",
        Token::Целое16 => "целое16",
        Token::Целое32 => "целое32",
        Token::Целое64 => "целое64",
        Token::Беззнак8 => "беззнак8",
        Token::Беззнак16 => "беззнак16",
        Token::Беззнак32 => "беззнак32",
        Token::Беззнак64 => "беззнак64",
        Token::Дробное => "дробное",
        Token::Дробное32 => "дробное32",
        Token::Дробное64 => "дробное64",
        other => unreachable!("имя_токена_типа вызвана для неожиданного токена: {:?}", other),
    }
    .to_string()
}

fn разобрать_текстовый_литерал(текст: String) -> Выражение {
    if !текст.contains('$') {
        return Выражение::ТекстЛит(текст);
    }

    let символы: Vec<char> = текст.chars().collect();
    let mut фрагменты = Vec::new();
    let mut текущий_текст = String::new();
    let mut позиция = 0;

    while позиция < символы.len() {
        let c = символы[позиция];

        if c == '$' && позиция + 1 < символы.len() && является_началом_идентификатора(символы[позиция + 1]) {
            // Закрываем накопленный текстовый кусок (если есть) и начинаем
            // читать имя переменной после "$".
            if !текущий_текст.is_empty() {
                фрагменты.push(ФрагментТекста::Текст(std::mem::take(&mut текущий_текст)));
            }

            позиция += 1; // пропускаем сам "$"
            let начало_имени = позиция;
            while позиция < символы.len() && является_частью_идентификатора(символы[позиция]) {
                позиция += 1;
            }
            let имя: String = символы[начало_имени..позиция].iter().collect();
            фрагменты.push(ФрагментТекста::Переменная(имя));
        } else {
            текущий_текст.push(c);
            позиция += 1;
        }
    }

    if !текущий_текст.is_empty() {
        фрагменты.push(ФрагментТекста::Текст(текущий_текст));
    }

    // Если единственным "фрагментом" оказался обычный текст (например,
    // строка содержала "$", но не была похожа на переменную — "цена: 5$")
    // — возвращаем простой литерал, без обёртки в интерполяцию.
    if фрагменты.len() == 1 {
        if let ФрагментТекста::Текст(единственный) = &фрагменты[0] {
            return Выражение::ТекстЛит(единственный.clone());
        }
    }
    if фрагменты.is_empty() {
        return Выражение::ТекстЛит(String::new());
    }

    Выражение::ИнтерполированныйТекст(фрагменты)
}

/// Может ли символ быть ПЕРВЫМ символом идентификатора внутри интерполяции —
/// такое же правило, как в lexer.rs (буквы любого алфавита, подчёркивание,
/// не цифра). Отдельная копия для parser.rs — см. комментарий выше.
fn является_началом_идентификатора(c: char) -> bool {
    c.is_alphabetic() || c == '_'
}

fn является_частью_идентификатора(c: char) -> bool {
    c.is_alphanumeric() || c == '_'
}

fn выражение_в_место_записи(выражение: Выражение) -> Result<МестоЗаписи, String> {
    match выражение {
        Выражение::Идентификатор(имя) => Ok(МестоЗаписи::Имя(имя)),
        Выражение::ДоступКПолю { объект, поле } => {
            let объект_как_место = выражение_в_место_записи(*объект)?;
            Ok(МестоЗаписи::Поле {
                объект: Box::new(объект_как_место),
                поле,
            })
        }
        Выражение::ДоступПоИндексу { массив, индекс } => {
            let массив_как_место = выражение_в_место_записи(*массив)?;
            Ok(МестоЗаписи::Индекс {
                массив: Box::new(массив_как_место),
                индекс,
            })
        }
        other => Err(format!(
            "нельзя присвоить значение в {:?} — это не переменная, не поле структуры и не элемент массива",
            other
        )),
    }
}

fn является_началом_типа(токен: &Token) -> bool {
    matches!(
        токен,
        Token::Целое
            | Token::Целое8
            | Token::Целое16
            | Token::Целое32
            | Token::Целое64
            | Token::Беззнак8
            | Token::Беззнак16
            | Token::Беззнак32
            | Token::Беззнак64
            | Token::Дробное
            | Token::Дробное32
            | Token::Дробное64
            | Token::Текст
            | Token::Верно
            | Token::Результат
            | Token::Канал
    )
    // Примечание: Token::Идентификатор здесь намеренно НЕ считается началом типа
    // на этом уровне разбора оператора — потому что "Идентификатор имя = ...;"
    // неоднозначен между "объявление пользовательского типа" и "присваивание".
    // Различение по тому, объявлен ли уже такое имя как тип, — задача
    // семантического анализа (см. grammar.md, раздел 4). Парсер на этом этапе
    // трактует голый идентификатор в начале оператора как потенциальное
    // присваивание/вызов, что покрывает главный рабочий случай уже сейчас.
}

fn есть_бинарный_оператор(токен: &Token) -> bool {
    токен_в_бинарный_оператор(токен).is_some()
}

fn токен_в_бинарный_оператор(токен: &Token) -> Option<БинарныйОператор> {
    match токен {
        Token::Плюс => Some(БинарныйОператор::Плюс),
        Token::Минус => Some(БинарныйОператор::Минус),
        Token::Звёздочка => Some(БинарныйОператор::Умножить),
        Token::Слэш => Some(БинарныйОператор::Разделить),
        Token::Процент => Some(БинарныйОператор::Остаток),
        Token::РавноРавно => Some(БинарныйОператор::Равно),
        Token::НеРавно => Some(БинарныйОператор::НеРавно),
        Token::Меньше => Some(БинарныйОператор::Меньше),
        Token::Больше => Some(БинарныйОператор::Больше),
        Token::МеньшеРавно => Some(БинарныйОператор::МеньшеРавно),
        Token::БольшеРавно => Some(БинарныйОператор::БольшеРавно),
        Token::И => Some(БинарныйОператор::И),
        Token::Или => Some(БинарныйОператор::Или),
        _ => None,
    }
}
