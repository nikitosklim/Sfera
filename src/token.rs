//! Токены языка — минимальные "неделимые" единицы исходного кода,
//! на которые лексер разбивает текст программы.

#[derive(Debug, Clone, PartialEq)]
pub enum Token {
    // --- Литералы ---
    ЦелоеЛит(i64),
    ДробноеЛит(f64),
    ТекстЛит(String),
    ВерноЛит(bool),
    НеуказаноЛит,

    // --- Идентификатор (имя переменной/функции/типа) ---
    Идентификатор(String),

    // --- Ключевые слова ---
    Функция,
    Структура,
    /// "внешняя функция имя(параметры) -> тип;" — объявление привязки к
    /// функции из внешней C-библиотеки (FFI). См. подробный комментарий
    /// у ast::ОбъявлениеВнешнейФункции.
    Внешняя,
    /// "внешняя функция русское_имя(...) -> тип как "РеальноеИмя";" —
    /// позволяет вызывать внешнюю функцию ПОЛНОСТЬЮ по-русски в коде,
    /// сохраняя реальное имя символа библиотеки скрытым в одной строке
    /// объявления. См. ast::ОбъявлениеВнешнейФункции.
    Как,
    Контракт,
    Подключить,
    Если,
    Иначе,
    Для,
    Каждого,
    В,
    Пока,
    Вернуть,
    Публично,
    Приватно,
    Результат,
    Успех,
    Ошибка,
    Слабая,
    Неизменно,
    Ссылка,
    Параллельно,
    /// НОВОЕ (детерминированный планировщик — см. ДОКУМЕНТАЦИЯ_ЯЗЫКА.md,
    /// раздел "Детерминированность"/"Многопоточность"): модификатор у
    /// "параллельно детерминировано { ... }" — не отдельная конструкция,
    /// а необязательное ключевое слово сразу после "параллельно".
    Детерминировано,
    Канал,
    Это,
    /// "прервать;" — немедленный выход из ближайшего охватывающего цикла
    /// (пока/для каждого). Раньше не было вообще — выход из цикла
    /// эмулировался булевым флагом в условии.
    Прервать,
    /// "продолжить;" — пропустить остаток тела ближайшего охватывающего
    /// цикла и перейти к следующей итерации (для пока — сразу к проверке
    /// условия; для для каждого — к следующему элементу).
    Продолжить,
    /// НОВОЕ (русская раскладка): "конец" — закрывает блок вместо "}".
    /// Открывающего слова нет: блок начинается сразу после заголовка
    /// (после ")" условия, после списка параметров функции и так далее).
    Конец,
    /// НОВОЕ (русская раскладка): "из" — вместо "<...>" у обобщённых типов:
    /// "Список из целое", "Словарь из текст и целое".
    Из,

    // Ключевые слова базовых типов
    Целое,
    Целое8,
    Целое16,
    Целое32,
    Целое64,
    Беззнак8,
    Беззнак16,
    Беззнак32,
    Беззнак64,
    Дробное,
    Дробное32,
    Дробное64,
    Текст,
    Верно,

    // --- Операторы ---
    Плюс,           // +
    Минус,          // -
    Звёздочка,      // *
    Слэш,           // /
    Процент,        // %
    Равно,          // =
    РавноРавно,     // ==
    НеРавно,        // !=
    Меньше,         // <
    Больше,         // >
    МеньшеРавно,    // <=
    БольшеРавно,    // >=
    И,              // &&
    Или,            // ||
    Не,             // !
    Вопрос,         // ?
    Доллар,         // $ (для интерполяции строк)
    // НОВОЕ: настоящие побитовые операторы — раньше их не было вообще,
    // при работе с сетевыми сокетами пришлось обходить арифметикой
    // (умножение вместо сдвига) — честная заплатка для одного узкого
    // случая, не общее решение.
    //
    // ⚠️ Честно нет сдвигов (<<, >>) в этой версии — язык уже использует
    // '<'/'>' для обобщённых типов (Список<целое>), а вложенные обобщённые
    // типы (Список<Список<целое>>) дали бы лексеру два подряд идущих '<',
    // которые легко перепутать с одним токеном сдвига — та же самая
    // ловушка, что была в ранних версиях C++ до отдельного разбора ">>".
    // Решаемо, но требует более аккуратной, контекстно-зависимой логики,
    // не сделанной "на глаз" сейчас.
    БитИ,           // & (побитовое И, не путать с && выше)
    БитИли,         // | (побитовое ИЛИ, не путать с || выше)
    БитИскл,        // ^ (побитовое ИСКЛЮЧАЮЩЕЕ ИЛИ, xor)
    БитНе,          // ~ (побитовое отрицание, унарный)

    // --- Разделители ---
    ОткрФигурная,   // {
    ЗакрФигурная,   // }
    ОткрКруглая,    // (
    ЗакрКруглая,    // )
    ОткрКвадратная, // [
    ЗакрКвадратная, // ]
    Точка,          // .
    Запятая,        // ,
    ТочкаЗапятой,   // ;
    Двоеточие,      // :
    Стрелка,        // ->

    // --- Служебное ---
    КонецФайла,
}

impl Token {
    /// Как токен выглядит в исходном коде — для сообщений об ошибках
    /// («ожидалось «конец», встретилось «;»» вместо Debug-вида `Конец`).
    pub fn в_тексте(&self) -> String {
        use Token::*;
        let слово: &str = match self {
            ЦелоеЛит(н) => return format!("число {}", н),
            ДробноеЛит(н) => return format!("число {}", н),
            ТекстЛит(т) => return format!("строка \"{}\"", т),
            ВерноЛит(true) => "да",
            ВерноЛит(false) => "нет",
            НеуказаноЛит => "неуказано",
            Идентификатор(и) => return format!("имя «{}»", и),
            Функция => "функция", Структура => "структура", Внешняя => "внешняя", Как => "как",
            Контракт => "контракт", Подключить => "подключить", Если => "если", Иначе => "иначе",
            Для => "для", Каждого => "каждого", В => "в", Пока => "пока", Вернуть => "вернуть",
            Публично => "публично", Приватно => "приватно", Результат => "результат",
            Успех => "успех", Ошибка => "ошибка", Слабая => "слабая", Неизменно => "неизменно",
            Ссылка => "ссылка", Параллельно => "параллельно", Детерминировано => "детерминировано",
            Канал => "канал", Это => "это", Прервать => "прервать", Продолжить => "продолжить",
            Конец => "конец", Из => "из",
            Целое => "целое", Целое8 => "целое8", Целое16 => "целое16", Целое32 => "целое32",
            Целое64 => "целое64", Беззнак8 => "беззнак8", Беззнак16 => "беззнак16",
            Беззнак32 => "беззнак32", Беззнак64 => "беззнак64", Дробное => "дробное",
            Дробное32 => "дробное32", Дробное64 => "дробное64", Текст => "текст", Верно => "верно",
            Плюс => "+", Минус => "-", Звёздочка => "*", Слэш => "/", Процент => "%", Равно => "=",
            РавноРавно => "==", НеРавно => "!=", Меньше => "<", Больше => ">", МеньшеРавно => "<=",
            БольшеРавно => ">=", И => "и", Или => "или", Не => "не", Вопрос => "?", Доллар => "$",
            БитИ => "&", БитИли => "|", БитИскл => "^", БитНе => "~",
            ОткрФигурная => "{", ЗакрФигурная => "}", ОткрКруглая => "(", ЗакрКруглая => ")",
            ОткрКвадратная => "[", ЗакрКвадратная => "]", Точка => ".", Запятая => ",",
            ТочкаЗапятой => ";", Двоеточие => ":", Стрелка => "->",
            КонецФайла => return "конец файла".to_string(),
        };
        format!("«{}»", слово)
    }
}

/// Токен с привязкой к позиции в исходном коде — нужно для внятных
/// сообщений об ошибках ("ошибка на строке 5, столбец 10"), а не
/// абстрактного "где-то что-то не так".
#[derive(Debug, Clone, PartialEq)]
pub struct ТокенСПозицией {
    pub токен: Token,
    pub строка: usize,
    pub столбец: usize,
    /// Смещения в исходном тексте в СИМВОЛАХ (не байтах): [начало, конец).
    /// Нужны конвертеру старого синтаксиса в новый (`--в-русский`).
    pub начало: usize,
    pub конец: usize,
}
