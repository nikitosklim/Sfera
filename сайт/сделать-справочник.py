#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Собирает страницы «Справочник API» из content/api-источник/*.md.

Блок ```код запустить  — программа компилируется и запускается настоящим
компилятором, а её вывод вставляется под примером («Что выведет программа»).
Блок ```код            — просто пример, без запуска.
Запуск: python3 сделать-справочник.py [путь-к-запустить]
"""
import os, re, subprocess, sys, tempfile, pathlib

корень = pathlib.Path(__file__).resolve().parent
источник = корень / "content" / "api-источник"
вывод = корень / "content" / "docs"
запустить = sys.argv[1] if len(sys.argv) > 1 else str(корень.parent / "target" / "release" / "запустить")

блок = re.compile(r"```код( запустить(?::([^\n]*))?)?\n(.*?)```", re.S)
ошибок = 0

def выполнить(код, имя, флаги=""):
    global ошибок
    with tempfile.TemporaryDirectory() as т:
        f = pathlib.Path(т) / "пример.код"
        f.write_text(код, encoding="utf-8")
        р = subprocess.run([запустить, str(f)] + флаги.split(), cwd=т, capture_output=True, text=True, timeout=120)
        if р.returncode != 0:
            ошибок += 1
            print(f"ОШИБКА в {имя}:\n{код}\n{р.stdout}{р.stderr}", file=sys.stderr)
            return None
        return р.stdout.rstrip("\n")

# латинское имя страницы -> файл модуля в стандартной_библиотека
# страницы, для которых выписываются ВСЕ функции с пояснениями из исходников
подробные = {"markdown", "web", "net", "sqlite", "graphics", "browser", "android", "hw-base", "hw-x86", "boards", "user-sys"}
модули = {"markdown": "разметка", "web": "веб", "net": "сеть", "sqlite": "база_данных", "graphics": "графика",
          "browser": "браузер", "android": "приложение_android", "user-sys": "сис_пользователя",
          "hw-base": "голое_железо,дробные_программно", "hw-x86": "железо_х86,память_х86,экран_х86,задачи_х86,диск_х86,пользователь_х86",
          "boards": "плата_х86_пк,плата_х86_ос,плата_riscv_virt,плата_cortex_m_mps2,плата_rp2040",
          "files": "файлы", "log": "лог", "metrics": "метрики", "storage": "хранилище", "tracing": "трейсинг", "profiler": "профилировщик"}

def первые_предложения(т, предел=320):
    т = re.sub(r"\s+", " ", т).strip()
    if len(т) <= предел:
        return т
    обрезано = т[:предел]
    k = max(обрезано.rfind(". "), обрезано.rfind("; "))
    return (обрезано[:k + 1] if k > 80 else обрезано.rstrip() + "…")

def подробный_список(имя):
    """Все функции и структуры модулей страницы: сигнатура и пояснение из исходника."""
    вых = "\n\n## Все функции и структуры\n\nПолный список из исходников модуля. Пояснения взяты из комментариев к функциям.\n"
    for файл_модуля in модули[имя].split(","):
        путь = корень.parent / "стандартная_библиотека" / (файл_модуля + ".код")
        код = путь.read_text(encoding="utf-8").splitlines()
        вых += f"\n### Модуль «{файл_модуля}»\n\n"
        for н, с in enumerate(код):
            if not re.match(r"^(экспорт )?(внешняя функция|функция|структура) ", с):
                continue
            заметка = []
            k = н - 1
            while k >= 0 and код[k].startswith("//"):
                заметка.insert(0, код[k][2:].strip())
                k -= 1
            голова = re.split(r" как \"", с)[0].rstrip(";").rstrip()
            строка = f"- `{голова}`"
            т = первые_предложения(" ".join(заметка))
            if т:
                строка += " — " + т
            вых += строка + "\n"
    return вых

def сигнатуры(имя):
    """Автоматический список: все функции и структуры модуля, как они объявлены."""
    if имя in подробные:
        return подробный_список(имя)
    м = модули.get(имя)
    if not м:
        return ""
    код = (корень.parent / "стандартная_библиотека" / (м + ".код")).read_text(encoding="utf-8").splitlines()
    строки = []
    for н, с in enumerate(код):
        if re.match(r"^(экспорт )?(функция|структура) ", с):
            заметка = []
            k = н - 1
            while k >= 0 and код[k].startswith("//"):
                заметка.insert(0, код[k][2:].strip())
                k -= 1
            голова = с.split(" вернуть ")[0].rstrip()
            строки.append((голова, " ".join(заметка)))
    if not строки:
        return ""
    вых = "\n\n## Полный список объявлений\n\nТак эти функции объявлены в исходниках модуля:\n\n```\n"
    вых += "\n".join(г for г, _ in строки) + "\n```\n"
    return вых

for файл in sorted(источник.glob("*.md")):
    текст = файл.read_text(encoding="utf-8")
    def замена(м):
        код = м.group(3)
        запуск = м.group(1)
        флаги = м.group(2) or ""
        результат = "```\n" + код + "```"
        if запуск:
            out = выполнить(код, файл.name, флаги)
            if out is not None:
                результат += "\n\n**Что выведет программа:**\n\n```\n" + out + "\n```"
        return результат
    итог = блок.sub(замена, текст)
    итог = итог.replace("<!--", "")  # заготовка
    итог += сигнатуры(файл.stem)
    цель = вывод / f"api-{файл.stem}.md"
    цель.write_text(итог, encoding="utf-8")
    print("записано", цель.name)
sys.exit(1 if ошибок else 0)
