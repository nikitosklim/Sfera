def slug(заголовок):
    s = заголовок.lower().replace("`", "")
    s = re.sub(r"[^\w\s-]", "", s)
    return s.replace(" ", "-")

текст = open(ИСТОЧНИК, encoding="utf-8").read().replace("\r\n", "\n")
строки = текст.split("\n")

# 1. делим на разделы по "## " (вне блоков кода)
разделы = []   # (заголовок, [строки])
в_коде = False
текущий = None
for с in строки:
    if с.startswith("```"):
        в_коде = not в_коде
    if not в_коде and с.startswith("## "):
        текущий = (с[3:].strip(), [])
        разделы.append(текущий)
        continue
    if текущий is not None:
        текущий[1].append(с)

# 2. карта якорей: любой заголовок -> файл темы
def найти_тему(заголовок):
    for начало, файл, _, _ in ТЕМЫ:
        if заголовок.startswith(начало):
            return файл
    return None

якоря = {}
for заголовок, тело in разделы:
    файл = найти_тему(заголовок)
    if not файл:
        continue
    якоря[slug(заголовок)] = файл
    в_коде = False
    for с in тело:
        if с.startswith("```"):
            в_коде = not в_коде
        m = re.match(r"^(#{3,6}) (.+)$", с)
        if m and not в_коде:
            якоря[slug(m.group(2).strip())] = файл

def починить_ссылки(с):
    def замена(m):
        файл = якоря.get(m.group(2))
        return f"{m.group(1)}](/docs/{файл})" if файл else m.group(0)
    return re.sub(r"(\[[^\]]*)\]\(#([^)]+)\)", замена, с)

os.makedirs(ПАПКА, exist_ok=True)
список = ["# Формат: имя файла без .md | название | описание | категория"]
использованы = set()
for начало, файл, категория, описание in ТЕМЫ:
    найден = [(з, т) for з, т in разделы if з.startswith(начало)]
    if not найден:
        print("НЕ НАЙДЕН раздел:", начало)
        continue
    заголовок, тело = найден[0]
    использованы.add(заголовок)
    вых = [f"# {заголовок}", ""]
    в_коде = False
    for с in тело:
        if с.startswith("```"):
            в_коде = not в_коде
            вых.append(с)
            continue
        if not в_коде:
            m = re.match(r"^(#{3,6}) (.+)$", с)
            if m:
                с = "#" * (len(m.group(1)) - 1) + " " + m.group(2)
            с = починить_ссылки(с)
        вых.append(с)
    while вых and вых[-1].strip() in ("", "---"):
        вых.pop()
    open(os.path.join(ПАПКА, файл + ".md"), "w", encoding="utf-8", newline="\n").write("\n".join(вых) + "\n")
    название = re.sub(r"\s*\(.*?\)", "", заголовок.replace("`", "")).split(" — ")[0].strip()
    список.append(f"{файл} | {название} | {описание} | {категория}")
open(os.path.join(ПАПКА, "list.txt"), "w", encoding="utf-8", newline="\n").write("\n".join(список) + "\n")
пропущены = [з for з, _ in разделы if з not in использованы and з != "Содержание"]
print("Тем:", len(список) - 1, "Не вошли разделы:", пропущены)
