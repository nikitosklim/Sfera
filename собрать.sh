#!/bin/bash
# Пересобирает компилятор "Сфера" и обновляет команду "запустить" в PATH.
# Нужен только ПОКА мы вместе дорабатываем сам компилятор — как только
# исходники компилятора перестанут меняться каждую сессию, этот скрипт
# больше не понадобится: "запустить" останется как обычная, самостоятельная
# команда, полностью независимая от cargo.
#
# Использование:
#   ./собрать.sh

set -e  # остановиться при первой же ошибке, не продолжать вслепую

echo "Пересобираю компилятор (cargo build --release)..."
cargo build --release

echo "Обновляю команду 'запустить' в /usr/local/bin..."
sudo cp target/release/sfera /usr/local/bin/запустить

# НОВОЕ (найдено реальным, честным вопросом — "разработчик создаёт новую
# папку проекта на рабочем столе, и раз язык установлен в системе,
# встроенные модули должны находиться сами, без ручного копирования
# файлов стандартной библиотеки в каждый новый проект" — та же модель,
# что "import os" в Python): компилятор сам умеет искать
# "стандартная_библиотека/" рядом с собой по пути .../lib/sfera/
# стандартная_библиотека/ относительно установленного бинарника — этот
# шаг синхронно копирует туда актуальную версию при каждой пересборке,
# чтобы библиотека никогда не отставала от компилятора.
echo "Обновляю системную стандартную библиотеку в /usr/local/lib/sfera/..."
sudo mkdir -p /usr/local/lib/sfera
sudo rm -rf /usr/local/lib/sfera/стандартная_библиотека
sudo cp -r стандартная_библиотека /usr/local/lib/sfera/стандартная_библиотека

echo ""
echo "Готово. Команда 'запустить' обновлена и указывает на свежую сборку."
echo "Стандартная библиотека доступна из любого проекта без копирования файлов."
echo "Пример: запустить привет.код"
