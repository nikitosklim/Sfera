# минимальный_рантайм.s — замена libc для "автономного" (freestanding)
# режима языка «Сфера». Настоящий x86-64 ассемблер, без единой строчки
# C или чего-либо ещё — берёт на себя ровно то, что обычно незаметно
# делает операционная система через libc: точку входа и системные вызовы.
#
# АРХИТЕКТУРНАЯ ИДЕЯ: наш компилятор УЖЕ генерирует настоящую
# C-совместимую функцию "main" (вызывающую пользовательскую "главная"),
# рассчитывая, что libc её найдёт и вызовет через свою обычную цепочку
# _start -> __libc_start_main -> main. В "автономном" режиме этой цепочки
# нет вообще — значит нужно самим предоставить "_start" (первую
# инструкцию, которая выполнится после запуска), которая вызовет "main"
# напрямую, без единого посредника.
#
# Собирается отдельно: as минимальный_рантайм.s -o минимальный_рантайм.o
# Линкуется вместе с программой на Сфере через --линковать (см. main.rs,
# флаг --автономно).

.intel_syntax noprefix
.text
.global _start

# НОВОЕ: резервированная область памяти ("арена") — 1 МБ, зарезервирован
# заранее прямо здесь, в самом рантайме (в секции .bss — память,
# заполненная нулями при запуске, не занимающая места в самом файле
# программы). Нужна, чтобы структуры и текст под ARC могли работать в
# автономном режиме — своего "malloc" без операционной системы взять
# неоткуда, значит нужен какой-то заранее известный, надёжный кусок
# памяти, из которого можно выделять — и он написан на САМОМ ЯЗЫКЕ Сфера
# (см. арена_распределитель.код), не здесь, в ассемблере — здесь только
# место и способ узнать его адрес.
.bss
.align 16
арена:
    .skip 1048576

.text

# Точка входа программы — ПЕРВОЕ, что выполнится после запуска процесса.
# Ядро Linux (само ядро, не libc!) кладёт на стек при запуске ЛЮБОГО
# ELF-файла: [argc][argv[0]]...[argv[argc-1]][NULL][envp...][NULL] —
# в момент входа в _start регистр rsp указывает ровно на начало этого
# блока (на argc). Достаточно прочитать его напрямую со стека — libc
# для этого совершенно не нужен, это делает сам процессор/ядро.
_start:
    mov rdi, [rsp]          # argc — первый аргумент для main (по ABI: rdi)
    lea rsi, [rsp + 8]      # argv — второй аргумент для main (по ABI: rsi)
    and rsp, -16            # выравнивание стека на 16 байт — требование
                             # System V ABI перед вызовом любой функции

    # НОВОЕ: инициализация арены — первые 8 байт арены хранят "текущее
    # смещение" (сколько байт уже выделено) — начинаем с 8, пропуская
    # само это восьмибайтовое поле-заголовок. Распределитель на Сфере
    # (арена_распределитель.код) читает и обновляет это поле при каждом
    # выделении памяти.
    lea rax, [rip + арена]
    mov qword ptr [rax], 8

    call main                # вызываем УЖЕ ГОТОВУЮ функцию "main",
                             # сгенерированную компилятором Сферы —
                             # никаких изменений в самом компиляторе
                             # для этого не понадобилось

    # main вернул код завершения программы в регистре eax (стандартное
    # соглашение ABI для функций, возвращающих int) — передаём его
    # напрямую в системный вызов "exit_group", которым обычно и
    # завершается программа (то же самое, что делает и libc внутри
    # своей exit(), просто без её кода вокруг).
    mov edi, eax             # код завершения — первый аргумент syscall
    mov eax, 231              # номер системного вызова exit_group на x86-64
    syscall                  # ЕДИНСТВЕННЫЙ способ попросить ядро что-то
                             # сделать без libc — прямая инструкция
                             # процессора, переход в режим ядра

# sfera_write(fd, буфер, количество_байт) -> количество_записанных_байт
# Тонкая обёртка вокруг системного вызова "write" (номер 1 на x86-64) —
# ДАЁТ программе на Сфере способ вывести текст на экран БЕЗ printf/libc.
# Специально устроена так, что System V ABI для ОБЫЧНОГО вызова функции
# (аргументы в rdi, rsi, rdx) СОВПАДАЕТ с соглашением для самого
# системного вызова write — можно передать их напрямую, без единой
# перестановки регистров.
.global sfera_write
sfera_write:
    mov rax, 1                # номер системного вызова write
    syscall
    ret

# text sfera_адрес_арены() — возвращает адрес зарезервированной области
# памяти (см. .bss выше). Простейшая функция — просто отдаёт адрес,
# всю логику распределения (что и где выделять) ведёт код на Сфере.
.global sfera_адрес_арены
sfera_адрес_арены:
    lea rax, [rip + арена]
    ret

# size_t strlen(const char* s) — считает байты до null-терминатора.
# ⚠️ ЧЕСТНАЯ НАХОДКА: обнаружена реальным тестом линковки, не предвидена
# заранее — функция стандартной библиотеки языка Сфера "длина(...)"
# внутри себя вызывает настоящий strlen из libc, который в "автономном"
# режиме взять неоткуда — нужна собственная реализация.
.global strlen
strlen:
    xor rax, rax
strlen_цикл:
    cmp byte ptr [rdi + rax], 0
    je strlen_готово
    inc rax
    jmp strlen_цикл
strlen_готово:
    ret
