# установить-windows.ps1 — установщик среды разработки языка "Сфера" для Windows.
#
# В ОТЛИЧИЕ от собрать.sh (macOS) — тот скрипт лишь пересобирает компилятор,
# ПРЕДПОЛАГАЯ, что Rust/LLVM уже установлены вручную. Этот скрипт делает
# гораздо больше: устанавливает ВСЕ зависимости с нуля, затем собирает
# компилятор и добавляет команду "запустить" в PATH.
#
# ⚠️ ЧЕСТНО: компилятор "Сфера" никогда раньше не собирался и не
# тестировался на Windows. Этот скрипт написан максимально тщательно, на
# основе известных, документированных требований инструментов (Rust,
# llvm-sys/inkwell), но НЕ был проверен вживую на настоящей Windows-машине
# (я работаю в Linux-песочнице, без доступа к Windows). Если что-то пойдёт
# не так — это ожидаемо для первой попытки, не повод считать скрипт
# бесполезным. Пришли мне точный текст ошибки из консоли — так же, как мы
# уже разбирали ошибки для Android — и я поправлю скрипт по факту, а не
# вслепую.
#
# Требуется запускать в PowerShell с правами администратора (для установки
# переменных окружения и Rust) — правой кнопкой по файлу → "Запуск с
# помощью PowerShell" может не хватить прав; надёжнее открыть PowerShell
# от имени администратора и запустить:
#   Set-ExecutionPolicy -Scope Process Bypass -Force
#   .\установить-windows.ps1

$ErrorActionPreference = "Stop"

# ⚠️ НАЙДЕНО РЕАЛЬНОЙ ПРОВЕРКОЙ (Windows): если запустить этот скрипт с
# перенаправлением "*> лог.txt" (все потоки в файл — так мы просили
# пользователя делать для диагностики), PowerShell конвертирует ЛЮБОЙ
# вывод внешней программы в stderr (например, обычные предупреждения
# cargo/rustc вроде "warning: found both '**' and 'c' as identifiers,
# which look alike") в настоящую завершающую ошибку PowerShell — и при
# $ErrorActionPreference = "Stop" это обрывает весь скрипт на первом же
# безобидном предупреждении компилятора, даже если сама команда потом
# завершилась бы кодом 0. Без "*>" эта проблема не проявляется, но скрипт
# не должен зависеть от того, как именно его запустят. Оборачиваем вызовы
# внешних программ этим хелпером: на время вызова ослабляем
# $ErrorActionPreference до "Continue" (внешний процесс сам решает, что
# писать в stderr — это не повод останавливать скрипт), а статус
# проверяем по $LASTEXITCODE, как и раньше.
function Выполнить-Внешнюю {
    param([ScriptBlock]$Команда)
    $прежнийEAP = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    try {
        & $Команда
    } finally {
        $ErrorActionPreference = $прежнийEAP
    }
}

function Написать-Шаг {
    param([string]$Текст)
    Write-Host ""
    Write-Host "=== $Текст ===" -ForegroundColor Cyan
}

function Написать-Успех {
    param([string]$Текст)
    Write-Host $Текст -ForegroundColor Green
}

function Написать-Ошибку {
    param([string]$Текст)
    Write-Host $Текст -ForegroundColor Red
}

# ---------------------------------------------------------------------------
# Шаг 0: рабочие папки
# ---------------------------------------------------------------------------
$ПапкаСферы = Join-Path $env:LOCALAPPDATA "Сфера"
$ПапкаLLVM = Join-Path $ПапкаСферы "LLVM"
$ПапкаBin = Join-Path $ПапкаСферы "bin"
$ПапкаВременная = Join-Path $ПапкаСферы "временные_файлы"

New-Item -ItemType Directory -Force -Path $ПапкаСферы | Out-Null
New-Item -ItemType Directory -Force -Path $ПапкаBin | Out-Null
New-Item -ItemType Directory -Force -Path $ПапкаВременная | Out-Null

# ---------------------------------------------------------------------------
# Шаг 1: проверка Visual Studio Build Tools (C++) — обязательное требование
# готового пакета LLVM (см. ниже), НЕ устанавливается автоматически —
# это огромный, долгий установщик с выбором компонентов, который
# правильнее запустить пользователю самому, а не молча в фоне.
# ---------------------------------------------------------------------------
Написать-Шаг "Проверяю Visual Studio Build Tools (нужны для линковки C++/LLVM)"

$vswhere = "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe"
$естьVS = $false
if (Test-Path $vswhere) {
    $найденоVS = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
    if ($найденоVS) {
        $естьVS = $true
        Написать-Успех "Найден компонент C++ Build Tools: $найденоVS"
    }
}

if (-not $естьVS) {
    Написать-Ошибку @"
Не найден компонент "Desktop development with C++" (C++ Build Tools).
Без него не соберётся ни LLVM-пакет, ни сам компилятор "Сфера".

Установи Visual Studio Build Tools (бесплатно, без полной IDE):
  https://visualstudio.microsoft.com/visual-cpp-build-tools/

При установке обязательно отметь галочку "Desktop development with C++".
После установки запусти этот скрипт заново.
"@
    exit 1
}

# ---------------------------------------------------------------------------
# Шаг 2: Rust
# ---------------------------------------------------------------------------
Написать-Шаг "Проверяю Rust"

$rustcУстановлен = Get-Command rustc -ErrorAction SilentlyContinue
if ($rustcУстановлен) {
    $версияRust = & rustc --version
    Написать-Успех "Rust уже установлен: $версияRust"
} else {
    Написать-Шаг "Rust не найден — скачиваю официальный установщик (rustup)"
    $rustupInit = Join-Path $ПапкаВременная "rustup-init.exe"
    Invoke-WebRequest -Uri "https://static.rust-lang.org/rustup/dist/x86_64-pc-windows-msvc/rustup-init.exe" -OutFile $rustupInit
    # -y — без интерактивных вопросов; --default-toolchain stable — обычный,
    # стабильный канал Rust, ничего экзотического компилятору не нужно.
    Выполнить-Внешнюю { & $rustupInit -y --default-toolchain stable --profile default }
    if ($LASTEXITCODE -ne 0) {
        Написать-Ошибку "Установка Rust завершилась с ошибкой (код $LASTEXITCODE)."
        exit 1
    }
    # rustup только что дописал PATH в реестр — в ЭТОМ же процессе PowerShell
    # он ещё не подхвачен, поэтому добавляем путь к cargo вручную для
    # оставшейся части скрипта.
    $env:Path = "$env:USERPROFILE\.cargo\bin;$env:Path"
    Написать-Успех "Rust установлен."
}

# ---------------------------------------------------------------------------
# Шаг 3: LLVM 18 — готовый, предварительно собранный пакет специально под
# inkwell/llvm-sys для Windows (не сборка LLVM с нуля — это заняло бы
# часы). Источник — vovkos/llvm-package-windows, открытый, специально
# создан именно для этой цели (Rust-проекты на llvm-sys/inkwell на Windows
# используют его же).
# ---------------------------------------------------------------------------
Написать-Шаг "Проверяю LLVM 18 (LLVM_SYS_180_PREFIX)"

$llvmConfigПуть = Join-Path $ПапкаLLVM "bin\llvm-config.exe"
if (Test-Path $llvmConfigПуть) {
    Написать-Успех "LLVM уже установлен в $ПапкаLLVM"
} else {
    Написать-Шаг "Скачиваю LLVM 18.1.8 (пакет для Windows, около 500 МБ — может занять время)"

    # Находим АКТУАЛЬНОЕ имя файла релиза через GitHub API, а не жёстко
    # прописанное — так скрипт не сломается, если формат имени файла
    # слегка изменится в будущем релизе.
    $релизИнфо = Invoke-RestMethod -Uri "https://api.github.com/repos/vovkos/llvm-package-windows/releases/tags/llvm-18.1.8"
    # НАЙДЕНО РЕАЛЬНОЙ ПРОВЕРКОЙ: фильтр раньше не исключал "-dbg" варианты —
    # в итоге скачивался debug-пакет, у которого вдобавок обрезаны некоторые
    # редкие таргеты (см. Cargo.toml) — предпочитаем обычный release.
    $актив = $релизИнфо.assets | Where-Object { $_.name -match "windows" -and $_.name -match "(amd64|x64)" -and $_.name -match "msvc" -and $_.name -notmatch "dbg" } | Select-Object -First 1
    if (-not $актив) {
        # на случай, если release-варианта вдруг не найдётся — лучше debug,
        # чем ничего.
        $актив = $релизИнфо.assets | Where-Object { $_.name -match "windows" -and $_.name -match "(amd64|x64)" -and $_.name -match "msvc" } | Select-Object -First 1
    }

    if (-not $актив) {
        Написать-Ошибку @"
Не удалось автоматически найти нужный файл LLVM в релизе GitHub.
Скачай вручную с https://github.com/vovkos/llvm-package-windows/releases/tag/llvm-18.1.8
— файл для Windows amd64/x64 с MSVC (расширение .7z) — распакуй в:
  $ПапкаLLVM
и запусти этот скрипт заново (шаг LLVM будет пропущен, раз файл уже на месте).
"@
        exit 1
    }

    $архивLLVM = Join-Path $ПапкаВременная $актив.name
    Написать-Шаг "Найден файл: $($актив.name) — скачиваю..."
    Invoke-WebRequest -Uri $актив.browser_download_url -OutFile $архивLLVM

    # Пакет — формат .7z, встроенный Expand-Archive его не понимает.
    # Скачиваем портативный 7za.exe (без установки) специально для распаковки.
    $семьЗип = Join-Path $ПапкаВременная "7za.exe"
    if (-not (Test-Path $семьЗип)) {
        Написать-Шаг "Скачиваю портативный 7-Zip (нужен для распаковки .7z)"
        Invoke-WebRequest -Uri "https://www.7-zip.org/a/7zr.exe" -OutFile $семьЗип
    }

    Написать-Шаг "Распаковываю LLVM в $ПапкаLLVM"
    New-Item -ItemType Directory -Force -Path $ПапкаLLVM | Out-Null
    Выполнить-Внешнюю { & $семьЗип x $архивLLVM "-o$ПапкаLLVM" -y | Out-Null }
    if ($LASTEXITCODE -ne 0) {
        Написать-Ошибку "Распаковка LLVM завершилась с ошибкой (код $LASTEXITCODE)."
        exit 1
    }

    if (-not (Test-Path $llvmConfigПуть)) {
        Написать-Ошибку @"
После распаковки не найден llvm-config.exe по ожидаемому пути:
  $llvmConfigПуть
Возможно, архив распаковался с дополнительной вложенной папкой —
проверь содержимое $ПапкаLLVM вручную и, если нужно, перемести файлы
так, чтобы bin\llvm-config.exe оказался прямо внутри $ПапкаLLVM.
"@
        exit 1
    }
    Написать-Успех "LLVM установлен в $ПапкаLLVM"
}

# Переменная окружения — постоянно, на уровне пользователя (не только для
# этого процесса), чтобы cargo build находил LLVM и при последующих
# запусках, из обычного, нового окна PowerShell.
[Environment]::SetEnvironmentVariable("LLVM_SYS_180_PREFIX", $ПапкаLLVM, "User")
$env:LLVM_SYS_180_PREFIX = $ПапкаLLVM

# ---------------------------------------------------------------------------
# Шаг 3.5: Clang — НАЙДЕНО РЕАЛЬНОЙ ПРОВЕРКОЙ (живая Windows-машина):
# "запустить.exe" собирается и линкуется через llvm-sys/inkwell без clang —
# но финальный шаг, линковка готового .o файла в .exe, делается через
# ВНЕШНИЙ `clang` (см. src/main.rs, слинковать_исполняемый_файл) — то есть
# clang.exe нужен не для сборки САМОГО компилятора, а для того, чтобы
# компилятор впоследствии мог собирать программы на "Сфере".
#
# Важно: clang — это СОВСЕМ ОТДЕЛЬНЫЙ релиз на GitHub, не входящий в пакет
# LLVM из шага 3 (у vovkos/llvm-package-windows для каждой версии две
# отдельные страницы релизов — "llvm-X.Y.Z" и "clang-X.Y.Z" — качаются и
# распаковываются раздельно). Шаг 3 про это ничего не знал, отсюда и
# ошибка "Не удалось запустить clang: program not found" после успешной
# сборки компилятора.
# ---------------------------------------------------------------------------
Написать-Шаг "Проверяю Clang (нужен для линковки программ на Сфере)"

$ПапкаClang = Join-Path $ПапкаСферы "Clang"
$clangПуть = Join-Path $ПапкаClang "bin\clang.exe"
if (Test-Path $clangПуть) {
    Написать-Успех "Clang уже установлен в $ПапкаClang"
} else {
    Написать-Шаг "Скачиваю Clang 18.1.8 (пакет для Windows)"

    $релизИнфоClang = Invoke-RestMethod -Uri "https://api.github.com/repos/vovkos/llvm-package-windows/releases/tags/clang-18.1.8"
    # debug-вариант этого пакета собирается с CLANG_BUILD_TOOLS=OFF — то есть
    # САМОГО clang.exe там нет вообще, только библиотеки — поэтому "-dbg"
    # здесь исключаем безусловно, в отличие от LLVM.
    $активClang = $релизИнфоClang.assets | Where-Object { $_.name -match "windows" -and $_.name -match "(amd64|x64)" -and $_.name -match "msvc" -and $_.name -notmatch "dbg" } | Select-Object -First 1

    if (-not $активClang) {
        Написать-Ошибку @"
Не удалось автоматически найти нужный файл Clang в релизе GitHub.
Скачай вручную с https://github.com/vovkos/llvm-package-windows/releases/tag/clang-18.1.8
— файл для Windows amd64/x64 с MSVC, НЕ "-dbg" (расширение .7z) — распакуй в:
  $ПапкаClang
и запусти этот скрипт заново.
"@
        exit 1
    }

    $архивClang = Join-Path $ПапкаВременная $активClang.name
    Написать-Шаг "Найден файл: $($активClang.name) — скачиваю..."
    Invoke-WebRequest -Uri $активClang.browser_download_url -OutFile $архивClang

    $семьЗип = Join-Path $ПапкаВременная "7za.exe"
    if (-not (Test-Path $семьЗип)) {
        Написать-Шаг "Скачиваю портативный 7-Zip (нужен для распаковки .7z)"
        Invoke-WebRequest -Uri "https://www.7-zip.org/a/7zr.exe" -OutFile $семьЗип
    }

    Написать-Шаг "Распаковываю Clang в $ПапкаClang"
    New-Item -ItemType Directory -Force -Path $ПапкаClang | Out-Null
    Выполнить-Внешнюю { & $семьЗип x $архивClang "-o$ПапкаClang" -y | Out-Null }
    if ($LASTEXITCODE -ne 0) {
        Написать-Ошибку "Распаковка Clang завершилась с ошибкой (код $LASTEXITCODE)."
        exit 1
    }

    if (-not (Test-Path $clangПуть)) {
        Написать-Ошибку @"
После распаковки не найден clang.exe по ожидаемому пути:
  $clangПуть
Возможно, архив распаковался с дополнительной вложенной папкой — проверь
содержимое $ПапкаClang вручную и, если нужно, перемести файлы так, чтобы
bin\clang.exe оказался прямо внутри $ПапкаClang.
"@
        exit 1
    }
    Написать-Успех "Clang установлен в $ПапкаClang"
}

# В PATH пользователя — постоянно, чтобы компилятор "Сфера" (который
# вызывает "clang" как внешнюю программу при линковке) находил его из
# любого нового окна PowerShell, не только из этой сессии установки.
$ПапкаClangBin = Join-Path $ПапкаClang "bin"
$текущийPATHClang = [Environment]::GetEnvironmentVariable("Path", "User")
if ($текущийPATHClang -notlike "*$ПапкаClangBin*") {
    [Environment]::SetEnvironmentVariable("Path", "$текущийPATHClang;$ПапкаClangBin", "User")
}
$env:Path = "$env:Path;$ПапкаClangBin"

# ---------------------------------------------------------------------------
# Шаг 4: исходники компилятора — если скрипт запущен внутри уже
# склонированного репозитория (рядом Cargo.toml), используем текущую
# папку; иначе клонируем с GitHub.
# ---------------------------------------------------------------------------
Написать-Шаг "Проверяю исходники компилятора"

$ПапкаПроекта = $PSScriptRoot
if (-not (Test-Path (Join-Path $ПапкаПроекта "Cargo.toml"))) {
    Написать-Шаг "Скрипт запущен не изнутри репозитория — клонирую с GitHub"
    $gitУстановлен = Get-Command git -ErrorAction SilentlyContinue
    if (-not $gitУстановлен) {
        Написать-Ошибку "Git не найден — установи Git для Windows (https://git-scm.com/download/win) и запусти скрипт заново."
        exit 1
    }
    $ПапкаКлона = Join-Path $env:USERPROFILE "Sfera"
    if (-not (Test-Path $ПапкаКлона)) {
        Выполнить-Внешнюю { & git clone https://github.com/nikitosklim/Sfera.git $ПапкаКлона }
    }
    $ПапкаПроекта = $ПапкаКлона
}
Написать-Успех "Исходники: $ПапкаПроекта"

# ---------------------------------------------------------------------------
# Шаг 5: сборка компилятора
# ---------------------------------------------------------------------------
Написать-Шаг "Собираю компилятор (cargo build --release) — может занять несколько минут"

Push-Location $ПапкаПроекта
try {
    # НОВОЕ: раньше собирался только "запустить" (сам компилятор) — но
    # "Панель Сферы" (инструменты\панель-разработчика\панель.код,
    # установить_сферу) при самоустановке копирует ТРИ бинарника:
    # запустить, сфера_lsp (языковой сервер) и сфера_пакеты (пакетный
    # менеджер) — оба объявлены неявно, по правилу Cargo "каждый файл в
    # src\bin\ — отдельный бинарник", без отдельной записи [[bin]] в
    # Cargo.toml. Если собрать только "запустить", самоустановка из
    # панели будет молча копировать несуществующие файлы и падать.
    Выполнить-Внешнюю { & cargo build --release --bin запустить --bin сфера_lsp --bin сфера_пакеты }
    if ($LASTEXITCODE -ne 0) {
        Написать-Ошибку "Сборка компилятора завершилась с ошибкой (код $LASTEXITCODE) — см. вывод выше."
        exit 1
    }
} finally {
    Pop-Location
}

$Бинарники = @("запустить", "сфера_lsp", "сфера_пакеты")
foreach ($имяБинарника in $Бинарники) {
    $СобранныйБинарник = Join-Path $ПапкаПроекта "target\release\$имяБинарника.exe"
    if (-not (Test-Path $СобранныйБинарник)) {
        Написать-Ошибку "Сборка как будто прошла успешно, но файл target\release\$имяБинарника.exe не найден."
        exit 1
    }
    Copy-Item $СобранныйБинарник (Join-Path $ПапкаBin "$имяБинарника.exe") -Force
}
Написать-Успех "Компилятор собран и скопирован в $ПапкаBin"

# НОВОЕ: "Панель Сферы" при самоустановке копирует пример привет.код
# рядом с установленными бинарниками (см. путь_встроенного_бандла в
# панель.код — на Windows указывает именно сюда, в $ПапкаBin) — без
# этого шага самоустановка из панели падала бы на копировании
# несуществующего файла.
Copy-Item (Join-Path $ПапкаПроекта "examples\привет.код") (Join-Path $ПапкаBin "привет.код") -Force

# НОВОЕ (найдено реальным, честным вопросом — "разработчик создаёт новую
# папку проекта на рабочем столе, и раз язык установлен в системе,
# встроенные модули должны находиться сами, без ручного копирования
# файлов стандартной библиотеки в каждый новый проект" — та же модель,
# что "import os" в Python): компилятор сам умеет искать
# "стандартная_библиотека\" рядом с собой, по пути bin\..\lib\sfera\
# стандартная_библиотека\ относительно установленного bin\запустить.exe
# — копируем её туда, синхронно с самим компилятором, чтобы не отставала.
$ПапкаСистемнойБиблиотеки = Join-Path $ПапкаСферы "lib\sfera\стандартная_библиотека"
Написать-Шаг "Копирую стандартную библиотеку в $ПапкаСистемнойБиблиотеки"
if (Test-Path $ПапкаСистемнойБиблиотеки) {
    Remove-Item $ПапкаСистемнойБиблиотеки -Recurse -Force
}
New-Item -ItemType Directory -Force -Path (Split-Path $ПапкаСистемнойБиблиотеки -Parent) | Out-Null
Copy-Item (Join-Path $ПапкаПроекта "стандартная_библиотека") $ПапкаСистемнойБиблиотеки -Recurse -Force
Написать-Успех "Стандартная библиотека установлена — доступна из любого проекта без копирования файлов."

# НОВОЕ (найдено реальным запуском на Windows — LNK2019: unresolved external
# symbol pthread_mutex_init/pthread_cond_init при линковке ЛЮБОЙ программы на
# Сфере, даже простейшего "привет.код"): codegen.rs безусловно вызывает
# pthread_* в обёртке main каждой программы (см. рантайм_windows\pthread_win.c —
# там подробно объяснено, почему). На Linux/macOS pthread — часть системной
# libc, но на чистом Windows такой библиотеки нет вовсе, поэтому проект несёт
# свою маленькую Win32-реализацию и компилирует её прямо здесь, тем же clang,
# который установщик уже поставил — один раз, при установке, а не при каждой
# сборке пользовательской программы.
$ПапкаPthreadОбъектник = Join-Path $ПапкаСферы "lib\sfera"
$PthreadОбъектник = Join-Path $ПапкаPthreadОбъектник "pthread_win.o"
$PthreadИсходник = Join-Path $ПапкаПроекта "рантайм_windows\pthread_win.c"
Написать-Шаг "Компилирую обёртку pthread для Windows (pthread_win.o)"
if (-not (Test-Path $PthreadИсходник)) {
    Написать-Ошибку "Не найден исходник $PthreadИсходник — обёртка pthread для Windows не установлена. Программы на Сфере не будут линковаться на этой машине."
} else {
    New-Item -ItemType Directory -Force -Path $ПапкаPthreadОбъектник | Out-Null
    Выполнить-Внешнюю { & $clangПуть -c $PthreadИсходник -o $PthreadОбъектник }
    if ($LASTEXITCODE -ne 0 -or -not (Test-Path $PthreadОбъектник)) {
        Написать-Ошибку "Не удалось скомпилировать pthread_win.c (код $LASTEXITCODE) — программы на Сфере не будут линковаться на этой машине. Проверьте вывод выше."
    } else {
        Написать-Успех "Обёртка pthread для Windows собрана: $PthreadОбъектник"
    }
}

# НОВОЕ (найдено реальным запуском — порт "Панели Сферы", графического
# инструмента разработчика, на Windows: инструменты\панель-разработчика,
# прежде собиралась только под macOS через "--линковать SDL2 --линковать
# SDL2_ttf --линковать m"): на Linux/macOS SDL2 ставится через системный
# пакетный менеджер и лежит в стандартных путях поиска линковщика — на
# Windows такого единого места нет, поэтому ставим SDL2 и SDL2_ttf сюда
# же, в папку Сферы, и говорим компилятору, где их искать, через
# SFERA_LIB_PATHS (см. main.rs, собрать_команду — тот же приём, что и
# SFERA_PTHREAD_WIN_O выше). "-lm" компилятор на Windows теперь молча
# пропускает сам (там нет отдельной libm) — поэтому команду сборки
# "--линковать m" менять не нужно, она просто ничего не делает на Windows.
Написать-Шаг "Устанавливаю SDL2 и SDL2_ttf (нужны для Панели Сферы)"
$ПапкаSDL = Join-Path $ПапкаСферы "SDL2"
$путиБиблиотек = @()
$путиDll = @()

function Установить-SDL-Пакет {
    param(
        [string]$Репозиторий,   # например "libsdl-org/SDL"
        [string]$ИмяПапки,      # например "SDL2"
        [string]$ЦелеваяПапка   # например $ПапкаSDL\SDL2
    )
    # НЕ берём "/releases/latest" — в этом же GitHub-репозитории теперь
    # разрабатывается и SDL3 (со своими несовместимыми именами функций:
    # например, в SDL3 сигнатура SDL_CreateWindow другая), и "latest" там
    # вполне может оказаться релизом SDL3, а не SDL2. Сфера написана под
    # SDL2 (см. графика.код, "внешняя функция ... как SDL_Init" и т.д.),
    # поэтому ищем явно по имени файла "$ИмяПапки-devel-2.*-VC.zip" среди
    # ВСЕХ релизов, начиная с самых свежих — так находим актуальную
    # версию именно 2.x, какой бы тег ни был "последним" в репозитории.
    try {
        $релизы = Invoke-RestMethod -Uri "https://api.github.com/repos/$Репозиторий/releases?per_page=20"
    } catch {
        Написать-Ошибку "Не удалось получить список релизов $Репозиторий — проверь интернет-соединение. Панель Сферы собираться не будет, пока это не исправлено."
        return $null
    }
    $актив = $null
    foreach ($релиз in $релизы) {
        $актив = $релиз.assets | Where-Object { $_.name -match "^$ИмяПапки-devel-2\." -and $_.name -match "VC\.zip$" } | Select-Object -First 1
        if ($актив) { break }
    }
    if (-not $актив) {
        Написать-Ошибку "Среди последних релизов $Репозиторий не нашёл файл '$ИмяПапки-devel-2.*-VC.zip' (возможно, ветка 2.x ушла дальше в историю, или формат имени поменялся). Посмотри вручную: https://github.com/$Репозиторий/releases"
        return $null
    }
    if (Test-Path (Join-Path $ЦелеваяПапка "lib\x64")) {
        Написать-Успех "$ИмяПапки уже установлен в $ЦелеваяПапка"
    } else {
        $архив = Join-Path $ПапкаВременная $актив.name
        Написать-Шаг "Скачиваю $($актив.name)"
        Invoke-WebRequest -Uri $актив.browser_download_url -OutFile $архив
        New-Item -ItemType Directory -Force -Path $ПапкаSDL | Out-Null
        # У SDL-архивов, в отличие от LLVM/Clang, внутри сразу папка с
        # версией в имени (например "SDL2-2.30.9\") — Expand-Archive (это
        # обычный .zip, не .7z, портативный 7-Zip тут не нужен) распаковывает
        # как есть, а затем по образцу уже пройденной истории с
        # LLVM/Clang (см. выше по файлу) переименовываем/перемещаем
        # содержимое в постоянную, не зависящую от номера версии папку.
        Expand-Archive -Path $архив -DestinationPath $ПапкаSDL -Force
        $распакованная = Get-ChildItem -Path $ПапкаSDL -Directory | Where-Object { $_.Name -like "$ИмяПапки-*" } | Select-Object -First 1
        if (-not $распакованная) {
            Написать-Ошибку "После распаковки $($актив.name) не нашёл папку '$ИмяПапки-*' внутри $ПапкаSDL — посмотри содержимое вручную."
            return $null
        }
        if (Test-Path $ЦелеваяПапка) {
            Remove-Item $ЦелеваяПапка -Recurse -Force
        }
        Move-Item $распакованная.FullName $ЦелеваяПапка -Force
        Написать-Успех "$ИмяПапки установлен в $ЦелеваяПапка"
    }
    $либПуть = Join-Path $ЦелеваяПапка "lib\x64"
    if (-not (Test-Path $либПуть)) {
        Написать-Ошибку "Ожидался путь $либПуть (64-битные .lib/.dll) — не найден. Возможно, структура архива $ИмяПапки изменилась."
        return $null
    }
    return $либПуть
}

$либSDL2 = Установить-SDL-Пакет -Репозиторий "libsdl-org/SDL" -ИмяПапки "SDL2" -ЦелеваяПапка (Join-Path $ПапкаSDL "SDL2")
if ($либSDL2) { $путиБиблиотек += $либSDL2; $путиDll += $либSDL2 }
$либSDL2ttf = Установить-SDL-Пакет -Репозиторий "libsdl-org/SDL_ttf" -ИмяПапки "SDL2_ttf" -ЦелеваяПапка (Join-Path $ПапкаSDL "SDL2_ttf")
if ($либSDL2ttf) { $путиБиблиотек += $либSDL2ttf; $путиDll += $либSDL2ttf }

if ($путиБиблиотек.Count -gt 0) {
    $SFERA_LIB_PATHS = $путиБиблиотек -join ";"
    [Environment]::SetEnvironmentVariable("SFERA_LIB_PATHS", $SFERA_LIB_PATHS, "User")
    $env:SFERA_LIB_PATHS = $SFERA_LIB_PATHS
    Написать-Успех "SFERA_LIB_PATHS настроен: $SFERA_LIB_PATHS"

    # .dll нужны РЯДОМ С СОБРАННОЙ ПРОГРАММОЙ (или где-то в PATH) во время
    # ЗАПУСКА — в отличие от .lib, которые нужны только компилятору при
    # линковке. Кладём их в $ПапкаBin: он и так уже добавлен в PATH ниже,
    # так что любая собранная через "sfera" программа найдёт SDL2.dll и
    # SDL2_ttf.dll (и их зависимости вроде libfreetype*.dll — тоже лежат
    # в этой же папке архива) само собой, без ручного копирования рядом
    # с каждым .exe.
    foreach ($папкаDll in $путиDll) {
        Get-ChildItem -Path $папкаDll -Filter "*.dll" | ForEach-Object {
            Copy-Item $_.FullName $ПапкаBin -Force
        }
    }
    Написать-Успех "DLL-файлы SDL2 скопированы в $ПапкаBin"
}

# ---------------------------------------------------------------------------
# Шаг 6: добавляем команду "запустить" в PATH пользователя
# ---------------------------------------------------------------------------
Написать-Шаг "Добавляю команду 'запустить' в PATH"

$текущийPATH = [Environment]::GetEnvironmentVariable("Path", "User")
if ($текущийPATH -notlike "*$ПапкаBin*") {
    [Environment]::SetEnvironmentVariable("Path", "$текущийPATH;$ПапкаBin", "User")
    Написать-Успех "PATH обновлён (потребуется открыть НОВОЕ окно PowerShell, чтобы изменение подействовало)."
} else {
    Написать-Успех "PATH уже содержит нужную папку."
}
$env:Path = "$env:Path;$ПапкаBin"

