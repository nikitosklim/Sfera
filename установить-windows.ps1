# установить-windows.ps1 — установщик среды разработки языка "Сфера" для Windows.
#
# В ОТЛИЧИЕ от собрать.sh (macOS) — тот скрипт лишь пересобирает компилятор,
# ПРЕДПОЛАГАЯ, что Rust/LLVM уже установлены вручную. Этот скрипт делает
# гораздо больше: устанавливает ВСЕ зависимости с нуля, затем собирает
# компилятор и добавляет команду "запустить" в PATH.
#
# ⚠️ ЧЕСТНО: компилятор "Сфера" никогда раньше не собирался и не
# тестировался на Windows. Этот скрипт написан максимально тщательно, на
# основе известных, документированных требований инструментов (Rust,
# llvm-sys/inkwell), но НЕ был проверен вживую на настоящей Windows-машине
# (я работаю в Linux-песочнице, без доступа к Windows). Если что-то пойдёт
# не так — это ожидаемо для первой попытки, не повод считать скрипт
# бесполезным. Пришли мне точный текст ошибки из консоли — так же, как мы
# уже разбирали ошибки для Android — и я поправлю скрипт по факту, а не
# вслепую.
#
# Требуется запускать в PowerShell с правами администратора (для установки
# переменных окружения и Rust) — правой кнопкой по файлу → "Запуск с
# помощью PowerShell" может не хватить прав; надёжнее открыть PowerShell
# от имени администратора и запустить:
#   Set-ExecutionPolicy -Scope Process Bypass -Force
#   .\установить-windows.ps1

$ErrorActionPreference = "Stop"

function Написать-Шаг {
    param([string]$Текст)
    Write-Host ""
    Write-Host "=== $Текст ===" -ForegroundColor Cyan
}

function Написать-Успех {
    param([string]$Текст)
    Write-Host $Текст -ForegroundColor Green
}

function Написать-Ошибку {
    param([string]$Текст)
    Write-Host $Текст -ForegroundColor Red
}

# ---------------------------------------------------------------------------
# Шаг 0: рабочие папки
# ---------------------------------------------------------------------------
$ПапкаСферы = Join-Path $env:LOCALAPPDATA "Сфера"
$ПапкаLLVM = Join-Path $ПапкаСферы "LLVM"
$ПапкаBin = Join-Path $ПапкаСферы "bin"
$ПапкаВременная = Join-Path $ПапкаСферы "временные_файлы"

New-Item -ItemType Directory -Force -Path $ПапкаСферы | Out-Null
New-Item -ItemType Directory -Force -Path $ПапкаBin | Out-Null
New-Item -ItemType Directory -Force -Path $ПапкаВременная | Out-Null

# ---------------------------------------------------------------------------
# Шаг 1: проверка Visual Studio Build Tools (C++) — обязательное требование
# готового пакета LLVM (см. ниже), НЕ устанавливается автоматически —
# это огромный, долгий установщик с выбором компонентов, который
# правильнее запустить пользователю самому, а не молча в фоне.
# ---------------------------------------------------------------------------
Написать-Шаг "Проверяю Visual Studio Build Tools (нужны для линковки C++/LLVM)"

$vswhere = "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe"
$естьVS = $false
if (Test-Path $vswhere) {
    $найденоVS = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
    if ($найденоVS) {
        $естьVS = $true
        Написать-Успех "Найден компонент C++ Build Tools: $найденоVS"
    }
}

if (-not $естьVS) {
    Написать-Ошибку @"
Не найден компонент "Desktop development with C++" (C++ Build Tools).
Без него не соберётся ни LLVM-пакет, ни сам компилятор "Сфера".

Установи Visual Studio Build Tools (бесплатно, без полной IDE):
  https://visualstudio.microsoft.com/visual-cpp-build-tools/

При установке обязательно отметь галочку "Desktop development with C++".
После установки запусти этот скрипт заново.
"@
    exit 1
}

# ---------------------------------------------------------------------------
# Шаг 2: Rust
# ---------------------------------------------------------------------------
Написать-Шаг "Проверяю Rust"

$rustcУстановлен = Get-Command rustc -ErrorAction SilentlyContinue
if ($rustcУстановлен) {
    $версияRust = & rustc --version
    Написать-Успех "Rust уже установлен: $версияRust"
} else {
    Написать-Шаг "Rust не найден — скачиваю официальный установщик (rustup)"
    $rustupInit = Join-Path $ПапкаВременная "rustup-init.exe"
    Invoke-WebRequest -Uri "https://static.rust-lang.org/rustup/dist/x86_64-pc-windows-msvc/rustup-init.exe" -OutFile $rustupInit
    # -y — без интерактивных вопросов; --default-toolchain stable — обычный,
    # стабильный канал Rust, ничего экзотического компилятору не нужно.
    & $rustupInit -y --default-toolchain stable --profile default
    if ($LASTEXITCODE -ne 0) {
        Написать-Ошибку "Установка Rust завершилась с ошибкой (код $LASTEXITCODE)."
        exit 1
    }
    # rustup только что дописал PATH в реестр — в ЭТОМ же процессе PowerShell
    # он ещё не подхвачен, поэтому добавляем путь к cargo вручную для
    # оставшейся части скрипта.
    $env:Path = "$env:USERPROFILE\.cargo\bin;$env:Path"
    Написать-Успех "Rust установлен."
}

# ---------------------------------------------------------------------------
# Шаг 3: LLVM 18 — готовый, предварительно собранный пакет специально под
# inkwell/llvm-sys для Windows (не сборка LLVM с нуля — это заняло бы
# часы). Источник — vovkos/llvm-package-windows, открытый, специально
# создан именно для этой цели (Rust-проекты на llvm-sys/inkwell на Windows
# используют его же).
# ---------------------------------------------------------------------------
Написать-Шаг "Проверяю LLVM 18 (LLVM_SYS_180_PREFIX)"

$llvmConfigПуть = Join-Path $ПапкаLLVM "bin\llvm-config.exe"
if (Test-Path $llvmConfigПуть) {
    Написать-Успех "LLVM уже установлен в $ПапкаLLVM"
} else {
    Написать-Шаг "Скачиваю LLVM 18.1.8 (пакет для Windows, около 500 МБ — может занять время)"

    # Находим АКТУАЛЬНОЕ имя файла релиза через GitHub API, а не жёстко
    # прописанное — так скрипт не сломается, если формат имени файла
    # слегка изменится в будущем релизе.
    $релизИнфо = Invoke-RestMethod -Uri "https://api.github.com/repos/vovkos/llvm-package-windows/releases/tags/llvm-18.1.8"
    $актив = $релизИнфо.assets | Where-Object { $_.name -match "windows" -and $_.name -match "(amd64|x64)" -and $_.name -match "msvc" } | Select-Object -First 1

    if (-not $актив) {
        Написать-Ошибку @"
Не удалось автоматически найти нужный файл LLVM в релизе GitHub.
Скачай вручную с https://github.com/vovkos/llvm-package-windows/releases/tag/llvm-18.1.8
— файл для Windows amd64/x64 с MSVC (расширение .7z) — распакуй в:
  $ПапкаLLVM
и запусти этот скрипт заново (шаг LLVM будет пропущен, раз файл уже на месте).
"@
        exit 1
    }

    $архивLLVM = Join-Path $ПапкаВременная $актив.name
    Написать-Шаг "Найден файл: $($актив.name) — скачиваю..."
    Invoke-WebRequest -Uri $актив.browser_download_url -OutFile $архивLLVM

    # Пакет — формат .7z, встроенный Expand-Archive его не понимает.
    # Скачиваем портативный 7za.exe (без установки) специально для распаковки.
    $семьЗип = Join-Path $ПапкаВременная "7za.exe"
    if (-not (Test-Path $семьЗип)) {
        Написать-Шаг "Скачиваю портативный 7-Zip (нужен для распаковки .7z)"
        Invoke-WebRequest -Uri "https://www.7-zip.org/a/7zr.exe" -OutFile $семьЗип
    }

    Написать-Шаг "Распаковываю LLVM в $ПапкаLLVM"
    New-Item -ItemType Directory -Force -Path $ПапкаLLVM | Out-Null
    & $семьЗип x $архивLLVM "-o$ПапкаLLVM" -y | Out-Null
    if ($LASTEXITCODE -ne 0) {
        Написать-Ошибку "Распаковка LLVM завершилась с ошибкой (код $LASTEXITCODE)."
        exit 1
    }

    if (-not (Test-Path $llvmConfigПуть)) {
        Написать-Ошибку @"
После распаковки не найден llvm-config.exe по ожидаемому пути:
  $llvmConfigПуть
Возможно, архив распаковался с дополнительной вложенной папкой —
проверь содержимое $ПапкаLLVM вручную и, если нужно, перемести файлы
так, чтобы bin\llvm-config.exe оказался прямо внутри $ПапкаLLVM.
"@
        exit 1
    }
    Написать-Успех "LLVM установлен в $ПапкаLLVM"
}

# Переменная окружения — постоянно, на уровне пользователя (не только для
# этого процесса), чтобы cargo build находил LLVM и при последующих
# запусках, из обычного, нового окна PowerShell.
[Environment]::SetEnvironmentVariable("LLVM_SYS_180_PREFIX", $ПапкаLLVM, "User")
$env:LLVM_SYS_180_PREFIX = $ПапкаLLVM

# ---------------------------------------------------------------------------
# Шаг 4: исходники компилятора — если скрипт запущен внутри уже
# склонированного репозитория (рядом Cargo.toml), используем текущую
# папку; иначе клонируем с GitHub.
# ---------------------------------------------------------------------------
Написать-Шаг "Проверяю исходники компилятора"

$ПапкаПроекта = $PSScriptRoot
if (-not (Test-Path (Join-Path $ПапкаПроекта "Cargo.toml"))) {
    Написать-Шаг "Скрипт запущен не изнутри репозитория — клонирую с GitHub"
    $gitУстановлен = Get-Command git -ErrorAction SilentlyContinue
    if (-not $gitУстановлен) {
        Написать-Ошибку "Git не найден — установи Git для Windows (https://git-scm.com/download/win) и запусти скрипт заново."
        exit 1
    }
    $ПапкаКлона = Join-Path $env:USERPROFILE "Sfera"
    if (-not (Test-Path $ПапкаКлона)) {
        & git clone https://github.com/nikitosklim/Sfera.git $ПапкаКлона
    }
    $ПапкаПроекта = $ПапкаКлона
}
Написать-Успех "Исходники: $ПапкаПроекта"

# ---------------------------------------------------------------------------
# Шаг 5: сборка компилятора
# ---------------------------------------------------------------------------
Написать-Шаг "Собираю компилятор (cargo build --release) — может занять несколько минут"

Push-Location $ПапкаПроекта
try {
    & cargo build --release --bin запустить
    if ($LASTEXITCODE -ne 0) {
        Написать-Ошибку "Сборка компилятора завершилась с ошибкой (код $LASTEXITCODE) — см. вывод выше."
        exit 1
    }
} finally {
    Pop-Location
}

$СобранныйБинарник = Join-Path $ПапкаПроекта "target\release\запустить.exe"
if (-not (Test-Path $СобранныйБинарник)) {
    Написать-Ошибку "Сборка как будто прошла успешно, но файл target\release\запустить.exe не найден."
    exit 1
}

Copy-Item $СобранныйБинарник (Join-Path $ПапкаBin "запустить.exe") -Force
Написать-Успех "Компилятор собран и скопирован в $ПапкаBin"

# ---------------------------------------------------------------------------
# Шаг 6: добавляем команду "запустить" в PATH пользователя
# ---------------------------------------------------------------------------
Написать-Шаг "Добавляю команду 'запустить' в PATH"

$текущийPATH = [Environment]::GetEnvironmentVariable("Path", "User")
if ($текущийPATH -notlike "*$ПапкаBin*") {
    [Environment]::SetEnvironmentVariable("Path", "$текущийPATH;$ПапкаBin", "User")
    Написать-Успех "PATH обновлён (потребуется открыть НОВОЕ окно PowerShell, чтобы изменение подействовало)."
} else {
    Написать-Успех "PATH уже содержит нужную папку."
}
$env:Path = "$env:Path;$ПапкаBin"

# ---------------------------------------------------------------------------
# Шаг 7: проверка — компилируем и запускаем "привет.код"
# ---------------------------------------------------------------------------
Написать-Шаг "Проверяю установку — компилирую examples\привет.код"

$ПриветКод = Join-Path $ПапкаПроекта "examples\привет.код"
if (Test-Path $ПриветКод) {
    Push-Location (Join-Path $ПапкаПроекта "examples")
    try {
        & $СобранныйБинарник "привет.код"
        if ($LASTEXITCODE -eq 0 -and (Test-Path "привет.exe")) {
            $вывод = & ".\привет.exe"
            Написать-Успех "Тестовый запуск: $вывод"
        } else {
            Написать-Ошибку "Компиляция теста не удалась — см. вывод выше. Основная установка при этом могла пройти успешно, стоит разобраться отдельно."
        }
    } finally {
        Pop-Location
    }
}

Write-Host ""
Написать-Успех "==================================================================="
Написать-Успех "Готово. Открой НОВОЕ окно PowerShell и попробуй:"
Написать-Успех "  запустить путь\к\файлу.код"
Написать-Успех "==================================================================="
Write-Host ""
Write-Host "Честно: графические (SDL2) и примеры с базой данных (SQLite) пока" -ForegroundColor Yellow
Write-Host "потребуют отдельной установки этих библиотек под Windows — этот" -ForegroundColor Yellow
Write-Host "скрипт устанавливает только сам компилятор языка." -ForegroundColor Yellow
