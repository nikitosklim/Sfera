// Разбор одного файла в «индекс»: функции, структуры, контракты, глобальные, подключения.
function разобратьФайл(текст) {
  const исх = текст.split('\n');
  const чист = очистить(текст).split('\n');
  const инд = { функции: [], структуры: [], контракты: [], глобальные: [], подключения: [], описание: '', строк: исх.length };

  // описание файла — первая строка шапки из комментариев
  for (let i = 0; i < Math.min(исх.length, 6); i++) {
    const т = исх[i].trim();
    if (т.startsWith('//')) {
      const содержимое = т.replace(/^\/\/+\s?/, '').trim();
      if (содержимое) { инд.описание = содержимое.replace(/^[^\s—–-]+\.код\s*[—–-]\s*/u, ''); break; }
    } else if (т) break;
  }

  const стек = [];
  for (let i = 0; i < чист.length; i++) {
    const л = чист[i];
    const т = л.trim();
    if (!т) continue;
    let м;
    let открыл = null;
    let пропуститьДо = i;

    if (стек.length === 0 && /^подключить(?![\p{L}\p{N}_])/u.test(т)) {
      const м2 = /^подключить\s+"?([^";\s]+)"?\s*;?/u.exec(исх[i].trim());
      if (м2) инд.подключения.push({ имя: м2[1], строка: i });
    } else if ((м = РЕГЕКС_ФУНКЦИЯ.exec(т))) {
      // подпись может занимать несколько строк
      let подпись = л.slice(л.indexOf(м[0]) + м[0].length);
      let j = i;
      const скобок = () => (подпись.match(/\(/g) || []).length - (подпись.match(/\)/g) || []).length;
      while (скобок() > 0 && j + 1 < чист.length && j < i + 6) { j++; подпись += ' ' + чист[j].trim(); }
      const о = подпись.indexOf('(');
      let параметры = [], возврат = '', безТела = !!м[2];
      if (о >= 0) {
        let г = 0, з = -1;
        for (let k = о; k < подпись.length; k++) {
          if (подпись[k] === '(') г++;
          else if (подпись[k] === ')') { г--; if (г === 0) { з = k; break; } }
        }
        const внутри = з >= 0 ? подпись.slice(о + 1, з) : подпись.slice(о + 1);
        параметры = разобратьПараметры(внутри);
        let хвост = з >= 0 ? подпись.slice(з + 1) : '';
        const мв = /^\s*(?::|->)\s*([^;]*?)\s*(?:;|$)/u.exec(хвост);
        if (мв) возврат = мв[1].replace(/\s+как\s.*$/u, '').trim();
        if (/;\s*$/.test(хвост.trim()) || /;\s*$/.test(хвост)) безТела = true;
      }
      const вершина = стек.length ? стек[стек.length - 1] : null;
      const ф = {
        имя: м[3], параметры, возврат, строка: i, столбец: л.indexOf(м[3], л.indexOf('функция')), конец: -1,
        структура: вершина && вершина.вид === 'структура' ? вершина.имя : (вершина && вершина.вид === 'контракт' ? вершина.имя : null),
        док: докНад(исх, i), публично: м[1] !== 'приватно', внешняя: !!м[2]
      };
      if (вершина && вершина.вид === 'структура') вершина.ссылка.методы.push(ф);
      else if (вершина && вершина.вид === 'контракт') вершина.ссылка.методы.push(ф);
      else if (!вершина) инд.функции.push(ф);
      if (!безТела) открыл = { вид: 'функция', ссылка: ф };
      пропуститьДо = j; // строки многострочной подписи пропускаются
    } else if ((м = РЕГЕКС_СТРУКТУРА.exec(т)) && !стек.length) {
      const с = { имя: м[2], поля: [], методы: [], строка: i, столбец: л.indexOf(м[2], л.indexOf('структура')), конец: -1, док: докНад(исх, i), публично: м[1] !== 'приватно' };
      инд.структуры.push(с);
      открыл = { вид: 'структура', имя: с.имя, ссылка: с };
    } else if ((м = РЕГЕКС_КОНТРАКТ.exec(т)) && !стек.length) {
      const к = { имя: м[2], методы: [], строка: i, столбец: л.indexOf(м[2], л.indexOf('контракт')), конец: -1, док: докНад(исх, i) };
      инд.контракты.push(к);
      открыл = { вид: 'контракт', имя: к.имя, ссылка: к };
    } else if (РЕГЕКС_БЛОК.test(т)) {
      открыл = { вид: 'блок' };
    } else if (стек.length === 0 && (м = РЕГЕКС_ОБЪЯВЛЕНИЕ.exec(т)) && !РЕЗЕРВ.has(первоеСлово(т))) {
      инд.глобальные.push({ тип: м[1], имя: м[2], строка: i, столбец: л.indexOf(м[2]), неизменная: /неизменно/.test(т), док: докНад(исх, i) });
    } else if (стек.length && стек[стек.length - 1].вид === 'структура' && (м = РЕГЕКС_ПОЛЕ.exec(т)) && !РЕЗЕРВ.has(первоеСлово(т))) {
      стек[стек.length - 1].ссылка.поля.push({ тип: м[1], имя: м[2], строка: i, столбец: л.indexOf(м[2]) });
    }

    if (открыл) стек.push(открыл);
    const закрытий = (т.match(РЕГЕКС_КОНЕЦ) || []).length;
    for (let k = 0; k < закрытий; k++) {
      const з = стек.pop();
      if (з && з.ссылка) з.ссылка.конец = i;
    }
    i = пропуститьДо;
  }
  // незакрытые блоки (код ещё пишется) — считаем, что они идут до конца файла
  for (const з of стек) if (з.ссылка) з.ссылка.конец = чист.length;
  return инд;
}

// ---------- работа с типами ----------

function разобратьТип(т) {
  т = (т || '').trim();
  if (!т) return null;
  if (т.endsWith('?')) return { вид: 'опц', внутр: т.slice(0, -1).trim() };
  const м = new RegExp(`^(${Б})(?:\\s+из\\s+(.+?))?(?:\\([^)]*\\))*$`, 'u').exec(т);
  if (!м) return null;
  const арг = м[2] ? м[2].split(/\s+и\s+/u).map(s => s.trim()) : [];
  return { вид: 'имя', база: м[1], арг };
}

function типСтрокой(т) { return (т || '').replace(/\s+/g, ' ').trim(); }

// ---------- проект: поиск модулей и сводка символов ----------

class Проект {
  constructor({ подсказки = [], стдлибПути = [] } = {}) {
    this.подсказки = подсказки;
    this.стдлибПути = стдлибПути.filter(Boolean);
    this.кэш = new Map();
    this.списокСтдлиб = null;
    this.подсказкиПоИмени = new Map(подсказки.map(п => [п.имя, п]));
  }

  индексФайла(путь) {
    let ст;
    try { ст = fs.statSync(путь); } catch (e) { return null; }
    const к = this.кэш.get(путь);
    if (к && к.время === ст.mtimeMs) return к.индекс;
    let текст;
    try { текст = fs.readFileSync(путь, 'utf8'); } catch (e) { return null; }
    const индекс = разобратьФайл(текст);
    индекс.путь = путь;
    this.кэш.set(путь, { время: ст.mtimeMs, индекс });
    return индекс;
  }

  // Ищет файл модуля так же, как компилятор: рядом, в пакеты/, в стандартной библиотеке.
  найтиМодуль(имя, откуда, корень) {
    const папка = откуда ? path.dirname(откуда) : (корень || '.');
    const есть = (п) => { try { return fs.statSync(п).isFile(); } catch (e) { return false; } };
    if (имя.includes('/') || имя.endsWith('.код')) {
      const п = path.join(папка, имя);
      return есть(п) ? п : null;
    }
    const отн = имя.includes('.') ? имя.split('.').join(path.sep) + '.код' : имя + '.код';
    const кандидаты = [path.join(папка, отн)];
    const корни = [корень, папка].filter(Boolean);
    for (const к of корни) {
      кандидаты.push(path.join(к, 'пакеты', отн));
      if (!имя.includes('.')) кандидаты.push(path.join(к, 'пакеты', имя, имя + '.код'));
    }
    for (const с of this.стдлибПути) кандидаты.push(path.join(с, отн));
    for (const к of кандидаты) if (есть(к)) return к;
    return null;
  }

  // Все модули, которые можно подключить: файлы рядом, в пакеты/ и стандартная библиотека.
  доступныеМодули(откуда, корень) {
    const рез = new Map();
    const добавить = (папка, префикс, источник) => {
      let записи;
      try { записи = fs.readdirSync(папка, { withFileTypes: true }); } catch (e) { return; }
      for (const з of записи) {
        if (з.isFile() && з.name.endsWith('.код')) {
          const имя = префикс + з.name.slice(0, -4);
          const п = path.join(папка, з.name);
          if (откуда && path.resolve(п) === path.resolve(откуда)) continue;
          if (!рез.has(имя)) рез.set(имя, { имя, путь: п, источник });
        } else if (з.isDirectory() && источник === 'пакеты' && !з.name.startsWith('.')) {
          const вложенный = path.join(папка, з.name, з.name + '.код');
          if (!рез.has(з.name)) {
            try { if (fs.statSync(вложенный).isFile()) рез.set(з.name, { имя: з.name, путь: вложенный, источник }); } catch (e) { /* нет */ }
          }
        }
      }
    };
    if (откуда) добавить(path.dirname(откуда), '', 'рядом');
    for (const к of [корень, откуда ? path.dirname(откуда) : null].filter(Boolean)) добавить(path.join(к, 'пакеты'), '', 'пакеты');
    for (const с of this.стдлибПути) добавить(с, '', 'стандартная библиотека');
    return [...рез.values()].sort((а, б) => а.имя.localeCompare(б.имя, 'ru'));
  }

  // Сводка видимого из файла: текущий файл + подключённые (с вложенными подключениями).
  область(путьФайла, индексТекущего, корень) {
    const модули = []; // { ключ, путь, индекс, прямой }
    const посещённые = new Set();
    if (путьФайла) посещённые.add(path.resolve(путьФайла));
    const очередь = индексТекущего.подключения.map(п => ({ имя: п.имя, откуда: путьФайла, прямой: true, глубина: 1 }));
    while (очередь.length) {
      const э = очередь.shift();
      const п = this.найтиМодуль(э.имя, э.откуда, корень);
      if (!п) continue;
      const абс = path.resolve(п);
      if (посещённые.has(абс)) continue;
      посещённые.add(абс);
      const индекс = this.индексФайла(п);
      if (!индекс) continue;
      const ключ = э.имя.includes('/') || э.имя.endsWith('.код') ? path.basename(п, '.код') : э.имя.split('.').join('_');
      модули.push({ ключ, имя: э.имя, путь: п, индекс, прямой: э.прямой });
      if (э.глубина < 5) for (const вл of индекс.подключения) очередь.push({ имя: вл.имя, откуда: п, прямой: false, глубина: э.глубина + 1 });
    }
    return { текущий: индексТекущего, путь: путьФайла, модули, корень };
  }
}

// ---------- работа в контексте документа ----------

class Движок {
  constructor(параметры) {
    this.проект = new Проект(параметры);
    this.подсказки = параметры.подсказки || [];
  }

  // Подготовка контекста для документа: разобранный индекс, очищенные строки, область видимости.
  контекст(текст, путьФайла, корень) {
    const индекс = разобратьФайл(текст);
    индекс.путь = путьФайла;
    return {
      текст, путьФайла, корень,
      индекс,
      исходные: текст.split('\n'),
      чистые: очистить(текст).split('\n'),
      область: this.проект.область(путьФайла, индекс, корень)
    };
  }

  // -- структуры и функции, видимые из контекста
  _видимыеСтруктуры(к) {
    const рез = [];
    for (const с of к.индекс.структуры) рез.push({ с, модуль: null });
    for (const м of к.область.модули) for (const с of м.индекс.структуры) рез.push({ с, модуль: м });
    return рез;
  }

  _найтиСтруктуру(к, имя) {
    const в = this._видимыеСтруктуры(к);
    let н = в.find(э => э.с.имя === имя);
    if (н) return н;
    // падежи: «Список из Пользователей» → Пользователь
    н = в.find(э => имя.length >= 4 && имя.startsWith(э.с.имя.slice(0, Math.max(3, э.с.имя.length - 2))) && э.с.имя.length >= 3);
    return н || null;
  }

  _функцияВОбласти(к, имя) {
    let н = к.индекс.функции.find(ф => ф.имя === имя);
    if (н) return { ф: н, модуль: null };
    for (const м of к.область.модули) {
      н = м.индекс.функции.find(ф => ф.имя === имя && ф.публично);
      if (н) return { ф: н, модуль: м };
    }
    return null;
  }

  // -- функция, внутри которой находится строка
  _охватывающаяФункция(к, строка) {
    let лучшая = null;
    const проверить = (ф) => {
      if (ф.строка <= строка && (ф.конец === -1 || строка <= ф.конец)) {
        if (!лучшая || ф.строка > лучшая.строка) лучшая = ф;
      }
    };
    for (const ф of к.индекс.функции) проверить(ф);
    for (const с of к.индекс.структуры) for (const ф of с.методы) проверить(ф);
    return лучшая;
  }

  // -- локальные переменные: параметры + объявления выше курсора внутри функции
  _локальные(к, строка) {
    const ф = this._охватывающаяФункция(к, строка);
    const рез = new Map();
    if (!ф) return { ф: null, локальные: рез };
    for (const п of ф.параметры) рез.set(п.имя, { имя: п.имя, тип: п.тип, вид: 'параметр', строка: ф.строка, столбец: к.чистые[ф.строка].indexOf(п.имя) });
    for (let i = ф.строка + 1; i < строка && i < к.чистые.length; i++) {
      const т = к.чистые[i].trim();
      if (!т) continue;
      let м;
      if ((м = РЕГЕКС_ДЛЯ.exec(т))) {
        let тип = м[1] || '';
        if (!тип) {
          const тк = this._типВыражения(к, м[3].replace(/[;\s]+$/, ''), строка, рез);
          const р = разобратьТип(тк);
          if (р && р.вид === 'имя' && р.арг.length) тип = this._типЭлемента(к, р.арг[0]);
        }
        рез.set(м[2], { имя: м[2], тип, вид: 'переменная', строка: i, столбец: к.чистые[i].indexOf(м[2]) });
        continue;
      }
      if (РЕГЕКС_БЛОК.test(т) || /^(вернуть|иначе|конец|прервать|продолжить)(?![\p{L}\p{N}_])/u.test(т)) continue;
      if ((м = РЕГЕКС_ОБЪЯВЛЕНИЕ.exec(т)) && !РЕЗЕРВ.has(первоеСлово(т))) {
        рез.set(м[2], { имя: м[2], тип: м[1], вид: 'переменная', строка: i, столбец: к.чистые[i].indexOf(м[2], к.чистые[i].indexOf(м[1]) + м[1].length) });
        continue;
      }
      if ((м = РЕГЕКС_ПРИСВАИВАНИЕ.exec(т)) && !рез.has(м[1])) {
        const тип = this._типПоПравойЧасти(к, м[2]);
        рез.set(м[1], { имя: м[1], тип, вид: 'переменная', строка: i, столбец: к.чистые[i].indexOf(м[1]) });
      }
    }
    return { ф, локальные: рез };
  }

  _типПоПравойЧасти(к, п) {
    п = п.trim().replace(/;\s*$/, '');
    let м;
    if (/^"/.test(п)) return 'текст';
    if (/^-?\d+$/.test(п) || /^0[xXbB][0-9a-fA-F_]+$/.test(п)) return 'целое';
    if (/^-?\d+\.\d+$/.test(п)) return 'дробное';
    if ((м = new RegExp(`^(${Б}(?:\\s+из\\s+${Б}(?:\\s+и\\s+${Б})*)?)\\s*\\(`, 'u').exec(п))) {
      const имя = первоеСлово(м[1]);
      if (this._найтиСтруктуру(к, имя) || /^[А-ЯЁA-Z]/u.test(имя) || ВСТРОЕННЫЕ_МЕТОДЫ[имя]) return м[1];
      const ф = this._функцияВОбласти(к, имя);
      if (ф && ф.ф.возврат) return ф.ф.возврат;
    }
    return '';
  }

  _типЭлемента(к, слово) {
    if (РОДИТЕЛЬНЫЕ[слово]) return РОДИТЕЛЬНЫЕ[слово];
    const с = this._найтиСтруктуру(к, слово);
    return с ? с.с.имя : слово;
  }

  // -- тип выражения-«цепочки»: имя, это, имя.поле, имя.метод(...), функция(...)
  _типВыражения(к, выражение, строка, локальные) {
    const сегменты = this._сегменты(выражение);
    if (!сегменты.length) return '';
    локальные = локальные || this._локальные(к, строка).локальные;
    let текущий; // { тип } | { модуль }
    const первый = сегменты[0];
    if (первый.имя === 'это') {
      const ф = this._охватывающаяФункция(к, строка);
      текущий = { тип: ф && ф.структура ? ф.структура : '' };
    } else if (локальные.has(первый.имя) && !первый.вызов) {
      текущий = { тип: локальные.get(первый.имя).тип };
    } else if (!первый.вызов && к.индекс.глобальные.some(г => г.имя === первый.имя)) {
      текущий = { тип: к.индекс.глобальные.find(г => г.имя === первый.имя).тип };
    } else if (!первый.вызов && к.область.модули.some(м => м.ключ === первый.имя)) {
      текущий = { модуль: к.область.модули.find(м => м.ключ === первый.имя) };
    } else if (первый.вызов) {
      const ф = this._функцияВОбласти(к, первый.имя);
      const с = this._найтиСтруктуру(к, первый.имя);
      if (ф) текущий = { тип: ф.ф.возврат };
      else if (с) текущий = { тип: с.с.имя };
      else if (this.проект.подсказкиПоИмени.has(первый.имя)) текущий = { тип: this._возвратПодсказки(первый.имя) };
      else текущий = { тип: '' };
    } else текущий = { тип: '' };

    for (let i = 1; i < сегменты.length; i++) {
      const с = сегменты[i];
      if (текущий.модуль) {
        const м = текущий.модуль;
        const ф = м.индекс.функции.find(ф => ф.имя === с.имя);
        const г = м.индекс.глобальные.find(г => г.имя === с.имя);
        const ст = м.индекс.структуры.find(ст => ст.имя === с.имя);
        текущий = { тип: ф ? ф.возврат : г ? г.тип : ст ? ст.имя : '' };
        continue;
      }
      текущий = { тип: this._типЧлена(к, текущий.тип, с.имя) };
    }
    return текущий.тип || '';
  }

  _возвратПодсказки(имя) {
    const п = this.проект.подсказкиПоИмени.get(имя);
    if (!п) return '';
    const м = /\):\s*(.+)$/u.exec(п.деталь || '');
    return м ? м[1].trim() : '';
  }

  _типЧлена(к, типСтр, имя) {
    const р = разобратьТип(типСтр);
    if (!р) return '';
    if (р.вид === 'опц') return имя === 'значение' ? р.внутр : (имя === 'есть' ? 'верно' : '');
    const б = р.база;
    if (б === 'результат') return имя === 'значение' ? (р.арг[0] || '') : (имя === 'успешно' ? 'верно' : (имя === 'сообщение' ? 'текст' : ''));
    if (ВСТРОЕННЫЕ_МЕТОДЫ[б]) {
      const м = ВСТРОЕННЫЕ_МЕТОДЫ[б].find(м => м.имя === имя);
      if (!м || !м.возврат) return '';
      if (м.возврат === '@элемент') return р.арг[0] ? this._типЭлемента(к, р.арг[0]) : '';
      if (м.возврат === '@ключ') return р.арг[0] ? this._типЭлемента(к, р.арг[0]) : '';
      if (м.возврат === '@значение') return р.арг[1] ? this._типЭлемента(к, р.арг[1]) : '';
      if (м.возврат === '@результат_значения') return р.арг[1] ? 'результат из ' + this._типЭлемента(к, р.арг[1]) : '';
      return м.возврат;
    }
    const с = this._найтиСтруктуру(к, б);
    if (!с) return '';
    const п = с.с.поля.find(п => п.имя === имя);
    if (п) return п.тип;
    const м = с.с.методы.find(м => м.имя === имя);
    return м ? м.возврат : '';
  }

  // Разбор цепочки «а.б(…).в» в сегменты [{имя, вызов}]
  _сегменты(выражение) {
    const в = выражение.trim();
    const сег = [];
    let i = 0;
    const идент = new RegExp(`^${Б}`, 'u');
    while (i < в.length) {
      const м = идент.exec(в.slice(i));
      if (!м) return [];
      i += м[0].length;
      let вызов = false;
      while (в[i] === '(' || в[i] === '[') {
        const откр = в[i], закр = откр === '(' ? ')' : ']';
        let г = 0, j = i;
        for (; j < в.length; j++) {
          if (в[j] === откр) г++;
          else if (в[j] === закр) { г--; if (г === 0) break; }
        }
        if (г !== 0) return [];
        if (откр === '(') вызов = true;
        i = j + 1;
      }
      сег.push({ имя: м[0], вызов });
      if (в[i] === '.') i++;
      else break;
    }
    return i >= в.length ? сег : [];
  }

  // Выражение слева от точки: идём назад по идентификаторам, точкам и скобкам.
  _приёмникСлева(строкаТекста, позицияТочки) {
    let i = позицияТочки - 1;
    while (i >= 0) {
      const с = строкаТекста[i];
      if (с === ')' || с === ']') {
        const откр = с === ')' ? '(' : '[';
        let г = 0;
        for (; i >= 0; i--) {
          if (строкаТекста[i] === с) г++;
          else if (строкаТекста[i] === откр) { г--; if (г === 0) break; }
        }
        if (i < 0) break;
        i--;
        continue;
      }
      if (/[\p{L}\p{N}_.]/u.test(с)) { i--; continue; }
      break;
    }
    return строкаТекста.slice(i + 1, позицияТочки).trim();
  }

  // ---------- подсказки ----------

  дополнить(к, строка, столбец) {
    const л = к.чистые[строка] || '';
    const исходнаяСтрока = к.исходные[строка] || '';
    const доКурсора = л.slice(0, столбец);
    // внутри строки или комментария подсказок нет
    if (this._вСтрокеИлиКомментарии(к, строка, столбец)) return [];

    // подключить …
    let м = new RegExp(`^\\s*подключить\\s+([\\p{L}\\p{N}_.]*)$`, 'u').exec(доКурсора);
    if (м) return this._подсказкиМодулей(к, м[1]);

    // после точки
    м = new RegExp(`\\.([\\p{L}\\p{N}_]*)$`, 'u').exec(доКурсора);
    if (м && !/\d$/.test(доКурсора.slice(0, доКурсора.length - м[0].length))) {
      const приёмник = this._приёмникСлева(доКурсора, доКурсора.length - м[0].length);
      if (приёмник) return this._подсказкиЧленов(к, приёмник, строка);
      return [];
    }

    return this._общиеПодсказки(к, строка, доКурсора, исходнаяСтрока);
  }

  _вСтрокеИлиКомментарии(к, строка, столбец) {
    const исх = к.исходные[строка] || '';
    const чист = к.чистые[строка] || '';
    // позиция столбец: если в исходнике есть непробельный символ, а в очищенном пробел — это строка/комментарий
    // (проверяем символ слева от курсора и сам символ строки)
    if (столбец > 0) {
      const а = исх[столбец - 1], б = чист[столбец - 1];
      if (а !== undefined && а.trim() && !(б || '').trim()) {
        // сам закрывающий символ строки '"' остаётся в очищенном тексте, так что сюда попадает только внутренность
        return true;
      }
    }
    // курсор сразу после открывающей кавычки: «"|»
    const доКурсора = чист.slice(0, столбец);
    const кавычек = (доКурсора.match(/"/g) || []).length;
    return кавычек % 2 === 1;
  }

  _подсказкиМодулей(к, префикс) {
    const рез = [];
    const уже = new Set(к.индекс.подключения.map(п => п.имя));
    for (const м of this.проект.доступныеМодули(к.путьФайла, к.корень)) {
      if (уже.has(м.имя)) continue;
      const индекс = this.проект.индексФайла(м.путь);
      рез.push({ метка: м.имя, вид: 'модуль', деталь: м.источник, док: индекс && индекс.описание ? индекс.описание : '', сортировка: '1' + м.имя });
    }
    return рез;
  }

  _подсказкиЧленов(к, приёмник, строка) {
    const рез = [];
    const сегменты = this._сегменты(приёмник);
    if (!сегменты.length) return [];
    // модуль: сеть.…
    if (сегменты.length === 1 && !сегменты[0].вызов) {
      const м = к.область.модули.find(м => м.ключ === сегменты[0].имя);
      if (м) {
        const л = this._локальные(к, строка).локальные;
        if (!л.has(сегменты[0].имя)) return this._символыМодуля(м);
      }
    }
    const тип = this._типВыражения(к, приёмник, строка);
    const р = разобратьТип(тип);
    if (р) {
      if (р.вид === 'опц') {
        for (const п of ПОЛЯ_ОПЦИОНАЛЬНОГО) рез.push({ метка: п.имя, вид: 'поле', деталь: п.имя + ': ' + (п.тип === '@элемент' ? р.внутр : п.тип), док: п.док, сортировка: '0' + п.имя });
        return рез;
      }
      if (р.база === 'результат') {
        for (const п of ПОЛЯ_РЕЗУЛЬТАТА) рез.push({ метка: п.имя, вид: 'поле', деталь: п.имя + ': ' + (п.тип === '@элемент' ? (р.арг[0] || 'значение') : п.тип), док: п.док, сортировка: '0' + п.имя });
        return рез;
      }
      if (ВСТРОЕННЫЕ_МЕТОДЫ[р.база]) {
        for (const м of ВСТРОЕННЫЕ_МЕТОДЫ[р.база]) рез.push(this._элементВстроенногоМетода(р, м));
        return рез;
      }
      const с = this._найтиСтруктуру(к, р.база);
      if (с) {
        for (const п of с.с.поля) рез.push({ метка: п.имя, вид: 'поле', деталь: п.тип + ' ' + п.имя, док: '', сортировка: '0' + п.имя, определение: this._определение(с.модуль, к, п) });
        for (const м of с.с.методы) {
          if (!м.публично) continue;
          рез.push(this._элементФункции(м, '1', 'метод', с.модуль, к));
        }
        return рез;
      }
    }
    // тип неизвестен — показываем всё, что может быть после точки
    const видели = new Set();
    for (const { с, модуль } of this._видимыеСтруктуры(к)) {
      for (const п of с.поля) if (!видели.has(п.имя)) { видели.add(п.имя); рез.push({ метка: п.имя, вид: 'поле', деталь: `${п.тип} ${п.имя} — поле ${с.имя}`, док: '', сортировка: '5' + п.имя }); }
      for (const м of с.методы) if (м.публично && !видели.has(м.имя)) { видели.add(м.имя); const э = this._элементФункции(м, '5', 'метод', модуль, к); э.деталь += ` — метод ${с.имя}`; рез.push(э); }
    }
    for (const имя of Object.keys(ВСТРОЕННЫЕ_МЕТОДЫ)) for (const м of ВСТРОЕННЫЕ_МЕТОДЫ[имя]) if (!видели.has(м.имя)) { видели.add(м.имя); рез.push(this._элементВстроенногоМетода({ база: имя, арг: [] }, м, '6')); }
    return рез;
  }

  _элементВстроенногоМетода(р, м, сорт = '1') {
    const возврат = !м.возврат ? '' : (м.возврат === '@элемент' ? (р.арг[0] || 'элемент') : м.возврат.startsWith('@') ? '' : м.возврат);
    return {
      метка: м.имя, вид: 'метод',
      деталь: `${м.имя}(${м.парам.join(', ')})${возврат ? ': ' + возврат : ''}`,
      док: м.док || '', сортировка: сорт + м.имя,
      вставка: м.парам.length ? `${м.имя}(${м.парам.map((п, i) => `\${${i + 1}:${п}}`).join(', ')})` : `${м.имя}()`,
      сигнатура: { парам: м.парам, возврат }
    };
  }

  _символыМодуля(м) {
    const рез = [];
    for (const ф of м.индекс.функции) if (ф.публично) рез.push(this._элементФункции(ф, '1', 'функция', м, null));
    for (const с of м.индекс.структуры) if (с.публично) рез.push({ метка: с.имя, вид: 'структура', деталь: `структура ${с.имя}`, док: с.док, сортировка: '2' + с.имя, определение: { путь: м.путь, строка: с.строка, столбец: с.столбец } });
    for (const г of м.индекс.глобальные) рез.push({ метка: г.имя, вид: 'константа', деталь: `${г.тип} ${г.имя}`, док: г.док, сортировка: '3' + г.имя, определение: { путь: м.путь, строка: г.строка, столбец: г.столбец } });
    return рез;
  }

  _определение(модуль, к, символ) {
    return { путь: модуль ? модуль.путь : к.путьФайла, строка: символ.строка, столбец: символ.столбец };
  }

  _подписьФункции(ф) {
    const параметры = ф.параметры.map(п => (п.тип ? п.тип + ' ' : '') + п.имя).join(', ');
    return `${ф.имя}(${параметры})${ф.возврат ? ': ' + ф.возврат : ''}`;
  }

  _элементФункции(ф, сортПрефикс, вид, модуль, к) {
    const вставкаПараметров = ф.параметры.length ? ф.параметры.map((п, i) => `\${${i + 1}:${п.имя}}`).join(', ') : '';
    return {
      метка: ф.имя, вид, деталь: this._подписьФункции(ф) + (модуль ? `  — ${модуль.ключ}` : ''),
      док: ф.док, сортировка: сортПрефикс + ф.имя,
      вставка: `${ф.имя}(${вставкаПараметров})`,
      определение: { путь: модуль ? модуль.путь : (к ? к.путьФайла : null), строка: ф.строка, столбец: ф.столбец },
      подписьДляПараметров: ф
    };
  }

  _общиеПодсказки(к, строка, доКурсора, исходнаяСтрока) {
    const рез = [];
    const занято = new Set();
    const добавить = (э) => { if (!занято.has(э.метка)) { занято.add(э.метка); рез.push(э); } };

    const { ф, локальные } = this._локальные(к, строка);
    if (ф && ф.структура) добавить({ метка: 'это', вид: 'переменная', деталь: `это — ${ф.структура}`, док: 'текущий экземпляр структуры', сортировка: '0это' });
    for (const л of локальные.values()) добавить({ метка: л.имя, вид: л.вид, деталь: (л.тип ? л.тип + ' ' : '') + л.имя, док: '', сортировка: '0' + л.имя, определение: { путь: к.путьФайла, строка: л.строка, столбец: л.столбец } });

    for (const ф2 of к.индекс.функции) добавить(this._элементФункции(ф2, '1', 'функция', null, к));
    for (const с of к.индекс.структуры) добавить({ метка: с.имя, вид: 'структура', деталь: `структура ${с.имя}`, док: с.док, сортировка: '1' + с.имя, определение: { путь: к.путьФайла, строка: с.строка, столбец: с.столбец } });
    for (const кн of к.индекс.контракты) добавить({ метка: кн.имя, вид: 'контракт', деталь: `контракт ${кн.имя}`, док: кн.док, сортировка: '1' + кн.имя });
    for (const г of к.индекс.глобальные) добавить({ метка: г.имя, вид: 'константа', деталь: `${г.тип} ${г.имя}`, док: г.док, сортировка: '1' + г.имя, определение: { путь: к.путьФайла, строка: г.строка, столбец: г.столбец } });

    // подключённые модули (и вложенные)
    for (const м of к.область.модули) {
      добавить({ метка: м.ключ, вид: 'модуль', деталь: 'модуль', док: м.индекс.описание, сортировка: '2' + м.ключ, определение: { путь: м.путь, строка: 0, столбец: 0 } });
      for (const э of this._символыМодуля(м)) добавить({ ...э, сортировка: '2' + э.метка });
    }

    // встроенные функции, типы, ключевые слова
    for (const п of this.подсказки) {
      if (занято.has(п.имя)) continue;
      const вид = п.вид === 'КлючевоеСлово' ? 'ключевое' : п.вид === 'Тип' ? 'тип' : 'функция';
      const э = { метка: п.имя, вид, деталь: п.деталь || '', док: п.док || '', сортировка: (вид === 'функция' ? '3' : '4') + п.имя };
      if (вид === 'функция') {
        const м = new RegExp(`^${п.имя}\\((.*?)\\)`, 'u').exec(п.деталь || '');
        if (м) {
          const парам = разобратьПараметры(м[1]);
          э.вставка = парам.length ? `${п.имя}(${парам.map((п2, i) => `\${${i + 1}:${п2.имя}}`).join(', ')})` : `${п.имя}()`;
        }
      }
      добавить(э);
    }

    // функции из ещё не подключённых модулей стандартной библиотеки — с автоматическим «подключить»
    const слово = (new RegExp(`(${Б})$`, 'u').exec(доКурсора) || [])[1] || '';
    if (слово.length >= 2 && !/^\s*(?:публично|приватно)?\s*(?:функция|структура)\s+\S*$/u.test(доКурсора)) {
      const подключённые = new Set(к.область.модули.map(м => path.resolve(м.путь)));
      for (const мод of this.проект.доступныеМодули(к.путьФайла, к.корень)) {
        if (подключённые.has(path.resolve(мод.путь))) continue;
        const индекс = this.проект.индексФайла(мод.путь);
        if (!индекс) continue;
        const виртуальный = { ключ: мод.имя, путь: мод.путь, индекс };
        for (const э of this._символыМодуля(виртуальный)) {
          if (занято.has(э.метка) || !э.метка.startsWith(слово)) continue;
          занято.add(э.метка);
          рез.push({ ...э, сортировка: '9' + э.метка, деталь: э.деталь.replace(/\s+—\s+\S+$/, '') + `  — из «${мод.имя}», будет добавлено «подключить»`, подключить: мод.имя });
        }
      }
    }
    return рез;
  }

  // ---------- подсказка параметров ----------

  подсказкаПараметров(к, строка, столбец) {
    // идём назад по очищенным строкам и ищем незакрытую «(»
    let г = 0, акт = 0;
    let стр = строка, поз = столбец;
    let найдено = null;
    for (let шаг = 0; шаг < 25 && стр >= 0 && !найдено; шаг++) {
      const л = к.чистые[стр] || '';
      for (let i = Math.min(поз, л.length) - 1; i >= 0; i--) {
        const с = л[i];
        if (с === ')' || с === ']') г++;
        else if (с === '[') { if (г > 0) г--; }
        else if (с === '(') {
          if (г === 0) { найдено = { стр, i }; break; }
          г--;
        } else if (с === ',' && г === 0) акт++;
        else if (с === ';' || с === '{' || с === '}') { if (г === 0) { return null; } }
      }
      стр--; поз = (к.чистые[стр] || '').length;
    }
    if (!найдено) return null;
    const л = к.чистые[найдено.стр];
    const слева = л.slice(0, найдено.i);
    const м = new RegExp(`(${Б})\\s*$`, 'u').exec(слева);
    if (!м) return null;
    const имя = м[1];
    if (РЕЗЕРВ.has(имя) && имя !== 'это') return null;
    const доИмени = слева.slice(0, слева.length - м[0].length);
    let сигнатура = null;

    if (доИмени.endsWith('.')) {
      const приёмник = this._приёмникСлева(доИмени, доИмени.length - 1);
      const тип = приёмник ? this._типВыражения(к, приёмник, найдено.стр) : '';
      const р = разобратьТип(тип);
      if (р && р.вид === 'имя') {
        if (ВСТРОЕННЫЕ_МЕТОДЫ[р.база]) {
          const вм = ВСТРОЕННЫЕ_МЕТОДЫ[р.база].find(х => х.имя === имя);
          if (вм) сигнатура = { метка: `${имя}(${вм.парам.join(', ')})`, параметры: вм.парам, док: вм.док };
        } else {
          const с = this._найтиСтруктуру(к, р.база);
          const мф = с && с.с.методы.find(х => х.имя === имя);
          if (мф) сигнатура = { метка: this._подписьФункции(мф), параметры: мф.параметры.map(п => (п.тип ? п.тип + ' ' : '') + п.имя), док: мф.док };
        }
      }
      if (!сигнатура && приёмник && /^[\p{L}_][\p{L}\p{N}_]*$/u.test(приёмник)) {
        const мод = к.область.модули.find(х => х.ключ === приёмник);
        const фм = мод && мод.индекс.функции.find(х => х.имя === имя && х.публично);
        if (фм) сигнатура = { метка: this._подписьФункции(фм), параметры: фм.параметры.map(п => (п.тип ? п.тип + ' ' : '') + п.имя), док: фм.док };
      }
    } else {
      const н = this._функцияВОбласти(к, имя);
      if (н) сигнатура = { метка: this._подписьФункции(н.ф), параметры: н.ф.параметры.map(п => (п.тип ? п.тип + ' ' : '') + п.имя), док: н.ф.док };
      else {
        const с = this._найтиСтруктуру(к, имя);
        if (с && с.с.имя === имя) {
          сигнатура = { метка: `${имя}(${с.с.поля.map(п => п.тип + ' ' + п.имя).join(', ')})`, параметры: с.с.поля.map(п => п.тип + ' ' + п.имя), док: 'конструктор: по всем полям в порядке объявления' };
        } else {
          const п = this.проект.подсказкиПоИмени.get(имя);
          const мм = п && new RegExp(`^${имя}\\((.*?)\\)(?::\\s*(.+))?$`, 'u').exec(п.деталь || '');
          if (мм) сигнатура = { метка: п.деталь, параметры: разобратьПараметры(мм[1]).map(х => (х.тип ? х.тип + ' ' : '') + х.имя), док: п.док || '' };
        }
      }
    }
    if (!сигнатура) return null;
    return { ...сигнатура, активный: Math.min(акт, Math.max(0, сигнатура.параметры.length - 1)) };
  }

  // ---------- определение и справка ----------

  _словоПодКурсором(к, строка, столбец) {
    const л = к.чистые[строка] || '';
    let н = столбец, к2 = столбец;
    const буква = /[\p{L}\p{N}_]/u;
    while (н > 0 && буква.test(л[н - 1])) н--;
    while (к2 < л.length && буква.test(л[к2])) к2++;
    if (н === к2) return null;
    return { слово: л.slice(н, к2), начало: н, конец: к2 };
  }

  определить(к, строка, столбец) {
    const с = this._словоПодКурсором(к, строка, столбец);
    if (!с) return null;
    const л = к.чистые[строка];
    // после точки: поле, метод или символ модуля
    if (с.начало > 0 && л[с.начало - 1] === '.') {
      const приёмник = this._приёмникСлева(л, с.начало - 1);
      const сегм = this._сегменты(приёмник);
      if (сегм.length === 1 && !сегм[0].вызов) {
        const м = к.область.модули.find(х => х.ключ === сегм[0].имя);
        if (м) {
          const э = this._символыМодуля(м).find(х => х.метка === с.слово);
          return э && э.определение ? { ...э.определение, детали: э } : null;
        }
      }
      const тип = this._типВыражения(к, приёмник, строка);
      const р = разобратьТип(тип);
      if (р && р.вид === 'имя') {
        const ст = this._найтиСтруктуру(к, р.база);
        if (ст) {
          const п = ст.с.поля.find(х => х.имя === с.слово);
          if (п) return { ...this._определение(ст.модуль, к, п) };
          const м = ст.с.методы.find(х => х.имя === с.слово);
          if (м) return { путь: ст.модуль ? ст.модуль.путь : к.путьФайла, строка: м.строка, столбец: м.столбец };
        }
      }
      return null;
    }
    const { локальные } = this._локальные(к, строка);
    if (локальные.has(с.слово)) { const л2 = локальные.get(с.слово); return { путь: к.путьФайла, строка: л2.строка, столбец: л2.столбец }; }
    for (const ф of к.индекс.функции) if (ф.имя === с.слово) return { путь: к.путьФайла, строка: ф.строка, столбец: ф.столбец };
    for (const ст of к.индекс.структуры) if (ст.имя === с.слово) return { путь: к.путьФайла, строка: ст.строка, столбец: ст.столбец };
    for (const г of к.индекс.глобальные) if (г.имя === с.слово) return { путь: к.путьФайла, строка: г.строка, столбец: г.столбец };
    for (const м of к.область.модули) {
      if (м.ключ === с.слово) return { путь: м.путь, строка: 0, столбец: 0 };
      const э = this._символыМодуля(м).find(х => х.метка === с.слово);
      if (э && э.определение) return э.определение;
    }
    return null;
  }

  справка(к, строка, столбец) {
    const с = this._словоПодКурсором(к, строка, столбец);
    if (!с) return null;
    const л = к.чистые[строка];
    if (new RegExp(`^подключить\\s`, 'u').test(л.trim())) {
      const м = к.область.модули.find(х => х.имя === с.слово || х.ключ === с.слово);
      if (м) return { заголовок: `модуль ${м.ключ}`, текст: м.индекс.описание };
    }
    const после = л.slice(с.начало - 1, с.начало);
    if (после === '.') {
      const приёмник = this._приёмникСлева(л, с.начало - 1);
      const сегм = this._сегменты(приёмник);
      if (сегм.length === 1 && !сегм[0].вызов) {
        const м = к.область.модули.find(х => х.ключ === сегм[0].имя);
        if (м) {
          const э = this._символыМодуля(м).find(х => х.метка === с.слово);
          if (э) return { заголовок: э.деталь, текст: э.док };
        }
      }
      const тип = this._типВыражения(к, приёмник, строка);
      const р = разобратьТип(тип);
      if (р && р.вид === 'имя') {
        if (ВСТРОЕННЫЕ_МЕТОДЫ[р.база]) {
          const вм = ВСТРОЕННЫЕ_МЕТОДЫ[р.база].find(х => х.имя === с.слово);
          if (вм) return { заголовок: `${вм.имя}(${вм.парам.join(', ')})`, текст: вм.док };
        }
        const ст = this._найтиСтруктуру(к, р.база);
        if (ст) {
          const п = ст.с.поля.find(х => х.имя === с.слово);
          if (п) return { заголовок: `${п.тип} ${п.имя}`, текст: `поле структуры ${ст.с.имя}` };
          const м = ст.с.методы.find(х => х.имя === с.слово);
          if (м) return { заголовок: this._подписьФункции(м), текст: м.док };
        }
      }
      return null;
    }
    const { локальные } = this._локальные(к, строка);
    if (локальные.has(с.слово)) { const х = локальные.get(с.слово); return { заголовок: `${х.тип ? х.тип + ' ' : ''}${х.имя}`, текст: х.вид }; }
    const н = this._функцияВОбласти(к, с.слово);
    if (н) return { заголовок: this._подписьФункции(н.ф), текст: н.ф.док };
    const ст = this._найтиСтруктуру(к, с.слово);
    if (ст && ст.с.имя === с.слово) return { заголовок: `структура ${ст.с.имя}`, текст: ст.с.док || ст.с.поля.map(п => `${п.тип} ${п.имя}`).join('\n') };
    const г = к.индекс.глобальные.find(х => х.имя === с.слово);
    if (г) return { заголовок: `${г.тип} ${г.имя}`, текст: г.док };
    const п = this.проект.подсказкиПоИмени.get(с.слово);
    if (п) return { заголовок: п.деталь || п.имя, текст: п.док || '' };
    return null;
  }
}

