// Заменяет содержимое комментариев и строк пробелами (длина и переводы строк сохраняются —
// номера строк и столбцы остаются теми же).
function очистить(текст) {
  const вых = [];
  let состояние = 0; // 0 код, 1 строка, 2 строчный комментарий, 3 блочный комментарий
  for (let i = 0; i < текст.length; i++) {
    const с = текст[i];
    const сл = текст[i + 1];
    if (состояние === 0) {
      if (с === '/' && сл === '/') { состояние = 2; вых.push(' '); continue; }
      if (с === '/' && сл === '*') { состояние = 3; вых.push(' '); continue; }
      if (с === '"') { состояние = 1; вых.push('"'); continue; }
      вых.push(с);
    } else if (состояние === 1) {
      if (с === '\\') { вых.push(' '); if (сл !== undefined && сл !== '\n') { вых.push(' '); i++; } continue; }
      if (с === '"') { состояние = 0; вых.push('"'); continue; }
      if (с === '\n') { состояние = 0; вых.push('\n'); continue; } // незакрытая строка не «съедает» остаток файла
      вых.push(' ');
    } else if (состояние === 2) {
      if (с === '\n') { состояние = 0; вых.push('\n'); } else вых.push(' ');
    } else {
      if (с === '*' && сл === '/') { вых.push(' ', ' '); i++; состояние = 0; continue; }
      вых.push(с === '\n' ? '\n' : ' ');
    }
  }
  return вых.join('');
}

function докНад(исходныеСтроки, строка) {
  const части = [];
  for (let i = строка - 1; i >= 0; i--) {
    const т = исходныеСтроки[i].trim();
    if (т.startsWith('//')) части.unshift(т.replace(/^\/\/+\s?/, ''));
    else break;
  }
  return части.join('\n').trim();
}

function разделитьПоВерхнемуУровню(текст, разделитель) {
  const части = [];
  let глубина = 0, начало = 0;
  for (let i = 0; i < текст.length; i++) {
    const с = текст[i];
    if (с === '(' || с === '[') глубина++;
    else if (с === ')' || с === ']') глубина--;
    else if (с === разделитель && глубина === 0) { части.push(текст.slice(начало, i)); начало = i + 1; }
  }
  части.push(текст.slice(начало));
  return части;
}

function разобратьПараметры(текст) {
  const рез = [];
  for (const ч of разделитьПоВерхнемуУровню(текст, ',')) {
    const т = ч.trim();
    if (!т) continue;
    const м = new RegExp(`^(.*?)\\s*(${Б})$`, 'u').exec(т);
    if (м && м[1]) рез.push({ тип: м[1].trim(), имя: м[2] });
    else рез.push({ тип: '', имя: т });
  }
  return рез;
}

