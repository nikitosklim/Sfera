'use strict';
// Проверка движка подсказок на настоящей стандартной библиотеке. Запуск: node tests/движок.test.js
const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { Движок, разобратьФайл } = require('../src/движок.js');

const подсказки = require('../src/подсказки.json');
const стдлиб = [path.join(__dirname, '..', 'stdlib'), path.join(__dirname, '..', '..', '..', 'стандартная_библиотека')].find(п => fs.existsSync(п));
assert.ok(стдлиб, 'не найдена стандартная библиотека');
const движок = new Движок({ подсказки, стдлибПути: [стдлиб] });
const папка = fs.mkdtempSync(path.join(os.tmpdir(), 'сфера-тест-'));
const файл = path.join(папка, 'главная.код');

// Текст с маркером курсора «|»
function в(текстСКурсором) {
  const индекс = текстСКурсором.indexOf('|');
  const текст = текстСКурсором.replace('|', '');
  const до = текст.slice(0, индекс).split('\n');
  const строка = до.length - 1, столбец = до[до.length - 1].length;
  return { к: движок.контекст(текст, файл, папка), строка, столбец };
}
const метки = (э) => э.map(х => х.метка);
let пройдено = 0;
function тест(имя, ф) {
  try { ф(); пройдено++; console.log('  ок   ' + имя); }
  catch (e) { console.log('  FAIL ' + имя + '\n       ' + (e.stack || e).toString().split('\n').slice(0, 4).join('\n       ')); process.exitCode = 1; }
}

тест('разбор всех файлов стандартной библиотеки без падений', () => {
  let функций = 0;
  for (const ф of fs.readdirSync(стдлиб).filter(х => х.endsWith('.код'))) {
    const и = разобратьФайл(fs.readFileSync(path.join(стдлиб, ф), 'utf8'));
    функций += и.функции.length;
  }
  assert.ok(функций > 200, 'функций найдено слишком мало: ' + функций);
});

тест('хеш.код: бах1 найдена с параметрами, типом и описанием', () => {
  const и = разобратьФайл(fs.readFileSync(path.join(стдлиб, 'хеш.код'), 'utf8'));
  const ф = и.функции.find(х => х.имя === 'бах1');
  assert.ok(ф);
  assert.deepStrictEqual(ф.параметры, [{ тип: 'текст', имя: 'данные' }]);
  assert.strictEqual(ф.возврат, 'Список из целых');
  assert.ok(и.описание.length > 5);
});

тест('подсказки из подключённой библиотеки', () => {
  const { к, строка, столбец } = в('подключить хеш;\n\nфункция главная(): целое\n    бах|\n    вернуть 0;\nконец\n');
  const м = метки(движок.дополнить(к, строка, столбец));
  assert.ok(м.includes('бах1') && м.includes('бах256_текстом') && м.includes('основание64'), 'нет функций хеш: ' + м.slice(0, 10));
});

тест('функции из НЕподключённой библиотеки предлагаются с автоподключением', () => {
  const { к, строка, столбец } = в('функция главная(): целое\n    бах2|\n    вернуть 0;\nконец\n');
  const э = движок.дополнить(к, строка, столбец).find(х => х.метка === 'бах256');
  assert.ok(э, 'бах256 не предложена');
  assert.strictEqual(э.подключить, 'хеш');
});

тест('модуль.… показывает содержимое модуля', () => {
  const { к, строка, столбец } = в('подключить хеш;\nфункция главная(): целое\n    хеш.|\n    вернуть 0;\nконец\n');
  const м = метки(движок.дополнить(к, строка, столбец));
  assert.ok(м.includes('бах1') && !м.includes('вернуть'));
});

тест('после «подключить » — список модулей с описаниями', () => {
  const { к, строка, столбец } = в('подключить |\n');
  const э = движок.дополнить(к, строка, столбец);
  assert.ok(метки(э).includes('сеть') && метки(э).includes('хеш'));
  assert.ok(э.find(х => х.метка === 'хеш').док.length > 5);
});

тест('методы Список после точки (тип из объявления)', () => {
  const { к, строка, столбец } = в('функция главная(): целое\n    Список из целых числа = Список из целых();\n    числа.|\n    вернуть 0;\nконец\n');
  const м = метки(движок.дополнить(к, строка, столбец));
  assert.deepStrictEqual(м.sort(), ['добавить', 'освободить', 'получить', 'размер', 'удалить', 'установить'].sort());
});

тест('тип выводится из присваивания (имя = Список из текстов())', () => {
  const { к, строка, столбец } = в('функция главная(): целое\n    имена = Список из текстов();\n    имена.|\n    вернуть 0;\nконец\n');
  assert.ok(метки(движок.дополнить(к, строка, столбец)).includes('добавить'));
});

тест('Словарь и результат из получить(...)', () => {
  const { к, строка, столбец } = в('функция главная(): целое\n    Словарь из текста и целого в = Словарь из текста и целого();\n    результат из целого р = в.получить("а");\n    р.|\n    вернуть 0;\nконец\n');
  assert.deepStrictEqual(метки(движок.дополнить(к, строка, столбец)).sort(), ['значение', 'сообщение', 'успешно']);
});

const СТРУКТУРА = 'структура Точка\n    целое х;\n    целое у;\n\n    функция сумма_координат(): целое\n        вернуть это.х + это.у;\n    конец\n\n    функция сдвинуть(целое дх, целое ду)\n        это.|\n    конец\nконец\n';

тест('«это.» внутри метода: поля и методы структуры', () => {
  const { к, строка, столбец } = в(СТРУКТУРА);
  const м = метки(движок.дополнить(к, строка, столбец));
  assert.deepStrictEqual(м.sort(), ['сдвинуть', 'сумма_координат', 'х', 'у'].sort());
});

тест('поля и методы экземпляра структуры', () => {
  const { к, строка, столбец } = в(СТРУКТУРА.replace('это.|', 'х = 1;') + '\nфункция главная(): целое\n    Точка т = Точка(3, 4);\n    т.|\n    вернуть 0;\nконец\n');
  const м = метки(движок.дополнить(к, строка, столбец));
  assert.ok(м.includes('х') && м.includes('у') && м.includes('сумма_координат'), м.join());
});

тест('элемент цикла «для каждого» знает тип (Список из Точек)', () => {
  const { к, строка, столбец } = в(СТРУКТУРА.replace('это.|', 'х = 1;') + '\nфункция главная(): целое\n    Список из Точек точки = Список из Точек();\n    для каждого т в точки\n        т.|\n    конец\n    вернуть 0;\nконец\n');
  assert.ok(метки(движок.дополнить(к, строка, столбец)).includes('сумма_координат'));
});

тест('локальные переменные и параметры предлагаются первыми', () => {
  const { к, строка, столбец } = в('функция сложить(целое первое, целое второе): целое\n    целое итог = первое + второе;\n    вернуть ит|\nконец\n');
  const э = движок.дополнить(к, строка, столбец);
  const итог = э.find(х => х.метка === 'итог');
  assert.ok(итог && итог.сортировка.startsWith('0'));
  assert.ok(метки(э).includes('первое') && метки(э).includes('второе'));
});

тест('локальные из другой функции НЕ попадают в подсказки', () => {
  const { к, строка, столбец } = в('функция а(): целое\n    целое секрет = 1;\n    вернуть секрет;\nконец\n\nфункция б(): целое\n    вернуть сек|\nконец\n');
  assert.ok(!метки(движок.дополнить(к, строка, столбец)).includes('секрет'));
});

тест('подсказки не пропадают при незавершённом коде', () => {
  const { к, строка, столбец } = в('функция помощник(целое а): целое\n    вернуть а;\nконец\n\nфункция главная(): целое\n    если (\n    пом|\n');
  assert.ok(метки(движок.дополнить(к, строка, столбец)).includes('помощник'));
});

тест('в строке и в комментарии подсказок нет', () => {
  const а = в('функция главная(): целое\n    вывести("при|вет");\nконец\n');
  assert.deepStrictEqual(движок.дополнить(а.к, а.строка, а.столбец), []);
  const б = в('функция главная(): целое\n    // комм|\nконец\n');
  assert.deepStrictEqual(движок.дополнить(б.к, б.строка, б.столбец), []);
});

тест('подсказка параметров: встроенная, своя функция, метод', () => {
  const а = в('функция главная(): целое\n    вывести(|);\nконец\n');
  assert.strictEqual(движок.подсказкаПараметров(а.к, а.строка, а.столбец).метка, 'вывести(значение)');
  const б = в('функция сложить(целое первое, целое второе): целое\n    вернуть первое + второе;\nконец\nфункция главная(): целое\n    целое х = сложить(1, |);\nконец\n');
  const с = движок.подсказкаПараметров(б.к, б.строка, б.столбец);
  assert.strictEqual(с.активный, 1);
  assert.strictEqual(с.метка, 'сложить(целое первое, целое второе): целое');
  const в2 = в('функция главная(): целое\n    Список из целых л = Список из целых();\n    л.установить(0, |);\nконец\n');
  const м = движок.подсказкаПараметров(в2.к, в2.строка, в2.столбец);
  assert.strictEqual(м.метка, 'установить(индекс, значение)');
  assert.strictEqual(м.активный, 1);
});

тест('подсказка параметров функции из библиотеки', () => {
  const а = в('подключить хеш;\nфункция главная(): целое\n    бах256_текстом(|);\nконец\n');
  assert.ok(движок.подсказкаПараметров(а.к, а.строка, а.столбец).метка.startsWith('бах256_текстом('));
});

тест('переход к определению: своя функция, переменная, функция из библиотеки', () => {
  const а = в('функция помощник(): целое\n    вернуть 1;\nконец\nфункция главная(): целое\n    целое икс = пом|ощник();\n    вернуть икс;\nконец\n');
  const о = движок.определить(а.к, а.строка, а.столбец);
  assert.strictEqual(о.строка, 0);
  const б = в('подключить хеш;\nфункция главная(): целое\n    бах2|56_текстом("а");\nконец\n');
  const о2 = движок.определить(б.к, б.строка, б.столбец);
  assert.ok(о2.путь.endsWith('хеш.код') && о2.строка > 0);
});

тест('справка при наведении содержит подпись и комментарий-описание', () => {
  const а = в('подключить хеш;\nфункция главная(): целое\n    бах1|("а");\nконец\n');
  const с = движок.справка(а.к, а.строка, а.столбец);
  assert.ok(с.заголовок.startsWith('бах1('), с.заголовок);
  assert.ok(с.текст.includes('БАХ-1'), с.текст);
});

