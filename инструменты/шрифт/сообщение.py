#!/usr/bin/env python3
"""Превращает текст в список номеров знаков шрифта 8x16 (для загрузчика, который рисует текст сам).

Использование:  python3 сообщение.py "Загрузчик Сферы" > сообщение.inc
Номера: 0–94 — символы 32..126, 95–158 — А…я, 159 — Ё, 160 — ё, 161 — «, 162 — », 163 — —, 164 — №. Конец списка — 255.
"""
import sys
def номер(с):
    к = ord(с)
    if 32 <= к <= 126: return к - 32
    if 0x410 <= к <= 0x44F: return 95 + к - 0x410
    return {0x401: 159, 0x451: 160, 0xAB: 161, 0xBB: 162, 0x2014: 163, 0x2116: 164}.get(к, 31)
print("    .byte " + ",".join(str(номер(с)) for с in sys.argv[1]) + ",255")
