#!/usr/bin/env python3
"""собрать_диск.py — делает образ диска с файловой системой СФС (см. стандартная_библиотека/диск_х86.код).
Использование: собрать_диск.py образ.img имя=файл [имя=файл ...]
Имя файла на диске — до 19 байт UTF-8 (можно по-русски). Файлы идут подряд с сектора 1, каждый с границы сектора."""
import os, struct, sys

def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    выход, пары = sys.argv[1], sys.argv[2:]
    if len(пары) > 15:
        sys.exit("в одном секторе таблицы помещается не больше 15 файлов")
    записи, тело, сектор = [], b"", 1
    for пара in пары:
        имя, путь = пара.split("=", 1)
        имя_байты = имя.encode("utf-8")
        if len(имя_байты) > 19:
            sys.exit(f"имя «{имя}» длиннее 19 байт")
        данные = open(путь, "rb").read()
        записи.append(имя_байты.ljust(20, b"\0") + struct.pack("<II", сектор, len(данные)) + b"\0" * 4)
        секторов = (len(данные) + 511) // 512
        тело += данные.ljust(секторов * 512, b"\0")
        сектор += секторов
    таблица = (b"SFS1" + struct.pack("<I", len(записи)) + b"\0" * 8 + b"".join(записи)).ljust(512, b"\0")
    open(выход, "wb").write(таблица + тело)
    print(f"{выход}: {len(записи)} файлов, {сектор} секторов")

main()
