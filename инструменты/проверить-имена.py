#!/usr/bin/env python3
"""Ищет в стандартной библиотеке публичные имена с латиницей.

Программист на Сфере не должен переключать раскладку, поэтому имена функций
и структур, которые он вызывает, пишутся по-русски. Исключения:
 - «внешняя функция …» (это имена из C-библиотек, пользователь их не пишет);
 - служебные имена, начинающиеся с «sfera_» или «__» (их вызывает компилятор).
Запуск: python3 инструменты/проверить-имена.py  (код возврата 1, если нашлось).
"""
import re, sys, pathlib

корень = pathlib.Path(__file__).resolve().parent.parent / "стандартная_библиотека"
шаблон = re.compile(r"^\s*(функция|структура|контракт)\s+([^\s(<:]+)")
нашли = []
for файл in sorted(корень.glob("*.код")):
    if файл.name == "голое_железо.код":
        continue  # замены libc: имена обязаны совпадать с C (malloc, memcpy…)
    for номер, строка in enumerate(файл.read_text(encoding="utf8").splitlines(), 1):
        if строка.lstrip().startswith("//") or "внешняя" in строка:
            continue
        m = шаблон.match(строка)
        if not m:
            continue
        имя = m.group(2)
        if имя.startswith(("sfera_", "__")):
            continue
        if re.search(r"[A-Za-z]", имя):
            нашли.append(f"{файл.name}:{номер}: {имя}")
print("\n".join(нашли) if нашли else "латинских публичных имён нет")
sys.exit(1 if нашли else 0)
